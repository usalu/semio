/** @emoji 🔤 `pluginId` (kebab-case, e.g. `"protocol-module-procedural"`) → the PascalCase export name used above. */
function toPascalCase(pluginId: string): string {
  return pluginId
    .split("-")
    .map((segment) => segment.charAt(0).toUpperCase() + segment.slice(1))
    .join("");
}


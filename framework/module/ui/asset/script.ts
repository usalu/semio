//#region 📦Catalog
function readCatalogSvgs(iconsDir: string): Record<string, string> {
  if (!existsSync(iconsDir)) {
    throw new Error(`Missing UI icon catalog directory: ${iconsDir}`);
  }
  const svgFiles = readdirSync(iconsDir).filter((name) => name.endsWith(".svg"));
  if (svgFiles.length === 0) {
    throw new Error(`UI icon catalog is empty: ${iconsDir}`);
  }
  const out: Record<string, string> = {};
  for (const file of svgFiles) {
    const id = basename(file, ".svg");
    out[id] = normalizeCatalogSvg(readFileSync(join(iconsDir, file), "utf8"));
  }
  return out;
}
//#endregion 📦Catalog

//#region 🧬Codegen
function escapeTsString(value: string): string {
  return value.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$/g, "\\$");
}

function escapeCSharpString(value: string): string {
  return value.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
}

function escapePythonString(value: string): string {
  return value.replace(/\\/g, "\\\\").replace(/"""/g, '\\"\\"\\"');
}

function generateJs(icons: Record<string, string>, generatedDir: string): void {
  const entries = Object.keys(icons)
    .sort()
    .map((id) => `  "${id}": \`${escapeTsString(icons[id]!)}\`,`)
    .join("\n");
  const body = `// Generated by framework/ui/asset/script.ts — do not edit.
export const ICONS = {
${entries}
} as const;

export type IconName = keyof typeof ICONS;

export const ICON_NAMES = Object.keys(ICONS) as IconName[];

export function isIconName(key: string): key is IconName {
  return key in ICONS;
}
`;
  writeFileSync(join(generatedDir, "icons.ts"), body, "utf8");
}

function generateCs(icons: Record<string, string>, generatedDir: string): void {
  const constants = Object.keys(icons)
    .sort()
    .map((id) => `    public const string ${iconIdToPascal(id)} = "${id}";`)
    .join("\n");
  const dictEntries = Object.keys(icons)
    .sort()
    .map((id) => `            ["${id}"] = @"${escapeCSharpString(icons[id]!)}",`)
    .join("\n");
  const body = `// Generated by framework/ui/asset/script.ts — do not edit.
namespace Ui.Assets;

public static class Icons
{
${constants}

    public static IReadOnlyDictionary<string, string> SvgByName { get; } = new Dictionary<string, string>
    {
${dictEntries}
    };
}
`;
  writeFileSync(join(generatedDir, "Icons.cs"), body, "utf8");
}

function generateRust(icons: Record<string, string>, generatedDir: string): void {
  const ids = Object.keys(icons).sort();
  const variants = ids.map((id) => {
    const variant = iconIdToRustVariant(id);
    return `    #[serde(rename = "${id}")]\n    ${variant},`;
  }).join("\n");
  const asStrArms = ids.map((id) => `            Self::${iconIdToRustVariant(id)} => "${id}",`).join("\n");
  const fromStrArms = ids.map((id) => `            "${id}" => Some(Self::${iconIdToRustVariant(id)}),`).join("\n");
  const allEntries = ids.map((id) => `    IconName::${iconIdToRustVariant(id)},`).join("\n");
  const svgArms = ids.map((id) => {
    const safe = id.replace(/[^a-zA-Z0-9]/g, "_");
    return `        IconName::${iconIdToRustVariant(id)} => Some(include_str!("icon_svgs/${safe}.svg")),`;
  }).join("\n");
  for (const id of ids) {
    const safe = id.replace(/[^a-zA-Z0-9]/g, "_");
    const svgDir = join(generatedDir, "icon_svgs");
    mkdirSync(svgDir, { recursive: true });
    writeFileSync(join(svgDir, `${safe}.svg`), icons[id]!, "utf8");
  }
  const body = `// Generated by framework/ui/asset/script.ts — do not edit.

#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, serde::Serialize, serde::Deserialize)]
#[cfg_attr(feature = "typegen", derive(ts_rs::TS))]
pub enum IconName {
${variants}
}

impl IconName {
    pub const ALL: &'static [Self] = &[
${allEntries}
    ];

    pub fn as_str(self) -> &'static str {
        match self {
${asStrArms}
        }
    }

    pub fn from_str(s: &str) -> Option<Self> {
        match s.trim() {
${fromStrArms}
            _ => None,
        }
    }

    pub fn svg(self) -> Option<&'static str> {
        match self {
${svgArms}
        }
    }
}

impl std::fmt::Display for IconName {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(self.as_str())
    }
}

impl From<&str> for IconName {
    fn from(value: &str) -> Self {
        Self::from_str(value).expect("invalid catalog icon name")
    }
}

/// Compile-time catalog icon id from a string literal.
#[macro_export]
macro_rules! icon_name {
${ids.map((id) => `    (${JSON.stringify(id)}) => { $crate::IconName::${iconIdToRustVariant(id)} };`).join("\n")}
    ($other:literal) => {
        ::core::compile_error!(::core::concat!("unknown catalog icon name: ", $other))
    };
}
`;
  writeFileSync(join(generatedDir, "icon_name.rs"), body, "utf8");
}

function generatePy(icons: Record<string, string>, generatedDir: string): void {
  const literals = Object.keys(icons)
    .sort()
    .map((id) => `    "${id}": """${escapePythonString(icons[id]!)}""",`)
    .join("\n");
  const names = Object.keys(icons)
    .sort()
    .map((id) => `    "${id}",`)
    .join("\n");
  const body = `# Generated by framework/ui/asset/script.ts — do not edit.
from __future__ import annotations

from typing import Final, Literal

IconName = Literal[
${names}
]

ICONS: Final[dict[str, str]] = {
${literals}
}
`;
  writeFileSync(join(generatedDir, "icons.py"), body, "utf8");
}

function writeCatalogReadme(assetsDir: string, ids: readonly string[]): void {
  const sorted = [...ids].sort();
  const list = sorted.map((id) => `- \`${id}\``).join("\n");
  const body = `# UI assets

Shared fonts, cursors, lists, and UI chrome icons served at \`/asset/*\`.

## Icons

Chrome icons are committed SVGs under \`icon/\`. Many were originally derived from [Lucide](https://lucide.dev) (**ISC License**); source: https://github.com/lucide-icons/lucide

Add or edit SVGs under \`icon/\`, then run **build ui assets** (\`bun ./script.ts generate all\`).

### Catalog icon ids

${list}
`;
  writeFileSync(join(assetsDir, "README.md"), body, "utf8");
}

type GemojiEntry = {
  emoji?: string;
  aliases?: string[];
};

/** @emoji 🔖 Builds universal shortcode tables (GitHub-style emoji aliases + UI catalog ids). */
async function generateShortcodes(icons: Record<string, string>): Promise<void> {
  const generatedDir = join(import.meta.dir, "icon", "generated");
  mkdirSync(generatedDir, { recursive: true });
  const emoji: Record<string, string> = {};
  const catalog = Object.keys(icons).sort();

  try {
    const res = await fetch("https://raw.githubusercontent.com/github/gemoji/master/db/emoji.json");
    if (!res.ok) {
      throw new Error(`gemoji fetch failed: ${res.status}`);
    }
    const entries = (await res.json()) as GemojiEntry[];
    for (const entry of entries) {
      const glyph = entry.emoji?.trim();
      if (!glyph) continue;
      for (const alias of entry.aliases ?? []) {
        const key = alias.trim().toLowerCase();
        if (key !== "" && !(key in emoji)) {
          emoji[key] = glyph;
        }
      }
    }
  } catch (err) {
    console.warn("[framework/ui/asset] gemoji fetch failed; keeping existing emoji shortcodes if present", err);
    const existingPath = join(generatedDir, "shortcodes.json");
    if (existsSync(existingPath)) {
      const existing = JSON.parse(readFileSync(existingPath, "utf8")) as { emoji?: Record<string, string> };
      Object.assign(emoji, existing.emoji ?? {});
    }
  }

  for (const id of catalog) {
    if (!(id in emoji)) {
      continue;
    }
    delete emoji[id];
  }

  const payload = { emoji, catalog };
  writeFileSync(join(generatedDir, "shortcodes.json"), `${JSON.stringify(payload, null, 2)}\n`, "utf8");

  const emojiEntries = Object.keys(emoji)
    .sort()
    .map((key) => `  ${JSON.stringify(key)}: ${JSON.stringify(emoji[key])},`)
    .join("\n");
  const catalogEntries = catalog.map((id) => `  ${JSON.stringify(id)},`).join("\n");
  const tsBody = `// Generated by framework/ui/asset/script.ts — do not edit.
export const SHORTCODE_EMOJI = {
${emojiEntries}
} as const;

export type ShortcodeEmojiName = keyof typeof SHORTCODE_EMOJI;

export const SHORTCODE_CATALOG = [
${catalogEntries}
] as const;

export type ShortcodeCatalogName = (typeof SHORTCODE_CATALOG)[number];

/** @emoji 🔍 Resolves a shortcode body (without colons) to emoji glyph when known. */
export function shortcodeEmoji(code: string): string | undefined {
  const key = code.trim().toLowerCase();
  return (SHORTCODE_EMOJI as Record<string, string>)[key];
}

/** @emoji 🔍 True when the shortcode body names a vendored UI catalog icon. */
export function shortcodeCatalogKey(code: string): ShortcodeCatalogName | undefined {
  const key = code.trim();
  return (SHORTCODE_CATALOG as readonly string[]).includes(key) ? (key as ShortcodeCatalogName) : undefined;
}
`;
  writeFileSync(join(generatedDir, "shortcodes.ts"), tsBody, "utf8");
  console.log(`[framework/ui/asset] generated ${Object.keys(emoji).length} emoji + ${catalog.length} catalog shortcodes`);
}

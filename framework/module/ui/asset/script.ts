//#region 🚀Commands
function runGenerate(target: string): void {
  const assetsDir = import.meta.dir;
  const iconsDir = join(assetsDir, "icon");
  const generatedDir = join(iconsDir, "generated");
  mkdirSync(generatedDir, { recursive: true });
  const icons = readCatalogSvgs(iconsDir);
  writeCatalogReadme(assetsDir, Object.keys(icons));
  if (target === "js" || target === "all") generateJs(icons, generatedDir);
  if (target === "net" || target === "all") generateCs(icons, generatedDir);
  if (target === "py" || target === "all") generatePy(icons, generatedDir);
  if (target === "rust" || target === "all") generateRust(icons, generatedDir);
  console.log(`[framework/ui/asset] generated ${Object.keys(icons).length} icons → ${target}`);
}

async function runGenerateAll(): Promise<void> {
  const assetsDir = import.meta.dir;
  const iconsDir = join(assetsDir, "icon");
  const generatedDir = join(iconsDir, "generated");
  mkdirSync(generatedDir, { recursive: true });
  const icons = readCatalogSvgs(iconsDir);
  writeCatalogReadme(assetsDir, Object.keys(icons));
  generateJs(icons, generatedDir);
  generateCs(icons, generatedDir);
  generatePy(icons, generatedDir);
  generateRust(icons, generatedDir);
  await generateShortcodes(icons);
  console.log(`[framework/ui/asset] generated ${Object.keys(icons).length} icons + shortcodes → all`);
}

class GenerateScript extends BundleScript {
  async run(segments: string[]): Promise<void> {
    const target = (segments[0] ?? "all").toLowerCase();
    if (!["js", "net", "py", "rust", "all"].includes(target)) {
      throw new Error(`Unknown generate target: ${target}`);
    }
    if (target === "all") {
      await runGenerateAll();
      return;
    }
    runGenerate(target);
  }
}

const router = new ScriptRouter(import.meta.dir).register("generate", GenerateScript);

await runBundleScriptMain(router, import.meta.url, { defaultCommand: "generate" });

if (import.meta.vitest) {
  const { describe, expect, it } = import.meta.vitest;
  describe("normalizeCatalogSvg", () => {
    it("strips root svg width/height and keeps currentColor stroke", () => {
      const raw = `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" stroke="#000"><path d="M0 0"/></svg>`;
      const out = normalizeCatalogSvg(raw);
      expect(out).not.toMatch(/<svg[^>]*width="/);
      expect(out).toContain('stroke="currentColor"');
    });

    it("preserves width/height on child shapes such as layout-grid rects", () => {
      const raw = `<svg width="24" height="24"><rect width="7" height="7" x="3" y="3" rx="1" /></svg>`;
      const out = normalizeCatalogSvg(raw);
      expect(out).not.toMatch(/<svg[^>]*width="/);
      expect(out).toContain('width="7"');
      expect(out).toContain('height="7"');
    });
  });
  describe("iconIdToPascal", () => {
    it("maps kebab-case to PascalCase", () => {
      expect(iconIdToPascal("layout-grid")).toBe("LayoutGrid");
    });
  });
  describe("iconIdToRustVariant", () => {
    it("maps metabolism stems to Rust variants", () => {
      expect(iconIdToRustVariant("capsule_J")).toBe("CapsuleJ");
    });
  });
  describe("resolveCatalogIconSvgFromTheme", () => {
    it("prefers theme variants over catalog defaults", async () => {
      const { resolveCatalogIconSvgFromTheme } = await import("./js/icon_resolver.ts");
      const svg = resolveCatalogIconSvgFromTheme("search", { variants: { search: "<svg data-variant></svg>" } });
      expect(svg).toContain("data-variant");
    });
  });
}

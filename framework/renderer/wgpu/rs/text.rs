//! 🖋️ Glyph atlas — fontdue when bytes are available, built-in bitmap fallback.

use std::collections::HashMap;

pub struct GlyphEntry {
    pub atlas_x: u32,
    pub atlas_y: u32,
    pub width: u32,
    pub height: u32,
    pub advance: f32,
    pub bearing_x: f32,
    pub bearing_y: f32,
}

enum FontSource {
    Fontdue(fontdue::Font),
    Bitmap,
}

pub struct FontAtlas {
    pub width: u32,
    pub height: u32,
    pub pixels: Vec<u8>,
    source: FontSource,
    glyphs: HashMap<char, GlyphEntry>,
    cursor_x: u32,
    cursor_y: u32,
    row_height: u32,
}


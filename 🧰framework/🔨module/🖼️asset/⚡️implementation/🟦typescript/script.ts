import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, join } from "node:path";
import { BundleScript, ScriptRouter, runBundleScriptMain } from "../../../../../🧰framework/🛍️product/🦑repo/🔨module/📚lib/⚡️implementation/🟦typescript/📦index.ts";

/** @emoji 🦀 PascalCase Rust enum variant from kebab/snake icon id. */
function iconIdToRustVariant(id: string): string {
  return id
    .split(/[-_]/)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");
}
// #endregion 🔌Adapters

//#region 📦Catalog
function readMetabolismSvgs(iconsDir: string): Record<string, string> {
  if (!existsSync(iconsDir)) {
    throw new Error(`Missing metabolism icon directory: ${iconsDir}`);
  }
  const svgFiles = readdirSync(iconsDir).filter((name) => name.endsWith(".svg"));
  const out: Record<string, string> = {};
  for (const file of svgFiles) {
    const id = basename(file, ".svg");
    out[id] = readFileSync(join(iconsDir, file), "utf8").trim();
  }
  return out;
}
//#endregion 📦Catalog

//#region 🧬Codegen
function escapeTsString(value: string): string {
  return value.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$/g, "\\$");
}

function generateJsMetabolism(icons: Record<string, string>, generatedDir: string): void {
  const entries = Object.keys(icons)
    .sort()
    .map((id) => `  "${id}": \`${escapeTsString(icons[id]!)}\`,`)
    .join("\n");
  const body = `// Generated by asset/script.ts — do not edit.
export const METABOLISM_ICONS = {
${entries}
} as const;

export type MetabolismIconName = keyof typeof METABOLISM_ICONS;

export const METABOLISM_ICON_NAMES = Object.keys(METABOLISM_ICONS) as MetabolismIconName[];

export function isMetabolismIconName(key: string): key is MetabolismIconName {
  return key in METABOLISM_ICONS;
}
`;
  writeFileSync(join(generatedDir, "🟦metabolism_🟦icons.ts"), body, "utf8");
}

function generateRustMetabolism(icons: Record<string, string>, generatedDir: string): void {
  const ids = Object.keys(icons).sort();
  const variants = ids.map((id) => `    #[serde(rename = "${id}")]\n    ${iconIdToRustVariant(id)},`).join("\n");
  const asStrArms = ids.map((id) => `            Self::${iconIdToRustVariant(id)} => "${id}",`).join("\n");
  const fromStrArms = ids.map((id) => `            "${id}" => Some(Self::${iconIdToRustVariant(id)}),`).join("\n");
  const allEntries = ids.map((id) => `    MetabolismIconName::${iconIdToRustVariant(id)},`).join("\n");
  const svgArms = ids.map((id) => {
    const safe = id.replace(/[^a-zA-Z0-9]/g, "_");
    return `        MetabolismIconName::${iconIdToRustVariant(id)} => Some(include_str!("metabolism_svgs/${safe}.svg")),`;
  }).join("\n");
  for (const id of ids) {
    const safe = id.replace(/[^a-zA-Z0-9]/g, "_");
    const svgDir = join(generatedDir, "metabolism_svgs");
    mkdirSync(svgDir, { recursive: true });
    writeFileSync(join(svgDir, `${safe}.svg`), icons[id]!, "utf8");
  }
  const body = `// Generated by asset/script.ts — do not edit.

#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, serde::Serialize, serde::Deserialize)]
pub enum MetabolismIconName {
${variants}
}

impl MetabolismIconName {
    pub const ALL: &'static [Self] = &[
${allEntries}
    ];

    pub fn as_str(self) -> &'static str {
        match self {
${asStrArms}
        }
    }

    pub fn from_str(s: &str) -> Option<Self> {
        match s.trim() {
${fromStrArms}
            _ => None,
        }
    }

    pub fn svg(self) -> Option<&'static str> {
        match self {
${svgArms}
        }
    }
}

impl std::fmt::Display for MetabolismIconName {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(self.as_str())
    }
}

impl From<&str> for MetabolismIconName {
    fn from(value: &str) -> Self {
        Self::from_str(value).expect("invalid metabolism icon name")
    }
}
`;
  writeFileSync(join(generatedDir, "🦀metabolism_🦀icon_name.rs"), body, "utf8");
}
//#endregion 🧬Codegen

//#region 🚀Commands
function runGenerate(): void {
  const assetsDir = import.meta.dir;
  const iconsDir = join(assetsDir, "metabolism/icon");
  const generatedDir = join(assetsDir, "metabolism/icon/generated");
  mkdirSync(generatedDir, { recursive: true });
  const icons = readMetabolismSvgs(iconsDir);
  generateJsMetabolism(icons, generatedDir);
  generateRustMetabolism(icons, generatedDir);
  console.log(`[asset] generated ${Object.keys(icons).length} metabolism icons`);
}

class GenerateScript extends BundleScript {
  run(): void {
    runGenerate();
  }
}

class BuildScript extends BundleScript {
  run(): void {
    runGenerate();
    console.log("@semio-tech/semio-asset build complete.");
  }
}

const router = new ScriptRouter(import.meta.dir).register("generate", GenerateScript).register("build", BuildScript);

await runBundleScriptMain(router, import.meta.url, { defaultCommand: "build" });

if (import.meta.vitest) {
  const { describe, expect, it } = import.meta.vitest;
  describe("metabolism icon codegen", () => {
    it("maps metabolism stems to Rust variants", () => {
      expect(iconIdToRustVariant("capsule_J")).toBe("CapsuleJ");
      expect(iconIdToRustVariant("cylindric-tambour_first-storey")).toBe("CylindricTambourFirstStorey");
    });
  });
}

#!/usr/bin/env bun
/** 🦀 `@semio-tech/framework-core` task router: `bun ./📜script.ts test|generate|check|lint`. */
import { BundleScript, ScriptRouter, buildBudgetMs, runBundleScriptMain, runCargoLint, runCargoTestBudgeted, runCmdStatus, runVitest, resolveTestLevel } from "../../../🧰framework/🛍️product/🦑repo/🔨module/📚lib/⚡️implementation/🟦typescript/📦index.ts";
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

class TestScript extends BundleScript {
  async run(segments: string[]): Promise<void> {
    const { rest } = resolveTestLevel(segments);
    await runCargoTestBudgeted(["semio-framework-core"], this.repoRoot, rest);
    await runVitest(this.root, rest, "js/🧪vitest.config.ts");
  }
}

/** 🧹Zero-warning clippy gate: `cargo clippy -p semio-framework-core --all-targets -- -D warnings`. */
class LintScript extends BundleScript {
  run(segments: string[]): void {
    runCargoLint(["semio-framework-core"], join(this.root, "rs"), segments);
  }
}

//#region 🔖Typegen
/** 🧬 Name of the `#[cfg(test, feature = "typegen")]` test in `rs/lib.rs` that calls `TS::export()` for every mirrored type. */
const TYPEGEN_TEST_FILTER = "exports_typescript_bindings";

/** 📁 ts-rs' default per-crate export directory — a scratch dir, never committed. */
function bindingsDir(root: string): string {
  return join(root, "rs", "bindings");
}

function generatedManifestPath(root: string): string {
  return join(root, "js", "generated", "manifest.ts");
}

/** 🧬 Runs the ts-rs export test with the `typegen` feature enabled, populating `bindings/*.ts`. */
function runTypegenExportTest(root: string): void {
  const status = runCmdStatus("cargo", ["test", "--features", "typegen", TYPEGEN_TEST_FILTER], {
    cwd: join(root, "rs"),
    env: process.env,
    budgetMs: buildBudgetMs(),
  });
  if (status !== 0) {
    console.error("framework-core typegen: `cargo test --features typegen` failed — see output above.");
    process.exit(status);
  }
}

/** ✂️ Strips ts-rs' per-file header comment and local `import type { ... } from "./X"` boilerplate, leaving the bare `export type`/`export interface` declaration. */
function stripTsRsBoilerplate(source: string): string {
  return source
    .split("\n")
    .filter((line) => line.trim().length > 0 && !line.startsWith("//") && !line.startsWith("import "))
    .join("\n")
    .trim();
}

/** 🧬 Reads every ts-rs per-type file out of `dir`, strips its boilerplate, and flattens them into one de-duplicated, alphabetically ordered manifest body. */
function consolidateBindings(dir: string): string {
  const files = readdirSync(dir)
    .filter((name) => name.endsWith(".ts"))
    .sort();
  const seen = new Set<string>();
  const blocks: string[] = [];
  for (const name of files) {
    const body = stripTsRsBoilerplate(readFileSync(join(dir, name), "utf8"));
    const typeName = body.match(/^export (?:type|interface) (\w+)/)?.[1] ?? name.replace(/\.ts$/, "");
    if (seen.has(typeName)) continue;
    seen.add(typeName);
    blocks.push(body);
  }
  return `/** @generated by \`bun nx run @semio-tech/framework-core:generate\` from framework/core/rs/lib.rs via ts-rs. Do not edit. */\n\n${blocks.join("\n\n")}\n`;
}

/** 🧬 Runs the ts-rs export test into a scratch `rs/bindings/` dir, consolidates it in memory, then removes the scratch dir — the caller decides whether to write the result. */
function buildManifest(root: string): string {
  const dir = bindingsDir(root);
  rmSync(dir, { recursive: true, force: true });
  runTypegenExportTest(root);
  if (!existsSync(dir)) {
    console.error(`framework-core typegen: expected ts-rs to write ${dir}, found nothing.`);
    process.exit(1);
  }
  const manifest = consolidateBindings(dir);
  rmSync(dir, { recursive: true, force: true });
  return manifest;
}

class GenerateScript extends BundleScript {
  run(_segments: string[]): void {
    const manifest = buildManifest(this.root);
    const outPath = generatedManifestPath(this.root);
    mkdirSync(join(this.root, "js", "generated"), { recursive: true });
    writeFileSync(outPath, manifest);
    console.log(`framework-core typescript mirror refreshed -> ${outPath}`);
  }
}

/** 🔎 Rebuilds the manifest in memory and byte-compares it against `js/generated/manifest.ts` — never writes that file (a lint/verify step must never let the auto-commit daemon land regenerated files). */
class CheckScript extends BundleScript {
  run(_segments: string[]): void {
    const manifest = buildManifest(this.root);
    const outPath = generatedManifestPath(this.root);
    if (!existsSync(outPath) || readFileSync(outPath, "utf8") !== manifest) {
      console.error(`framework-core typescript mirror is stale: ${outPath}`);
      console.error("run `bun nx run @semio-tech/framework-core:generate` to refresh.");
      process.exit(1);
    }
    console.log("framework-core typescript mirror is fresh.");
  }
}
//#endregion 🔖Typegen

const router = new ScriptRouter(import.meta.dir).register("test", TestScript).register("generate", GenerateScript).register("check", CheckScript).register("lint", LintScript);

await runBundleScriptMain(router, import.meta.url, { defaultCommand: "test" });

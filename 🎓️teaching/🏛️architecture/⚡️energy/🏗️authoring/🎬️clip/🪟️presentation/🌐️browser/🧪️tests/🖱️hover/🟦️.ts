/** 🖱️ Avoid redundant compositor work for descendant-to-descendant pointer motion. */
import assert from "node:assert/strict";
import {readFile} from "node:fs/promises";
import path from "node:path";
import {pathToFileURL} from "node:url";
import {JSDOM} from "jsdom";
const c=JSON.parse(await readFile(new URL("./🔣️.json",import.meta.url),"utf8"));
const api=await import(pathToFileURL(path.join(process.cwd(),"🧰️framework/🔨️modules/🖱️ui/🧱️elements/🗂️WindowChrome/shared-border.ts")).href);
const dom=new JSDOM("<body><div id=owner><span id=a></span><span id=b></span></div><div id=outside></div></body>",{pretendToBeVisual:true});
globalThis.Element=dom.window.Element;
globalThis.MutationObserver=dom.window.MutationObserver;
const root=dom.window.document.body, owner=dom.window.document.getElementById("owner");
const compositor=new api.BorderCompositor(root);
compositor.windows.set("window",{element:owner});
let calls=0;compositor.schedule=()=>calls++;
const a=dom.window.document.getElementById("a"),b=dom.window.document.getElementById("b"),outside=dom.window.document.getElementById("outside");
compositor.pointer({type:"pointerover",target:a});
compositor.pointer({type:"pointerout",target:a,relatedTarget:b});
compositor.pointer({type:"pointerover",target:b});
assert.equal(calls,c.same_owner_schedules);
compositor.pointer({type:"pointerout",target:b,relatedTarget:outside});
assert.equal(calls,c.leave_owner_schedules);
compositor.windows.set("nested",{element:b});
compositor.pointer({type:"pointerover",target:a});
compositor.pointer({type:"pointerout",target:a,relatedTarget:b});
assert.equal(calls,c.nested_owner_schedules);
b.remove();
compositor.pointer({type:"pointerout",target:b,relatedTarget:outside});
assert.equal(calls,c.detached_owner_schedules);
compositor.dispose();
console.log("PASS effective-hover-owners");

const React=await import("react");
const {renderToStaticMarkup}=await import("react-dom/server");
const {OverviewCard}=await import(pathToFileURL(path.join(process.cwd(),"🧰️framework/🔨️modules/🖱️ui/🧱️elements/🃏️OverviewCard/🟦️.tsx")).href);
const card=new JSDOM(renderToStaticMarkup(React.createElement(OverviewCard,{as:"button",label:"Example",title:"Example"}))).window.document.querySelector("button");
assert.equal(card.tagName,c.card_hit_target);
assert.equal(card.querySelector("[data-overview-card-paint]")?.tagName,c.card_lift_target);
assert(!card.className.includes("hover:-translate-y-0.5"));
assert(card.querySelector("[data-overview-card-paint]").className.includes("group-hover:-translate-y-0.5"));

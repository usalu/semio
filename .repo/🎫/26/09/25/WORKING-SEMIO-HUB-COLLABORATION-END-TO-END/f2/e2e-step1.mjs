import { chromium } from "/home/user/semio/node_modules/playwright/index.mjs";
const out = process.argv[2];
const base = process.env.SKETCHPAD_URL ?? "http://127.0.0.1:5174";
const hubUrl = process.env.HUB_URL ?? "http://127.0.0.1:8090";
const browser = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium-1194/chrome-linux/chrome", args: ["--use-angle=swiftshader", "--enable-unsafe-swiftshader"] });
const ctx = await browser.newContext({ viewport: { width: 1500, height: 900 } });
const page = await ctx.newPage();
page.on("pageerror", (e) => console.log("[pageerror]", String(e).slice(0, 400)));
page.on("console", (m) => { if (m.type() === "error" || m.type() === "warning") console.log("[console]", m.type(), m.text().slice(0, 1500)); });
const t0 = Date.now();
const log = (...a) => console.log(`[${((Date.now() - t0) / 1000).toFixed(1)}s]`, ...a);
await page.goto(`${base}/?hub=${encodeURIComponent(hubUrl)}`, { waitUntil: "domcontentloaded" });
await page.locator('[id="ui.panelToggle.chat"]').click({ timeout: 60_000 });
const unique = Date.now().toString(36);
await page.getByTestId("sketchpad-hub-name").fill("Ada");
await page.getByTestId("sketchpad-hub-email").fill(`ada-${unique}@semio.test`);
await page.getByTestId("sketchpad-hub-password").fill("secret-ada");
await page.locator('[id="sketchpad.hub.register"]').click();
await page.getByTestId("sketchpad-hub-person").waitFor({ timeout: 30_000 });
log("signed in", await page.getByTestId("sketchpad-hub-person").textContent());
await page.locator('[id="ui.search.toggle"]').click();
await page.getByRole("dialog").getByPlaceholder("Search...").fill("metabolism");
await page.getByRole("dialog").getByText("Open metabolism fixture").click();
await page.waitForURL(/\/kits\/[0-9a-f-]{36}/i, { timeout: 180_000 });
log("metabolism open", page.url());
await page.locator('[id="sketchpad.hub.shareActive"]').click({ timeout: 60_000 });
await page.waitForFunction((prev) => location.pathname !== prev && /\/kits\//.test(location.pathname), new URL(page.url()).pathname, { timeout: 180_000 });
log("shared kit open", page.url());
await page.getByTestId("sketchpad-hub-session-status").waitFor({ timeout: 60_000 });
log("status", await page.getByTestId("sketchpad-hub-session-status").textContent(), "footer", await page.getByTestId("sketchpad-hub-footer").textContent());
await page.screenshot({ path: `${out}/e2e-a-shared.png` });
await browser.close();

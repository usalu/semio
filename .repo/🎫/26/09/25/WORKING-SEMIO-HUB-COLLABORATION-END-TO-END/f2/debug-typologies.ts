import { readFile } from "node:fs/promises";
import { SemioKitClient, semioHubKitProjection } from "/home/user/semio/semio/client/lib/react/index.ts";
const bytes = new Uint8Array(await readFile("/home/user/semio/semio/fixtures/metabolism.zip"));
const t0 = Date.now();
const client = await SemioKitClient.open({ kind: "bytes", data: bytes });
console.log("[DEBUG] opened in", Date.now() - t0, "ms");
const t1 = Date.now();
const projection = await semioHubKitProjection(client) as any;
console.log("[DEBUG] projection in", Date.now() - t1, "ms", "size", JSON.stringify(projection).length);
const topo = projection.typologies?.items ?? [];
console.log("[DEBUG] typologies", topo.map((t: any) => `${t.name}(${t.types?.items?.length ?? 0}t/${t.designs?.items?.length ?? 0}d)`).join(", "));
const hash = String((await client.store.readKitInner("hash"))?.["hash"]);
const other = await SemioKitClient.open({ kind: "empty", name: "" });
const t2 = Date.now();
await other.store.installProjection(JSON.stringify(projection));
console.log("[DEBUG] install in", Date.now() - t2, "ms");
const otherProjection = JSON.parse(String((await other.store.readKitInner("projection"))?.["projection"]));
console.log("[DEBUG] reinstalled typologies", (otherProjection.typologies?.items ?? []).map((t: any) => t.name).join(", "));
console.log("[DEBUG] hashes local", hash.slice(0, 12), "copy", String((await other.store.readKitInner("hash"))?.["hash"]).slice(0, 12), "(copy has a fresh kit id)");
await client.dispose(); await other.dispose();

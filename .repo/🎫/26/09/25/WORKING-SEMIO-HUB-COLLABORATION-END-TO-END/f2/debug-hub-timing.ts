import { readFile } from "node:fs/promises";
import { HubClient, SemioKitClient, openSemioHubKit, semioHubKitProjection } from "/home/user/semio/semio/client/lib/react/index.ts";
const hubUrl = process.env.HUB_URL ?? "http://127.0.0.1:8090";
const client = await SemioKitClient.open({ kind: "bytes", data: new Uint8Array(await readFile("/home/user/semio/semio/fixtures/metabolism.zip")) });
const projection = await semioHubKitProjection(client);
const hub = new HubClient({ url: hubUrl });
await hub.register("Timer", `timer-${Date.now()}@semio.test`, "password-timer");
let t = Date.now();
const session = await hub.createSession("timing", projection);
console.log("[DEBUG] POST /sessions", Date.now() - t, "ms");
t = Date.now();
const kit = await hub.sessionKit(session.id);
console.log("[DEBUG] GET /kit", Date.now() - t, "ms", "hash", kit.hash.slice(0, 12));
t = Date.now();
const opened = await openSemioHubKit(hub, session.id, "timer");
console.log("[DEBUG] openSemioHubKit", Date.now() - t, "ms", "local hash", String((await opened.kit.store.readKitInner("hash"))?.["hash"]).slice(0, 12));
t = Date.now();
console.log("[DEBUG] createDesign", (await opened.kit.execute((k) => k.createDesign("timed"))).ok, Date.now() - t, "ms");
await opened.replica.whenIdle();
console.log("[DEBUG] op round trip", Date.now() - t, "ms", JSON.stringify(opened.replica.status));
opened.replica.dispose(); await opened.kit.dispose(); await client.dispose();
await hub.deleteSession(session.id);

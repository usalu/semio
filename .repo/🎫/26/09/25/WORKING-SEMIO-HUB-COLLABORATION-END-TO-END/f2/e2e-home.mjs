import { chromium } from "/home/user/semio/node_modules/playwright/index.mjs";
const out = process.argv[2];
const base = "http://127.0.0.1:5174", hubUrl = "http://127.0.0.1:8090";
const browser = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium-1194/chrome-linux/chrome", args: ["--enable-unsafe-webgpu", "--enable-features=Vulkan", "--use-vulkan=swiftshader", "--use-webgpu-adapter=swiftshader"] });
const page = await browser.newPage({ viewport: { width: 1500, height: 900 } });
page.on("pageerror", (e) => console.log("[pageerror]", String(e).slice(0, 300)));
await page.goto(`${base}/?hub=${encodeURIComponent(hubUrl)}`, { waitUntil: "domcontentloaded" });
await page.locator('[id="ui.panelToggle.chat"]').click({ timeout: 60_000 });
await page.getByTestId("sketchpad-hub-name").fill("Cleo");
await page.getByTestId("sketchpad-hub-email").fill(`cleo-${Date.now()}@semio.test`);
await page.getByTestId("sketchpad-hub-password").fill("secret-cleo");
await page.locator('[id="sketchpad.hub.register"]').click();
await page.getByTestId("sketchpad-hub-shared-kits").waitFor({ timeout: 30_000 });
await page.getByTestId("sketchpad-hub-new-name").fill("Cleo's pavilion");
await page.locator('[id="sketchpad.hub.newSession"]').click();
await page.waitForURL(/\/kits\//, { timeout: 60_000 });
console.log("[DEBUG] empty shared kit open", page.url(), await page.getByTestId("sketchpad-hub-session-status").textContent({ timeout: 30_000 }));
await page.evaluate(async () => { const m = await import("/index.ts"); m.navigateSketchpadTo("/"); });
await page.locator('[data-testid="sketchpad-hub-session"]').first().waitFor({ timeout: 30_000 });
console.log("[DEBUG] shared kits", await page.locator('[data-testid="sketchpad-hub-session"]').evaluateAll((rows) => rows.map((r) => r.getAttribute("data-session-name"))));
await page.screenshot({ path: `${out}/10-home-shared-kits.png` });
await browser.close();

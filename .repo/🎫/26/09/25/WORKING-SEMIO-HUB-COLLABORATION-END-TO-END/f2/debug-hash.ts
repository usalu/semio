console.log("[DEBUG] install ok", install.ok, "hub", await hash(hub.st), "a", await hash(a.st));
const pa = await proj(a.st), ph = await proj(hub.st);
console.log("[DEBUG] hub proj", JSON.stringify(ph).slice(0, 400));
console.log("[DEBUG] a   proj", JSON.stringify(pa).slice(0, 400));

type Closure={name:string;version:string;source?:string};
const tomlClosure=(text:string,roots:readonly string[]):string[]=>{
 const lock=(Bun as unknown as {TOML:{parse:(value:string)=>{package:{name:string;version:string;source?:string;dependencies?:string[]}[]}}}).TOML.parse(text);
 const key=(row:Closure)=>row.name+" "+row.version+(row.source?" "+row.source:"");
 const seen=new Map<string,typeof lock.package[number]>(),queue=lock.package.filter(row=>roots.includes(row.name));
 for(const row of queue)seen.set(key(row),row);
 while(queue.length){
  const row=queue.pop()!;
  for(const dependency of row.dependencies??[]){
   const[name,version,source]=[...dependency.matchAll(/^(\S+)(?: (\S+)(?: \((.+)\))?)?$/gu)][0]!.slice(1);
   for(const next of lock.package.filter(candidate=>candidate.name===name&&(version===undefined||candidate.version===version)&&(source===undefined||candidate.source===source)))if(!seen.has(key(next))){seen.set(key(next),next);queue.push(next);}
  }
 }
 return[...seen.keys()].sort();
};


#!/usr/bin/env bun
/** 🦀️ `@semio-tech/framework-actor` task router: `bun ./📜️script.ts <test|typegen|wasm>`. */
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { BundleScript, ScriptRouter, buildBudgetMs, runBundleScriptMain, runCargoTestBudgeted, runCmdStatus, runWasmPackWebBuild, resolveTestLevel } from "../../../../🛍️products/🦑️repo/🔨️modules/📚️library/📦️packages/🟦️typescript/📦️index.ts";

class TestScript extends BundleScript {
  async run(segments: string[]): Promise<void> {
    const { rest } = resolveTestLevel(segments);
    await runCargoTestBudgeted(["semio-framework-actor"], this.repoRoot, rest);
  }
}

//#region 🔖️Typegen
/** 🧬️ Name of the `#[cfg(test, feature = "typegen")]` test in `🦀️component.rs` that calls `TS::export()` for every mirrored type. */
const TYPEGEN_TEST_FILTER = "exports_typescript_bindings";

/** 📁️ ts-rs' default per-crate export directory — a scratch dir, never committed. */
function bindingsDir(root: string): string {
  return join(root, "bindings");
}

/** 🎯️ The mirror lives at `<owner>/🤖️generated/🟦️actor.ts`, a sibling of `📦️packages`. */
function generatedBindingsPath(root: string): string {
  return join(root, "..", "..", "🤖️generated", "🟦️actor.ts");
}

function runTypegenExportTest(root: string): void {
  const status = runCmdStatus("cargo", ["test", "--features", "typegen", TYPEGEN_TEST_FILTER], { cwd: root, env: process.env, budgetMs: buildBudgetMs() });
  if (status !== 0) {
    console.error("framework-actor typegen: `cargo test --features typegen` failed — see output above.");
    process.exit(status);
  }
}

/** ✂️ Strips ts-rs' per-file header comment and local `import type { ... } from "./X"` boilerplate, leaving the bare `export type`/`export interface` declaration. */
function stripTsRsBoilerplate(source: string): string {
  return source
    .split("\n")
    .filter((line) => line.trim().length > 0 && !line.startsWith("//") && !line.startsWith("import "))
    .join("\n")
    .trim();
}

/** 🧬️ Reads every ts-rs per-type file out of `dir`, strips its boilerplate, and flattens them into one de-duplicated, alphabetically ordered mirror body. */
function consolidateBindings(dir: string): string {
  const files = readdirSync(dir)
    .filter((name) => name.endsWith(".ts"))
    .sort();
  const seen = new Set<string>();
  const blocks: string[] = [];
  for (const name of files) {
    const body = stripTsRsBoilerplate(readFileSync(join(dir, name), "utf8"));
    const typeName = body.match(/^export (?:type|interface) (\w+)/)?.[1] ?? name.replace(/\.ts$/, "");
    if (seen.has(typeName)) continue;
    seen.add(typeName);
    blocks.push(body);
  }
  return `/** @generated by \`bun nx run @semio-tech/framework-actor-rs:typegen\` from 🎭️actor/🦀️component.rs via ts-rs. Do not edit. */\n\n${blocks.join("\n\n")}\n`;
}

function buildMirror(root: string): string {
  const dir = bindingsDir(root);
  rmSync(dir, { recursive: true, force: true });
  runTypegenExportTest(root);
  if (!existsSync(dir)) {
    console.error(`framework-actor typegen: expected ts-rs to write ${dir}, found nothing.`);
    process.exit(1);
  }
  const mirror = consolidateBindings(dir);
  rmSync(dir, { recursive: true, force: true });
  return mirror;
}

class TypegenScript extends BundleScript {
  run(): void {
    const mirror = buildMirror(this.root);
    const outPath = generatedBindingsPath(this.root);
    mkdirSync(join(this.root, "..", "..", "🤖️generated"), { recursive: true });
    writeFileSync(outPath, mirror);
    console.log(`framework-actor typescript mirror refreshed -> ${outPath}`);
  }
}
//#endregion 🔖️Typegen

class WasmScript extends BundleScript {
  run(): void {
    runWasmPackWebBuild({
      rsDir: this.root,
      skipEnvVar: "FRAMEWORK_ACTOR_RS_SKIP_WASM_BUILD",
      logPrefix: "framework/actor/rs",
      wasmBaseName: "framework_actor",
      shipProfile: "wasm-release",
      pkg: {
        name: "@semio-tech/framework-actor-rs",
        files: ["framework_actor_bg.wasm", "framework_actor.js", "framework_actor.d.ts", "framework_actor_bg.wasm.d.ts"],
        main: "framework_actor.js",
        module: "framework_actor.js",
        types: "framework_actor.d.ts",
      },
    });
  }
}

const router = new ScriptRouter(import.meta.dir).register("test", TestScript).register("typegen", TypegenScript).register("wasm", WasmScript);

await runBundleScriptMain(router, import.meta.url, { defaultCommand: "test" });

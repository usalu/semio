#!/usr/bin/env bun
/** 📜️ `@semio-tech/framework-schema` — the `schema-entity-catalog` generator: the single-source entity
 * kind catalog `🔣️entity-kinds.json` (contract `framework.schema#/$defs/EntityKindCatalog`) projected
 * into its TypeScript, Rust and Go consumers. Every projection carries the same provenance header and
 * the same FIRST-WINS emoji index. */
import { createHash } from "node:crypto";
import { existsSync, readFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { BundleScript, getWorkspaceRoot, ScriptRouter, runBundleScriptMain } from "../../../../../🧰️framework/🛍️products/🦑️repo/🔨️modules/📚️library/📦️packages/🟦️typescript/🟦️.ts";
import { writeGeneratedFileIfChanged } from "../../../../../🧰️framework/🛍️products/🦑️repo/🔨️modules/📚️library/⚡️caching/📦️artifacts/🗂️files/🟦️.ts";
import { entityKindIndexByEmoji, parseEntityKindCatalog, type EntityKindCatalog } from "../../🟦️.ts";

const packageRoot = import.meta.dir ?? dirname(fileURLToPath(import.meta.url));
// 🌳️ Shape V2: data (`🔣️entity-kinds.json`/`🤖️generated/`/`🤖️generated.rs`) lives at the owner
// root, a sibling of `📦️packages`, never inside it — see `🔣️taxonomy.json`'s `rootDataDirNames`.
const ownerRoot = join(packageRoot, "..", "..");

//#region 🔖️EntityCatalogSource
const GENERATOR_ID = "schema-entity-catalog";
const REFRESH_COMMAND = "bun nx run @semio-tech/framework-schema:generate";

type EntityCatalogSource = { readonly kinds: EntityKindCatalog; readonly sourceRel: string; readonly sha256: string };

/** 📥️ Reads the single source through the owned `framework.schema` parser, so a catalog violating
 * `🔣️.json#/$defs/EntityKindCatalog` fails the generator instead of reaching three projections. */
function readEntityCatalog(repoRoot: string): EntityCatalogSource {
  const path = join(ownerRoot, "🔣️entity-kinds.json");
  const bytes = readFileSync(path);
  return {
    kinds: parseEntityKindCatalog(JSON.parse(bytes.toString("utf8"))),
    sourceRel: relative(repoRoot, path).replaceAll("\\", "/").normalize("NFC"),
    sha256: createHash("sha256").update(bytes).digest("hex"),
  };
}

/** 🧾️ The two provenance lines every projection repeats verbatim, comment syntax aside. */
function provenance(source: EntityCatalogSource): readonly string[] {
  return [`🤖️ @generated by \`${GENERATOR_ID}\` from \`${source.sourceRel}\` (sha256 ${source.sha256}) — do not edit.`, `Refresh with \`${REFRESH_COMMAND}\`.`];
}
//#endregion 🔖️EntityCatalogSource

//#region 🔖️emit-typescript
function emitTypeScript(source: EntityCatalogSource): string {
  const [origin, refresh] = provenance(source);
  const rows = source.kinds.map((kind) => `\t{ id: ${JSON.stringify(kind.id)}, emoji: ${JSON.stringify(kind.emoji)}, iconId: ${JSON.stringify(kind.iconId)}, label: ${JSON.stringify(kind.label)}, filterable: ${kind.filterable} },`).join("\n");
  return `/** ${origin}
 * ${refresh} */
import type { EntityKind, EntityKindCatalog } from "../🟦️";

export type { EntityKind, EntityKindCatalog };

/** 📚️ The entity-kind catalog in declaration order — the TypeScript projection of
 * \`🔣️entity-kinds.json\`. Order is contract: the emoji index below keeps the FIRST entry. */
export const ENTITY_KINDS: EntityKindCatalog = [
${rows}
];

/** 🔍️ FIRST-WINS emoji index: when two kinds share one emoji the first declared kind wins, so 🌱️
 * resolves to \`technology-mono\` (not \`interaction-started\`) and 📝️ to \`draft\` (not \`todo\`).
 * \`new Map(ENTITY_KINDS.map((kind) => [kind.emoji, kind]))\` would be LAST-wins. */
export const ENTITY_KIND_BY_EMOJI: ReadonlyMap<string, EntityKind> = ((): ReadonlyMap<string, EntityKind> => {
\tconst index = new Map<string, EntityKind>();
\tfor (const kind of ENTITY_KINDS) if (!index.has(kind.emoji)) index.set(kind.emoji, kind);
\treturn index;
})();

/** 🔎️ Resolves one emoji prefix to its entity kind through {@link ENTITY_KIND_BY_EMOJI}. */
export function entityKindByEmoji(emoji: string): EntityKind | undefined {
\treturn ENTITY_KIND_BY_EMOJI.get(emoji);
}
`;
}
//#endregion 🔖️emit-typescript

//#region 🔖️emit-go
function emitGo(source: EntityCatalogSource): string {
  const [origin, refresh] = provenance(source);
  const rows = source.kinds.map((kind) => `\t{ID: ${JSON.stringify(kind.id)}, Emoji: ${JSON.stringify(kind.emoji)}, IconID: ${JSON.stringify(kind.iconId)}, Label: ${JSON.stringify(kind.label)}, Filterable: ${kind.filterable}},`).join("\n");
  return `// ${origin}
// ${refresh}

package client

// 🏷️EntityKind holds one entry of the entity-kind catalog (kind → emoji/icon/label/filterable).
type EntityKind struct {
\tID         string
\tEmoji      string
\tIconID     string
\tLabel      string
\tFilterable bool
}

// EntityKindCatalog is the entity-kind catalog in declaration order — the Go projection of
// 🔣️entity-kinds.json. Named distinctly from the pre-existing EntityKinds (tree-node category
// strings) elsewhere in this package.
var EntityKindCatalog = []EntityKind{
${rows}
}

// entityKindsByEmoji is the FIRST-WINS emoji index: when two kinds share one emoji the first
// declared kind wins, so 🌱️ resolves to technology-mono and 📝️ to draft.
var entityKindsByEmoji = func() map[string]EntityKind {
\tindex := make(map[string]EntityKind, len(EntityKindCatalog))
\tfor _, kind := range EntityKindCatalog {
\t\tif _, taken := index[kind.Emoji]; !taken {
\t\t\tindex[kind.Emoji] = kind
\t\t}
\t}
\treturn index
}()

// EntityKindByEmoji resolves one emoji prefix to its entity kind through the first-wins index.
func EntityKindByEmoji(emoji string) (EntityKind, bool) {
\tkind, found := entityKindsByEmoji[emoji]
\treturn kind, found
}
`;
}
//#endregion 🔖️emit-go

//#region 🔖️emit-rust
function emitRust(source: EntityCatalogSource): string {
  const [origin, refresh] = provenance(source);
  const rows = source.kinds.map((kind) => `\tEntityKind { id: ${JSON.stringify(kind.id)}, emoji: ${JSON.stringify(kind.emoji)}, icon_id: ${JSON.stringify(kind.iconId)}, label: ${JSON.stringify(kind.label)}, filterable: ${kind.filterable} },`).join("\n");
  return `// ${origin}
// ${refresh}

/// 🏷️ One entry of the entity-kind catalog — the Rust projection of \`🔣️.json#/$defs/EntityKind\`.
pub struct EntityKind {
    pub id: &'static str,
    pub emoji: &'static str,
    pub icon_id: &'static str,
    pub label: &'static str,
    pub filterable: bool,
}

/// 📚️ The entity-kind catalog in declaration order — the Rust projection of \`🔣️entity-kinds.json\`.
pub const ENTITY_KINDS: &[EntityKind] = &[
${rows}
];

/// 🔍️ Looks up an entity kind by its emoji prefix, FIRST-WINS: when two kinds share one emoji the
/// first declared kind wins, so 🌱️ resolves to \`technology-mono\` (not \`interaction-started\`) and
/// 📝️ to \`draft\` (not \`todo\`) — the same rule the TypeScript and Go projections apply.
pub fn entity_kind_by_emoji(emoji: &str) -> Option<&'static EntityKind> {
    ENTITY_KINDS.iter().find(|kind| kind.emoji == emoji)
}
`;
}
//#endregion 🔖️emit-rust

//#region 🔖️targets
type GeneratedTarget = { readonly path: string; readonly content: string };

function generatedTargets(repoRoot: string, source: EntityCatalogSource): GeneratedTarget[] {
  return [
    { path: join(ownerRoot, "🤖️generated", "🟦️entity-kinds.ts"), content: emitTypeScript(source) },
    { path: join(repoRoot, "🧰️framework/🛍️products/🦑️repo/🔨️modules/💻️client/⌨️cli/🐹️entity_kinds.g.go"), content: emitGo(source) },
    { path: join(ownerRoot, "🤖️generated.rs"), content: emitRust(source) },
  ];
}
//#endregion 🔖️targets

//#region 🔖️preview-generated
/** 🧾️ Emits the canonical read-only generator protocol from the same byte plan as generate/check. */
class PreviewGeneratedScript extends BundleScript {
  run(_segments: string[]): void {
    const repoRoot = getWorkspaceRoot();
    const nodes = generatedTargets(repoRoot, readEntityCatalog(repoRoot))
      .map((target) => ({ bytesBase64: Buffer.from(target.content).toString("base64"), mode: 0o644, nodeKind: "file" as const, path: relative(repoRoot, target.path).replaceAll("\\", "/").normalize("NFC") }))
      .sort((left, right) => Buffer.from(left.path).compare(Buffer.from(right.path)));
    process.stdout.write(`${JSON.stringify({ contractId: GENERATOR_ID, nodes, schemaVersion: 1, staleRemovals: [] })}\n`);
  }
}
//#endregion 🔖️preview-generated

//#region 🔖️generate
class GenerateScript extends BundleScript {
  run(_segments: string[]): void {
    const repoRoot = getWorkspaceRoot();
    const source = readEntityCatalog(repoRoot);
    for (const target of generatedTargets(repoRoot, source)) {
      writeGeneratedFileIfChanged(target.path, target.content);
    }
    const shadowed = source.kinds.length - entityKindIndexByEmoji(source.kinds).size;
    console.log(`entity catalog refreshed (${source.kinds.length} entity kinds, ${shadowed} emoji-shadowed, sha256 ${source.sha256}) -> 🤖️generated/🟦️entity-kinds.ts, ⌨️cli/🐹️entity_kinds.g.go, 🤖️generated.rs`);
  }
}
//#endregion 🔖️generate

//#region 🔖️check
/** @emoji 🔎️ Renders the catalog in memory and byte-compares it against the committed generated files — never writes. */
class CheckScript extends BundleScript {
  run(_segments: string[]): void {
    const repoRoot = getWorkspaceRoot();
    const source = readEntityCatalog(repoRoot);
    const stale = generatedTargets(repoRoot, source)
      .filter((target) => !existsSync(target.path) || readFileSync(target.path, "utf8") !== target.content)
      .map((target) => target.path);
    if (stale.length > 0) {
      console.error(`entity catalog is stale: ${stale.join(", ")}`);
      console.error(`run \`${REFRESH_COMMAND}\` to refresh.`);
      process.exit(1);
    }
    console.log(`entity catalog is fresh (${source.kinds.length} entity kinds, sha256 ${source.sha256}).`);
  }
}
//#endregion 🔖️check

const router = new ScriptRouter(import.meta.dir).register("generate", GenerateScript).register("preview-generated", PreviewGeneratedScript).register("check", CheckScript);

if (import.meta.main) {
  await runBundleScriptMain(router, import.meta.url, { defaultCommand: "generate" });
}

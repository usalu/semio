#!/usr/bin/env bun
/** 📜️ `@semio-tech/framework-schema` — single-source entity catalog codegen (kind → emoji/icon/label/filterable) for CLI, VS Code and Rust consumers. */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { BundleScript, getWorkspaceRoot, ScriptRouter, runBundleScriptMain } from "../../../../../🧰️framework/🛍️products/🦑️repo/🔨️modules/📚️lib/⚡️implementations/🟦️typescript/📦️index.ts";

const packageRoot = import.meta.dir ?? dirname(fileURLToPath(import.meta.url));
// 🌳️ Shape V2: data (`🔣️entity-kinds.json`/`🤖️generated/`/`🤖️generated.rs`) lives at the owner
// root, a sibling of `📦️packages`, never inside it — see `🔣️taxonomy.json`'s `rootDataDirNames`.
const ownerRoot = join(packageRoot, "..", "..");

//#region 🔖️EntityKindSpec
export type EntityKindSpec = {
  readonly id: string;
  readonly emoji: string;
  readonly iconId: string;
  readonly label: string;
  readonly filterable: boolean;
};

function readEntityKinds(): EntityKindSpec[] {
  const path = join(ownerRoot, "🔣️entity-kinds.json");
  return JSON.parse(readFileSync(path, "utf8")) as EntityKindSpec[];
}
//#endregion 🔖️EntityKindSpec

//#region 🔖️emit-typescript
function emitTypeScript(kinds: EntityKindSpec[]): string {
  const rows = kinds
    .map((k) => `\t{ id: ${JSON.stringify(k.id)}, emoji: ${JSON.stringify(k.emoji)}, iconId: ${JSON.stringify(k.iconId)}, label: ${JSON.stringify(k.label)}, filterable: ${k.filterable} },`)
    .join("\n");
  return `/** @generated by framework/schema/script.ts — do not edit. */
export type EntityKindSpec = {
\treadonly id: string;
\treadonly emoji: string;
\treadonly iconId: string;
\treadonly label: string;
\treadonly filterable: boolean;
};

export const ENTITY_KINDS: readonly EntityKindSpec[] = [
${rows}
];

export const ENTITY_KIND_BY_EMOJI: ReadonlyMap<string, EntityKindSpec> = new Map(ENTITY_KINDS.map((spec) => [spec.emoji, spec]));
`;
}
//#endregion 🔖️emit-typescript

//#region 🔖️emit-go
function emitGo(kinds: EntityKindSpec[]): string {
  const rows = kinds
    .map((k) => `\t{ID: ${JSON.stringify(k.id)}, Emoji: ${JSON.stringify(k.emoji)}, IconID: ${JSON.stringify(k.iconId)}, Label: ${JSON.stringify(k.label)}, Filterable: ${k.filterable}},`)
    .join("\n");
  return `// @generated by framework/schema/script.ts — do not edit.

package client

// 🔖️EntityKindSpec holds one entry of the single-source entity catalog (kind → emoji/icon/label/filterable).
type EntityKindSpec struct {
\tID         string
\tEmoji      string
\tIconID     string
\tLabel      string
\tFilterable bool
}

// EntityKindCatalog is the ordered, single-source entity catalog shared with the TS and Rust consumers.
// Named distinctly from the pre-existing EntityKinds (tree-node category strings) elsewhere in this package.
var EntityKindCatalog = []EntityKindSpec{
${rows}
}
`;
}
//#endregion 🔖️emit-go

//#region 🔖️emit-rust
function emitRust(kinds: EntityKindSpec[]): string {
  const rows = kinds
    .map((k) => `\tEntityKindSpec { id: ${JSON.stringify(k.id)}, emoji: ${JSON.stringify(k.emoji)}, icon_id: ${JSON.stringify(k.iconId)}, label: ${JSON.stringify(k.label)}, filterable: ${k.filterable} },`)
    .join("\n");
  return `// @generated by framework/schema/script.ts — do not edit.

/// 🔖️EntityKindSpec holds one entry of the single-source entity catalog (kind → emoji/icon/label/filterable).
pub struct EntityKindSpec {
    pub id: &'static str,
    pub emoji: &'static str,
    pub icon_id: &'static str,
    pub label: &'static str,
    pub filterable: bool,
}

pub const ENTITY_KINDS: &[EntityKindSpec] = &[
${rows}
];

/// 🔍️ Looks up an entity kind by its emoji prefix; when two kinds share an emoji (a pre-existing
/// source-of-truth collision, e.g. technology-mono / interaction-started both use 🌱️) the last
/// declared entry wins, mirroring \`ENTITY_KIND_BY_EMOJI\`'s \`Map\` insertion-order semantics on the TS side.
pub fn entity_kind_by_emoji(emoji: &str) -> Option<&'static EntityKindSpec> {
    ENTITY_KINDS.iter().rev().find(|spec| spec.emoji == emoji)
}
`;
}
//#endregion 🔖️emit-rust

//#region 🔖️targets
type GeneratedTarget = { readonly path: string; readonly content: string };

function generatedTargets(repoRoot: string, kinds: EntityKindSpec[]): GeneratedTarget[] {
  const generatedDir = join(ownerRoot, "🤖️generated");
  return [
    { path: join(generatedDir, "🟦️entity-kinds.ts"), content: emitTypeScript(kinds) },
    { path: join(repoRoot, "🧰️framework/🛍️products/🦑️repo/🔨️modules/💻️client/⌨️cli/⚡️implementations/🐹️go/🐹️entity_kinds.g.go"), content: emitGo(kinds) },
    { path: join(ownerRoot, "🤖️generated.rs"), content: emitRust(kinds) },
  ];
}
//#endregion 🔖️targets

//#region 🔖️generate
class GenerateScript extends BundleScript {
  run(_segments: string[]): void {
    const repoRoot = getWorkspaceRoot();
    const kinds = readEntityKinds();
    for (const target of generatedTargets(repoRoot, kinds)) {
      mkdirSync(dirname(target.path), { recursive: true });
      writeFileSync(target.path, target.content);
    }
    console.log(`entity catalog refreshed (${kinds.length} entity kinds) -> 🤖️generated/🟦️entity-kinds.ts, 🐹️entity_kinds.g.go, 🤖️generated.rs`);
  }
}
//#endregion 🔖️generate

//#region 🔖️check
/** @emoji 🔎️ Renders the catalog in memory and byte-compares it against the committed generated files — never writes. */
class CheckScript extends BundleScript {
  run(_segments: string[]): void {
    const repoRoot = getWorkspaceRoot();
    const kinds = readEntityKinds();
    const stale = generatedTargets(repoRoot, kinds)
      .filter((target) => !existsSync(target.path) || readFileSync(target.path, "utf8") !== target.content)
      .map((target) => target.path);
    if (stale.length > 0) {
      console.error(`entity catalog is stale: ${stale.join(", ")}`);
      console.error("run `bun nx run @semio-tech/framework-schema:generate` to refresh.");
      process.exit(1);
    }
    console.log(`entity catalog is fresh (${kinds.length} entity kinds).`);
  }
}
//#endregion 🔖️check

const router = new ScriptRouter(import.meta.dir).register("generate", GenerateScript).register("check", CheckScript);

if (import.meta.main) {
  await runBundleScriptMain(router, import.meta.url, { defaultCommand: "generate" });
}

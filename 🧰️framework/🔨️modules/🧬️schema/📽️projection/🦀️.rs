    use std::collections::HashSet;

    /// 🧬️ One versioned framework wire type and its owned TypeScript projection.
    #[derive(Clone, Copy, Debug, PartialEq, Eq)]
    pub struct SchemaMetadata {
        pub name: &'static str,
        pub version: u16,
        pub typescript: &'static str,
    }

    #[path = "🧾️rows-a-h/🦀️.rs"]
    mod rows_a_h;
    #[path = "🎟️rows-h-t/🦀️.rs"]
    mod rows_h_t;
    #[path = "📖️rows-t-z/🦀️.rs"]
    mod rows_t_z;

    const ROW_COUNT: usize = rows_a_h::ROWS.len() + rows_h_t::ROWS.len() + rows_t_z::ROWS.len();

    pub const TYPES: &[SchemaMetadata] = &concat::<ROW_COUNT>(&[rows_a_h::ROWS, rows_h_t::ROWS, rows_t_z::ROWS]);

    /// 🧮️ Concatenates the child row tables into one table, preserving declaration order.
    const fn concat<const N: usize>(parts: &[&[SchemaMetadata]]) -> [SchemaMetadata; N] {
        let mut rows = [SchemaMetadata { name: "", version: 0, typescript: "" }; N];
        let mut index = 0;
        let mut part = 0;
        while part < parts.len() {
            let mut row = 0;
            while row < parts[part].len() {
                rows[index] = parts[part][row];
                index += 1;
                row += 1;
            }
            part += 1;
        }
        rows
    }

    /// 🔍️ Rejects unversioned, duplicate, or name-mismatched schema rows before generation.
    pub fn validate() -> Result<(), String> {
        let mut names = HashSet::with_capacity(TYPES.len());
        for metadata in TYPES {
            if metadata.version == 0 {
                return Err(format!("schema '{}' has version zero", metadata.name));
            }
            if !names.insert(metadata.name) {
                return Err(format!("duplicate schema '{}'", metadata.name));
            }
            let type_prefix = format!("export type {}", metadata.name);
            let interface_prefix = format!("export interface {}", metadata.name);
            if !metadata.typescript.contains(&type_prefix) && !metadata.typescript.contains(&interface_prefix) {
                return Err(format!("schema '{}' declaration has a mismatched name", metadata.name));
            }
        }
        Ok(())
    }

    /// 🟦️ Renders the stable language projection consumed by framework clients.
    pub fn render_typescript() -> String {
        let mut output = String::from("/** @generated by `bun repo run @semio-tech/framework:generate` from versioned owned framework schema metadata. Do not edit. */\n\nimport type { Label, StyleSpec, MenuRef as UiMenuRef, RowActionPlacement as UiTreeActionPlacement, Tone, WindowStackCorner } from \"../📜️ui-contract/🟦️.ts\";\nimport type { ShellLocale as Locale, ShellTerminology as Terminology } from \"../🎚️ui-axes/🟦️.ts\";\n\n");
        for (index, metadata) in TYPES.iter().enumerate() {
            output.push_str(metadata.typescript);
            output.push_str(if index + 1 == TYPES.len() { "\n" } else { "\n\n" });
        }
        output
    }

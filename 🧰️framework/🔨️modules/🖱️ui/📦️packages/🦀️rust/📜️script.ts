#!/usr/bin/env bun
/** @emoji ⚙️ Runs `cargo test`/wasm checks for the `semio-framework-ui` crate and regenerates the
 * cross-language UI axes (`Locale`/`Terminology`) from `🎯️targets/🧊️wgpu/🔣️ui-axes.json` — single
 * source of truth for every `app_labels!` exhaustive match and every locale/terminology-typed field
 * in Rust and TypeScript. */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { BundleScript, ScriptRouter, buildBudgetMs, getWorkspaceRoot, resolveTestLevel, runBundleScriptMain, runCargoTestBudgeted, runCmd } from "../../../../🛍️products/🦑️repo/🔨️modules/📚️library/📦️packages/🟦️typescript/📦️index.ts";

const packageRoot = import.meta.dir ?? dirname(fileURLToPath(import.meta.url));
const uiOwnerRoot = join(packageRoot, "..", "..");
const wgpuTargetRoot = join(packageRoot, "🎯️targets", "🧊️wgpu");

//#region 🔖️UiAxesSpec
type UiAxisEntry = { readonly id: string; readonly variant: string; readonly label?: string };
type UiAxesSpec = { readonly locales: readonly UiAxisEntry[]; readonly terminologies: readonly UiAxisEntry[] };

function readUiAxes(): UiAxesSpec {
  return JSON.parse(readFileSync(join(uiOwnerRoot, "🔣️ui-axes.json"), "utf8")) as UiAxesSpec;
}
//#endregion 🔖️UiAxesSpec

//#region 🔖️emit-rust
function emitRustEnum(name: string, entries: readonly UiAxisEntry[]): string {
  const variants = entries.map((e, i) => `    ${i === 0 ? "#[default]\n    " : ""}${e.variant},`).join("\n");
  const asStrArms = entries.map((e) => `            ${name}::${e.variant} => ${JSON.stringify(e.id)},`).join("\n");
  const indexArms = entries.map((e, i) => `            ${name}::${e.variant} => ${i},`).join("\n");
  const parseArms = entries.map((e) => `            ${JSON.stringify(e.id)} => Some(${name}::${e.variant}),`).join("\n");
  const allList = entries.map((e) => `${name}::${e.variant}`).join(", ");
  return `#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum ${name} {
${variants}
}

impl ${name} {
    pub const ALL: [${name}; ${entries.length}] = [${allList}];
    pub const COUNT: usize = ${entries.length};

    pub const fn as_str(self) -> &'static str {
        match self {
${asStrArms}
        }
    }

    pub const fn index(self) -> usize {
        match self {
${indexArms}
        }
    }

    pub fn parse(value: &str) -> Option<${name}> {
        match value {
${parseArms}
            _ => None,
        }
    }
}

impl std::fmt::Display for ${name} {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(self.as_str())
    }
}
`;
}

function emitRust(axes: UiAxesSpec): string {
  return `// @generated by ui/script.ts from 🔣️ui-axes.json — do not edit.

use serde::{Deserialize, Serialize};

/// 🌐️ Chrome-complete UI locales — generated. Adding a locale here breaks every exhaustive
/// \`match\` on \`Locale\` (every \`app_labels!\` cell resolver, \`resolve_labels\`, chrome bundles)
/// until the new variant is covered — that failure list is the correctness guarantee.
${emitRustEnum("Locale", axes.locales)}
/// 🗣️ Terminology ids — generated. Same contract as \`Locale\`.
${emitRustEnum("Terminology", axes.terminologies)}
`;
}
//#endregion 🔖️emit-rust

//#region 🔖️emit-typescript
function emitTypeScript(axes: UiAxesSpec): string {
  const localeIds = axes.locales.map((e) => JSON.stringify(e.id)).join(", ");
  const terminologyIds = axes.terminologies.map((e) => JSON.stringify(e.id)).join(", ");
  return `/** @generated by ui/script.ts from 🔣️ui-axes.json — do not edit. */

export const SHELL_LOCALES = [${localeIds}] as const;
export type ShellLocale = (typeof SHELL_LOCALES)[number];

export const SHELL_TERMINOLOGIES = [${terminologyIds}] as const;
export type ShellTerminology = (typeof SHELL_TERMINOLOGIES)[number];

/** 🧭️ Membership guard — the runtime twin of the Rust \`Locale::parse\`/exhaustive-match guarantee. */
export const isShellLocale = (value: string): value is ShellLocale => (SHELL_LOCALES as readonly string[]).includes(value);
/** 🧭️ Membership guard — the runtime twin of the Rust \`Terminology::parse\`/exhaustive-match guarantee. */
export const isShellTerminology = (value: string): value is ShellTerminology => (SHELL_TERMINOLOGIES as readonly string[]).includes(value);

/** 🗺️ Full locale×terminology matrix for a manifest label, mirroring Rust \`LocalizedLabel\`. */
export type LocalizedLabel = Readonly<Record<ShellTerminology, Readonly<Record<ShellLocale, string>>>>;
`;
}
//#endregion 🔖️emit-typescript

//#region 🔖️targets
type GeneratedTarget = { readonly path: string; readonly content: string };

function generatedTargets(repoRoot: string, axes: UiAxesSpec): GeneratedTarget[] {
  return [
    { path: join(wgpuTargetRoot, "🤖️generated.rs"), content: emitRust(axes) },
    { path: join(repoRoot, "🧰️framework/🔨️modules/🛂️manifest/🤖️generated/🟦️ui-axes.ts"), content: emitTypeScript(axes) },
  ];
}
//#endregion 🔖️targets

//#region 🔖️preview-generated
/** 🧾️ Emits the canonical read-only generator protocol from the same byte plan as generate/check. */
class PreviewGeneratedScript extends BundleScript {
  run(_segments: string[]): void {
    const repoRoot = getWorkspaceRoot();
    const nodes = generatedTargets(repoRoot, readUiAxes())
      .map((target) => ({ bytesBase64: Buffer.from(target.content).toString("base64"), mode: 0o644, nodeKind: "file" as const, path: relative(repoRoot, target.path).replaceAll("\\", "/").normalize("NFC") }))
      .sort((left, right) => Buffer.from(left.path).compare(Buffer.from(right.path)));
    process.stdout.write(`${JSON.stringify({ contractId: "ui-axes", nodes, schemaVersion: 1, staleRemovals: [] })}\n`);
  }
}
//#endregion 🔖️preview-generated

//#region 🔖️generate
class GenerateAxesScript extends BundleScript {
  run(_segments: string[]): void {
    const repoRoot = getWorkspaceRoot();
    const axes = readUiAxes();
    for (const target of generatedTargets(repoRoot, axes)) {
      mkdirSync(dirname(target.path), { recursive: true });
      writeFileSync(target.path, target.content);
    }
    console.log(`ui axes refreshed (${axes.locales.length} locales, ${axes.terminologies.length} terminologies) -> 🤖️generated.rs, 🤖️generated/🟦️ui-axes.ts`);
  }
}
//#endregion 🔖️generate

//#region 🔖️check
/** @emoji 🔎️ Renders the axes in memory and byte-compares against the committed generated files — never writes. */
class CheckAxesScript extends BundleScript {
  run(_segments: string[]): void {
    const repoRoot = getWorkspaceRoot();
    const axes = readUiAxes();
    const stale = generatedTargets(repoRoot, axes)
      .filter((target) => !existsSync(target.path) || readFileSync(target.path, "utf8") !== target.content)
      .map((target) => target.path);
    if (stale.length > 0) {
      console.error(`ui axes are stale: ${stale.join(", ")}`);
      console.error("run `bun nx run @semio-tech/ui-rs:generate` to refresh.");
      process.exit(1);
    }
    console.log(`ui axes are fresh (${axes.locales.length} locales, ${axes.terminologies.length} terminologies).`);
  }
}
//#endregion 🔖️check

//#region 🔖️test
class TestScript extends BundleScript {
  run(segments: string[]): void {
    const { rest } = resolveTestLevel(segments);
    runCargoTestBudgeted([], packageRoot, ["--features", "tui-terminal,wgpu", ...rest]);
  }
}

/** @emoji 🧪️ Runs the retained wgpu engine's native unit tests through the standard budgeted harness. */
class TestWgpuEngineScript extends BundleScript {
  run(segments: string[]): void {
    const { rest } = resolveTestLevel(segments);
    runCargoTestBudgeted([], packageRoot, ["--features", "wgpu-engine", ...rest]);
  }
}
//#endregion 🔖️test

//#region 🔖️check-wasm
/** @emoji 🌐️ Both targets on their own wasm flavours: the tui host on `wasm32-unknown-unknown`, the wgpu component types on `wasm32-wasip2` (the program-component admission gate). */
class CheckWasmScript extends BundleScript {
  run(): void {
    const check = (args: string[]) => runCmd("cargo", ["check", "-p", "semio-framework-ui", ...args], { cwd: packageRoot, budgetMs: buildBudgetMs() });
    check(["--target", "wasm32-unknown-unknown", "--features", "tui"]);
    check(["--target", "wasm32-unknown-unknown", "--features", "tui-bindgen"]);
    check(["--target", "wasm32-wasip2", "--features", "wgpu"]);
  }
}

/** @emoji 🧊️ Checks the full retained render seam on browser WebGPU. */
class CheckWgpuEngineWasmScript extends BundleScript {
  run(): void {
    runCmd("cargo", ["check", "-p", "semio-framework-ui", "--target", "wasm32-unknown-unknown", "--features", "wgpu-engine"], { cwd: packageRoot, budgetMs: buildBudgetMs() });
  }
}
//#endregion 🔖️check-wasm

if (import.meta.main) {
  const router = new ScriptRouter(import.meta.dir)
    .register("generate", GenerateAxesScript)
    .register("preview-generated", PreviewGeneratedScript)
    .register("check", CheckAxesScript)
    .register("test", TestScript)
    .register("test-wgpu-engine", TestWgpuEngineScript)
    .register("check-wasm", CheckWasmScript)
    .register("check-wgpu-engine-wasm", CheckWgpuEngineWasmScript);
  await runBundleScriptMain(router, import.meta.url);
}

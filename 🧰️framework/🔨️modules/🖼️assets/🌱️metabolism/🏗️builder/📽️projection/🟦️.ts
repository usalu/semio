import { readFileSync } from "node:fs";
import { join } from "node:path";
import { iconIdToRustVariant, readCatalogSources, type AssetArtifact } from "../../../🔣️icons/🏗️builder/📽️projection/🟦️.ts";

const assetsRoot = (): string => join(import.meta.dirname, "..", "..", "..");

//#region 📦️Catalog
function readMetabolismSvgs(iconsDir: string, sources: readonly { id: string; path: string }[]): Record<string, string> {
  const out: Record<string, string> = {};
  for (const { id, path } of sources) {
    out[id] = readFileSync(join(iconsDir, path), "utf8").trim();
  }
  return out;
}
//#endregion 📦️Catalog

//#region 🧬️Codegen
function escapeMetabolismTsString(value: string): string {
  return value.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$/g, "\\$");
}

function renderJsMetabolism(icons: Record<string, string>, generatedDir: string): AssetArtifact {
  const entries = Object.keys(icons)
    .sort()
    .map((id) => `  "${id}": \`${escapeMetabolismTsString(icons[id]!)}\`,`)
    .join("\n");
  const body = `// Generated by asset/script.ts — do not edit.
export const METABOLISM_ICONS = {
${entries}
} as const;

export type MetabolismIconName = keyof typeof METABOLISM_ICONS;

export const METABOLISM_ICON_NAMES = Object.keys(METABOLISM_ICONS) as MetabolismIconName[];

export function isMetabolismIconName(key: string): key is MetabolismIconName {
  return key in METABOLISM_ICONS;
}
`;
  return { path: join(generatedDir, "🖼️icons", "🟦️.ts"), content: body };
}

function renderRustMetabolism(icons: Record<string, string>, generatedDir: string): readonly AssetArtifact[] {
  const ids = Object.keys(icons).sort();
  const variants = ids.map((id) => `    #[serde(rename = "${id}")]\n    ${iconIdToRustVariant(id)},`).join("\n");
  const asStrArms = ids.map((id) => `            Self::${iconIdToRustVariant(id)} => "${id}",`).join("\n");
  const fromStrArms = ids.map((id) => `            "${id}" => Some(Self::${iconIdToRustVariant(id)}),`).join("\n");
  const allEntries = ids.map((id) => `        MetabolismIconName::${iconIdToRustVariant(id)},`).join("\n");
  const body = `// Generated by asset/script.ts — do not edit.

#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, serde::Serialize, serde::Deserialize)]
pub enum MetabolismIconName {
${variants}
}

impl MetabolismIconName {
    pub const ALL: &'static [Self] = &[
${allEntries}
    ];

    pub fn as_str(self) -> &'static str {
        match self {
${asStrArms}
        }
    }

    pub fn parse(s: &str) -> Option<Self> {
        match s.trim() {
${fromStrArms}
            _ => None,
        }
    }
}

impl std::fmt::Display for MetabolismIconName {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(self.as_str())
    }
}

impl From<&str> for MetabolismIconName {
    fn from(value: &str) -> Self {
        Self::parse(value).expect("invalid metabolism icon name")
    }
}
`;
  return [{ path: join(generatedDir, "🪪️icon-name", "🦀️.rs"), content: body }];
}
//#endregion 🧬️Codegen

//#region 🚀️Commands
export function renderMetabolismArtifacts(): readonly AssetArtifact[] {
  const assetsDir = assetsRoot();
  const iconsDir = join(assetsDir, "🌱️metabolism/🔣️icons");
  const generatedDir = join(assetsDir, "🌱️metabolism/🔣️icons/🤖️generated");
  const sources = readCatalogSources(iconsDir);
  const icons = readMetabolismSvgs(iconsDir, sources);
  return [renderJsMetabolism(icons, generatedDir), ...renderRustMetabolism(icons, generatedDir)];
}
//#endregion 🚀️Commands

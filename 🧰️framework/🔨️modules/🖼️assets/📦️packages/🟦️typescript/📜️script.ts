function catalogDirs(assetsDir: string): { iconsDir: string; generatedDir: string } {
  const iconsDir = join(assetsDir, "🔣️icons");
  const generatedDir = join(iconsDir, "🤖️generated");
  return { iconsDir, generatedDir };
}

function renderCatalogArtifacts(target: string): readonly AssetArtifact[] {
  const assetsDir = assetsRoot();
  const { iconsDir, generatedDir } = catalogDirs(assetsDir);
  const icons = readCatalogSvgs(iconsDir);
  const artifacts: AssetArtifact[] = [renderCatalogReadme(assetsDir, Object.keys(icons))];
  if (target === "js" || target === "all") artifacts.push(renderJs(icons, generatedDir));
  if (target === "net" || target === "all") artifacts.push(renderCs(icons, generatedDir));
  if (target === "py" || target === "all") artifacts.push(renderPy(icons, generatedDir));
  if (target === "rust" || target === "all") artifacts.push(...renderRust(icons, generatedDir));
  if (target === "all") artifacts.push(renderShortcodes(icons, generatedDir));
  return artifacts;
}

function writeAssetArtifacts(artifacts: readonly AssetArtifact[]): void {
  for (const artifact of artifacts) {
    mkdirSync(dirname(artifact.path), { recursive: true });
    writeFileSync(artifact.path, artifact.content, "utf8");
  }
}

function runGenerate(target: string): void {
  const artifacts = renderCatalogArtifacts(target);
  writeAssetArtifacts(artifacts);
  console.log(`[asset] wrote ${artifacts.length} catalog artifacts → ${target}`);
}

function runGenerateAll(): void {
  const artifacts = renderCatalogArtifacts("all");
  writeAssetArtifacts(artifacts);
  console.log(`[asset] wrote ${artifacts.length} catalog artifacts → all`);
}

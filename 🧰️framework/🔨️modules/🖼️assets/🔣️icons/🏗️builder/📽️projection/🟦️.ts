function renderPy(icons: Record<string, string>, generatedDir: string): AssetArtifact {
  const literals = Object.keys(icons)
    .sort()
    .map((id) => `    "${id}": """${escapePythonString(icons[id]!)}""",`)
    .join("\n");
  const names = Object.keys(icons)
    .sort()
    .map((id) => `    "${id}",`)
    .join("\n");
  const body = `# Generated by asset/script.ts — do not edit.
from __future__ import annotations

from typing import Final, Literal

IconName = Literal[
${names}
]

ICONS: Final[dict[str, str]] = {
${literals}
}
`;
  return { path: join(generatedDir, "🖼️icons", "🐍️.py"), content: body };
}

function renderCatalogReadme(assetsDir: string, ids: readonly string[]): AssetArtifact {
  const sorted = [...ids].sort();
  const list = sorted.map((id) => `- \`${id}\``).join("\n");
  const body = `# UI assets

Shared fonts, cursors, lists, and UI chrome icons served at \`/🖼️assets/*\`.

## Icons

Chrome icons are committed SVGs grouped by subject under \`🔣️icons/\`. Each source has one handpicked emoji; its public icon id is independent of that path. Many were originally derived from [Lucide](https://lucide.dev) (**ISC License**); source: https://github.com/lucide-icons/lucide

Add or edit SVGs under \`🔣️icons/\`, then run the assets build launch configuration (\`bun nx run @semio-tech/assets:build\`). Generated Rust SVG copies retain the exact source paths.

### Catalog icon ids

${list}
`;
  return { path: join(assetsDir, "README.md"), content: body };
}

/** @emoji 🔖️ Renders universal shortcode bindings from the explicit external emoji snapshot. */
function renderShortcodes(icons: Record<string, string>, generatedDir: string): AssetArtifact {
  const catalog = Object.keys(icons).sort();
  const snapshotPath = join(generatedDir, "🔣️shortcodes.json");
  if (!existsSync(snapshotPath)) throw new Error("missing external 🔣️shortcodes.json snapshot");
  const snapshot = JSON.parse(readFileSync(snapshotPath, "utf8")) as { emoji?: Record<string, string>; catalog?: string[] };
  if (!snapshot.emoji || !Array.isArray(snapshot.catalog)) throw new Error("invalid external 🔣️shortcodes.json snapshot");
  if (JSON.stringify(snapshot.catalog) !== JSON.stringify(catalog)) throw new Error("external 🔣️shortcodes.json catalog is stale");
  const emoji = snapshot.emoji;

  const emojiEntries = Object.keys(emoji)
    .sort()
    .map((key) => `  ${JSON.stringify(key)}: ${JSON.stringify(emoji[key])},`)
    .join("\n");
  const catalogEntries = catalog.map((id) => `  ${JSON.stringify(id)},`).join("\n");
  const tsBody = `// Generated by asset/script.ts — do not edit.
export const SHORTCODE_EMOJI = {
${emojiEntries}
} as const;

export type ShortcodeEmojiName = keyof typeof SHORTCODE_EMOJI;

export const SHORTCODE_CATALOG = [
${catalogEntries}
] as const;

export type ShortcodeCatalogName = (typeof SHORTCODE_CATALOG)[number];

/** @emoji 🔍️ Resolves a shortcode body (without colons) to emoji glyph when known. */
export function shortcodeEmoji(code: string): string | undefined {
  const key = code.trim().toLowerCase();
  return (SHORTCODE_EMOJI as Record<string, string>)[key];
}

/** @emoji 🔍️ True when the shortcode body names a vendored UI catalog icon. */
export function shortcodeCatalogKey(code: string): ShortcodeCatalogName | undefined {
  const key = code.trim();
  return (SHORTCODE_CATALOG as readonly string[]).includes(key) ? (key as ShortcodeCatalogName) : undefined;
}
`;
  return { path: join(generatedDir, "🔤️shortcodes", "🟦️.ts"), content: tsBody };
}

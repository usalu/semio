/// 🚦️ Runs one `semio` invocation and returns its process exit code.
pub fn run(argv: Vec<String>) -> i32 {
    let root = workspace::find_root(&std::env::current_dir().unwrap_or_else(|_| PathBuf::from(".")));
    if argv.is_empty() {
        if !std::io::stdout().is_terminal() {
            print_usage();
            return 1;
        }
        return tui_dashboard::run(&root);
    }
    let parsed = args::parse(&argv);
    match parsed.verb.as_str() {
        "dev" => dev::run_dev(&root, &parsed),
        "catalog" => {
            if parsed.has_flag("json") {
                print!("{}", catalog::playgrounds_json_text(&root));
                return 0;
            }
            let catalog = catalog::load_playground_catalog(&root);
            for row in &catalog {
                println!("{}\t{}\treact:{}\twgpu:{}", row.variant, row.plugin_id, row.ports.react, row.ports.wgpu);
            }
            0
        }
        "plugin" if parsed.segments.first().map(String::as_str) == Some("registry") => plugin_registry_command::run(&root, parsed.segments.get(1).map(String::as_str).unwrap_or("generate")),
        _ => {
            let mut forward = vec!["./📜️script.ts".to_string(), parsed.verb.clone()];
            forward.extend(parsed.segments.clone());
            let forward_refs: Vec<&str> = forward.iter().map(String::as_str).collect();
            proc::spawn_inherit("bun", &forward_refs, &root, &[])
        }
    }
}

fn print_usage() {
    eprintln!("semio — semio monorepo orchestrator\n\nUsage:\n  semio                 interactive TUI dashboard (requires a TTY)\n  semio dev <variant…>  start a plugin dev session\n  semio catalog         list playgrounds\n  semio plugin registry generate|check\n  semio <verb> …        forwarded to `bun ./📜️script.ts <verb> …`");
}

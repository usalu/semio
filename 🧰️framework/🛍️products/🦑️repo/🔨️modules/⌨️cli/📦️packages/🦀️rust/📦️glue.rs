pub mod options {
    /// 🔀️ One CLI option pick: switchable at runtime, or locked to one value at boot.
    #[derive(Debug, Clone, PartialEq, Eq)]
    pub enum Lock {
        All,
        Individual(String),
    }

    /// 📥️ Parses a `--flag` value: `"all"` (case-insensitive) means runtime-switchable.
    pub fn parse_lock(raw: &str) -> Lock {
        if raw.eq_ignore_ascii_case("all") {
            Lock::All
        } else {
            Lock::Individual(raw.to_string())
        }
    }
}

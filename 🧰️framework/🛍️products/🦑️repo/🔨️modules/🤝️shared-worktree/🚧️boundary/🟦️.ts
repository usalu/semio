/** 🙈️ A compiled root `.gitignore`: the digest of its text and the verdict for one worktree-relative path; `child` decides a path whose parent directories are already known to be shared, without walking or caching the ancestors. */
export type FleetIgnoreV1=Readonly<{digest:string;ignores(path:string,isDirectory:boolean):boolean;child?(path:string,isDirectory:boolean):boolean;local?(path:string):boolean}>;

/** 🚫️ Why a path is never shared. */
export type FleetPathRefusalV1="not-nfc"|"too-long"|"component-too-long"|"illegal-character"|"trailing-dot-or-space"|"reserved-name"|"case-collision"|"unsafe-link";

/** 📄️ One shared file or link as the scanner saw it. */
export type FleetScanEntryV1=Readonly<{path:string;kind:"file"|"link";bytes:number;mtimeMs:number;executable:boolean;target?:string}>;

/** 🗂️ The shared entries and the refused paths of one scan, both sorted by path. */
export type FleetScanV1=Readonly<{entries:readonly FleetScanEntryV1[];refused:readonly Readonly<{path:string;reason:FleetPathRefusalV1}>[]}>;

type Rule=Readonly<{index:number;negate:boolean;dirOnly:boolean;anchored:boolean;expression:RegExp;literal:string|undefined}>;

const POSIX:Readonly<Record<string,string>>={alpha:"A-Za-z",digit:"0-9",alnum:"A-Za-z0-9",upper:"A-Z",lower:"a-z",space:"\\t\\n\\v\\f\\r ",blank:"\\t ",punct:"!-/:-@\\[-`{-~",xdigit:"0-9A-Fa-f",cntrl:"\\u0000-\\u001f\\u007f",print:" -~",graph:"!-~",word:"A-Za-z0-9_"};
const RESERVED_START=/^[cpanl]/iu;
const reservedName=(name:string):boolean=>RESERVED_START.test(name)&&RESERVED.test(name.split(".")[0].replace(/ +$/u,"").toUpperCase());
const ILLEGAL=/[<>:"|?*\\\u0000-\u001f\u007f-\u009f]/u;
const RESERVED=/^(?:CON|PRN|AUX|NUL|CONIN\$|CONOUT\$|CLOCK\$|COM[1-9\u00b9\u00b2\u00b3]|LPT[1-9\u00b9\u00b2\u00b3])$/u;
const LIMIT=20000;

const code=(char:string):number=>char.codePointAt(0) as number;
const escapeChar=(char:string):string=>code(char)>127||/^[A-Za-z0-9]$/u.test(char)?char:`\\u{${code(char).toString(16)}}`;
const FOLD=new Map<number,string>(foldTable.map.map((row):[number,string]=>[Number(row[0]),String(row[1])]));
const ASCII=/^[\u0000-\u007f]*$/u;
const FOLD_PATTERN=new RegExp(`[A-Z${[...FOLD.keys()].map(key=>`\\u{${key.toString(16)}}`).join("")}]`,"gu");

/** 🧿️ Folds a file name so that names which collide on a case-insensitive file system fold to the same text: NFC, then every code point through the checked-in table (`🔤️fold/🔣️.json`, generated by its script from the case mapping of ICU: full case folding with `ß`, `ẞ` and `SS` meeting at `ss`, the final and the medial sigma meeting, `ı` and `ſ` meeting `i` and `s` as NTFS' upper-case table does, ligatures expanded), NFC again. The fold is the union of APFS (full case folding, normalisation-insensitive), NTFS (upper-case table, normalisation-sensitive) and Linux with a case-folding directory, so a path set that has no collision here has none on any of them. The emoji variation selector `U+FE0F` is a code point of its own on APFS and NTFS and stays significant; ASCII is lower-cased directly, so a name needs no table lookup unless it holds a non-ASCII letter. */
export function foldNameV1(name:string):string{
 if(ASCII.test(name))return name.toLowerCase();
 return name.normalize("NFC").replace(FOLD_PATTERN,char=>FOLD.get(char.codePointAt(0) as number)??char.toLowerCase()).normalize("NFC");
}

/** 📐️ The longest worktree-relative path the fleet shares, in UTF-16 code units (JavaScript `length`, the unit of Windows paths and of NTFS file names): 256. A path of this length still needs `LongPathsEnabled` on Windows, whose `MAX_PATH` is 260 units including the drive prefix and the terminating NUL (see `pathBudgetV1`). */
export const PATH_LIMIT_UNITS_V1=256;

/** 📏️ The budget of an absolute path on one operating system: `win32` counts UTF-16 units against 259 (`MAX_PATH` less the NUL) or, with long paths, against 32766; `darwin` counts UTF-8 bytes against 1023 (`PATH_MAX`); `linux` counts UTF-8 bytes against 4095. `unitsOf` measures the absolute path `worktree` + separator + `path` in that unit. */
export function pathBudgetV1(platform:NodeJS.Platform,longPaths:boolean=false):Readonly<{unit:"utf16"|"utf8";limit:number;separator:string}>{
 return platform==="win32"?{unit:"utf16",limit:longPaths?32766:259,separator:"\\"}:{unit:"utf8",limit:platform==="darwin"?1023:4095,separator:"/"};
}

/** 📏️ Measures `worktree` + separator + `path` in the unit of the budget. */
export function absoluteUnitsV1(budget:ReturnType<typeof pathBudgetV1>,worktree:string,path:string):number{
 const absolute=`${worktree.replace(/[\\/]+$/u,"")}${budget.separator}${budget.separator==="/"?path:path.replaceAll("/","\\")}`;
 return budget.unit==="utf16"?absolute.length:Buffer.byteLength(absolute);
}

const compare=(left:string,right:string):number=>left<right?-1:left>right?1:0;
const windowsSeparators=(target:string):string=>process.platform==="win32"?target.replaceAll("\\","/"):target;
const vanished=(error:unknown):boolean=>{const name=(error as {code?:string}).code;return name==="ENOENT"||name==="ENOTDIR";};
const overlong=(error:unknown):boolean=>(error as {code?:string}).code==="ENAMETOOLONG";

function parseClass(chars:readonly string[],open:number):Readonly<{source:string;next:number}>|undefined{
 let j=open+1,negate=false,items="",first=true;
 if(chars[j]==="!"||chars[j]==="^"){negate=true;j++;}
 for(;j<chars.length;first=false){
  let char=chars[j];
  if(char==="]"&&!first)return {source:items===""&&!negate?"(?!)":`[${negate?"^/":""}${items}]`,next:j+1};
  if(char==="["&&chars[j+1]===":"){
   const close=chars.findIndex((c,k)=>k>j+1&&c===":"&&chars[k+1]==="]"),name=close<0?"":chars.slice(j+2,close).join("");
   if(Object.hasOwn(POSIX,name)){items+=POSIX[name];j=close+2;continue;}
  }
  if(char==="\\"&&j+1<chars.length)char=chars[++j];
  if(chars[j+1]==="-"&&j+2<chars.length&&chars[j+2]!=="]"){
   let high=chars[j+2],skip=3;
   if(high==="\\"&&j+3<chars.length){high=chars[j+3];skip=4;}
   if(code(char)<=code(high))items+=`${escapeChar(char)}-${escapeChar(high)}`;
   j+=skip;continue;
  }
  items+=escapeChar(char);j++;
 }
 return undefined;
}

function translate(glob:string):Readonly<{source:string;literal:string|undefined}>{
 const chars=Array.from(glob);
 let source="",literal="",plain=true,i=0;
 while(i<chars.length){
  const char=chars[i];
  if(char==="*"){
   let end=i;while(chars[end+1]==="*")end++;
   const next=chars[end+1];plain=false;
   if(end>i&&(i===0||chars[i-1]==="/")&&(next===undefined||next==="/")){
    if(next==="/"){source+="(?:.*/)?";i=end+2;}else{source+=i===0?".*":".+";i=end+1;}
    continue;
   }
   source+="[^/]*";i=end+1;continue;
  }
  if(char==="?"){source+="[^/]";plain=false;i++;continue;}
  if(char==="["){
   const parsed=parseClass(chars,i);
   if(parsed){source+=parsed.source;plain=false;i=parsed.next;continue;}
  }
  const literalChar=char==="\\"&&i+1<chars.length?chars[++i]:char;
  source+=escapeChar(literalChar);literal+=literalChar;i++;
 }
 return {source,literal:plain?literal:undefined};
}

function parseLine(raw:string,index:number,insensitive:boolean):Rule|undefined{
 let line=raw.endsWith("\r")?raw.slice(0,-1):raw,end=line.length;
 while(end>0&&line[end-1]===" ")end--;
 if(end<line.length){let slashes=0;while(slashes<end&&line[end-1-slashes]==="\\")slashes++;if(slashes%2===1)end++;}
 line=line.slice(0,end);
 if(line===""||line.startsWith("#"))return undefined;
 const negate=line.startsWith("!");
 if(negate)line=line.slice(1);
 const dirOnly=line.endsWith("/");
 if(dirOnly)line=line.slice(0,-1);
 const anchored=line.includes("/");
 if(line.startsWith("/"))line=line.slice(1);
 if(line==="")return undefined;
 const {source,literal}=translate(line);
 return {index,negate,dirOnly,anchored,expression:new RegExp(`^(?:${source})$`,insensitive?"isu":"su"),literal:literal===undefined||!insensitive?literal:foldNameV1(literal)};
}

/** 🧱️ Compiles gitignore text with full semantics (anchoring, `**`, negation, directory-only rules, classes, escapes) into a dependency-free matcher; a path below an excluded directory is always excluded. Matching is case-sensitive, like Linux git and like `core.ignorecase=false`; `caseInsensitive` compiles the same rules the way a git with `core.ignorecase=true` (macOS, Windows) applies them, for `caseDependentIgnoresV1`. */
export function compileIgnoreV1(gitignoreText:string,options:Readonly<{caseInsensitive?:boolean}>={}):FleetIgnoreV1{
 const insensitive=options.caseInsensitive===true;
 const rules:Rule[]=[],literals=new Map<string,Rule[]>(),wild:Rule[]=[],anchored:Rule[]=[];
 for(const line of gitignoreText.split("\n")){const rule=parseLine(line,rules.length,insensitive);if(rule)rules.push(rule);}
 for(const rule of rules){
  if(rule.anchored)anchored.push(rule);
  else if(rule.literal!==undefined)literals.set(rule.literal,[...(literals.get(rule.literal)??[]),rule]);
  else wild.push(rule);
 }
 const names=new Map<string,number>(),directories=new Map<string,boolean>();
 const byName=(name:string,isDirectory:boolean):number=>{
  const key=`${isDirectory?1:0}${name}`,known=names.get(key);
  if(known!==undefined)return known;
  let best=-1;
  for(const rule of literals.get(insensitive?foldNameV1(name):name)??[])if(isDirectory||!rule.dirOnly)best=Math.max(best,rule.index);
  for(let k=wild.length-1;k>=0&&wild[k].index>best;k--){const rule=wild[k];if((isDirectory||!rule.dirOnly)&&rule.expression.test(name)){best=rule.index;break;}}
  if(names.size>LIMIT)names.clear();
  names.set(key,best);return best;
 };
 const decide=(path:string,isDirectory:boolean):boolean=>{
  let best=byName(path.slice(path.lastIndexOf("/")+1),isDirectory);
  for(let k=anchored.length-1;k>=0&&anchored[k].index>best;k--){const rule=anchored[k];if((isDirectory||!rule.dirOnly)&&rule.expression.test(path)){best=rule.index;break;}}
  return best<0?false:!rules[best].negate;
 };
 const ignores=(path:string,isDirectory:boolean):boolean=>{
  const clean=path.endsWith("/")?path.slice(0,-1):path;
  if(clean==="")return false;
  for(let cut=clean.indexOf("/");cut>0;cut=clean.indexOf("/",cut+1)){
   const prefix=clean.slice(0,cut);
   let state=directories.get(prefix);
   if(state===undefined){state=decide(prefix,true);if(directories.size>LIMIT)directories.clear();directories.set(prefix,state);}
   if(state)return true;
  }
  const state=decide(clean,isDirectory);
  if(isDirectory)directories.set(clean,state);
  return state;
 };
 const child=(path:string,isDirectory:boolean):boolean=>decide(path.endsWith("/")?path.slice(0,-1):path,isDirectory);
 return Object.freeze({digest:createHash("sha256").update(gitignoreText).digest("hex"),ignores,child});
}

/** 🪞️ Lists the shallowest paths that a case-insensitive `.gitignore` match would hide but the case-sensitive match of the replica shares: a `Backup/` rule against an existing `backup/` directory. The given worktree-relative paths are sorted and walked once, every distinct directory and file name is judged once (a quarter of a million paths take about ten seconds of CPU, so the walk yields to the event loop every 2,000 judgements and stops with the signal), and each hidden path is reported once at the level where the two verdicts first differ. */
export async function caseDependentIgnoresV1(gitignoreText:string,paths:Iterable<string>,options:Readonly<{signal?:AbortSignal}>={}):Promise<readonly string[]>{
 const strict=compileIgnoreV1(gitignoreText),loose=compileIgnoreV1(gitignoreText,{caseInsensitive:true}),found=new Set<string>(),sorted=[...paths].sort(compare);
 const judge=(matcher:FleetIgnoreV1,path:string,directory:boolean):boolean=>(matcher.child??matcher.ignores)(path,directory);
 let previous:string[]=[],levels:boolean[]=[],calls=0;
 for(const path of sorted){
  const parts=path.split("/");
  let common=0;
  while(common<parts.length-1&&common<previous.length-1&&parts[common]===previous[common])common++;
  const state=levels.slice(0,common);
  let hidden=state.some(Boolean);
  if(!hidden)for(let level=common;level<parts.length;level++){
   const prefix=parts.slice(0,level+1).join("/"),directory=level<parts.length-1,hit=judge(loose,prefix,directory)&&!judge(strict,prefix,directory);
   state[level]=hit;
   if(hit){found.add(prefix);break;}
   if(++calls%2000===0){options.signal?.throwIfAborted();await new Promise<void>(resume=>{setImmediate(resume);});}
  }
  previous=parts;levels=state;
 }
 return [...found].sort(compare);
}

/** 🛂️ Names why a worktree-relative path is never shared (NFC, length in UTF-16 units against `PATH_LIMIT_UNITS_V1`, illegal characters, trailing dot or space, device names); `undefined` means the path is acceptable. Case collisions are decided by the scanner. */
export function refusePathV1(path:string):FleetPathRefusalV1|undefined{
 if(path!==path.normalize("NFC"))return "not-nfc";
 if(path.length>PATH_LIMIT_UNITS_V1)return "too-long";
 for(let start=0;;){
  const slash=path.indexOf("/",start),end=slash<0?path.length:slash;
  if(end-start>85&&Buffer.byteLength(path.slice(start,end))>255)return "component-too-long";
  if(slash<0)break;
  start=slash+1;
 }
 if(ILLEGAL.test(path))return "illegal-character";
 let trailing=false,reserved=false;
 for(let start=0;;){
  const slash=path.indexOf("/",start),end=slash<0?path.length:slash;
  if(end>start){
   const last=path.charCodeAt(end-1);
   if(last===46||last===32)trailing=true;
   else if(!reserved&&reservedName(path.slice(start,end)))reserved=true;
  }
  if(slash<0)break;
  start=slash+1;
 }
 if(trailing)return "trailing-dot-or-space";
 if(reserved)return "reserved-name";
 return undefined;
}

function refuseLeaf(path:string,name:string):FleetPathRefusalV1|undefined{
 if(name!==name.normalize("NFC"))return "not-nfc";
 if(path.length>PATH_LIMIT_UNITS_V1)return "too-long";
 if(Buffer.byteLength(name)>255)return "component-too-long";
 if(ILLEGAL.test(name))return "illegal-character";
 if(name.endsWith(".")||name.endsWith(" "))return "trailing-dot-or-space";
 if(reservedName(name))return "reserved-name";
 return undefined;
}

/** 🔗️ Refuses a symbolic link whose target is absolute, drive-qualified, empty or climbs out of the worktree; backslashes count as separators. */
export function linkRefusalV1(path:string,target:string):FleetPathRefusalV1|undefined{
 const normal=target.replaceAll("\\","/");
 if(normal===""||normal.includes("\0")||normal.startsWith("/")||/^[A-Za-z]:/u.test(normal))return "unsafe-link";
 let depth=path.split("/").length-1;
 for(const part of normal.split("/")){
  if(part===""||part===".")continue;
  if(part===".."){if(--depth<0)return "unsafe-link";}else depth++;
 }
 return undefined;
}

const GIT_SHARED_FILES=new Set(["HEAD","packed-refs","shallow"]);
const GIT_SHARED_DIRECTORIES=new Set(["refs","objects"]);

/** 🌿 Tells whether a path inside the root `.git` is shared: the allow-list is `HEAD`, `packed-refs`, `shallow`, everything below `refs` and everything below `objects` except temporary objects (`tmp_` prefix in `objects`), `objects/info/alternates` and every name ending `.lock`; the `.git` directory itself is shared, every other path (index, config, logs, hooks, info, in-progress operation files, IDE files) stays on the machine. A path outside the root `.git` is not decided here and answers false. */
export function gitSharedV1(path:string):boolean{
 const parts=path.split("/");
 if(parts[0]!==".git")return false;
 const rest=parts.slice(1),name=rest.at(-1)??"";
 if(rest.length===0)return true;
 if(name.endsWith(".lock"))return false;
 if(rest.length===1&&GIT_SHARED_FILES.has(name))return true;
 if(!GIT_SHARED_DIRECTORIES.has(rest[0]!))return false;
 if(rest[0]==="objects")return !name.startsWith("tmp_")&&rest.join("/")!=="objects/info/alternates";
 return true;
}

/** 🔒 A path inside the root `.git` that stays on this machine: the complement of `gitSharedV1`. */
export function gitPrivateV1(path:string):boolean{
 return (path===".git"||path.startsWith(".git/"))&&!gitSharedV1(path);
}

/** 🤝 Tells whether a worktree-relative path is shared. The root `.git` replicates regardless of the gitignore, but only the allow-list of `gitSharedV1`. A nested `.git`, an ignored path and a path the policy refuses stay local. */
export function sharedV1(path:string,isDirectory:boolean,ignore:FleetIgnoreV1):boolean{
 if(path===".git"||path.startsWith(".git/"))return gitSharedV1(path)&&refusePathV1(path)===undefined&&ignore.local?.(path)!==true;
 return !path.split("/").includes(".git")&&!ignore.ignores(path,isDirectory)&&refusePathV1(path)===undefined;
}

type Candidate={name:string;relative:string;kind:"directory"|"file"|"link"};

async function scanDirectory(worktree:string,directory:string,ignore:FleetIgnoreV1,signal:AbortSignal|undefined,entries:Pick<FleetScanEntryV1[],"push">,refused:{path:string;reason:FleetPathRefusalV1}[],listed?:(path:string,mtimeMs:number)=>void):Promise<string[]>{
 signal?.throwIfAborted();
 const absolute=directory===""?worktree:join(worktree,directory),candidates:Candidate[]=[],subdirectories:string[]=[],within=(name:string):string=>`${absolute}${sep}${name}`;
 if(listed!==undefined){const info=await lstat(absolute).catch(()=>undefined);if(info?.isDirectory()===true)listed(directory,info.mtimeMs);}
 try{
  for await(const item of await opendir(absolute)){
   signal?.throwIfAborted();
   if(item.name===".git"&&directory!=="")continue;
   const relative=directory===""?item.name:`${directory}/${item.name}`;
   const rootGit=relative===".git"||relative.startsWith(".git/");
   if(rootGit&&(gitPrivateV1(relative)||ignore.local?.(relative)===true))continue;
   let kind:Candidate["kind"]|undefined=item.isDirectory()?"directory":item.isSymbolicLink()?"link":item.isFile()?"file":undefined;
   if(kind===undefined&&!item.isSocket()&&!item.isFIFO()&&!item.isCharacterDevice()&&!item.isBlockDevice()){
    const info=await lstat(within(item.name));
    kind=info.isDirectory()?"directory":info.isSymbolicLink()?"link":info.isFile()?"file":undefined;
   }
   if(kind!==undefined&&(rootGit||!(ignore.child??ignore.ignores)(relative,kind==="directory")))candidates.push({name:item.name,relative,kind});
  }
 }catch(error){
  if(directory!==""&&overlong(error)){refused.push({path:directory,reason:"too-long"});return [];}
  if(directory!==""&&vanished(error))return [];
  throw error;
 }
 candidates.sort((left,right)=>compare(left.name,right.name));
 const seen=new Set<string>();
 for(const {name,relative,kind} of candidates){
  signal?.throwIfAborted();
  const reason=refuseLeaf(relative,name);
  if(reason){refused.push({path:relative,reason});continue;}
  const fold=foldNameV1(name);
  if(seen.has(fold)){refused.push({path:relative,reason:"case-collision"});continue;}
  seen.add(fold);
  if(kind==="directory"){subdirectories.push(relative);continue;}
  try{
   const info=await lstat(within(name));
   if(kind==="link"){
    const target=windowsSeparators(await readlink(within(name))),unsafe=linkRefusalV1(relative,target);
    if(unsafe)refused.push({path:relative,reason:unsafe});
    else entries.push({path:relative,kind:"link",bytes:info.size,mtimeMs:info.mtimeMs,executable:false,target});
   }else if(info.isFile())entries.push({path:relative,kind:"file",bytes:info.size,mtimeMs:info.mtimeMs,executable:process.platform!=="win32"&&(info.mode&0o111)!==0});
  }catch(error){
   if(overlong(error))refused.push({path:relative,reason:"too-long"});
   else if(!vanished(error))throw error;
  }
 }
 return subdirectories;
}

/** 🔍️ Walks the worktree once, depth first with bounded concurrency (the pending directories stay few), and returns every shared file and link plus every refused path, sorted; it never descends into ignored directories or a nested `.git`, it does descend into the root `.git` except for private git files, and it never follows symbolic links. With `visit` the entries are handed over one by one in discovery order and not kept (`entries` stays empty), so a caller can fold a huge tree in constant memory. A path that the operating system itself refuses as too long (`ENAMETOOLONG`, e.g. a short policy limit but a deep worktree) is listed as refused `too-long` instead of failing the walk. Rejects with the signal reason when aborted. With `listed` every scanned directory is reported with its modification time as read just before it was listed, so a later change of that time proves a change of the listing. */
export async function scanSharedV1(worktree:string,ignore:FleetIgnoreV1,signal?:AbortSignal,visit?:(entry:FleetScanEntryV1)=>void,listed?:(path:string,mtimeMs:number)=>void):Promise<FleetScanV1>{
 const entries:FleetScanEntryV1[]=[],refused:{path:string;reason:FleetPathRefusalV1}[]=[],sink=visit===undefined?entries:{push:(entry:FleetScanEntryV1)=>{visit(entry);return 0;}};
 const pending=[""],waiting:(()=>void)[]=[];
 let active=0;
 const wake=():void=>{for(const resume of waiting.splice(0))resume();};
 const worker=async():Promise<void>=>{
  for(;;){
   const directory=pending.pop();
   if(directory===undefined){
    if(active===0)return;
    await new Promise<void>(resume=>{waiting.push(resume);});
    continue;
   }
   active++;
   try{for(const child of await scanDirectory(worktree,directory,ignore,signal,sink,refused,listed))pending.push(child);}
   catch(error){pending.length=0;throw error;}
   finally{active--;wake();}
  }
 };
 await Promise.all(Array.from({length:16},worker));
 entries.sort((left,right)=>compare(left.path,right.path));
 refused.sort((left,right)=>compare(left.path,right.path)||compare(left.reason,right.reason));
 return {entries,refused};
}

type FileHash=Readonly<{sha256:string;bytes:number;stable:boolean}>;
type CheckedFileHash=Readonly<{sha256:string;bytes:number;stable:true}>|Readonly<{stable:false}>;
type HashChecks=Readonly<{signal?:AbortSignal;progress?:(done:number,total:number)=>void}>;
const hashChunkBytes=1<<20,hashIdentityBytes=8*hashChunkBytes;

async function checkedHashFile(file:string,{signal,progress}:HashChecks):Promise<CheckedFileHash>{
 signal?.throwIfAborted();
 const before=await lstat(file);
 signal?.throwIfAborted();
 if(!before.isFile())return {stable:false};
 const input=await open(file,"r"),same=(found:Stats|undefined):boolean=>found!==undefined&&found.isFile()&&found.dev===before.dev&&found.ino===before.ino&&found.size===before.size&&found.mtimeMs===before.mtimeMs&&found.ctimeMs===before.ctimeMs;
 const unchanged=async():Promise<boolean>=>{
  const named=await lstat(file).catch(error=>{if(error.code!=="ENOENT"&&error.code!=="ENOTDIR")throw error;return undefined;});
  const matched=same(named)&&same(await input.stat());
  signal?.throwIfAborted();
  return matched;
 };
 try{
  if(!await unchanged())return {stable:false};
  const hash=createHash("sha256"),buffer=Buffer.allocUnsafe(hashChunkBytes);
  let bytes=0,nextCheck=hashIdentityBytes;
  while(bytes<before.size){
   signal?.throwIfAborted();
   const {bytesRead}=await input.read(buffer,0,Math.min(buffer.length,before.size-bytes,nextCheck-bytes),null);
   signal?.throwIfAborted();
   if(bytesRead===0)return {stable:false};
   hash.update(buffer.subarray(0,bytesRead));bytes+=bytesRead;
   progress?.(bytes,before.size);
   await new Promise<void>(done=>setImmediate(done));
   signal?.throwIfAborted();
   if(bytes>=nextCheck&&bytes<before.size){
    if(!await unchanged())return {stable:false};
    nextCheck+=hashIdentityBytes;
   }
  }
  return await unchanged()?{sha256:hash.digest("hex"),bytes,stable:true}:{stable:false};
 }finally{await input.close();}
}

/** 🔐️ Streams a file through SHA-256. The default returns the digest and final stability check. Checked reads yield between chunks and return only `stable:false` when the opened file or its path changes. */
export function hashFileV1(file:string):Promise<FileHash>;
export function hashFileV1(file:string,checks:HashChecks):Promise<CheckedFileHash>;
export async function hashFileV1(file:string,checks?:HashChecks):Promise<FileHash|CheckedFileHash>{
 if(checks!==undefined)return checkedHashFile(file,checks);
 const before=await stat(file),hash=createHash("sha256");
 let bytes=0;
 for await(const chunk of createReadStream(file)){hash.update(chunk);bytes+=chunk.length;}
 const after=await stat(file);
 return {sha256:hash.digest("hex"),bytes,stable:before.size===after.size&&before.mtimeMs===after.mtimeMs&&bytes===after.size};
}

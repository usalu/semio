/** 🧪️ Independently validates the neutral source and the Repo-owned Go projection contract. */
import { strict as assert } from "node:assert";
import { readFileSync } from "node:fs";
import { join, relative } from "node:path";
import Ajv from "ajv";
import { readEntityCatalog } from "../../../../../../../🔨️modules/🧬️schema/🏷️entity-kinds/📥️source/🟦️.ts";
import { entityKindIndexByEmoji } from "../../../../../../../🔨️modules/🧬️schema/🟦️.ts";
import { emitGo, GENERATOR_ID, REFRESH_COMMAND } from "../../🏷️entity-kinds/📽️projection/🟦️.ts";
import { repoEntityKindTarget } from "../../📦️packages/🟦️typescript/📜️script.ts";

type OwnershipFixture = {
  readonly schemaVersion: 1;
  readonly contract: string;
  readonly generatorId: string;
  readonly output: string;
  readonly catalogLength: number;
  readonly emojiLength: number;
  readonly firstWins: readonly { readonly emoji: string; readonly id: string }[];
};

export function proveRepoEntityKindsOwnership(repoRoot: string): void {
  const owner = join(import.meta.dir, "..", "..");
  const fixture: unknown = JSON.parse(readFileSync(join(owner, "🧫️fixtures/🏷️entity-kinds/🔣️.json"), "utf8"));
  const ajv = new Ajv({ strict: false });
  assert(ajv.compile<OwnershipFixture>(JSON.parse(readFileSync(join(owner, "🧬️schema/🏷️entity-kinds/🔣️.json"), "utf8")))(fixture));
  const source = readEntityCatalog(repoRoot);
  const facet = JSON.parse(readFileSync(join(repoRoot, "🧰️framework/🔨️modules/🧬️schema/🔣️.json"), "utf8"));
  ajv.addSchema(facet);
  const catalogOracle = ajv.getSchema(`${facet.$id}#/$defs/EntityKindCatalog`);
  assert(catalogOracle?.(source.kinds), JSON.stringify(catalogOracle?.errors));
  assert.equal(source.kinds.length, fixture.catalogLength);
  const index = entityKindIndexByEmoji(source.kinds);
  assert.equal(index.size, fixture.emojiLength);
  for (const vector of fixture.firstWins) assert.equal(index.get(vector.emoji)?.id, vector.id);
  const target = repoEntityKindTarget(repoRoot, source);
  assert.equal(relative(repoRoot, target.path).replaceAll("\\", "/"), fixture.output);
  assert.equal(GENERATOR_ID, fixture.generatorId);
  assert.equal(readFileSync(target.path, "utf8"), target.content);
  assert.equal(target.content, emitGo(source));
  assert(target.content.includes(`@generated by \`${GENERATOR_ID}\` from \`${source.sourceRel}\` (sha256 ${source.sha256})`));
  assert(target.content.includes(REFRESH_COMMAND));
  for (const kind of source.kinds) assert(target.content.includes(`{ID: ${JSON.stringify(kind.id)}, Emoji: ${JSON.stringify(kind.emoji)}, IconID: ${JSON.stringify(kind.iconId)}, Label: ${JSON.stringify(kind.label)}, Filterable: ${kind.filterable}},`));
  const taxonomy = JSON.parse(readFileSync(join(repoRoot, "🧰️framework/🛍️products/🦑️repo/🔨️modules/📚️library/🔣️taxonomy.json"), "utf8"));
  const contracts = taxonomy.generatorContracts;
  assert(contracts, "missing generator contract collection");
  assert.deepEqual(contracts[GENERATOR_ID].outputRoots.map((output: { path: string }) => output.path), [fixture.output]);
  assert(contracts[GENERATOR_ID].inputPatterns.includes("🧰️framework/🔨️modules/🧬️schema/🏷️entity-kinds/📥️source/🟦️.ts"));
  console.log(`[DEBUG] Repo entity ownership: Ajv source, ${source.kinds.length} entries, ${index.size} FIRST-WINS emoji keys, Go byte freshness and explicit generator provenance observed`);
}

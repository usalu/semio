/** 🧬️ `schema twins`: projects every schema module's twins (TypeScript wire types and readers, Rust, protobuf, GraphQL) from its `🔣️.json`, the single source, and gates that the committed twins equal what the schemas produce.
 *
 * `generate` writes the twins (`--out <dir>` writes them into a scratch tree instead of the sources, `--only typescript,protobuf` limits the facets; the facet `json` is the layout of the schema document itself, canonical per `serializeSchema`: compact beyond `SCHEMA_INDENT_LINES`, else indented, so the JSON embedded in a crate never pushes it over the source boundary); `check` fails when a committed twin carries content the schema does not produce (`--strict` also fails on layout-only differences). A twin that carries the `🤖️ Generated by` banner belongs to another projection and is never touched.
 * @see 🧰️framework/🛍️products/🦑️repo/🔨️modules/📚️library/🎛️commands/🧬️schema/🟦️.ts
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, isAbsolute, join, relative, sep } from "node:path";
import { compare, difference, type Equivalence } from "./⚖️equivalence/🟦️.ts";
import { dialectOf } from "./🧭️dialect/🟦️.ts";
import { indexModules, leafDescriptor, loadModules, portable, serializeSchema, TWIN_FILE, type Facet, type Language, type SchemaModule } from "./🧩️model/🟦️.ts";
import { renderGraphqlTwin } from "./🔗️graphql/🟦️.ts";
import { renderProtobuf } from "./🛰️protobuf/🟦️.ts";
import { annotateRecords, annotationsFor, insertStruct, renderLeafStruct, renderRecordStruct, rustName, spliceStruct } from "./🦀️rust/🟦️.ts";
import { renderTypescript } from "./🟦️typescript/🟦️.ts";

//#region 🔖️Plans
/** 📄️ One twin the schema produces. */
export interface TwinPlan {
  readonly module: SchemaModule;
  readonly language: Facet;
  readonly path: string;
  readonly text: string;
  readonly problem?: string;
}

/** 🤖️ The marker of a twin another projection owns: the `surface-schema` banner and the `schema parsers` region. */
const FOREIGN_BANNER = /🤖️ Generated by|\/\/#region 🚪️Parsers/u;

/** 🙅️ True when any twin of a module carries a marker of another projection: that projection owns the module's twins as a whole. */
const ownedElsewhere = (module: SchemaModule): boolean => /\/(?:🎚️config|👥️presence)(?:\/|$)/u.test(module.dir.split(sep).join("/")) || module.twins.some((language) => FOREIGN_BANNER.test(readFileSync(join(module.dir, TWIN_FILE[language]), "utf8")));

const RENDERERS: Partial<Record<Language, (module: SchemaModule, index: ReadonlyMap<string, SchemaModule>, dialect: NonNullable<ReturnType<typeof dialectOf>>) => string>> = {
  typescript: renderTypescript,
  protobuf: (module, index) => renderProtobuf(module, index),
  graphql: (module, index) => renderGraphqlTwin(module, index),
};

/** 🗺️ Every twin the schemas under `scope` produce, for the languages asked. */
export function planTwins(scope: string, languages: readonly Facet[]): TwinPlan[] {
  const modules = loadModules(scope);
  const index = indexModules(modules);
  const plans: TwinPlan[] = [];
  for (const module of modules) {
    const dialect = dialectOf(module);
    if (dialect === undefined || !dialect.enabled || ownedElsewhere(module)) continue;
    if (languages.includes("json")) plans.push({ module, language: "json", path: module.jsonPath, text: serializeSchema(module.schema, readFileSync(module.jsonPath, "utf8")) });
    for (const language of module.twins) {
      const render = RENDERERS[language];
      if (render === undefined || !languages.includes(language)) continue;
      const path = join(module.dir, TWIN_FILE[language]);
      plans.push({ module, language, path, text: render(module, index, dialect) });
    }
  }
  if (languages.includes("rust")) plans.push(...planLeafStructs(modules, index), ...planRecordStructs(modules, index));
  return plans;
}

/** 🦀️ The leaf `🦀️.rs` files with their payload struct regenerated from the payload schema. */
function planLeafStructs(modules: readonly SchemaModule[], index: ReadonlyMap<string, SchemaModule>): TwinPlan[] {
  const plans: TwinPlan[] = [];
  for (const module of modules) {
    const dialect = dialectOf(module);
    if (dialect === undefined || !dialect.enabled || leafDescriptor(module) === undefined || ownedElsewhere(module)) continue;
    const path = join(dirname(module.dir), TWIN_FILE.rust);
    if (!existsSync(path)) continue;
    const generated = renderLeafStruct(module, index);
    const source = readFileSync(path, "utf8");
    const text = generated === undefined ? undefined : spliceStruct(source, String(module.schema.title), generated);
    plans.push({ module, language: "rust", path, text: text ?? source });
  }
  return plans;
}

/** 🏠️ The Rust file that holds the structs of a record module: the `🦀️.rs` beside its schema, else the one of the folder above (`🧬️schema`). */
function recordHome(module: SchemaModule): string | undefined {
  return [join(module.dir, TWIN_FILE.rust), join(dirname(module.dir), TWIN_FILE.rust)].find((path) => existsSync(path) && !FOREIGN_BANNER.test(readFileSync(path, "utf8")));
}

/** 🧱️ The `🦀️.rs` files whose record structs the schemas annotate (`x-semio-rust.derive`), each struct regenerated from its record. A file named by several modules is planned once. */
function planRecordStructs(modules: readonly SchemaModule[], index: ReadonlyMap<string, SchemaModule>): TwinPlan[] {
  const texts = new Map<string, { module: SchemaModule; text: string }>();
  const problems: TwinPlan[] = [];
  for (const module of modules) {
    const dialect = dialectOf(module);
    if (dialect === undefined || !dialect.enabled || leafDescriptor(module) !== undefined || ownedElsewhere(module)) continue;
    const path = recordHome(module);
    if (path === undefined) continue;
    const before = texts.get(path)?.text ?? readFileSync(path, "utf8");
    let text = before;
    const keys: (string | undefined)[] = [...(module.schema["x-semio-rust"]?.derive === undefined ? [] : [undefined]), ...[...module.definitions].filter(([, node]) => node["x-semio-rust"]?.derive !== undefined).map(([key]) => key)];
    let previous: string | undefined;
    try {
      for (const key of keys) {
        const generated = renderRecordStruct(module, index, key);
        if (generated === undefined) throw new Error(`[schema twins] ${module.jsonPath}: record ${key ?? "root"} is annotated for Rust but a property has no Rust type.`);
        const name = rustName(module, key);
        text = spliceStruct(text, name, generated) ?? insertStruct(text, previous, generated);
        previous = name;
      }
    } catch (error) {
      problems.push({ module, language: "rust", path, text: before, problem: (error as Error).message });
      continue;
    }
    if (keys.length > 0) texts.set(path, { module, text });
  }
  return [...[...texts].map(([path, { module, text }]) => ({ module, language: "rust" as const, path, text })), ...problems];
}

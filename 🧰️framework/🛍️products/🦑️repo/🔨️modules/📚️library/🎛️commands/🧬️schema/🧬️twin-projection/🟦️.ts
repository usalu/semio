/** 📊️ What one run found. */
export interface TwinReport {
  readonly counts: Readonly<Record<Equivalence, number>>;
  readonly byLanguage: Readonly<Record<string, Readonly<Record<Equivalence, number>>>>;
  readonly problems: readonly string[];
  readonly drifted: readonly string[];
  readonly styled: readonly string[];
  readonly written: number;
}

const LANGUAGES = [...Object.keys(TWIN_FILE), "json"] as Facet[];

/** 🔤️ Reads `<generate|check> [--under <path>] [--only a,b] [--out <dir>] [--strict]`; a mistyped flag is refused. */
export function parseTwinArguments(root: string, argv: readonly string[]): { readonly command: string; readonly scope: string; readonly languages: readonly Facet[]; readonly out?: string; readonly strict: boolean; readonly explain: boolean } {
  const command = argv[0] ?? "check";
  if (!["generate", "check", "annotate"].includes(command)) throw new Error(`[schema twins] unknown command ${JSON.stringify(command)} (expected generate | check | annotate).`);
  const value = (flag: string): string | undefined => {
    const at = argv.indexOf(flag);
    if (at < 0) return undefined;
    const found = argv[at + 1];
    if (found === undefined || found.startsWith("--")) throw new Error(`[schema twins] ${flag} requires a value.`);
    return found;
  };
  for (const token of argv.slice(1)) if (token.startsWith("--") && !["--under", "--only", "--out", "--strict", "--explain"].includes(token)) throw new Error(`[schema twins] unknown argument ${JSON.stringify(token)}.`);
  const only = value("--only")?.split(",") ?? LANGUAGES;
  for (const language of only) if (!LANGUAGES.includes(language as Facet)) throw new Error(`[schema twins] unknown language ${JSON.stringify(language)} (expected ${LANGUAGES.join(" | ")}).`);
  const under = value("--under") ?? "✏️s/🔌️plugins/📕️norm";
  const out = value("--out");
  return { command, scope: isAbsolute(under) ? under : join(root, under), languages: only as Facet[], out: out === undefined ? undefined : isAbsolute(out) ? out : join(root, out), strict: argv.includes("--strict"), explain: argv.includes("--explain") };
}

/** ▶️ Runs `generate` or `check` over the plans. Ctrl-C cancels between twins through `signal`; `progress` hears every twin done. */
export function runTwins(root: string, argv: readonly string[], signal?: AbortSignal, progress?: (done: number, total: number) => void): TwinReport {
  const options = parseTwinArguments(root, argv);
  const plans = planTwins(options.scope, options.languages);
  const counts: Record<Equivalence, number> = { identical: 0, style: 0, drift: 0 };
  const byLanguage: Record<string, Record<Equivalence, number>> = {};
  const drifted: string[] = [];
  const problems: string[] = [];
  const styled: string[] = [];
  let written = 0;
  for (const [done, plan] of plans.entries()) {
    signal?.throwIfAborted();
    progress?.(done, plans.length);
    if (plan.problem !== undefined) problems.push(plan.problem);
    const committed = readFileSync(plan.path, "utf8");
    const state = compare(plan.language, committed, plan.text);
    counts[state] += 1;
    (byLanguage[plan.language] ??= { identical: 0, style: 0, drift: 0 })[state] += 1;
    if (state === "drift") drifted.push(`${portable(root, plan.path)}${options.explain ? `\n    ${difference(plan.language, committed, plan.text)}` : ""}`);
    if (state === "style") styled.push(portable(root, plan.path));
    if (options.command === "generate" && state !== "identical") {
      const target = options.out === undefined ? plan.path : join(options.out, relative(root, plan.path));
      mkdirSync(dirname(target), { recursive: true });
      if (!existsSync(target) || readFileSync(target, "utf8") !== plan.text) writeFileSync(target, plan.text);
      written += 1;
    }
  }
  return { counts, byLanguage, problems, drifted, styled, written };
}

/** 🧾️ The report as the lines the command prints. */
export function renderTwinReport(command: string, report: TwinReport): string {
  const lines = [`[schema twins] ${command}: identical=${report.counts.identical} style=${report.counts.style} drift=${report.counts.drift}${command === "generate" ? ` written=${report.written}` : ""}`];
  for (const [language, counts] of Object.entries(report.byLanguage)) lines.push(`[schema twins]   ${language}: identical=${counts.identical} style=${counts.style} drift=${counts.drift}`);
  for (const problem of report.problems) lines.push(`[schema twins] problem ${problem}`);
  for (const path of report.drifted.slice(0, 40)) lines.push(`[schema twins] drift ${path}`);
  for (const path of report.styled.slice(0, 40)) lines.push(`[schema twins] style ${path}`);
  return `${lines.join("\n")}\n`;
}

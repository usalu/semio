//#region 🔖️Annotations
/** 🏷️ Writes the `x-semio-rust` annotations that make every leaf payload's derived struct equal its committed struct, so the JSON Schema carries what the Rust twin states and the generator can reproduce it. Returns the schema files it changed. */
export function annotateLeaves(scope: string): string[] {
  const changed: string[] = [];
  const modules = loadModules(scope);
  const index = indexModules(modules);
  const claimed = new Set<string>();
  for (const module of modules) {
    const dialect = dialectOf(module);
    if (dialect === undefined || !dialect.enabled || leafDescriptor(module) !== undefined || ownedElsewhere(module)) continue;
    const path = recordHome(module);
    if (path === undefined) continue;
    const records = annotateRecords(module, index, readFileSync(path, "utf8"), claimed).filter(({ key, node }) => JSON.stringify(key === undefined ? module.schema : module.definitions.get(key)) !== JSON.stringify(node));
    if (records.length === 0) continue;
    const original = readFileSync(module.jsonPath, "utf8");
    const document = JSON.parse(original);
    for (const { key, node } of records) {
      if (key === undefined) Object.assign(document, node);
      else (document.$defs ?? document.definitions)[key] = node;
    }
    const next = serializeSchema(document, original);
    if (next === original) continue;
    writeFileSync(module.jsonPath, next);
    changed.push(module.jsonPath);
  }
  for (const module of modules) {
    const dialect = dialectOf(module);
    if (dialect === undefined || !dialect.enabled || leafDescriptor(module) === undefined) continue;
    const path = join(dirname(module.dir), TWIN_FILE.rust);
    if (!existsSync(path)) continue;
    const notes = annotationsFor(module, index, readFileSync(path, "utf8"));
    if (notes === undefined || notes.size === 0) continue;
    const document = JSON.parse(readFileSync(module.jsonPath, "utf8"));
    for (const [key, note] of notes) document.properties[key]["x-semio-rust"] = { ...document.properties[key]["x-semio-rust"], ...note };
    const original = readFileSync(module.jsonPath, "utf8");
    const next = serializeSchema(document, original);
    if (next === original) continue;
    writeFileSync(module.jsonPath, next);
    changed.push(module.jsonPath);
  }
  return changed;
}

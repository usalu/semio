"""🚦️ Independent Python oracle of the width of a build's real actions: a born action starts only while fewer actions run than the jobs the run's grant holds now (no grant: no bound; an idle build always starts one); waiters start first come first served when an action leaves or a recheck finds more jobs; a waiter whose connection closes or whose signal aborts is refused. Writes `../🧫️fixtures/🔣️.json` (seeded traces with the state after every event); `--check` exits 1 when the stored fixture differs.
usage: python3 -I 🐍️.py [--check]"""
import json, os, random, sys

HERE = os.path.dirname(os.path.abspath(__file__))
TARGET = os.path.join(HERE, "..", "🧫️fixtures", "🔣️.json")


def replay(events):
    running, queue, refused, jobs, rows = set(), [], [], None, []
    def recheck():
        while queue:
            if jobs is not None and running and len(running) >= jobs: break
            running.add(queue.pop(0))
    for event in events:
        kind, value = event["event"], event.get("value")
        if kind == "enter": queue.append(value); recheck()
        elif kind == "leave":
            if value in running: running.discard(value); recheck()
            elif value in queue: queue.remove(value); recheck(); refused.append(value)
        elif kind == "abort":
            if value in queue: queue.remove(value); recheck(); refused.append(value)
        elif kind == "jobs": jobs = value
        elif kind == "recheck": recheck()
        rows.append({**event, "jobsNow": jobs, "expect": {"running": sorted(running), "waiting": sorted(queue), "refused": sorted(refused)}})
    return rows


def generate():
    rng = random.Random(1827); traces = []
    for index in range(100):
        keys, entered, events = ["a%d" % n for n in range(10)], set(), [{"event": "jobs", "value": rng.choice([None, 0, 1, 2, 3, 5, 8])}]
        for _ in range(rng.choice([12, 24, 36])):
            roll = rng.random()
            if roll < 0.4 and len(entered) < len(keys):
                key = rng.choice([k for k in keys if k not in entered]); entered.add(key); events.append({"event": "enter", "value": key})
            elif roll < 0.62 and entered: events.append({"event": "leave", "value": rng.choice(sorted(entered))})
            elif roll < 0.7 and entered: events.append({"event": "abort", "value": rng.choice(sorted(entered))})
            elif roll < 0.85: events.append({"event": "jobs", "value": rng.choice([None, 0, 1, 2, 3, 5, 8])})
            else: events.append({"event": "recheck"})
        traces.append({"name": "trace-%d" % index, "events": replay(events)})
    rows = [row for trace in traces for row in trace["events"]]
    def started_later(trace):
        seen, count = set(), 0
        for row in trace["events"]:
            for key in row["expect"]["running"]:
                if key not in seen and any(key in other["expect"]["waiting"] for other in trace["events"]): count += 1
                seen.add(key)
        return count
    coverage = {"waitedThenStarted": sum(started_later(trace) for trace in traces), "refusedByLeave": sum(1 for trace in traces for a, b in zip(trace["events"], trace["events"][1:]) if b["event"] == "leave" and b["value"] in a["expect"]["waiting"]), "refusedByAbort": sum(1 for trace in traces for a, b in zip(trace["events"], trace["events"][1:]) if b["event"] == "abort" and b["value"] in a["expect"]["waiting"]), "idleStartsOne": sum(1 for trace in traces for a, b in zip(trace["events"], trace["events"][1:]) if b["event"] == "enter" and not a["expect"]["running"] and b["expect"]["running"]), "unboundedWide": sum(1 for row in rows if row["jobsNow"] is None and len(row["expect"]["running"]) >= 4)}
    return {"version": 1, "about": "Generated by 🐍️oracle/🐍️.py; do not edit.", "traces": traces, "coverage": coverage}


if __name__ == "__main__":
    text = json.dumps(generate(), ensure_ascii=False, separators=(",", ":")) + "\n"
    if "--check" in sys.argv:
        same = open(TARGET, encoding="utf8").read() == text
        print("vectors equal the oracle" if same else "FIXTURE DIFFERS FROM THE ORACLE"); sys.exit(0 if same else 1)
    open(TARGET, "w", encoding="utf8").write(text); print("written", json.loads(text)["coverage"])

/** 🔀️ Contract: the promotion protocol is atomic under concurrent promoters and crashes. The language-agnostic corpus (`./🔣️.json`: schedules of advance, edit and crash tokens over up to three processes) is generated by an independent Python model (`./🐍️.py`) that knows only the protocol; the real TypeScript implementation (real files, real SQLite lock, real capture of a fixture tool) is driven gate by gate through the same schedules and must reach exactly the observables the model predicts. The model also checks its laws exhaustively over every interleaving of small configurations and fails when any of three mutations is applied (negative controls). */
import{afterAll,expect,test}from"bun:test";
import{spawnSync}from"node:child_process";
import{existsSync,readFileSync,rmSync}from"node:fs";
import{fileURLToPath}from"node:url";
import{Database}from"bun:sqlite";
import Ajv from"ajv";
import{requireTestToolV1}from"../../../../../../../../🔨️modules/🏃️process/🧪️testing/🧰️toolchain/🟦️.ts";
import corpus from"./🔣️.json";
import corpusSchema from"./🧬️schema/🔣️.json";
import{readSealedBlockedV1,readSealedPointerV1,readSealedSnapshotV1,sealedEntryOfV1}from"../../🟦️.ts";
import{resolveSealedImplementationV1,type SealedResolutionV1}from"../../📤️promotion/🟦️.ts";
import{fixtureCaptureV1,fixtureEntryV1,labelContentV1,labelOfTextV1,makeFixtureWorkspaceV1,setFixtureTreeV1,testPolicyV1}from"../🧫️fixtures/🟦️.ts";

const model=fileURLToPath(new URL("./🐍️.py",import.meta.url)),python=()=>requireTestToolV1("python"),roots:string[]=[];
afterAll(()=>{for(const root of roots)rmSync(root,{recursive:true,force:true});});
type Case=(typeof corpus.cases)[number];
class Crash extends Error{}

interface Runner{promise:Promise<unknown>;release:()=>void;reject:()=>void;arrived:Promise<void>|undefined;onArrive:(()=>void)|undefined;done:boolean;crashed:boolean;result:{status:string;label:string|null}|null}

async function replay(item:Case):Promise<unknown>{
 const root=makeFixtureWorkspaceV1(item.initial.current??item.initial.tree);roots.push(root);
 const entry=sealedEntryOfV1(root,fixtureEntryV1,testPolicyV1),captures:Record<string,number>={},load=async(text:string)=>labelOfTextV1(text)==="X"?{ok:false as const,rows:[{path:"tool/helper.ts",line:1,column:1,message:"export v not found"}]}:{ok:true as const,milliseconds:0};
 const labelNow=()=>Object.entries(labelContentV1).find(([,body])=>body===readFileSync(`${root}/tool/helper.ts`,"utf8"))![0];
 const capture=fixtureCaptureV1(root,fixtureEntryV1,()=>{const label=labelNow();captures[label]=(captures[label]??0)+1;});
 if(item.initial.current){await resolveSealedImplementationV1(root,entry,{capture,policy:testPolicyV1});for(const key of Object.keys(captures))delete captures[key];}
 setFixtureTreeV1(root,item.initial.tree);
 const runners:Runner[]=[];
 for(let index=0;index<item.processes;index++){
  const runner:Runner={promise:Promise.resolve(),release:()=>{},reject:()=>{},arrived:undefined,onArrive:undefined,done:false,crashed:false,result:null},first=new Promise<void>(accept=>{runner.onArrive=accept;});
  const gate=():Promise<void>=>new Promise<void>((accept,fail)=>{runner.release=accept;runner.reject=()=>fail(new Crash("crash"));runner.onArrive?.();});
  runner.promise=resolveSealedImplementationV1(root,entry,{capture,load,policy:testPolicyV1,step:gate}).then((value:SealedResolutionV1)=>{runner.result={status:value.status,label:labelOfTextV1(value.text)??null};},error=>{if(error instanceof Crash)runner.crashed=true;else if((error as{code?:string}).code==="SEMIO_IMPLEMENTATION_NONE")runner.result={status:"none",label:null};else throw error;}).finally(()=>{runner.done=true;runner.onArrive?.();});
  runners.push(runner);
  await first;
 }
 const advance=async(runner:Runner,crash=false)=>{
  if(runner.done)return;
  const arrived=new Promise<void>(accept=>{runner.onArrive=accept;});
  if(crash)runner.reject();else runner.release();
  await arrived;
 };
 for(const token of item.tokens as unknown as[string,string|number][]){
  if(token[0]==="p")await advance(runners[token[1] as number]!);
  else if(token[0]==="crash")await advance(runners[token[1] as number]!,true);
  else setFixtureTreeV1(root,token[1] as string);
 }
 let turn=0;
 for(;;){
  const alive=runners.filter(runner=>!runner.done);if(!alive.length)break;
  await advance(alive[turn%alive.length]!);turn++;
 }
 await Promise.all(runners.map(runner=>runner.promise));
 const pointer=readSealedPointerV1(entry),current=pointer?labelOfTextV1(readSealedSnapshotV1(entry,pointer)!)??null:null,blocked=readSealedBlockedV1(entry)?"X":null;
 let lockFree=!existsSync(entry.lock);if(!lockFree){const database=new Database(entry.lock);try{database.exec("PRAGMA busy_timeout=0");database.exec("BEGIN EXCLUSIVE");database.exec("ROLLBACK");lockFree=true;}catch{}finally{database.close();}}
 return{current,blocked,captures:Object.fromEntries(Object.entries(captures).sort(([a],[b])=>a<b?-1:1)),results:runners.map(runner=>runner.crashed?null:runner.result),lockFree};
}

test("the corpus is closed by its schema and equals what the independent Python model predicts",()=>{
 const ajv=new Ajv({strict:false}),validate=ajv.compile(corpusSchema);
 expect(validate(corpus),JSON.stringify(validate.errors)).toBe(true);
 expect(validate({...corpus,extra:1})).toBe(false);
 const run=spawnSync(python(),["-I",model,"expected",fileURLToPath(new URL("./🔣️.json",import.meta.url))],{encoding:"utf8"});
 expect(run.status,run.stderr).toBe(0);
 expect(JSON.parse(run.stdout)).toEqual(corpus.cases.map(item=>item.expected));
 const seen=new Set(corpus.cases.flatMap(item=>item.expected.results.map(result=>result?.status??"crashed")));
 for(const status of["promoted","fresh","served","blocked","none","refreshed","crashed"])expect(seen.has(status),status).toBe(true);
});

test("the model's laws hold over every interleaving, and each negative control breaks one",()=>{
 const ok=spawnSync(python(),["-I",model,"explore","quick"],{encoding:"utf8"});
 expect(ok.status,ok.stderr+ok.stdout).toBe(0);
 for(const mutation of["skip-validate","skip-reread","no-lock"]){
  const broken=spawnSync(python(),["-I",model,"explore","quick"],{encoding:"utf8",env:{...process.env,SEALED_MODEL_MUTATION:mutation}});
  expect(broken.status,mutation).not.toBe(0);
  expect(broken.stderr+broken.stdout).toContain("LAW BROKEN");
 }
},120_000);

test("the real implementation reaches the observables of the model on every scheduled interleaving",async()=>{
 expect(existsSync(model)).toBe(true);
 for(const item of corpus.cases.slice(0,Number(process.env.SEALED_INTERLEAVINGS??160)))expect(await replay(item),item.id+" "+JSON.stringify(item.tokens)).toEqual(item.expected);
},600_000);

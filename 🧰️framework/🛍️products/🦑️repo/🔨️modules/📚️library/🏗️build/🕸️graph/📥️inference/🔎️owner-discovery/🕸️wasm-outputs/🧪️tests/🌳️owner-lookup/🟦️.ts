import{expect,test}from"bun:test";
import{Database}from"bun:sqlite";
import{existsSync,readFileSync}from"node:fs";
import{join,resolve,sep}from"node:path";
import{findWorkspaceRoot}from"@semio-tech/process/routing";
import{wasmCompileOutputIndexV1,type WasmCompileOwnerV1}from"../../🟦️.ts";

const workspace=findWorkspaceRoot(import.meta.dir),registry=JSON.parse(readFileSync(join(workspace,"📋️build-owners.json"),"utf8")).owners as WasmCompileOwnerV1[];
const read=(path:string)=>{if(/\.(?:[cm]?js|d\.[cm]?ts)$/u.test(path))throw Error("Generated bytes must not be read");return existsSync(path)?readFileSync(path,"utf8"):undefined;};

test("over the whole owner registry every indexed output lies below no owner root or below its producer's as the deepest one, as an independent SQLite prefix query finds it",()=>{
 const index=wasmCompileOutputIndexV1(workspace,registry,read),db=new Database(":memory:");
 try{
  db.run("create table owners(at integer primary key,name text,root text)");
  const insert=db.prepare("insert into owners(at,name,root) values (?1,?2,?3)");
  registry.forEach((owner,at)=>{if(owner.root!==".")insert.run(at,owner.name,resolve(workspace,owner.root));});
  const deepest=db.prepare("select name from owners where ?1=root or substr(?1,1,length(root)+1)=root||?2 order by length(root) desc,at asc limit 1");
  const paths=[...index.outputs.keys()].filter(key=>key.startsWith(workspace+sep));
  expect(paths.length).toBeGreaterThan(0);
  const found=paths.map(path=>[(deepest.get(path,sep) as {name:string}|null)?.name,index.outputs.get(path)!.project]);
  for(const[name,project]of found)expect(name===undefined||name===project,`${name} ${project}`).toBe(true);
  expect(found.filter(([name])=>name!==undefined).length).toBeGreaterThan(0);
 }finally{db.close();}
});

test("an output under another owner's deeper root is refused as foreign, however many owners the registry holds",()=>{
 const index=wasmCompileOutputIndexV1(workspace,registry,read),[path,row]=[...index.outputs].find(([key])=>key.startsWith(workspace+sep))!,owner=registry.find(each=>each.name===row.project)!;
 const nested=resolve(workspace,row.output,".."),intruder={name:"@semio-tech/intruder",root:nested.slice(workspace.length+1),manifest:nested.slice(workspace.length+1)+"/📋️project.json"};
 expect(resolve(workspace,owner.root).length).toBeLessThan(nested.length);
 expect(()=>wasmCompileOutputIndexV1(workspace,[...registry,intruder],read)).toThrow("foreign owner");
 expect(path.startsWith(nested+sep)).toBe(true);
});

/** 🔖️ The one authority for the app-engine channel wire version.
 *
 * `🧫️fixtures/📡️channel/🔖️channel-version.json` owns the number. Every other place that states it — the Rust
 * `CHANNEL_VERSION`, the TS twins, the JSON Schema `const`s of the descriptor/execution-protocol contracts and the fixtures
 * that carry an execution protocol — is a registered CONSUMER below, written from the pin by `generate` and held to it by
 * `check` and the law in `🧪️tests/🔖️channel-version/🟦️.ts`. A version literal anywhere else in the repository is a
 * hand-written copy and fails the census: the 17 → 18 bump of 2026-09-27 moved the Rust constant and the pin but left the
 * directory schema, its TS twin, the hub inference schema and a dozen fixtures at 17 (and three contracts still at 15), so a
 * rebuilt browser would have refused every plan.
 *
 * A consumer declares how many version literals it holds (`occurrences`), which of them are deliberate foreign values
 * (`hostileValues`, e.g. a law's "wrong protocol" row), whether it is `arbitrary` (a codec round trip or a synthetic source
 * text whose value means nothing), whether it is `guest`-linked (rewritten only with `--guest`, inside a landing window) and
 * whether values derived from the version live beside it (`derived`: the generator refuses to rewrite such a fixture and
 * names what its owner must recompute). Plugin descriptors (`<plugin>/🔣️.json`, `🛂️.descriptor.semio`) are describe
 * OUTPUTS of the Rust constant and are regenerated by describe, not by this authority. The census reads the source files
 * under the roots of the registered consumers ([`CHANNEL_VERSION_CENSUS_ROOTS`]).
 */

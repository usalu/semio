/** 🧮️ One version literal found in a file: its byte offset and value. */
export type ChannelVersionLiteralV1 = Readonly<{ index: number; length: number; valueStart: number; value: number; encoded?: true }>;

/** 🔎️ Every version literal in `text`, in file order, with the exact span of its number. */
export function channelVersionLiterals(text: string): readonly ChannelVersionLiteralV1[] {
  const found: ChannelVersionLiteralV1[] = [];
  for (const pattern of CHANNEL_VERSION_LITERAL_PATTERNS) {
    for (const match of text.matchAll(new RegExp(pattern.source, pattern.flags))) {
      const number = match[1] ?? "";
      found.push({ index: match.index, length: match[0].length, valueStart: match.index + match[0].length - number.length, value: Number(number) });
    }
  }
  for (const match of text.matchAll(new RegExp(CHANNEL_VERSION_PACK_HEX_PATTERN.source, CHANNEL_VERSION_PACK_HEX_PATTERN.flags))) {
    const bytes = match[1] ?? "";
    found.push({ index: match.index, length: match[0].length, valueStart: match.index + match[0].length - bytes.length, value: Buffer.from(bytes, "hex").readDoubleLE(0), encoded: true });
  }
  return found.sort((left, right) => left.valueStart - right.valueStart).filter((literal, position, all) => position === 0 || all[position - 1]!.valueStart !== literal.valueStart);
}

/** 📦️ Plugin descriptors are describe outputs of the Rust constant, never hand-written. */
function isDescribeOutput(path: string): boolean {
  return /^✏️s\/🔌️plugins\/[^/]+\/(?:🧩️extensions\/[^/]+\/)?(?:🔣️\.json|🛂️\.descriptor\.semio)$/u.test(path);
}

/** 🗺️ The roots the census reads: the top-level directory of the pin and of every registered consumer — the version is
 * stated where its consumers live (plugin descriptors under `✏️s` are describe outputs), so registering a consumer in a new
 * root widens the census with it. Reading the whole repository (3 GB of research data and every plugin's assets) took
 * ~50 s under load and outran the law's time budget; these roots take ~6 s. */
export const CHANNEL_VERSION_CENSUS_ROOTS: readonly string[] = [...new Set([CHANNEL_VERSION_PIN_PATH, ...CHANNEL_VERSION_CONSUMERS.map((consumer) => consumer.path)].map((path) => path.split("/")[0]!))].sort();

/** 📄️ The source files a version literal is written in: Rust, TypeScript and JSON. */
export const CHANNEL_VERSION_CENSUS_EXTENSIONS: readonly string[] = ["rs", "ts", "tsx", "mts", "json", "jsonc"];

/** 🗂️ Every tracked or untracked (not ignored) source file under the census roots that could state the version, outside
 * describe outputs. */
export function channelVersionCandidateFiles(repoRoot: string): readonly string[] {
  const pathspecs = CHANNEL_VERSION_CENSUS_ROOTS.flatMap((root) => CHANNEL_VERSION_CENSUS_EXTENSIONS.map((extension) => `:(glob)${root}/**/*.${extension}`));
  const listed = spawnSync("git", ["-c", "core.quotePath=false", "grep", "-l", "-z", "--untracked", "-E", "appChannelVersion|CHANNEL_VERSION|app_channel_version|6170704368616e6e656c56657273696f6e", "--", ...pathspecs], { cwd: repoRoot, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 });
  if (listed.status !== 0 && listed.status !== 1) throw new Error(`channel-version census: git grep failed (${listed.status}): ${listed.stderr}`);
  return listed.stdout.split("\0").filter((path) => path.length > 0 && !isDescribeOutput(path) && path !== CHANNEL_VERSION_PIN_PATH && !path.startsWith(`${MOD}/🧑‍💻dev/🔖️channel-version/`) && !path.startsWith(`${MOD}/🧑‍💻dev/🧪️tests/🔖️channel-version/`));
}

/** 📌️ The version the pin owns. */
export function pinnedChannelVersion(repoRoot: string): number {
  const pin = JSON.parse(readFileSync(join(repoRoot, CHANNEL_VERSION_PIN_PATH), "utf8")) as { channelVersion?: unknown };
  if (!Number.isInteger(pin.channelVersion) || (pin.channelVersion as number) < 1) throw new Error(`${CHANNEL_VERSION_PIN_PATH} carries no positive integer channelVersion`);
  return pin.channelVersion as number;
}

/** 🧾️ One census finding: a file that states the version where it must not, or states it wrongly. */
export type ChannelVersionFindingV1 = Readonly<{ path: string; problem: "unregistered" | "missing" | "occurrences" | "drift"; detail: string }>;

/** 🔎️ The census: every candidate file is a registered consumer, holds exactly its declared literals, and every literal that
 * is not a declared hostile value (or arbitrary) equals the pin. */
export function channelVersionCensus(repoRoot: string): Readonly<{ pin: number; findings: readonly ChannelVersionFindingV1[] }> {
  const pin = pinnedChannelVersion(repoRoot);
  const findings: ChannelVersionFindingV1[] = [];
  const registered = new Map(CHANNEL_VERSION_CONSUMERS.map((consumer) => [consumer.path, consumer]));
  for (const path of channelVersionCandidateFiles(repoRoot)) {
    const literals = channelVersionLiterals(readFileSync(join(repoRoot, path), "utf8"));
    if (literals.length > 0 && !registered.has(path)) findings.push({ path, problem: "unregistered", detail: `${literals.length} hand-written version literal(s): ${literals.map((literal) => literal.value).join(", ")}` });
  }
  for (const consumer of CHANNEL_VERSION_CONSUMERS) {
    let text: string;
    try {
      text = readFileSync(join(repoRoot, consumer.path), "utf8");
    } catch {
      findings.push({ path: consumer.path, problem: "missing", detail: "a registered consumer no longer exists" });
      continue;
    }
    const literals = channelVersionLiterals(text);
    if (literals.length !== consumer.occurrences) findings.push({ path: consumer.path, problem: "occurrences", detail: `declares ${consumer.occurrences} version literal(s), holds ${literals.length}` });
    if (consumer.arbitrary) continue;
    const drifted = literals.filter((literal) => literal.value !== pin && !(consumer.hostileValues ?? []).includes(literal.value));
    if (drifted.length > 0) findings.push({ path: consumer.path, problem: "drift", detail: `${drifted.length} literal(s) at ${[...new Set(drifted.map((literal) => literal.value))].join(", ")}, the pin is ${pin}${consumer.derived ? `; derived values to recompute by the owner: ${consumer.derived}` : ""}` });
  }
  return { pin, findings };
}

/** ✍️ Writes the pin into every drifted literal of every consumer the caller may rewrite: never an arbitrary or hostile
 * literal, a guest-linked consumer only with `guest`, and never a consumer with derived values (those are reported). */
export function writeChannelVersionConsumers(repoRoot: string, options: Readonly<{ guest: boolean }>): Readonly<{ written: readonly string[]; refused: readonly string[] }> {
  const pin = pinnedChannelVersion(repoRoot);
  const written: string[] = [];
  const refused: string[] = [];
  for (const consumer of CHANNEL_VERSION_CONSUMERS) {
    if (consumer.arbitrary) continue;
    const path = join(repoRoot, consumer.path);
    const text = readFileSync(path, "utf8");
    const drifted = channelVersionLiterals(text).filter((literal) => literal.value !== pin && !(consumer.hostileValues ?? []).includes(literal.value));
    if (drifted.length === 0) continue;
    if (consumer.derived || drifted.some((literal) => literal.encoded) || (consumer.guest && !options.guest)) {
      refused.push(`${consumer.path}: ${consumer.derived ? `derived values (${consumer.derived}) must be recomputed by its owner` : drifted.some((literal) => literal.encoded) ? "Pack-encoded versions must be re-derived by its owner" : "guest-linked, rewrite inside a landing window with --guest"}`);
      continue;
    }
    let next = text;
    for (const literal of [...drifted].reverse()) {
      const digits = String(literal.value).length;
      next = `${next.slice(0, literal.valueStart)}${pin}${next.slice(literal.valueStart + digits)}`;
    }
    writeFileSync(path, next);
    written.push(consumer.path);
  }
  return { written, refused };
}

/** 🔖️ `channel-version <generate [--guest]|check>` — the generator and the census of the one channel version authority. */
export class ChannelVersionScript extends BundleScript {
  async run(segments: string[]): Promise<void> {
    const [verb, ...rest] = segments;
    const repoRoot = getWorkspaceRoot();
    if (verb === "generate") {
      const { written, refused } = writeChannelVersionConsumers(repoRoot, { guest: rest.includes("--guest") });
      for (const path of written) console.log(`[channel-version] wrote ${path}`);
      for (const line of refused) console.error(`[channel-version] refused ${line}`);
    } else if (verb !== "check") {
      throw new Error("usage: channel-version <generate [--guest]|check>");
    }
    const { pin, findings } = channelVersionCensus(repoRoot);
    for (const finding of findings) console.error(`[channel-version] ${finding.problem} ${finding.path}: ${finding.detail}`);
    console.log(`[channel-version] pin ${pin}: ${CHANNEL_VERSION_CONSUMERS.length} registered consumers, ${findings.length} finding(s)`);
    if (findings.length > 0) process.exitCode = 1;
  }
}

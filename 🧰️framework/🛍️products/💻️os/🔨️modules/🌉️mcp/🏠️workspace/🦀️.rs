/// 🧾️ The guest's own reason for refusing a command's ingress, read off the turn that reported it.
/// The reactor mints these two ways — a real `Fault` encoded through `dsl::encode_fault_bytes`, and
/// a handful of bare ASCII codes for the structural refusals (`plugin.command-page-invalid`,
/// `plugin.command-cancelled-by-close`, …) — so both are decoded, in that order, and neither is
/// ever silently dropped.
#[cfg(not(target_arch = "wasm32"))]
fn ingress_fault_text(status: &semio_framework::kernel::CommandIngressStatus) -> String {
    let semio_framework::kernel::CommandIngressStatus::Fault { fault, .. } = status else {
        return format!("the driver reported a fault while the guest reported {status:?}");
    };
    if let Ok(text) = std::str::from_utf8(fault) {
        if !text.is_empty() && text.chars().all(|character| character.is_ascii_graphic() || character == ' ') {
            return text.to_string();
        }
    }
    let decoded = decode_guest_fault(fault);
    format!("{}: {}", decoded.code, decoded.message)
}

/// 📨️ The `AppFrame` bytes one `Shell{instance}` send-message carries, or `None` when the effect is
/// not an app-frame message addressed at this instance. The endpoint carries three languages — a
/// command's answer and an interactive job's result page/ack — so the two job languages are told
/// apart by their own magic prefix rather than by a failed decode.
#[cfg(not(target_arch = "wasm32"))]
fn shell_app_frame_payload(instance: u32, effect: &semio_framework::kernel::Effect) -> Option<&[u8]> {
    let semio_framework::kernel::Effect::SendMessage { target: semio_framework::kernel::MessageEndpoint::Shell { instance: addressed }, payload } = effect else {
        return None;
    };
    if addressed.0 != instance.to_string() || payload.starts_with(TYPED_OPERATION_PAGE_MAGIC) || payload.starts_with(TYPED_OPERATION_ACK_MAGIC) {
        return None;
    }
    Some(payload.as_slice())
}

/// 🧵️ One effect's document-backbone payload, when it is one addressed at `actor_label` — the guest's
/// own `BackboneMessage::Mutations` bytes on their way to the document actor. The uri check is the
/// same ownership fence `route_document_backbone_effects` applies in the wgpu shell: a guest that
/// addresses another actor's backbone is publishing into a document this channel does not own, and
/// its bytes must not be relayed as if it did.
#[cfg(not(target_arch = "wasm32"))]
fn document_backbone_payload<'a>(actor_label: &str, effect: &'a semio_framework::kernel::Effect) -> Option<&'a [u8]> {
    let semio_framework::kernel::Effect::SendMessage { target: semio_framework::kernel::MessageEndpoint::Backbone { uri }, payload } = effect else {
        return None;
    };
    (uri == actor_label).then(|| payload.as_slice())
}

/// 🧾️ One effect named by SHAPE, never by payload — what a fault says the guest published instead
/// of the answer it owed. A shell message is named with the instance it addresses, because
/// "addressed at another instance" and "addressed at this one but unreadable" are different defects
/// and a fault that collapses them costs the next reader the measurement all over again.
#[cfg(not(target_arch = "wasm32"))]
fn effect_shape(instance: u32, effect: &semio_framework::kernel::Effect) -> String {
    match effect {
        semio_framework::kernel::Effect::SendMessage { target: semio_framework::kernel::MessageEndpoint::Shell { instance: addressed }, payload } => {
            let lane = if payload.starts_with(TYPED_OPERATION_PAGE_MAGIC) {
                "typed-operation-page".to_string()
            } else if payload.starts_with(TYPED_OPERATION_ACK_MAGIC) {
                "typed-operation-ack".to_string()
            } else {
                match semio_framework::io::resolve_ready(store::decode_app_frame(payload)) {
                    Ok(frame) => match app_frame_reply_seq(&frame) {
                        Some(reply) => format!("{}(in_reply_to {reply})", app_frame_tag(&frame)),
                        None => format!("{}(unsolicited)", app_frame_tag(&frame)),
                    },
                    Err(error) => format!("undecodable app-frame ({error})"),
                }
            };
            let mine = addressed.0 == instance.to_string();
            format!("sendMessage(shell:{}{}, {lane}, {} B)", addressed.0, if mine { "" } else { " — NOT this instance" }, payload.len())
        }
        semio_framework::kernel::Effect::SendMessage { target, .. } => format!("sendMessage({target:?})"),
        semio_framework::kernel::Effect::Respond { req, .. } => format!("respond(req {})", req.0),
        semio_framework::kernel::Effect::PublishEvent { topic, .. } => format!("publishEvent({topic})"),
        other => format!("{}", EffectTag(other)),
    }
}

/// 🧾️ A `Debug` rendering cut at its variant name — the payload of an effect is a guest's bytes and
/// has no place in an agent-facing fault.
#[cfg(not(target_arch = "wasm32"))]
struct EffectTag<'a>(&'a semio_framework::kernel::Effect);

#[cfg(not(target_arch = "wasm32"))]
impl std::fmt::Display for EffectTag<'_> {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        let rendered = format!("{:?}", self.0);
        let head: String = rendered.chars().take_while(|character| character.is_alphanumeric()).collect();
        formatter.write_str(if head.is_empty() { "effect" } else { &head })
    }
}

/// 🧾️ The shapes above, joined — or an explicit "nothing", because an empty list in a fault message
/// reads as a truncation rather than as a measurement.
#[cfg(not(target_arch = "wasm32"))]
fn named_shapes(shapes: &[String]) -> String {
    if shapes.is_empty() {
        "no effects at all".to_string()
    } else {
        shapes.join(", ")
    }
}

/// 📨️ The two non-`AppFrame` languages that ride the SAME `Shell{instance}` endpoint
/// (`🔌️plugin/🦀️.rs`'s `TypedOperationResultPage::{RENDERER_PAGE_MAGIC, RENDERER_ACK_MAGIC}`), so a
/// reader of this endpoint tells a command's answer from an interactive job's result page by prefix
/// rather than by a failed decode. Two banks, one literal: the renderer's own copy is
/// `🎭️actor/🖼️wire-turn/🟦️.ts`'s `TYPED_OPERATION_PAGE_MAGIC`/`TYPED_OPERATION_ACK_MAGIC`. This crate
/// does not depend on `🔌️plugin` (see its Cargo.toml), which is why the bytes are restated here.
#[cfg(not(target_arch = "wasm32"))]
const TYPED_OPERATION_PAGE_MAGIC: &[u8] = b"semio.typed-operation-page.v1\0";
#[cfg(not(target_arch = "wasm32"))]
const TYPED_OPERATION_ACK_MAGIC: &[u8] = b"semio.typed-operation-ack.v1\0";

/// 🔁️ What one `exchange_one_turn` produced: the command's terminal frame, or an honest "this
/// command owes another turn". Keeping these apart from `Fault` is what lets the loop above bound
/// the NUMBER of turns without having to read a fault's code to decide whether to continue.
#[cfg(not(target_arch = "wasm32"))]
enum CommandTurn {
    Settled(store::AppFrame),
    MoreWork,
}

/// 🛂️ Whether this process may submit a command envelope into a guest's paged ingress at all — the
/// same predicate `📺️renderer/…/🧊️wgpu/🧊️renderer` (the live, shipping consumer of the identical
/// `CommandBatchDriver`/`FixedCommandPage` machinery) asks over the identical kernel constants:
/// there must be at least one page, and one whole page must fit inside a command's total byte
/// budget. A hardcoded `false` here made EVERY `AppCommand` this gateway ever built answer
/// `AppCommand not wired` before it reached a guest, which is why no `action_prepare`/`action_invoke`
/// from a real MCP client could ever reach a plugin (ticket 26/09/18 slice A1).
#[cfg(not(target_arch = "wasm32"))]
fn persistent_command_completion_port_ready() -> bool {
    semio_framework::kernel::COMMAND_MAXIMUM_PAGES != 0 && semio_framework::kernel::COMMAND_MAXIMUM_BYTES >= semio_framework::kernel::COMMAND_PAGE_MAXIMUM_BYTES
}

/// 🧯️ Best-effort decode of a real guest `AppFrame::Error`/`TransactionPrepared.rejection` fault
/// blob into this port's own `Fault{code,message}` — the wire's real fault type
/// (`🔌️plugin::Fault`, wrapping `FaultOrigin`/`FaultCode`) is private to that crate (not reachable
/// from here), so this decodes the SAME `store::pack_rt`/`DslValue` wire envelope every real fault
/// travels over generically, as a `DslValue`, and reads `code`/`message` defensively —
/// never panics, never invents a code the guest did not send.
#[cfg(not(target_arch = "wasm32"))]
fn decode_guest_fault(bytes: &[u8]) -> Fault {
    let decoded = store::pack_rt::decode_wire_value(bytes).ok();
    match decoded {
        Some(value) => {
            let code = value.get("code").and_then(store::DslValue::as_str).unwrap_or("mutation.rejected").to_string();
            let message = value.get("message").and_then(store::DslValue::as_str).map(str::to_string).unwrap_or_else(|| store::os_pack::json::to_json_string(&value));
            Fault { code, message }
        }
        None => Fault { code: "mutation.rejected".to_string(), message: format!("guest rejected the command ({} bytes of fault detail, undecodable as JSON)", bytes.len()) },
    }
}

/// 📤️ Splits one wire ops-pack blob into this port's own `Vec<Vec<u8>>` lane shape — **one element
/// per complete op payload**, which is `PreparedOps`' own documented contract (`🔀️dispatch/🦀️.rs`:
/// "one element per complete op payload, never a single stream").
///
/// 🐛️ This used to hand the whole `encode_ops_vec` blob back as ONE opaque element, on the stated
/// assumption that "`TransactionPrepare`'s pre-planned form re-forwards the SAME bytes verbatim, so
/// the framing only has to round-trip through this one port, never be individually addressed". The
/// assumption is false and became measurable the moment WR3's paged routes let a real
/// `TransactionPrepare` reach a real guest: `VcsArtifactApp::transaction_prepare` runs
/// `A::Mutation::decode_op(op_bytes)` over EVERY element, so a whole ops-vec envelope handed in as
/// one element decodes as no mutation at all. It also made an EMPTY lane non-empty — `encode_ops_vec`
/// of nothing is a one-byte zero count, which became `[[0]]` — and `PluginArtifactChannel`'s own
/// `TransactionPrepare` arm refuses any prepare whose config/draft lane is non-empty, so every
/// two-phase invoke would have been refused for carrying config ops it never emitted.
#[cfg(not(target_arch = "wasm32"))]
fn ops_pack_lane(bytes: Vec<u8>) -> Result<Vec<Vec<u8>>, Fault> {
    if bytes.is_empty() {
        return Ok(Vec::new());
    }
    store::causal::decode_ops_vec(&bytes).map_err(|error| PluginArtifactChannel::not_wired("decoding the guest's emitted ops", format!("{error:?}")))
}

/// 📤️ Every OUT port one editor app can actually be exported through, in the order an export picks
/// them.
///
/// 🧭️ Measured across every committed descriptor in the repo (2026-09-20): `AppDefinition
/// .media_outputs` is **empty for all 35 plugins**. An app's real OUT ports live in
/// `AppIo.ports` with `direction: out` (`writer: text:out`, `lowpoly: mesh:out`, `draw:
/// vector:out`, …), and the builder method that fills `media_outputs` has no caller anywhere.
/// Reading only `media_outputs` is therefore why `artifact_export` answered
/// `declaredExportFormats: []` for a plugin that exports for real
/// (`📓️wr2-headless-command-response-wire.md` §7.2).
///
/// 🗿️ `artifact:out` closes the list rather than opening it: `AppIo::all_ports` gives every app that
/// implicit port and `ArtifactEditor::export_media`'s provided body answers it with the document's
/// own pack, so it is a real declared surface — but an app-specific port is the better answer when
/// one exists, and an export with no requested format takes the first.
#[cfg(not(target_arch = "wasm32"))]
fn app_media_out_ports(app: &semio_framework::AppDefinition) -> Vec<String> {
    let mut ports: Vec<String> = app
        .media_outputs
        .iter()
        .chain(app.io.ports.iter())
        .filter(|port| port.direction == semio_framework::MediaPortDirection::Out)
        .map(|port| port.id.clone())
        .collect();
    ports.push("artifact:out".to_string());
    let mut seen: std::collections::BTreeSet<String> = std::collections::BTreeSet::new();
    ports.retain(|port| seen.insert(port.clone()));
    ports
}

/// 🔗️ Folds the artifact this inference is being run ON into the canonical request body, under the
/// field the inference's OWN published contract names.
///
/// 🧭️ Declared, never invented. The host writes exactly `InferenceArtifactBinding.field`, in exactly
/// `InferenceArtifactBinding.encoding`, and refuses by name in every other case: an unpublished
/// contract, an encoding this host has no writer for, or a required binding with no artifact named.
/// Before this existed an agent could only ever send `{}` — `inference_run`'s tool schema had no
/// artifact at all — and the guest answered `missing field 'snapshot'` after the whole component had
/// been compiled and dispatched (`📓️pz2-puzzle-describe-under-budget.md` §5.2).
///
/// ✍️ A caller that supplies the bound field itself keeps it: the binding fills a GAP, it never
/// overwrites a body the caller authored.
#[cfg(not(target_arch = "wasm32"))]
fn bind_inference_document(declared: &semio_framework::ContributedInferenceMetadata, command: &crate::actions::InferCommand) -> Result<Vec<u8>, Fault> {
    let Some(binding) = declared.payload.as_ref().and_then(|contract| contract.artifact_binding.as_ref()) else {
        return Ok(command.canonical_payload.clone());
    };
    if binding.encoding != semio_framework::INFERENCE_ARTIFACT_PACK_BASE64 {
        return Err(Fault {
            code: "mutation.rejected".to_string(),
            message: format!("`{}` declares artifact binding encoding `{}`, which this gateway has no writer for (it writes `{}`)", declared.inference_schema, binding.encoding, semio_framework::INFERENCE_ARTIFACT_PACK_BASE64),
        });
    }
    let mut body: serde_json::Value = if command.canonical_payload.is_empty() {
        serde_json::json!({})
    } else {
        serde_json::from_slice(&command.canonical_payload).map_err(|error| Fault { code: "mutation.rejected".to_string(), message: format!("`{}` payload is not a JSON object: {error}", declared.inference_schema) })?
    };
    let Some(object) = body.as_object_mut() else {
        return Err(Fault { code: "mutation.rejected".to_string(), message: format!("`{}` payload is not a JSON object", declared.inference_schema) });
    };
    if object.contains_key(&binding.field) {
        return serde_json::to_vec(&body).map_err(|error| Fault { code: "plugin.internal".to_string(), message: format!("encoding the inference payload: {error}") });
    }
    match command.artifact_document.as_ref() {
        // 📦️ The one shape `INFERENCE_ARTIFACT_PACK_BASE64` names, written with the same standard
        // alphabet the guest's `ArtifactDocumentPayload::pair()` decodes with. The gateway does not
        // link the guest SDK (`🌉️mcp` depends on the plugin HOST, never on the plugin crate), so
        // the encoding constant is the contract between the two halves, not a shared type.
        Some(document) => {
            object.insert(binding.field.clone(), serde_json::json!({ "pack": crate::shell_channel::encode_base64(&document.pack), "spr": crate::shell_channel::encode_base64(&document.spr) }));
        }
        // 🧭️ `required` means "this inference needs SOME body and the caller cannot type one", not
        // "this field or nothing": a published contract may offer a second carrier (`🀄️wfc`'s own
        // request schema is `oneOf [document, snapshot]`), and a caller who stated one has already
        // answered the requirement. Refusing an authored body here made a hand-written `snapshot`
        // unroutable (measured 2026-09-22 21:2x) — the guest, which owns the schema, is the judge
        // of a body that exists; this gateway only refuses an EMPTY one.
        None if binding.required && object.is_empty() => {
            return Err(Fault {
                code: "mutation.rejected".to_string(),
                message: format!("`{}` is artifact-bound: name the artifact to run it on with `artifactId`, or supply `payload.{}` yourself", declared.inference_schema, binding.field),
            })
        }
        None => {}
    }
    serde_json::to_vec(&body).map_err(|error| Fault { code: "plugin.internal".to_string(), message: format!("encoding the inference payload: {error}") })
}

#[cfg(not(target_arch = "wasm32"))]
impl ArtifactChannel for PluginArtifactChannel {
    fn exchange(&mut self, instance: u32, commands: Vec<AppCommand>) -> Result<Vec<AppFrame>, Fault> {
        if commands.len() != 1 {
            return Err(Self::not_wired("exchange", format!("expected exactly one command, received {}", commands.len())));
        }
        // 💡️ `Infer` never touches the retained command-page lane, so it must not be gated on the
        // command-lane instance being open at all: it drives its own guest instance, on its own actor
        // ordinal, opened on first use by `ensure_inference_route`.
        if !matches!(commands.first(), Some(AppCommand::Infer(_))) {
            self.ensure_instance(instance)?;
        }
        let mut frames = Vec::with_capacity(commands.len());
        for command in commands {
            let frame = match command {
                AppCommand::ReadHistory => match self.exchange_one_real(instance, store::AppCommand::ReadHistory { seq: 0 })? {
                    store::AppFrame::HistorySnapshot { history_patch, .. } => {
                        let value = store::pack_rt::decode_wire_value(&history_patch).map_err(|error| Self::not_wired("decoding HistoryPatch", error))?;
                        let patch: semio_framework::kernel::HistoryPatch = store::from_dsl_value(value).map_err(|error| Self::not_wired("decoding HistoryPatch", error))?;
                        // 🔭️ The head is the newest APPLIED entry, not the newest entry.
                        // `HistoryPatch.upserts` is ordered newest-first and an undo does not
                        // remove its row — it clears `HistoryEntry.applied` — so reading
                        // `upserts.first()` reported the identical stamp before and after
                        // `history.undo`, and `expectedRevision` (the ONLY revision oracle an agent
                        // has for a plugin-owned artifact) could not express that a change had been
                        // walked back. Measured 2026-09-20 22:38 on a real `🗒️note` guest: an
                        // `addBlock` committed, undone and redone stamped `transaction:txn_…/1`
                        // throughout, so an optimistic-concurrency client would have re-committed
                        // over an undo without ever seeing a `REVISION_CONFLICT`.
                        AppFrame::HistorySnapshot(RevisionStamp {
                            artifact_id: self.stamped_artifact_id(),
                            head_edit_id: patch.upserts.iter().find(|entry| entry.applied).map(|entry| entry.action_id.clone()).unwrap_or_default(),
                            cursor: patch.cursor.to_string(),
                        })
                    }
                    other => return Err(Self::not_wired("ReadHistory", format!("unexpected real AppFrame variant {other:?}"))),
                },
                // 🧮️ PHASE ONE of the agent lane's two-phase contract: the guest validates, prices
                // and produces the ops WITHOUT applying any of them (`VcsArtifactApp::
                // preview_addressed_action`, whose own doc carries the soundness argument). The
                // frame is the SAME owner-qualified `ManifestActionInvocation` the shell's UI lane
                // sends on `AppCommand::Command` — one dispatch shape for both lanes — built here
                // from the plugin's own committed manifest, never parsed out of the capability id.
                // It used to be `{"capabilityId":…,"input":…}`, an opaque blob no guest could select
                // a command-specific pre-serde envelope from, which is exactly what the guest's
                // three-line refusal said (`interactive-job.missing-exact-key`).
                AppCommand::PureCommand { capability_id, input } => {
                    let invocation = self.addressed_action_invocation(&capability_id, &input)?;
                    let command = store::pack_rt::encode_wire_value(&store::ToValue::to_value(&invocation));
                    match self.exchange_one_real(
                        instance,
                        store::AppCommand::PureCommand { seq: 0, command, document: Vec::new(), document_spr: Vec::new(), config: Vec::new(), config_spr: Vec::new(), draft: Vec::new(), draft_spr: Vec::new() },
                    )? {
                        store::AppFrame::Emit { document_ops, config_ops, draft_ops, .. } => {
                            AppFrame::Emit { ops: PreparedOps { document: ops_pack_lane(document_ops)?, config: ops_pack_lane(config_ops)?, draft: ops_pack_lane(draft_ops)? }, warnings: Vec::new() }
                        }
                        store::AppFrame::Error { fault, .. } => return Err(decode_guest_fault(&fault)),
                        other => return Err(Self::not_wired("PureCommand", format!("unexpected real AppFrame variant {other:?}"))),
                    }
                }
                // 🚧️ Same honesty rule: real wire call, real answer. The wire's `TransactionPrepare`
                // carries ONE flat `prepared_ops` list (document lane only — `transaction_prepare`'s
                // own signature has no config/draft parameter); a config/draft-lane prepare has no
                // wire representation yet, reported as such rather than silently dropped.
                AppCommand::TransactionPrepare { txn_id, ops, label, origin: _origin } => {
                    if !ops.config.is_empty() || !ops.draft.is_empty() {
                        return Err(Self::not_wired("TransactionPrepare", "the real wire TransactionPrepare carries one flat prepared-ops list (document lane only) — config/draft-lane prepared ops have no wire representation yet"));
                    }
                    // 🚧️ `origin` is this port's own invented `MutationOrigin::Agent` shape — the
                    // real wire `os_spr::MutationOrigin` has exactly three variants
                    // (`Owner`/`Contributed`/`Transaction`), none of which represent "an agent
                    // principal invoked this headlessly"; sending empty bytes decodes as `None`
                    // (asserting no origin) rather than fabricating a wire shape that does not exist.
                    match self.exchange_one_real(
                        instance,
                        store::AppCommand::TransactionPrepare { seq: 0, txn_id: txn_id.clone(), mutation_id: String::new(), payload: Vec::new(), prepared_ops: ops.document, label, origin: Vec::new() },
                    )? {
                        store::AppFrame::TransactionPrepared { txn_id, rejection, .. } if rejection.is_empty() => AppFrame::TransactionPrepared { txn_id },
                        store::AppFrame::TransactionPrepared { rejection, .. } => return Err(decode_guest_fault(&rejection)),
                        store::AppFrame::Error { fault, .. } => return Err(decode_guest_fault(&fault)),
                        other => return Err(Self::not_wired("TransactionPrepare", format!("unexpected real AppFrame variant {other:?}"))),
                    }
                }
                // ✅️ Real and fully generic: `TransactionCommit`/`Rollback`/`Undo`/`Redo` need only
                // `txn_id`/`group_id` — no plugin-specific payload, so (unlike `PureCommand`/
                // `TransactionPrepare`) these genuinely work against any real committed transaction.
                AppCommand::TransactionCommit { txn_id } => match self.exchange_one_real(instance, store::AppCommand::TransactionCommit { seq: 0, txn_id: txn_id.clone() })? {
                    store::AppFrame::TransactionCommitted { txn_id, edit_id } => AppFrame::TransactionCommitted { txn_id, edit_id },
                    store::AppFrame::Error { fault, .. } => return Err(decode_guest_fault(&fault)),
                    other => return Err(Self::not_wired("TransactionCommit", format!("unexpected real AppFrame variant {other:?}"))),
                },
                AppCommand::TransactionRollback { txn_id } => match self.exchange_one_real(instance, store::AppCommand::TransactionRollback { seq: 0, txn_id: txn_id.clone() })? {
                    store::AppFrame::TransactionRolledBack { txn_id } => AppFrame::TransactionRolledBack { txn_id },
                    store::AppFrame::Error { fault, .. } => return Err(decode_guest_fault(&fault)),
                    other => return Err(Self::not_wired("TransactionRollback", format!("unexpected real AppFrame variant {other:?}"))),
                },
                AppCommand::TransactionUndo { group_id } => match self.exchange_one_real(instance, store::AppCommand::TransactionUndo { seq: 0, group_id: group_id.clone() })? {
                    store::AppFrame::Done { .. } => AppFrame::TransactionUndone { group_id },
                    store::AppFrame::Error { fault, .. } => return Err(decode_guest_fault(&fault)),
                    other => return Err(Self::not_wired("TransactionUndo", format!("unexpected real AppFrame variant {other:?}"))),
                },
                // ✅️ Real and general: every plugin-declared inference service, not just the one
                // hub-backed GIS Map job. Routed through `ArtifactInferenceRouter` exactly the way
                // `🏃️run`'s own plugin reactor routes `job_infer`, so the guest's result is the
                // guest's own — this arm fabricates nothing and short-circuits nothing.
                AppCommand::Infer(command) => {
                    let result = self.infer_real(&command)?;
                    AppFrame::Inferred { inference_schema: result.inference_schema, complete: result.complete, payload: result.canonical_payload }
                }
                AppCommand::TransactionRedo { group_id } => match self.exchange_one_real(instance, store::AppCommand::TransactionRedo { seq: 0, group_id: group_id.clone() })? {
                    store::AppFrame::Done { .. } => AppFrame::TransactionRedone { group_id },
                    store::AppFrame::Error { fault, .. } => return Err(decode_guest_fault(&fault)),
                    other => return Err(Self::not_wired("TransactionRedo", format!("unexpected real AppFrame variant {other:?}"))),
                },
                // 📤️ Real and general: the artifact's own pack bytes go in with `LoadDocument`, then
                // the app's own OUT port is read with `MediaOut` — the identical pair `🏃️run`'s
                // workflow executor drives per node (`🏃️run/🦀️.rs`'s `compute_node`). Nothing about
                // the exported bytes is interpreted here: `descriptor`/`data` are the guest's own.
                AppCommand::ExportMedia { port, document, document_spr } => {
                    match self.exchange_one_real(instance, store::AppCommand::LoadDocument { seq: 0, pack: document, spr: document_spr })? {
                        store::AppFrame::Done { .. } => {}
                        store::AppFrame::Error { fault, .. } => return Err(decode_guest_fault(&fault)),
                        other => return Err(Self::not_wired("ExportMedia/LoadDocument", format!("unexpected real AppFrame variant {other:?}"))),
                    }
                    match self.exchange_one_real(instance, store::AppCommand::MediaOut { seq: 0, port: port.clone(), request: Vec::new() })? {
                        store::AppFrame::Media { port, descriptor, data, .. } => AppFrame::Exported { port, descriptor, data },
                        store::AppFrame::Error { fault, .. } => return Err(decode_guest_fault(&fault)),
                        other => return Err(Self::not_wired("ExportMedia/MediaOut", format!("unexpected real AppFrame variant {other:?}"))),
                    }
                }
                // 🆕️ The guest's own genesis document, straight off `ReadDocument` — host-opaque
                // bytes this crate persists verbatim under the plugin's real schema id, which is how
                // `artifact_create{kind}` produces a plugin-typed artifact without this host ever
                // owning a plugin's document type.
                AppCommand::ReadArtifact => match self.exchange_one_real(instance, store::AppCommand::ReadDocument { seq: 0 })? {
                    store::AppFrame::Document { pack, spr, .. } => AppFrame::Artifact { pack, spr },
                    store::AppFrame::Error { fault, .. } => return Err(decode_guest_fault(&fault)),
                    other => return Err(Self::not_wired("ReadArtifact", format!("unexpected real AppFrame variant {other:?}"))),
                },
            };
            frames.push(frame);
        }
        Ok(frames)
    }

    fn activate(&mut self, instance: u32, scope: &ActivationScope) -> Result<(), Fault> {
        self.ensure_instance_scoped(instance, scope)
    }
}

//#region 🔖️Routing
/// 🧭️ `plugin_id` for every catalog entry `CapabilityOwner::Plugin{..}` names, deduplicated and
/// sorted — doubles as a stable, catalog-derived NUMBERING (`plugin_instance_slot`/
/// `plugin_for_instance_slot` below), not just a set: `ActionAdapter::prepare` issues a bare
/// `AppCommand::ReadHistory` (no capability id at all) BEFORE the `PureCommand` that names one
/// (`🔀️dispatch/🦀️.rs`'s own `prepare`), so `RoutingArtifactChannel::exchange` cannot always
/// read a capability id off the wire — it needs `instance` itself to already encode the plugin, which
/// only works if every caller derives `instance` from the SAME deterministic function of the catalog.
#[cfg(not(target_arch = "wasm32"))]
fn distinct_plugin_ids(catalog: &Catalog) -> Vec<String> {
    let set: std::collections::BTreeSet<String> = catalog.entries.iter().filter_map(|entry| match &entry.owner { CapabilityOwner::Plugin { plugin_id, .. } => Some(plugin_id.clone()), _ => None }).collect();
    set.into_iter().collect()
}

/// 🔢️ `plugin_id`'s position in [`distinct_plugin_ids`] — the `instance` [`HeadlessWorkspace::prepare_action`]
/// picks for a resolved capability so every command in that call's sequence (`ReadHistory` included)
/// decodes back to the same plugin via [`plugin_for_instance_slot`], with no shared mutable state.
#[cfg(not(target_arch = "wasm32"))]
fn plugin_instance_slot(catalog: &Catalog, plugin_id: &str) -> Option<u32> {
    distinct_plugin_ids(catalog).iter().position(|id| id == plugin_id).map(|index| index as u32)
}

/// 🎯️ The `instance` slot any caller must pass to [`ActionAdapter::prepare`]/[`ActionAdapter::invoke`]
/// for `capability_id` — [`plugin_instance_slot`] of the plugin that capability's own catalog entry
/// names. Public because the `action_prepare`/`action_invoke` MCP tools drive the ROOT-owned
/// adapter directly (never [`HeadlessWorkspace::prepare_action`]) and so need the identical
/// derivation: with the bare `0` they used to pass, `prepare`'s leading capability-less
/// `ReadHistory` was routed by [`plugin_for_instance_slot`] to whichever plugin happens to sort
/// first in the catalog, not to the capability's own.
#[cfg(not(target_arch = "wasm32"))]
pub fn capability_instance_slot(catalog: &Catalog, capability_id: &str) -> Option<u32> {
    plugin_instance_slot(catalog, &resolve_plugin_for_capability_in(catalog, capability_id).ok()?)
}

/// 🔢️ The inverse of [`plugin_instance_slot`] — what [`RoutingArtifactChannel::exchange`] decodes an
/// `instance` back into for any `AppCommand` that carries no capability id of its own.
#[cfg(not(target_arch = "wasm32"))]
fn plugin_for_instance_slot(catalog: &Catalog, instance: u32) -> Option<String> {
    distinct_plugin_ids(catalog).into_iter().nth(instance as usize)
}

/// 🔎️ `capability_id` → its owning plugin id — [`HeadlessWorkspace::resolve_plugin_for_capability`]'s
/// actual body, factored out so [`RoutingArtifactChannel`] (which holds only the `Arc<Catalog>` it
/// needs, not a whole `&HeadlessWorkspace`) can run the identical lookup for a `PureCommand` it is
/// asked to route, without a second copy of this match. An unknown id or one owned by anything other
/// than a plugin (`Os`/`Framework`/`🐚️Shell`/`Gateway`/`Extension`) is a typed error naming exactly
/// which of the two it was — never a guess.
#[cfg(not(target_arch = "wasm32"))]
fn resolve_plugin_for_capability_in(catalog: &Catalog, capability_id: &str) -> Result<String, GatewayError> {
    let capability = catalog.get(capability_id).ok_or_else(|| GatewayError::new(GatewayErrorCode::NotFound, format!("unknown capability: {capability_id}")))?;
    match &capability.owner {
        CapabilityOwner::Plugin { plugin_id, .. } => Ok(plugin_id.clone()),
        owner => Err(GatewayError::new(GatewayErrorCode::PluginUnavailable, format!("capability `{capability_id}` is owned by {}, not a plugin — no artifact channel routes to it", owner.dedup_key())).retryable()),
    }
}

/// 🚧️ `GatewayError` → the `Fault` shape [`ArtifactChannel::exchange`] can actually return —
/// `"capability.not-found"` for a caller-supplied bad id (client-fault, never retryable, matches
/// `GatewayErrorCode::NotFound`'s own `map_fault` arm added alongside this ticket), `"plugin.unavailable"`
/// for everything else (the target plugin genuinely cannot be reached right now — retryable, matches
/// `GatewayErrorCode::PluginUnavailable`).
#[cfg(not(target_arch = "wasm32"))]
fn routing_fault(error: GatewayError) -> Fault {
    let code = match error.code {
        GatewayErrorCode::NotFound => "capability.not-found",
        GatewayErrorCode::Cancelled => ACTIVATION_CANCELLED_FAULT_CODE,
        _ => "plugin.unavailable",
    };
    Fault { code: code.to_string(), message: error.message }
}

/// 🔌️ Shared body of [`HeadlessWorkspace::open_artifact_channel`] and
/// [`RoutingArtifactChannel::exchange`]'s own lazy-open step — both need exactly this (registry entry
/// → committed descriptor → editor app → real `PluginArtifactChannel`) for a bare `plugin_id`,
/// differing only in where `repo_root`/`actor_label` come from.
#[cfg(not(target_arch = "wasm32"))]
fn open_plugin_artifact_channel(source: Option<&PluginComponentSource>, plugin_id: &str, actor_label: &str) -> Result<PluginArtifactChannel, GatewayError> {
    open_plugin_artifact_channel_scoped(source, plugin_id, actor_label, &ActivationScope::detached())
}

/// 🔌️ [`open_plugin_artifact_channel`] under a caller's progress and cancel.
#[cfg(not(target_arch = "wasm32"))]
fn open_plugin_artifact_channel_scoped(source: Option<&PluginComponentSource>, plugin_id: &str, actor_label: &str, scope: &ActivationScope) -> Result<PluginArtifactChannel, GatewayError> {
    scope.enter(ActivationPhase::ResolvingComponent).map_err(activation_fault)?;
    let runtime = shared_plugin_runtime()?;
    let (compiled, descriptor) = match source.ok_or_else(|| {
        GatewayError::new(GatewayErrorCode::Internal, "this workspace is bound to no plugin component source — neither a repo build tree nor an authenticated hub execution target")
    })? {
        PluginComponentSource::Repo(repo_root) => {
            let registry = load_plugin_registry(repo_root)?;
            let entry = find_plugin_entry(&registry, plugin_id)?.clone();
            let descriptor = load_package_descriptor(&entry.owner_root)?;
            let wasm_path = resolve_plugin_wasm_path(repo_root, &entry)?;
            (scoped_compiled_component(runtime.as_ref(), plugin_id, ComponentBytes::File(&wasm_path), scope)?, descriptor)
        }
        PluginComponentSource::Hub(hub) => {
            let (bytes, descriptor) = hub.resolve(plugin_id)?;
            (scoped_compiled_component(runtime.as_ref(), plugin_id, ComponentBytes::Held(&bytes), scope)?, descriptor)
        }
    };
    let editor_app = descriptor.manifest.apps.iter().find(|app| app.role == semio_framework::AppRole::Editor).ok_or_else(|| GatewayError::new(GatewayErrorCode::NotFound, format!("plugin `{plugin_id}` declares no editor app")))?;
    let app_ref = semio_framework::AppRef { plugin_id: plugin_id.to_string(), app_id: editor_app.id.clone() };
    Ok(PluginArtifactChannel::from_compiled(runtime, compiled, plugin_id.to_string(), descriptor, app_ref, actor_label.to_string()))
}

//#region 🗂️GuestDocumentCodec
/// ⛽️ The ceiling one pure `codec` call runs under. The WIT states the contract these functions
/// honour — no storage, no window, no effect, one throwaway instance per call — so what bounds them
/// is wall time, not effect or frame counts. 60 s is the same order as [`headless_open_budget`],
/// because printing or applying against an 80 KB document pack is work of the same scale as bringing
/// an instance up, and a guest that needs longer is wedged rather than busy.
/// 🧵️ The binding generation this gateway claims for a document backbone. One session opens one
/// binding per instance and never rebinds — a rebind is what a shell does when a window swaps
/// documents, which a headless channel with one bound artifact per plugin cannot do — so the
/// generation is a constant rather than a counter that would imply a history it does not have.
#[cfg(not(target_arch = "wasm32"))]
const DOCUMENT_BACKBONE_BINDING_GENERATION: u64 = 1;

#[cfg(not(target_arch = "wasm32"))]
fn headless_codec_budget() -> semio_framework::kernel::Budget {
    semio_framework::kernel::Budget { fuel: u64::MAX, deadline_ms: 60_000, max_effects: 0, max_patch_bytes: 0, max_frames: 0 }
}

/// 🌐️ The process's tokio I/O reactor, for the hub DOCUMENT SOCKET and nothing else.
///
/// 🐛️ `store::sync`'s native artifact actor dials its document socket with
/// `tokio_tungstenite::connect_async` under a `tokio::time::timeout`
/// (`🏪️store/🔄️sync/🦀️.rs`, `connect_hub`), and `spawn_actor` captures
/// `tokio::runtime::Handle::try_current()` **at the moment `ArtifactHost::open` is awaited**, then
/// `enter()`s it around every turn it polls. A shell binary is inside a tokio runtime when it opens
/// a document; this gateway is not — `semio_framework_os_services::TokioHostRuntime` is the repo's
/// own `WorkerPool`-backed host runtime and carries no tokio reactor despite the name. So the
/// captured handle was `None` and the FIRST socket dial panicked the pool worker with "there is no
/// reactor running, must be called from the context of a Tokio 1.x runtime" (measured live on hub
/// 7681, 2026-09-22, `🗑️generated/m10-write-path-7681-note.txt`).
///
/// 🧭️ Multi-threaded on purpose, and tiny: a current-thread runtime would register the socket but
/// park nobody on its I/O driver, so readiness would never be delivered to a future this crate polls
/// on a worker thread. Two workers are enough for one websocket per open document, and the reactor
/// is process-wide so it outlives any one workspace — a document actor must not lose its driver
/// because the session that opened it went away mid-close.
#[cfg(not(target_arch = "wasm32"))]
fn hub_socket_reactor() -> Result<&'static tokio::runtime::Runtime, GatewayError> {
    static REACTOR: std::sync::OnceLock<Result<tokio::runtime::Runtime, String>> = std::sync::OnceLock::new();
    REACTOR
        .get_or_init(|| tokio::runtime::Builder::new_multi_thread().worker_threads(2).enable_io().enable_time().thread_name("semio-mcp-document-socket").build().map_err(|error| error.to_string()))
        .as_ref()
        .map_err(|error| GatewayError::new(GatewayErrorCode::Internal, format!("building the hub document-socket reactor: {error}")))
}

/// 🗂️ One package's own document codec, as the component exports it — the compiled component plus
/// the artifact schema it was registered for.
///
/// 🧭️ `runtime` is the process-wide [`shared_plugin_runtime`] and never a second one: a
/// `wasmtime::Component` belongs to the `Engine` that compiled it, so `compiled` is only
/// instantiable by the runtime that produced it.
#[cfg(not(target_arch = "wasm32"))]
struct GuestCodecRoute {
    artifact_schema: String,
    plugin_id: String,
    runtime: Arc<GuestRuntimes>,
    compiled: semio_framework_plugin_host::CompiledHandle,
}

/// 🗂️ Every guest-backed codec this process has registered, in registration order.
///
/// 🧭️ A process-global table exists because [`store::ArtifactCodec`]'s four operations are bare,
/// NON-CAPTURING `fn` pointers — an erasure table, by design, so that a schema-string-keyed caller
/// can print and apply without naming a concrete `P`/`Mutation`. A thunk therefore cannot close over
/// a component, and cannot be told which schema it was registered under either: the signatures carry
/// only bytes. So a thunk resolves its route by asking the components themselves, in order, and
/// taking the first that answers — see [`guest_print_mirror`] for why that is the WIT's own
/// discriminator rather than a guess.
#[cfg(not(target_arch = "wasm32"))]
fn guest_codec_routes() -> &'static Mutex<Vec<Arc<GuestCodecRoute>>> {
    static ROUTES: std::sync::OnceLock<Mutex<Vec<Arc<GuestCodecRoute>>>> = std::sync::OnceLock::new();
    ROUTES.get_or_init(|| Mutex::new(Vec::new()))
}

#[cfg(not(target_arch = "wasm32"))]
fn guest_codec_route_snapshot() -> Vec<Arc<GuestCodecRoute>> {
    guest_codec_routes().lock().unwrap_or_else(std::sync::PoisonError::into_inner).clone()
}

/// 📥️ `(pack, spr) -> (dsl, ops)` through whichever registered component owns this pair.
///
/// 🧭️ **The component IS the discriminator.** `interface codec`'s own contract states it: "a pair
/// the component cannot print back is not a document of this kind". So asking each registered
/// package in turn and taking the first that answers is not a guess at the schema — it is running
/// the exact fence the interface defines, once per candidate. In a real gateway session the
/// candidate list is the packages whose documents this agent has open, which is one or two.
#[cfg(not(target_arch = "wasm32"))]
fn guest_print_mirror<'a>(pack: &'a [u8], spr: &'a [u8]) -> std::pin::Pin<Box<dyn std::future::Future<Output = Result<store::ArtifactTextFiles, store::VcsError>> + Send + 'a>> {
    Box::pin(async move {
        let routes = guest_codec_route_snapshot();
        let mut refusals: Vec<String> = Vec::new();
        for route in &routes {
            match route.runtime.codec_print_mirror(&route.compiled, &route.artifact_schema, pack, spr, &headless_codec_budget()).await {
                Ok(mirror) => return Ok(store::ArtifactTextFiles { dsl: mirror.dsl, ops: mirror.ops }),
                Err(error) => refusals.push(format!("{}/{}: {error}", route.plugin_id, route.artifact_schema)),
            }
        }
        Err(store::VcsError::Deserialize(format!("no registered guest codec prints this pair ({} candidate(s): {})", routes.len(), refusals.join("; "))))
    })
}

/// 🧩️ `(pack, spr, encode_ops_vec) -> (pack, spr, ops text)` through the same route resolution.
/// The ops text is the component's own print of the RESULT pair, never a host re-derivation.
#[cfg(not(target_arch = "wasm32"))]
fn guest_apply_ops_binary<'a>(pack: &'a [u8], spr: &'a [u8], ops: &'a [u8]) -> store::ArtifactCodecApplyFuture<'a> {
    Box::pin(async move {
        let routes = guest_codec_route_snapshot();
        let mut refusals: Vec<String> = Vec::new();
        for route in &routes {
            let budget = headless_codec_budget();
            let applied = match route.runtime.codec_apply_ops(&route.compiled, &route.artifact_schema, pack, spr, ops, &budget).await {
                Ok(applied) => applied,
                Err(error) => {
                    refusals.push(format!("{}/{}: {error}", route.plugin_id, route.artifact_schema));
                    continue;
                }
            };
            let mirror = route
                .runtime
                .codec_print_mirror(&route.compiled, &route.artifact_schema, &applied.pack, &applied.spr, &budget)
                .await
                .map_err(|error| store::VcsError::Serialize(format!("{}/{} applied the batch but cannot print the result: {error}", route.plugin_id, route.artifact_schema)))?;
            return Ok((applied.pack, applied.spr, mirror.ops));
        }
        Err(store::VcsError::Deserialize(format!("no registered guest codec applies this batch ({} candidate(s): {})", routes.len(), refusals.join("; "))))
    })
}

/// 🚫️ `interface codec` exports four functions and neither of these is one of them: there is no
/// `compile-dsl` and no `edit-text-from-envelope` in the WIT, because both belong to the FOLDER text
/// lane (`FolderTextStorage`'s `.dsl`/`.ops` writes) and a guest-backed codec exists precisely for a
/// binding that has no folder. A typed refusal naming that is the honest answer; fabricating text
/// here would put bytes in a `.ops` file that no component ever produced.
#[cfg(not(target_arch = "wasm32"))]
fn guest_compile_dsl<'a>(_dsl: &'a str, _ops: &'a str) -> std::pin::Pin<Box<dyn std::future::Future<Output = Result<(store::ArtifactPackFiles, String), store::VcsError>> + Send + 'a>> {
    Box::pin(async move { Err(store::VcsError::Deserialize("a guest-backed document codec has no `compile-dsl`: `interface codec` exports pack-schema-hash, genesis, print-mirror and apply-ops only".to_string())) })
}

#[cfg(not(target_arch = "wasm32"))]
fn guest_edit_text_from_envelope<'a>(_envelope: &'a store::os_spr::MutationEnvelope) -> std::pin::Pin<Box<dyn std::future::Future<Output = Result<String, store::VcsError>> + 'a>> {
    Box::pin(async move { Err(store::VcsError::Deserialize("a guest-backed document codec has no per-envelope text printer: `interface codec` prints whole pairs, not single edits".to_string())) })
}

/// 🗂️ Registers `artifact_schema`'s document codec from the component's OWN `codec` export, and
/// answers the pack-schema hash the component itself computed.
///
/// 🪪️ `expected_pack_schema_hash` is the hub's declared hex hash for this document, and it is a
/// CROSS-CHECK, never the source: the hash that goes into the registry is the one
/// `codec.pack-schema-hash` returned from the component bytes the hub authorized and this process
/// verified by SHA-256. Registering the hub's own number would make `finish_connect_hub`'s
/// `local_schema_hash == authority.pack_schema_hash` compare the hub's value with itself, which is
/// not satisfying that check — it is deleting it.
///
/// 🔁️ Idempotent per schema: a second registration of a schema this process already serves is a
/// no-op that still verifies the hash, so re-opening a document never stacks routes.
#[cfg(not(target_arch = "wasm32"))]
fn register_guest_document_codec(plugin_id: &str, artifact_schema: &str, component: &[u8], expected_pack_schema_hash: &str) -> Result<[u8; 32], GatewayError> {
    let runtime = shared_plugin_runtime()?;
    let compiled = shared_compiled_component(runtime.as_ref(), plugin_id, component)?;
    let pack_schema_hash = semio_framework_async::block_on(runtime.codec_pack_schema_hash(&compiled, artifact_schema, &headless_codec_budget()))
        .map_err(|error| GatewayError::new(GatewayErrorCode::Internal, format!("`{plugin_id}` could not answer codec.pack-schema-hash for `{artifact_schema}`: {error}")))?;
    let computed = pack_schema_hash.iter().map(|byte| format!("{byte:02x}")).collect::<String>();
    if !expected_pack_schema_hash.is_empty() && computed != expected_pack_schema_hash {
        return Err(GatewayError::new(
            GatewayErrorCode::PreconditionFailed,
            format!("`{plugin_id}`'s own codec hashes `{artifact_schema}` to {computed}, but the hub's document descriptor declares {expected_pack_schema_hash}"),
        ));
    }
    let mut routes = guest_codec_routes().lock().unwrap_or_else(std::sync::PoisonError::into_inner);
    if routes.iter().any(|route| route.artifact_schema == artifact_schema) {
        return Ok(pack_schema_hash);
    }
    routes.push(Arc::new(GuestCodecRoute { artifact_schema: artifact_schema.to_string(), plugin_id: plugin_id.to_string(), runtime: Arc::clone(&runtime), compiled }));
    drop(routes);
    store::register_document_codec(store::ArtifactCodec {
        schema: artifact_schema.to_string(),
        // 📦️ The generic pack container extension. A guest-backed codec never reaches the folder
        // text lane (see [`guest_compile_dsl`]), which is the only place this is read.
        extension: "semio",
        pack_schema_hash,
        compile_dsl: guest_compile_dsl,
        print_mirror: guest_print_mirror,
        edit_text_from_envelope: guest_edit_text_from_envelope,
        apply_ops_binary: guest_apply_ops_binary,
    })
    .map_err(|error| GatewayError::new(GatewayErrorCode::Internal, format!("registering a guest-backed codec for `{artifact_schema}`: {error}")))?;
    Ok(pack_schema_hash)
}

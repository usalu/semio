/// 🏠️ The real `GatewayBackend` — see this file's module doc for the shape and the honest gaps.
pub struct HeadlessWorkspace {
    artifact_host: store::sync::ArtifactHost,
    origin: WorkspaceOrigin,
    principal: String,
    session_id: String,
    scopes: Vec<String>,
    repo_root: Option<PathBuf>,
    catalog: Arc<Catalog>,
    /// 🧵️ Every document this workspace has opened a live `ProbeStore`/backbone attachment for —
    /// `artifact_open`/`ensure_probe_artifact` populate this; `resolve_context`/`read_resource` read
    /// through it first before falling back to a cold `FolderSqliteStorage` read.
    open_probes: Mutex<HashMap<String, ProbeStore>>,
}

impl HeadlessWorkspace {
    fn new(origin: WorkspaceOrigin, principal: String, scopes: Vec<String>, catalog: Arc<Catalog>) -> Self {
        ensure_probe_codec_registered();
        let session_id = crate::mint_session_id(&principal, 0);
        Self { artifact_host: store::sync::ArtifactHost::new(), origin, principal, session_id, scopes, repo_root: find_repo_root().ok(), catalog, open_probes: Mutex::new(HashMap::new()) }
    }

    pub fn open_folder(path: PathBuf, principal: String, scopes: Vec<String>, catalog: Arc<Catalog>) -> Result<Self, GatewayError> {
        if !path.is_dir() {
            std::fs::create_dir_all(&path).map_err(|error| GatewayError::new(GatewayErrorCode::InputInvalid, format!("--folder `{}` does not exist and could not be created: {error}", path.display())))?;
        }
        Ok(Self::new(WorkspaceOrigin::Folder { path }, principal, scopes, catalog))
    }

    pub fn open_hub(base_url: String, space_id: String, token: Option<String>, principal: String, scopes: Vec<String>, catalog: Arc<Catalog>) -> Result<Self, GatewayError> {
        Ok(Self::new(WorkspaceOrigin::Hub { base_url, space_id, token }, principal, scopes, catalog))
    }

    pub fn origin(&self) -> &WorkspaceOrigin {
        &self.origin
    }

    fn actor_label(&self) -> String {
        format!("agent:{}#{}", self.principal, self.session_id)
    }

    /// 🗂️ Every document id currently persisted in this workspace's binding. Real for a folder
    /// binding (reads `FolderSqliteStorage`'s `document` table directly, no live actor needed); a hub
    /// binding honestly returns empty rather than fabricating a listing — enumerating a remote space's
    /// documents needs a REST listing endpoint this packet does not own (P4/hub territory), so this
    /// crate never invents one.
    pub fn workspace_artifact_ids(&self) -> Result<Vec<String>, GatewayError> {
        match &self.origin {
            WorkspaceOrigin::Folder { path } => {
                let storage = store::sync::FolderSqliteStorage::new(path.clone());
                storage.document_ids().map_err(|error| GatewayError::new(GatewayErrorCode::Internal, format!("listing {}: {error}", path.display())))
            }
            WorkspaceOrigin::Hub { .. } => Ok(Vec::new()),
        }
    }

    /// 📖️ Cold read of one document's real pack+spr bytes off the folder binding — no live actor,
    /// no codec, no interpretation: exactly what `semio://artifact/{id}` returns, host-opaque. `None`
    /// for a hub binding (needs a live `ArtifactHost::open` + wait-for-hydrate, not a cold local read)
    /// or a folder id with no row yet.
    pub fn read_artifact_bytes(&self, artifact_id: &str) -> Result<Option<(Vec<u8>, Vec<u8>)>, GatewayError> {
        match &self.origin {
            WorkspaceOrigin::Folder { path } => {
                let storage = store::sync::FolderSqliteStorage::new(path.clone());
                storage.read(artifact_id).map_err(|error| GatewayError::new(GatewayErrorCode::Internal, format!("reading `{artifact_id}`: {error}")))
            }
            WorkspaceOrigin::Hub { .. } => Ok(None),
        }
    }

    /// 🧪️ Opens (creating on first use) a real `ProbeStore` bound through `ArtifactHost` — real VCS
    /// history, real backbone attachment (`ArtifactHost::send`/`subscribe` — §6 of the brief: "guest
    /// `SendMessage{Backbone}` effects route to `ArtifactHost::send`; inbound
    /// `ArtifactEvent::RemoteMutations` come back as guest events"). Applies `initial` as the FIRST
    /// commit only if the document has no history yet, so re-running this against an already-seeded
    /// workspace is idempotent and never double-commits. Returns the resulting `RevisionStamp`.
    pub fn ensure_probe_artifact(&self, artifact_id: &str, initial: serde_json::Value) -> Result<crate::RevisionStamp, GatewayError> {
        let mut guard = self.open_probes.lock().unwrap_or_else(std::sync::PoisonError::into_inner);
        if !guard.contains_key(artifact_id) {
            let envelope = store::create_document_envelope::<ProbeSnapshot, ProbeMutation>(PROBE_SCHEMA, artifact_id, ProbeSnapshot::default(), None);
            let mut probe_store = ProbeStore::new(envelope).map_err(|error| GatewayError::new(GatewayErrorCode::Internal, format!("constructing probe store for `{artifact_id}`: {error}")))?;
            let channels = self.artifact_host.open(store::sync::ArtifactActorConfig { document_id: artifact_id.to_string(), schema: PROBE_SCHEMA.to_string(), bindings: vec![self.origin.persistence_binding()], watch_external: self.origin.watch_external(), actor: self.actor_label() });
            probe_store.attach_backbone(Box::new(channels.channel_backbone)).map_err(|error| GatewayError::new(GatewayErrorCode::Internal, format!("attaching backbone for `{artifact_id}`: {error}")))?;
            guard.insert(artifact_id.to_string(), probe_store);
        }
        let probe_store = guard.get_mut(artifact_id).expect("just inserted or already present");
        if probe_store.applied_edit_ids().is_empty() {
            probe_store.dispatch(store::ArtifactCommand::Apply { mutations: vec![ProbeMutation::SetValue(initial)], description: Some("os.agent headless seed".to_string()) }).map_err(|error| GatewayError::new(GatewayErrorCode::Internal, format!("seeding `{artifact_id}`: {error}")))?;
            self.artifact_host.send(artifact_id, store::sync::ArtifactActorMsg::LocalMutations { envelopes: Vec::new() });
        }
        let head_edit_id = probe_store.applied_edit_ids().last().cloned().unwrap_or_default();
        Ok(crate::RevisionStamp { artifact_id: artifact_id.to_string(), head_edit_id, cursor: probe_store.applied_edit_ids().len().to_string() })
    }

    /// 🔌️ Best-effort real activation attempt for `plugin_id` — see `activate_plugin_instance`'s own
    /// doc for exactly what this proves and what it deliberately does not.
    #[cfg(not(target_arch = "wasm32"))]
    pub fn attempt_plugin_activation(&self, plugin_id: &str) -> Result<PluginActivationOutcome, GatewayError> {
        let repo_root = self.repo_root.clone().ok_or_else(|| GatewayError::new(GatewayErrorCode::Internal, "repo root not found — cannot locate the plugin registry or compiled wasm"))?;
        let registry = load_plugin_registry(&repo_root)?;
        let entry = find_plugin_entry(&registry, plugin_id)?;
        let descriptor = load_package_descriptor(&entry.owner_root)?;
        let editor_app = descriptor
            .manifest
            .apps
            .iter()
            .find(|app| app.role == semio_framework::AppRole::Editor)
            .ok_or_else(|| GatewayError::new(GatewayErrorCode::NotFound, format!("plugin `{plugin_id}` declares no editor app")))?;
        let app_ref = semio_framework::AppRef { plugin_id: plugin_id.to_string(), app_id: editor_app.id.clone() };
        let runtime = semio_framework_plugin_host::WasmtimeRuntime::new(semio_framework_plugin_host::SharedEngineConfig::default()).map_err(|error| GatewayError::new(GatewayErrorCode::Internal, format!("building the shared wasmtime engine: {error}")))?;
        let (guest, outcome) = activate_plugin_instance(&runtime, &repo_root, entry, &descriptor, &app_ref, &self.actor_label(), 1)?;
        runtime.drop_instance(guest);
        Ok(outcome)
    }

    /// 🔌️ Constructs a real `crate::actions::ArtifactChannel` for `plugin_id` — what
    /// `P6-actions-policy`'s `ActionAdapter::new` takes in place of `MockArtifactChannel` once wired
    /// (bin.rs's job, once a real `--folder`/`--hub` workspace names which plugin its default
    /// instance targets).
    #[cfg(not(target_arch = "wasm32"))]
    pub fn open_artifact_channel(&self, plugin_id: &str) -> Result<PluginArtifactChannel, GatewayError> {
        let repo_root = self.repo_root.clone().ok_or_else(|| GatewayError::new(GatewayErrorCode::Internal, "repo root not found — cannot locate the plugin registry or compiled wasm"))?;
        let registry = load_plugin_registry(&repo_root)?;
        let entry = find_plugin_entry(&registry, plugin_id)?.clone();
        let descriptor = load_package_descriptor(&entry.owner_root)?;
        let editor_app = descriptor
            .manifest
            .apps
            .iter()
            .find(|app| app.role == semio_framework::AppRole::Editor)
            .ok_or_else(|| GatewayError::new(GatewayErrorCode::NotFound, format!("plugin `{plugin_id}` declares no editor app")))?;
        let app_ref = semio_framework::AppRef { plugin_id: plugin_id.to_string(), app_id: editor_app.id.clone() };
        PluginArtifactChannel::new(repo_root, entry, descriptor, app_ref, self.actor_label())
    }
}


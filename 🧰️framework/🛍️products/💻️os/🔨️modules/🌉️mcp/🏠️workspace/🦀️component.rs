//#region 🔖️ProbeDocument
/// 🧪️ A generic, single-JSON-value document kind this crate owns outright — used ONLY to exercise
/// the real `store::sync::ArtifactHost` / `ArtifactStore` / backbone-propagation pipeline end to end
/// (§6 of the packet brief: "a commit made headlessly propagates to any live shell on the same
/// folder/hub — prove it in a test if you can") without pretending to understand any actual plugin's
/// document schema, which is host-opaque by design (this file's own module doc). Schema id
/// `os.agent.probe/v1` is namespaced under `os.agent.*` precisely so it can never collide with a real
/// plugin schema id.
pub const PROBE_SCHEMA: &str = "os.agent.probe/v1";

#[derive(Clone, Debug, Default, PartialEq, serde::Serialize, serde::Deserialize)]
pub struct ProbeSnapshot(pub serde_json::Value);

impl store::ArtifactDsl for ProbeSnapshot {
    const EXTENSION: &'static str = "probe";

    fn parse_dsl(text: &str) -> Result<Self, store::TextError> {
        serde_json::from_str(text).map(ProbeSnapshot).map_err(|error| store::TextError::new(error.to_string(), store::TextSpan::at(0, 0)))
    }

    fn print_dsl(&self) -> String {
        serde_json::to_string(&self.0).unwrap_or_else(|_| "null".to_string())
    }
}

impl store::ArtifactPack for ProbeSnapshot {
    fn encode_pack_with(&self, _options: &store::PackEncodeOptions) -> Result<Vec<u8>, store::PackError> {
        serde_json::to_vec(&self.0).map_err(|error| store::PackError::Schema(error.to_string()))
    }

    fn decode_pack_with(bytes: &[u8], _options: &store::PackDecodeOptions) -> Result<Self, store::PackError> {
        serde_json::from_slice(bytes).map(ProbeSnapshot).map_err(|error| store::PackError::Schema(error.to_string()))
    }
}

#[derive(Clone, Debug, Default, PartialEq, serde::Serialize, serde::Deserialize)]
pub struct ProbeDiff(pub serde_json::Value);

impl store::MutationDiff<ProbeSnapshot> for ProbeDiff {
    fn apply(&self, _base: &ProbeSnapshot) -> store::MutationApplyResult<ProbeSnapshot> {
        Ok(ProbeSnapshot(self.0.clone()))
    }

    fn absorb(&mut self, other: Self) {
        self.0 = other.0;
    }
}

/// 🧪️ The only operation this probe document supports: whole-value replace — mirrors
/// `crate::os_store::impl_whole_record_config!`'s "no field-level diff" shape, the simplest legal
/// `Mutation` implementor.
#[derive(Clone, Debug, PartialEq, serde::Serialize, serde::Deserialize)]
pub enum ProbeMutation {
    SetValue(serde_json::Value),
}

impl store::Mutation<ProbeSnapshot> for ProbeMutation {
    type Diff = ProbeDiff;

    fn diff(&self, _base: &ProbeSnapshot) -> store::MutationOutcome<ProbeDiff> {
        let ProbeMutation::SetValue(value) = self;
        store::MutationOutcome::new(ProbeDiff(value.clone()))
    }

    fn inverse(&self, base: &ProbeSnapshot) -> Vec<Self> {
        vec![ProbeMutation::SetValue(base.0.clone())]
    }
}

impl store::OpText for ProbeMutation {
    fn print_op(&self) -> String {
        let ProbeMutation::SetValue(value) = self;
        serde_json::to_string(value).unwrap_or_else(|_| "null".to_string())
    }

    fn parse_op(line: &str) -> Result<Self, store::TextError> {
        serde_json::from_str(line).map(ProbeMutation::SetValue).map_err(|error| store::TextError::new(error.to_string(), store::TextSpan::at(0, 0)))
    }
}

impl store::OpBinary for ProbeMutation {
    fn encode_op(&self) -> Result<Vec<u8>, store::ProtocolError> {
        let ProbeMutation::SetValue(value) = self;
        serde_json::to_vec(value).map_err(|error| store::ProtocolError::Malformed { what: "probe-op", offset: 0, detail: error.to_string() })
    }

    fn decode_op(bytes: &[u8]) -> Result<Self, store::ProtocolError> {
        serde_json::from_slice(bytes).map(ProbeMutation::SetValue).map_err(|error| store::ProtocolError::Malformed { what: "probe-op", offset: 0, detail: error.to_string() })
    }
}

pub type ProbeStore = store::ArtifactStore<ProbeSnapshot, ProbeMutation>;

/// 🔒️ Registers the probe codec exactly once per process — mirrors
/// `🏪️store/🔄️sync/🦀️component.rs`'s own test-only `ensure_demo_codec_registered`, but real (not
/// `#[cfg(test)]`): the backbone actor needs the registered `ArtifactCodec` to turn a local `Edit`
/// into a schema-agnostic wire `MutationEnvelope` it can persist/replicate.
pub fn ensure_probe_codec_registered() {
    static ONCE: std::sync::Once = std::sync::Once::new();
    ONCE.call_once(|| {
        let _ = store::register_document_codec(store::ArtifactCodec::of::<ProbeSnapshot, ProbeMutation>(PROBE_SCHEMA));
    });
}

// (`🦀️component.rs`, not `📦️bin.rs`) so every consumer (this crate included) calls the same function
// instead of each maintaining its own copy. Until that lands, this reads the SAME generated data
// `🏃️run` itself reads (`🔌️plugin/📇️registry/🤖️generated/🔣️plugins.json` — gitignored, regenerated by
// `bun nx run @semio-tech/plugin-registry:generate`, the JSON-mirror twin of the `.rs`
// `PLUGIN_WASM_ARTIFACTS` table `🏃️run/📦️bin.rs` `include!`s) rather than guessing a naming
// convention — several plugin ids transform irregularly (`cad-extension-aec-building` ->
// `semio_s_plugin_cad_aec_building.wasm`, NOT the mechanical `_extension_` retained), so only the
// generated table is a source of truth.
#[derive(Clone, Debug)]
pub struct PluginRegistryEntry {
    pub plugin_id: String,
    /// 📁️ Owner root of the plugin package (`✏️s/🔌️plugins/<emoji dir>`, e.g. where
    /// `🔣️descriptor.json` lives) — NOT the `cratePath` the registry JSON stores (that names the
    /// `📦️packages/🦀️rust` crate root two levels below the owner root; see the taxonomy's own
    /// `_languageNeutralityComment`, restated in `📓️status.md`'s E1-describe entry: "descriptors
    /// live at the plugin/extension owner root ... siblings of `📦️packages`").
    pub owner_root: PathBuf,
    pub wasm_out: String,
}

const PLUGIN_WASM_TARGET_DIR: &str = "target/wasm32-wasip2";
const PLUGIN_WASM_PROFILE_DIRS: [&str; 2] = ["debug", "wasm-release"];

/// 🧭️ Locates the repo root — identical algorithm to `🏃️run/📦️bin.rs::find_repo_root` (walk up from
/// this crate's own `CARGO_MANIFEST_DIR` for `nx.json`, `SEMIO_REPO_ROOT` override first) so a direct
/// `cargo run -p semio-framework-os-mcp` from an arbitrary cwd still resolves correctly.
pub fn find_repo_root() -> Result<PathBuf, GatewayError> {
    if let Ok(value) = std::env::var("SEMIO_REPO_ROOT") {
        let candidate = PathBuf::from(value);
        if candidate.join("nx.json").is_file() {
            return Ok(candidate);
        }
    }
    let mut candidate = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    loop {
        if candidate.join("nx.json").is_file() {
            return Ok(candidate);
        }
        if !candidate.pop() {
            return Err(GatewayError::new(GatewayErrorCode::Internal, "could not locate the repo root (no nx.json found above SEMIO_REPO_ROOT or CARGO_MANIFEST_DIR)"));
        }
    }
}

/// 📇️ Reads `🔌️plugin/📇️registry/🤖️generated/🔣️plugins.json` — real generated registry data (not
/// this packet's own invention), parsed narrowly for the two fields this crate needs.
pub fn load_plugin_registry(repo_root: &Path) -> Result<Vec<PluginRegistryEntry>, GatewayError> {
    let registry_path = repo_root.join("🧰️framework/🛍️products/💻️os/🔨️modules/🔌️plugin/📇️registry/🤖️generated/🔣️plugins.json");
    let text = std::fs::read_to_string(&registry_path).map_err(|error| GatewayError::new(GatewayErrorCode::NotFound, format!("plugin registry not generated (looked at {}): {error} — run `bun nx run @semio-tech/plugin-registry:generate`", registry_path.display())))?;
    let raw: Vec<serde_json::Value> = serde_json::from_str(&text).map_err(|error| GatewayError::new(GatewayErrorCode::Internal, format!("plugin registry {} is not valid JSON: {error}", registry_path.display())))?;
    let mut entries = Vec::with_capacity(raw.len());
    for row in raw {
        let plugin_id = row.get("pluginId").and_then(serde_json::Value::as_str).ok_or_else(|| GatewayError::new(GatewayErrorCode::Internal, "plugin registry row missing pluginId"))?.to_string();
        let crate_path = row.get("cratePath").and_then(serde_json::Value::as_str).ok_or_else(|| GatewayError::new(GatewayErrorCode::Internal, format!("plugin registry row `{plugin_id}` missing cratePath")))?;
        let wasm_out = row.get("wasmOut").and_then(serde_json::Value::as_str).ok_or_else(|| GatewayError::new(GatewayErrorCode::Internal, format!("plugin registry row `{plugin_id}` missing wasmOut")))?.to_string();
        // 🎯️ `cratePath` = `<owner root>/📦️packages/🦀️rust` — two components back to the owner root,
        // the sibling directory `🔣️descriptor.json` actually lives in (see this fn's own doc).
        let owner_root = repo_root.join(crate_path).parent().and_then(Path::parent).ok_or_else(|| GatewayError::new(GatewayErrorCode::Internal, format!("plugin registry row `{plugin_id}` has an implausibly shallow cratePath `{crate_path}`")))?.to_path_buf();
        entries.push(PluginRegistryEntry { plugin_id, owner_root, wasm_out });
    }
    Ok(entries)
}

pub fn find_plugin_entry<'a>(entries: &'a [PluginRegistryEntry], plugin_id: &str) -> Result<&'a PluginRegistryEntry, GatewayError> {
    entries.iter().find(|entry| entry.plugin_id == plugin_id).ok_or_else(|| GatewayError::new(GatewayErrorCode::NotFound, format!("plugin `{plugin_id}` is not in the plugin registry")))
}

/// 🗺️ Resolves one plugin's compiled `.wasm` under `target/wasm32-wasip2/{debug,wasm-release}` —
/// same profile-dir fallback order as `🏃️run/📦️bin.rs::resolve_plugin_paths`.
pub fn resolve_plugin_wasm_path(repo_root: &Path, entry: &PluginRegistryEntry) -> Result<PathBuf, GatewayError> {
    let mut tried = Vec::new();
    for profile_dir in PLUGIN_WASM_PROFILE_DIRS {
        let path = repo_root.join(PLUGIN_WASM_TARGET_DIR).join(profile_dir).join(&entry.wasm_out);
        tried.push(path.display().to_string());
        if path.is_file() {
            return Ok(path);
        }
    }
    Err(GatewayError::new(GatewayErrorCode::NotFound, format!("plugin `{}`'s compiled wasm is missing (tried: {}); build it with `bun nx run @semio-tech/framework-os-dev:build -- {}`", entry.plugin_id, tried.join(", "), entry.plugin_id)))
}

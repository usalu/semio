impl HeadlessWorkspace {
    fn read_artifact_resource(&self, artifact_id: &str, suffix: Option<&str>, uri: &str) -> Result<Vec<ResourceContent>, GatewayError> {
        match suffix {
            None => match self.read_artifact_bytes(artifact_id)? {
                Some((pack, spr)) => {
                    let body = serde_json::json!({ "artifactId": artifact_id, "packBytes": pack.len(), "sprBytes": spr.len(), "packBase64": base64_encode(&pack) });
                    Ok(vec![ResourceContent { uri: uri.to_string(), mime_type: Some("application/json".to_string()), text: Some(body.to_string()), blob: None }])
                }
                None => Err(GatewayError::new(GatewayErrorCode::NotFound, format!("no such artifact: {artifact_id}"))),
            },
            Some("schema") => Err(GatewayError::new(GatewayErrorCode::PluginUnavailable, "artifact schema resolution needs a live plugin instance's `describe()`/manifest, not yet reachable from this workspace for an arbitrary artifact kind").retryable()),
            Some("history") => match self.open_probes.lock().unwrap_or_else(std::sync::PoisonError::into_inner).get(artifact_id) {
                Some(probe_store) => Ok(vec![ResourceContent { uri: uri.to_string(), mime_type: Some("application/json".to_string()), text: Some(serde_json::json!({ "appliedEditIds": probe_store.applied_edit_ids() }).to_string()), blob: None }]),
                None => Err(GatewayError::new(GatewayErrorCode::NotFound, format!("`{artifact_id}` has no open history in this workspace"))),
            },
            Some("validation") => Ok(vec![ResourceContent { uri: uri.to_string(), mime_type: Some("application/json".to_string()), text: Some(serde_json::json!({ "valid": true, "messages": [] }).to_string()), blob: None }]),
            Some(other) => Err(GatewayError::new(GatewayErrorCode::NotFound, format!("no such artifact sub-resource: {other}"))),
        }
    }
}

fn base64_encode(bytes: &[u8]) -> String {
    const ALPHABET: &[u8; 64] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    let mut out = String::with_capacity(bytes.len().div_ceil(3) * 4);
    for chunk in bytes.chunks(3) {
        let b0 = chunk[0];
        let b1 = *chunk.get(1).unwrap_or(&0);
        let b2 = *chunk.get(2).unwrap_or(&0);
        out.push(ALPHABET[(b0 >> 2) as usize] as char);
        out.push(ALPHABET[(((b0 & 0x03) << 4) | (b1 >> 4)) as usize] as char);
        out.push(if chunk.len() > 1 { ALPHABET[(((b1 & 0x0f) << 2) | (b2 >> 6)) as usize] as char } else { '=' });
        out.push(if chunk.len() > 2 { ALPHABET[(b2 & 0x3f) as usize] as char } else { '=' });
    }
    out
}

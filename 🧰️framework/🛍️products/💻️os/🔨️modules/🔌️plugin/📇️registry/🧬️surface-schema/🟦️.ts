//#region 🔖️Run
export type SurfaceSchemaOptions = {
  readonly check: boolean;
  readonly dryRun: boolean;
  readonly plugin?: string;
  readonly noRust: boolean;
  readonly signal?: AbortSignal;
  readonly onProgress?: (done: number, total: number, label: string) => void;
};

/** @emoji 🔐️ Who owns each required leaf of one lane on disk. `authored` leaves are hand-carved and
 * are never written; `absent` leaves are the holes the taxonomy reports. `hollow` — the whole reason
 * this is a named predicate — is the partly-authored lane: it has authored leaves AND holes, so the
 * projection must fill the holes without touching the authored ones, instead of ceding the lane. */
export function surfaceSchemaLaneOwnership(facetAbs: string, requiredLeaves: readonly string[]): { readonly authored: string[]; readonly absent: string[]; readonly hollow: boolean; readonly ceded: boolean } {
  const authored: string[] = [];
  const absent: string[] = [];
  for (const filename of requiredLeaves) {
    const abs = join(facetAbs, filename);
    if (!existsSync(abs)) absent.push(filename);
    else if (!readFileSync(abs, "utf8").includes(SURFACE_SCHEMA_BANNER)) authored.push(filename);
  }
  return { authored, absent, hollow: authored.length > 0 && absent.length > 0, ceded: authored.length > 0 && absent.length === 0 };
}

/** @emoji 🏃️ Projects (or, in `--check`, verifies) every discovered lane. Idempotent: a lane whose five
 * leaves already equal the projection is `current`; a lane whose leaves all exist without the
 * ownership banner is `authored` and is never rewritten; a banner-carrying leaf that differs is
 * `drift`.
 *
 * A lane is `authored` only when it is **complete**. A partly authored lane — some leaves hand-carved,
 * others absent — is a hole the taxonomy reports, so the projection fills the absent leaves from the
 * ordinary source of truth and leaves every authored leaf byte-untouched. `📏️field-parity` compares
 * name, optionality and cardinality (not scalar), so a mirror derived from the bound `pub struct`
 * stays parity-identical to a hand-carved normative `🔣️.json` that merely spells a scalar loosely. */
export function runSurfaceSchemaProjection(repoRoot: string, options: SurfaceSchemaOptions): SurfaceSchemaOutcome[] {
  const owners = discoverSurfaceSchemaOwners(repoRoot, options.plugin);
  const outcomes: SurfaceSchemaOutcome[] = [];
  for (let index = 0; index < owners.length; index++) {
    if (options.signal?.aborted) throw new Error(`${SURFACE_SCHEMA_CONTRACT_ID}: cancelled after ${index}/${owners.length} lane(s)`);
    const owner = owners[index]!;
    options.onProgress?.(index + 1, owners.length, `${owner.pluginId} ${owner.ownerLabel} ${owner.lane}`);
    const ownership = surfaceSchemaLaneOwnership(owner.facetAbs, taxonomySchemaFilenames(owner.facetAbs));
    const authoredLeaves = ownership.authored;
    if (ownership.ceded) {
      outcomes.push({ kind: "authored", owner, files: authoredLeaves.map((filename) => relative(repoRoot, join(owner.facetAbs, filename)).replaceAll("\\", "/")) });
      continue;
    }
    const source = resolveSurfaceSchemaSource(repoRoot, owner);
    if (!source) {
      outcomes.push({ kind: "blocked", owner, reason: owner.typeName ? `no \`pub struct ${owner.typeName}\` declaration found` : "the surface declares no `type Config`/`type Presence` binding" });
      continue;
    }
    const nested = resolveSurfaceSchemaDefinitions(repoRoot, owner, source.extract);
    if (nested.cyclic.length) {
      outcomes.push({ kind: "blocked", owner, reason: `nested declaration(s) ${nested.cyclic.join(", ")} are cyclic and need indirection no projection owns` });
      continue;
    }
    const blocker = surfaceSchemaProjectionBlocker(source.extract, nested.definitions);
    if (blocker) {
      outcomes.push({ kind: "blocked", owner, reason: blocker });
      continue;
    }
    const projected = projectSurfaceSchemaLane(repoRoot, owner, source.extract, source.sourceRel, nested.definitions);
    const stale = Object.entries(projected).filter(([filename, content]) => {
      if (authoredLeaves.includes(filename)) return false;
      const abs = join(owner.facetAbs, filename);
      return !existsSync(abs) || readFileSync(abs, "utf8") !== content;
    });
    const mount = options.noRust ? ({ ok: true, glueAbs: null } as const) : mountProjectedRustLeaf(owner.pluginRoot, owner, false);
    if (!mount.ok) {
      outcomes.push({ kind: "blocked", owner, reason: `Rust leaf cannot be mounted: ${mount.reason}` });
      continue;
    }
    if (stale.length === 0 && mount.glueAbs === null) {
      outcomes.push({ kind: "current", owner });
      continue;
    }
    const files = stale.map(([filename]) => relative(repoRoot, join(owner.facetAbs, filename)).replaceAll("\\", "/"));
    if (mount.glueAbs) files.push(relative(repoRoot, mount.glueAbs).replaceAll("\\", "/"));
    if (options.check || options.dryRun) {
      outcomes.push({ kind: options.check ? "drift" : "written", owner, files });
      continue;
    }
    mkdirSync(owner.facetAbs, { recursive: true });
    for (const [filename, content] of stale) writeFileSync(join(owner.facetAbs, filename), content);
    if (!options.noRust) mountProjectedRustLeaf(owner.pluginRoot, owner, true);
    outcomes.push({ kind: "written", owner, files });
  }
  return outcomes;
}

/** 🚪️ `surface-schema` CLI: project every lane, or verify with `--check`. */
export class SurfaceSchemaScript extends BundleScript {
  run(segments: string[]): void {
    const repoRoot = getWorkspaceRoot();
    const controller = new AbortController();
    const cancel = (): void => controller.abort();
    process.once("SIGINT", cancel);
    process.once("SIGTERM", cancel);
    const pluginIndex = segments.indexOf("--plugin");
    let last = 0;
    const outcomes = runSurfaceSchemaProjection(repoRoot, {
      check: segments.includes("--check"),
      dryRun: segments.includes("--dry-run"),
      plugin: pluginIndex >= 0 ? segments[pluginIndex + 1] : undefined,
      noRust: segments.includes("--no-rust"),
      signal: controller.signal,
      onProgress: (done, total, label) => {
        if (done !== total && done - last < 25) return;
        last = done;
        console.log(`[surface-schema] ${done}/${total} ${label}`);
      },
    });
    process.off("SIGINT", cancel);
    process.off("SIGTERM", cancel);
    const counted = (kind: SurfaceSchemaOutcome["kind"]): SurfaceSchemaOutcome[] => outcomes.filter((outcome) => outcome.kind === kind);
    for (const outcome of counted("blocked")) console.log(`  blocked ${outcome.owner.pluginId} ${outcome.owner.ownerLabel} ${outcome.owner.lane}: ${(outcome as { reason: string }).reason}`);
    for (const outcome of counted("drift")) console.error(`  drift ${(outcome as { files: string[] }).files.join(", ")}`);
    console.log(`[surface-schema] ${outcomes.length} lane(s): ${counted("written").length} written, ${counted("current").length} current, ${counted("authored").length} authored, ${counted("blocked").length} blocked, ${counted("drift").length} drifted`);
    if (segments.includes("--check") && counted("drift").length > 0) {
      console.error(`[surface-schema] run \`bun nx run @semio-tech/plugin-registry:surface-schema\` to refresh.`);
      process.exit(1);
    }
  }
}

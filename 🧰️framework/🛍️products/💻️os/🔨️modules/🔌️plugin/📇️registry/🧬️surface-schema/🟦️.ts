/** @emoji 📖️ Every `.rs` file under one root, sorted, so a struct lookup is deterministic. */
function rustFilesUnder(root: string, out: string[] = []): string[] {
  if (!existsSync(root)) return out;
  for (const name of readdirSync(root).sort()) {
    if (name.startsWith(".") || name === "target" || name === "node_modules") continue;
    const path = join(root, name);
    if (statSync(path).isDirectory()) rustFilesUnder(path, out);
    else if (name.endsWith(".rs")) out.push(path);
  }
  return out;
}

/** @emoji 🗄️ One walk of a plugin tree per run, not one per lane. `🗄️stdio` alone holds ~6 000 Rust
 * leaves against 352 lanes, so re-walking and re-parsing per lane is quadratic and never finishes;
 * the index below turns source resolution into a map lookup. */
const RUST_FILE_INDEX = new Map<string, string[]>();

/** @emoji 🏷️ `pub struct <Name>` → the sorted-first file declaring it, one cheap scan per plugin tree. */
const STRUCT_INDEX = new Map<string, Map<string, string>>();

/** @emoji 🧷️ Resolved `#[path]` target → the wiring file declaring it, one cheap scan per plugin tree. */
const MOUNT_INDEX = new Map<string, Map<string, string>>();

function rustFilesOf(root: string): string[] {
  const cached = RUST_FILE_INDEX.get(root);
  if (cached) return cached;
  const files = rustFilesUnder(root);
  RUST_FILE_INDEX.set(root, files);
  return files;
}

function structIndexOf(root: string): Map<string, string> {
  const cached = STRUCT_INDEX.get(root);
  if (cached) return cached;
  const index = new Map<string, string>();
  for (const file of rustFilesOf(root)) {
    const text = readFileSync(file, "utf8");
    // 🔁️ A projected leaf is never a source of truth for the next run: once 269 lanes each declare
    // `pub struct NoConfig {}`, indexing them makes a second run resolve `NoConfig` to a sibling
    // projection instead of the framework sentinel, rewriting every `@see` line — the projection
    // would never converge and `--check` would fail on a tree it had just written.
    if (text.includes(SURFACE_SCHEMA_BANNER)) continue;
    for (const match of text.matchAll(/\bpub\s+struct\s+([A-Za-z_][A-Za-z0-9_]*)\s*\{/gu)) {
      if (!index.has(match[1]!)) index.set(match[1]!, file);
    }
  }
  STRUCT_INDEX.set(root, index);
  return index;
}

/** @emoji ♻️ Drops the per-run source indexes; a second run in the same process re-reads the tree. */
export function resetSurfaceSchemaIndexes(): void {
  RUST_FILE_INDEX.clear();
  STRUCT_INDEX.clear();
  MOUNT_INDEX.clear();
}

/** @emoji 🔬️ Resolves one lane's Rust declaration, searching the narrowest owner first: the lane's own
 * leaf, the plugin root's lane leaf, the framework sentinel file, then the plugin tree. Returns
 * `null` rather than inventing a shape when nothing declares the bound type. */
export function resolveSurfaceSchemaSource(repoRoot: string, owner: SurfaceSchemaOwner): { readonly extract: PolicySchemaLeafExtract; readonly sourceRel: string } | null {
  if (!owner.typeName) return null;
  const laneDirName = owner.lane === "config" ? CONFIG_FACET_DIR : PRESENCE_FACET_DIR;
  const indexed = structIndexOf(owner.pluginRoot).get(owner.typeName);
  const sentinel = join(repoRoot, SURFACE_SCHEMA_SENTINEL_SOURCE);
  const candidates = [join(owner.laneAbs, TAXONOMY_LEAF_FILENAME), join(owner.pluginRoot, laneDirName, TAXONOMY_LEAF_FILENAME), ...(indexed ? [indexed] : []), sentinel];
  for (const candidate of candidates) {
    if (!existsSync(candidate) || !statSync(candidate).isFile()) continue;
    const extract = policyExtractRustSchemaFields(readFileSync(candidate, "utf8"), owner.typeName);
    if (extract.typeName === owner.typeName) return { extract, sourceRel: relative(repoRoot, candidate).replaceAll("\\", "/") };
  }
  return null;
}

/** @emoji 🔎️ One named Rust declaration anywhere in the plugin tree, or the framework sentinel file.
 * The same index `resolveSurfaceSchemaSource` uses, addressed by type name instead of by lane. */
function resolveRustDeclaration(repoRoot: string, owner: SurfaceSchemaOwner, typeName: string): PolicySchemaLeafExtract | null {
  const indexed = structIndexOf(owner.pluginRoot).get(typeName);
  for (const candidate of [...(indexed ? [indexed] : []), join(repoRoot, SURFACE_SCHEMA_SENTINEL_SOURCE)]) {
    if (!existsSync(candidate) || !statSync(candidate).isFile()) continue;
    const extract = policyExtractRustSchemaFields(readFileSync(candidate, "utf8"), typeName);
    if (extract.typeName === typeName) return extract;
  }
  return null;
}

/** @emoji 🪆️ Every nested declaration one lane's root shape references, transitively, dependencies
 * first and each emitted exactly once. A composite field is not a wall: the bound `pub struct` names
 * the nested type, the plugin tree declares it, so the projection resolves it the same way it
 * resolved the root and emits it as a `$defs` entry with a mirror in each of the four other formats.
 *
 * Two shapes are refused rather than invented: a type nothing declares (there is no shape to read),
 * and a cycle (a self-referential Rust struct needs indirection the projection does not own). */
export function resolveSurfaceSchemaDefinitions(repoRoot: string, owner: SurfaceSchemaOwner, root: PolicySchemaLeafExtract): { readonly definitions: PolicySchemaLeafExtract[]; readonly unresolved: string[]; readonly cyclic: string[] } {
  const definitions: PolicySchemaLeafExtract[] = [];
  const seen = new Set<string>([root.typeName]);
  const unresolved: string[] = [];
  const cyclic: string[] = [];
  const visit = (extract: PolicySchemaLeafExtract, stack: readonly string[]): void => {
    for (const field of extract.fields) {
      const name = field.scalar;
      if (SCALARS[name]) continue;
      if (stack.includes(name)) {
        if (!cyclic.includes(name)) cyclic.push(name);
        continue;
      }
      if (seen.has(name)) continue;
      seen.add(name);
      const nested = resolveRustDeclaration(repoRoot, owner, name);
      if (!nested) {
        unresolved.push(`${field.name}: ${name}`);
        continue;
      }
      visit(nested, [...stack, name]);
      definitions.push(nested);
    }
  };
  visit(root, [root.typeName]);
  return { definitions, unresolved, cyclic };
}

/** @emoji 🚧️ Why a resolved shape cannot be projected yet, or `null` when it can. Every composite
 * field must resolve to one of the `definitions` the lane nests; a map or an optional repeated field
 * has no cross-format-identical spelling in any of the five leaves. */
export function surfaceSchemaProjectionBlocker(extract: PolicySchemaLeafExtract, definitions: readonly PolicySchemaLeafExtract[] = []): string | null {
  const declared = new Set(definitions.map((definition) => definition.typeName));
  const shapes = [extract, ...definitions];
  const foreign = shapes.flatMap((shape) => shape.fields.filter((field) => !SCALARS[field.scalar] && !declared.has(field.scalar)).map((field) => `${field.name}: ${field.scalar}`));
  if (foreign.length) return `composite field type(s) ${foreign.join(", ")} have no resolvable Rust declaration to nest`;
  // 🈳️ GraphQL has no map type and proto3 forbids `optional` on a repeated or map field, so these two
  // shapes cannot hold identical optionality/cardinality across all five leaves; the repo library's
  // field-parity law would (rightly) report the divergence. They are authored, never projected.
  const inexpressible = shapes.flatMap((shape) => shape.fields.filter((field) => field.cardinality === "map" || (field.optional && (field.cardinality === "list" || field.cardinality === "fixedList"))).map((field) => field.name));
  return inexpressible.length ? `field(s) ${inexpressible.join(", ")} have no cross-format-identical spelling (map, or optional repeated)` : null;
}

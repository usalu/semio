//#region 🔖️Projection
function snake(name: string): string {
  return name.replace(/([a-z0-9])([A-Z])/gu, "$1_$2").toLowerCase();
}

/** @emoji 🍃️ One field's element node: a declared scalar, or a `$ref` into the lane's own `$defs`. */
function jsonElementNode(field: PolicySchemaFieldShape): Record<string, unknown> {
  const scalar = SCALARS[field.scalar];
  return scalar ? { ...scalar.json } : { $ref: `#/$defs/${field.scalar}` };
}

function jsonProperty(field: PolicySchemaFieldShape, lane: SurfaceSchemaLane): Record<string, unknown> {
  const leaf = jsonElementNode(field);
  const shaped =
    field.cardinality === "list" || field.cardinality === "fixedList" ? { type: "array", items: leaf }
    : field.cardinality === "map" ? { type: "object", additionalProperties: leaf }
    : leaf;
  return { ...shaped, "x-semio-state": lane };
}

function jsonObjectSchema(extract: PolicySchemaLeafExtract, lane: SurfaceSchemaLane): Record<string, unknown> {
  return {
    title: extract.typeName,
    type: "object",
    additionalProperties: false,
    required: extract.fields.filter((field) => !field.optional).map((field) => field.name),
    properties: Object.fromEntries(extract.fields.map((field) => [field.name, jsonProperty(field, lane)])),
  };
}

/** @emoji 🔣️ The normative leaf: a draft-07 object schema over the source struct's fields, with every
 * nested declaration the shape references carried in `$defs` and addressed by `$ref` — the dialect's
 * own composition mechanism, so the leaf stays one self-contained document. */
export function projectJsonSchema(extract: PolicySchemaLeafExtract, owner: SurfaceSchemaOwner, definitions: readonly PolicySchemaLeafExtract[] = []): string {
  const document: Record<string, unknown> = {
    $schema: TAXONOMY.schemaJsonDialect,
    $id: `${TAXONOMY.schemaExportResolution.idBase}app/${owner.appId.split(".").slice(1).join("/")}/${owner.lane}/schema.json`,
    $comment: SURFACE_SCHEMA_BANNER,
    ...jsonObjectSchema(extract, owner.lane),
  };
  if (definitions.length) document.$defs = Object.fromEntries(definitions.map((definition) => [definition.typeName, jsonObjectSchema(definition, owner.lane)]));
  return `${JSON.stringify(document, null, 2)}\n`;
}

function rustFieldType(field: PolicySchemaFieldShape): string {
  const scalar = SCALARS[field.scalar]?.rust ?? field.scalar;
  const shaped =
    field.cardinality === "list" || field.cardinality === "fixedList" ? `Vec<${scalar}>`
    : field.cardinality === "map" ? `std::collections::BTreeMap<String, ${scalar}>`
    : scalar;
  return field.optional ? `Option<${shaped}>` : shaped;
}

function rustStruct(extract: PolicySchemaLeafExtract, lane: SurfaceSchemaLane, docstring: string): string {
  const fields = extract.fields.map((field) => `    /// 🏷️ @state ${lane}\n    pub ${snake(field.name)}: ${rustFieldType(field)},`).join("\n");
  return [docstring, "#[derive(Clone, Debug, Default, PartialEq)]", `pub struct ${extract.typeName} {${fields ? `\n${fields}\n` : ""}}`].join("\n");
}

/** @emoji 🦀️ The Rust mirror. Derive-free and dependency-free on purpose: this leaf is the lane's
 * schema declaration, not its app wiring, so it compiles inside any plugin crate the projection
 * mounts it into without touching that crate's manifest. The state class rides a doc comment rather
 * than the authored lanes' `#[state(…)]`, because that attribute is consumed by the `ArtifactSchema`
 * derive and `rustc` rejects it without one — the normative `🔣️.json` leaf carries the machine-read
 * `x-semio-state` either way. */
export function projectRustLeaf(extract: PolicySchemaLeafExtract, owner: SurfaceSchemaOwner, sourceRel: string, definitions: readonly PolicySchemaLeafExtract[] = []): string {
  const nested = definitions.map((definition) => rustStruct(definition, owner.lane, `/// 🪆️ Nested \`${definition.typeName}\` of the \`${owner.appId}\` ${owner.lane} schema.`));
  return [
    `//! ${SURFACE_SCHEMA_BANNER}`,
    `//! @see ${sourceRel}`,
    "",
    ...nested.flatMap((declaration) => [declaration, ""]),
    rustStruct(extract, owner.lane, `/// 🧬️ ${owner.lane} schema of \`${owner.appId}\`, projected from \`${extract.typeName}\`.`),
    "",
  ].join("\n");
}

function typescriptFieldType(field: PolicySchemaFieldShape): string {
  const scalar = SCALARS[field.scalar]?.typescript ?? field.scalar;
  return field.cardinality === "list" || field.cardinality === "fixedList" ? `readonly ${scalar}[]` : field.cardinality === "map" ? `Readonly<Record<string, ${scalar}>>` : scalar;
}

function typescriptInterface(extract: PolicySchemaLeafExtract, lane: SurfaceSchemaLane): string {
  const fields = extract.fields.map((field) => `  /** @state ${lane} */\n  ${field.optional ? `${field.name}?` : field.name}: ${typescriptFieldType(field)};`).join("\n");
  return `export interface ${extract.typeName} {${fields ? `\n${fields}\n` : ""}}`;
}

/** @emoji 🟦️ The TypeScript mirror — plain interfaces, no imports, so it adds no diagnostics anywhere.
 * A 64-bit integer is a `number` bounded by the normative leaf's `minimum`/`maximum`, never a silent
 * wider carrier: that is exactly the contract `packValueToExactJson` enforces at runtime. */
export function projectTypescriptLeaf(extract: PolicySchemaLeafExtract, owner: SurfaceSchemaOwner, sourceRel: string, definitions: readonly PolicySchemaLeafExtract[] = []): string {
  return [
    `/** ${SURFACE_SCHEMA_BANNER}`,
    ` * @see ${sourceRel} */`,
    ...definitions.map((definition) => `${typescriptInterface(definition, owner.lane)}\n`),
    typescriptInterface(extract, owner.lane),
    "",
  ].join("\n");
}

function graphqlFieldType(field: PolicySchemaFieldShape): string {
  const scalar = SCALARS[field.scalar]?.graphql ?? field.scalar;
  const shaped = field.cardinality === "list" || field.cardinality === "fixedList" ? `[${scalar}!]` : scalar;
  return field.optional ? shaped : `${shaped}!`;
}

function graphqlType(extract: PolicySchemaLeafExtract, lane: SurfaceSchemaLane): string {
  const fields = extract.fields.map((field) => `  ${field.name}: ${graphqlFieldType(field)} @state(class: ${lane.toUpperCase()})`).join("\n");
  return fields ? `type ${extract.typeName} {\n${fields}\n}` : `type ${extract.typeName}`;
}

/** @emoji 🔗️ The GraphQL mirror. GraphQL has no empty-object type — `type X {}` is a syntax error — so
 * a field-less schema is the braceless `type X`, which real GraphQL parsers accept and which invents
 * no placeholder field. A nested declaration is an ordinary sibling `type` in the same document;
 * `Long` and `@state` come from the shared `GRAPHQL_STATE_PREAMBLE`, never redeclared per leaf. */
export function projectGraphqlLeaf(extract: PolicySchemaLeafExtract, owner: SurfaceSchemaOwner, sourceRel: string, definitions: readonly PolicySchemaLeafExtract[] = []): string {
  return [
    `# ${SURFACE_SCHEMA_BANNER}`,
    `# @see ${sourceRel}`,
    ...definitions.map((definition) => `${graphqlType(definition, owner.lane)}\n`),
    graphqlType(extract, owner.lane),
    "",
  ].join("\n");
}

/** @emoji 🛰️ The protobuf mirror; `optional` is illegal on a proto3 map entry, the one exemption the
 * repo library's field-parity law already grants. */
export function projectProtoLeaf(extract: PolicySchemaLeafExtract, owner: SurfaceSchemaOwner, sourceRel: string, definitions: readonly PolicySchemaLeafExtract[] = []): string {
  const message = (shape: PolicySchemaLeafExtract): string => {
    const fields = shape.fields.map((field, index) => {
      const scalar = SCALARS[field.scalar]?.proto ?? field.scalar;
      const shaped =
        field.cardinality === "list" || field.cardinality === "fixedList" ? `repeated ${scalar}`
        : field.cardinality === "map" ? `map<string, ${scalar}>`
        : field.optional ? `optional ${scalar}`
        : scalar;
      return `  // @state ${owner.lane}\n  ${shaped} ${snake(field.name)} = ${index + 1};`;
    }).join("\n");
    return `message ${shape.typeName} {${fields ? `\n${fields}\n` : ""}}`;
  };
  return [
    `// ${SURFACE_SCHEMA_BANNER}`,
    `// @see ${sourceRel}`,
    'syntax = "proto3";',
    `package semio.app.${owner.appId.split(".").slice(1).join(".")};`,
    ...definitions.map((definition) => `${message(definition)}\n`),
    message(extract),
    "",
  ].join("\n");
}

/** @emoji 🧬️ Every leaf of one lane, keyed by its taxonomy filename — the whole projection in one map. */
export function projectSurfaceSchemaLane(repoRoot: string, owner: SurfaceSchemaOwner, extract: PolicySchemaLeafExtract, sourceRel: string, definitions: readonly PolicySchemaLeafExtract[] = []): Record<string, string> {
  const byFormat: Record<string, string> = {
    "🔣️.json": projectJsonSchema(extract, owner, definitions),
    "🦀️.rs": projectRustLeaf(extract, owner, sourceRel, definitions),
    "🟦️.ts": projectTypescriptLeaf(extract, owner, sourceRel, definitions),
    "🔗️.graphql": projectGraphqlLeaf(extract, owner, sourceRel, definitions),
    "🛰️.proto": projectProtoLeaf(extract, owner, sourceRel, definitions),
  };
  const required = taxonomySchemaFilenames(owner.facetAbs);
  const missing = required.filter((filename) => byFormat[filename] === undefined);
  if (missing.length) throw new Error(`${SURFACE_SCHEMA_CONTRACT_ID}: no projection for taxonomy leaf ${missing.join(", ")} of ${relative(repoRoot, owner.facetAbs)}`);
  return Object.fromEntries(required.map((filename) => [filename, byFormat[filename]!]));
}

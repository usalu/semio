/** @emoji 🪢️ The glue file and anchor line that mount one surface's component leaf. Every plugin's
 * `🗿️artifacts/<a>/🦀️.rs` wiring module spells the mount as a literal `#[path]`, so resolving each
 * `#[path]` against its own file's directory locates the surface exactly, with no name matching. */
export function findSurfaceMountAnchor(pluginRoot: string, surfaceAbs: string): { readonly glueAbs: string; readonly line: number } | null {
  const componentAbs = resolve(join(surfaceAbs, TAXONOMY_LEAF_FILENAME));
  let glue = MOUNT_INDEX.get(pluginRoot)?.get(componentAbs);
  if (!glue) {
    if (!MOUNT_INDEX.has(pluginRoot)) {
      const index = new Map<string, string>();
      for (const glueAbs of rustFilesOf(pluginRoot)) {
        for (const match of readFileSync(glueAbs, "utf8").matchAll(/^[ \t]*#\[path\s*=\s*"([^"]+)"\][ \t]*$/gmu)) {
          const target = resolve(dirname(glueAbs), match[1]!);
          if (!index.has(target)) index.set(target, glueAbs);
        }
      }
      MOUNT_INDEX.set(pluginRoot, index);
    }
    glue = MOUNT_INDEX.get(pluginRoot)!.get(componentAbs);
  }
  if (!glue) return null;
  // 🔄️ The glue file is re-read here rather than caching a line number: the projection inserts lines
  // into these very files, so every anchor after the first write would otherwise be off by five.
  const lines = readFileSync(glue, "utf8").split("\n");
  for (let index = 0; index < lines.length; index++) {
    const match = /^\s*#\[path\s*=\s*"([^"]+)"\]\s*$/u.exec(lines[index]!);
    if (match && resolve(dirname(glue), match[1]!) === componentAbs) return { glueAbs: glue, line: index };
  }
  return null;
}

/** @emoji 🧷️ Adds the `#[path]` mount for one projected lane to the plugin's own wiring module, so the
 * generated Rust leaf is reachable from the Cargo manifest exactly like every authored one. Refuses
 * (returns a reason) rather than guessing whenever the anchor's block already declares the lane. */
export function mountProjectedRustLeaf(pluginRoot: string, owner: SurfaceSchemaOwner, apply: boolean): { readonly ok: true; readonly glueAbs: string | null } | { readonly ok: false; readonly reason: string } {
  if (!owner.surfaceAbs) return { ok: false, reason: "plugin-root lanes have no surface wiring anchor" };
  const anchor = findSurfaceMountAnchor(pluginRoot, owner.surfaceAbs);
  if (!anchor) return { ok: false, reason: "no #[path] mount of the surface component was found in the plugin's wiring modules" };
  const text = readFileSync(anchor.glueAbs, "utf8");
  const lines = text.split("\n");
  const moduleName = owner.lane;
  const leafRel = relative(dirname(anchor.glueAbs), join(owner.facetAbs, TAXONOMY_LEAF_FILENAME)).replaceAll("\\", "/");
  if (text.includes(`#[path = "${leafRel}"]`)) return { ok: true, glueAbs: null };
  // 🪆️ When the lane owns a real `🦀️.rs` the wiring mounts it as a FILE module (`pub mod config;`), so
  // the schema leaf belongs inside that file — the authored convention 21 lanes already use — and
  // never as a second `config` beside it (`E0428`).
  const laneLeafAbs = join(owner.laneAbs, TAXONOMY_LEAF_FILENAME);
  if (existsSync(laneLeafAbs)) {
    const laneText = readFileSync(laneLeafAbs, "utf8");
    const mount = `#[path = "${SCHEMA_FACET_DIR}/${TAXONOMY_LEAF_FILENAME}"]`;
    if (laneText.includes(mount)) return { ok: true, glueAbs: null };
    if (apply) writeFileSync(laneLeafAbs, `${laneText.replace(/\n*$/u, "\n")}\n${mount}\npub mod schema;\n`);
    return { ok: true, glueAbs: laneLeafAbs };
  }
  const indent = /^\s*/u.exec(lines[anchor.line]!)![0];
  let insertAt = anchor.line + 1;
  while (insertAt < lines.length && !/^\s*pub use component::\*;\s*$/u.test(lines[insertAt]!)) {
    if (insertAt > anchor.line + 4) return { ok: false, reason: "the surface mount is not the canonical `mod component; pub use component::*;` shape" };
    insertAt += 1;
  }
  if (insertAt >= lines.length) return { ok: false, reason: "the surface mount is not the canonical `mod component; pub use component::*;` shape" };
  // 🧱️ A sibling `pub mod config`/`pub mod presence` may sit anywhere inside the SAME enclosing module,
  // not within a fixed window of the anchor — `🀄️wfc`'s wiring declares it 40 lines later, and a
  // windowed guard silently emitted a second one (`E0428: the name 'config' is defined multiple
  // times`). The scan therefore runs to the end of the enclosing block, tracked by brace depth.
  const sibling = findSiblingModule(lines, insertAt + 1, indent, moduleName);
  if (sibling !== null) {
    if (!lines[sibling]!.includes("{")) return { ok: false, reason: `the wiring module declares \`pub mod ${moduleName};\` but the lane has no ${TAXONOMY_LEAF_FILENAME} to mount the schema leaf from` };
    if (existingSchemaMount(lines, sibling)) return { ok: true, glueAbs: null };
    const nested = [`${indent}    #[path = "${leafRel}"]`, `${indent}    pub mod schema;`];
    if (apply) writeFileSync(anchor.glueAbs, [...lines.slice(0, sibling + 1), ...nested, ...lines.slice(sibling + 1)].join("\n"));
    return { ok: true, glueAbs: anchor.glueAbs };
  }
  const block = [`${indent}#[path = "."]`, `${indent}pub mod ${moduleName} {`, `${indent}    #[path = "${leafRel}"]`, `${indent}    pub mod schema;`, `${indent}}`];
  if (apply) writeFileSync(anchor.glueAbs, [...lines.slice(0, insertAt + 1), ...block, ...lines.slice(insertAt + 1)].join("\n"));
  return { ok: true, glueAbs: anchor.glueAbs };
}

/** @emoji 🔍️ Index of `pub mod <name> {` declared at `indent` inside the block that encloses `from`,
 * or `null`. Depth tracking stops at the enclosing block's own closing brace, so a same-named module
 * belonging to a *different* surface never matches. */
function findSiblingModule(lines: string[], from: number, indent: string, moduleName: string): number | null {
  let depth = 0;
  for (let index = from; index < lines.length; index++) {
    const line = lines[index]!;
    if (depth === 0 && new RegExp(`^${indent}pub mod ${moduleName}\\s*[{;]`, "u").test(line)) return index;
    for (const character of line) {
      if (character === "{") depth += 1;
      else if (character === "}") depth -= 1;
    }
    if (depth < 0) return null;
  }
  return null;
}

/** @emoji 🧬️ Whether the module opening at `at` already mounts a `🧬️schema` leaf of its own. */
function existingSchemaMount(lines: string[], at: number): boolean {
  let depth = 0;
  for (let index = at; index < lines.length; index++) {
    const line = lines[index]!;
    if (index > at && depth === 1 && /#\[path\s*=\s*"[^"]*🧬️schema\/[^"]*"\]/u.test(line)) return true;
    for (const character of line) {
      if (character === "{") depth += 1;
      else if (character === "}") depth -= 1;
    }
    if (depth <= 0 && index > at) return false;
  }
  return false;
}

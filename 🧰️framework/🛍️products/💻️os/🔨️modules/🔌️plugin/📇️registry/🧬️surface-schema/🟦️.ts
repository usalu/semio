/** @emoji 🔎️ Last `::` segment of a Rust type path — `crate::cfg::HomeConfig` → `HomeConfig`. */
export function surfaceSchemaTypeTail(path: string): string {
  const tail = path.split("::").pop() ?? path;
  return tail.replace(/<.*$/u, "").trim();
}

/** @emoji 🪢️ The `type Config` / `type Presence` associated-type binding of one surface component. */
export function surfaceSchemaBinding(componentText: string, associated: "Config" | "Presence"): string | null {
  const match = new RegExp(`\\btype\\s+${associated}\\s*=\\s*([A-Za-z_][A-Za-z0-9_:<>\\s]*?)\\s*;`, "u").exec(componentText);
  return match ? surfaceSchemaTypeTail(match[1]!) : null;
}

/** @emoji 🆔️ `s.<plugin>.<artifact>` coordinate of one owner, read from the repository path — the same
 * grammar `🧬️schema/🦀️.rs` leaves already spell in `artifact_schema(id = …)`. */
export function surfaceSchemaAppId(repoRoot: string, pluginId: string, ownerAbs: string): string {
  const segments = relative(repoRoot, ownerAbs).replaceAll("\\", "/").split("/");
  const artifactsIndex = segments.indexOf(TAXONOMY.artifactsDirName);
  const plain = (segment: string): string => segment.replace(/[^\x21-\x7e]/gu, "").toLowerCase();
  const artifact = artifactsIndex >= 0 ? plain(segments[artifactsIndex + 1] ?? "") : "";
  return artifact ? `s.${plain(pluginId)}.${artifact}` : `s.${plain(pluginId)}`;
}

/** @emoji 🗂️ Every lane the taxonomy's `assertAppSchemaOwner` judges, in stable path order. An owner
 * exists exactly where a `🎚️config/` facet does — the same predicate the validator applies. */
export function discoverSurfaceSchemaOwners(repoRoot: string, pluginFilter?: string): SurfaceSchemaOwner[] {
  const owners: SurfaceSchemaOwner[] = [];
  for (const { pluginId, pluginRoot } of findNewContractPluginRoots(repoRoot)) {
    if (pluginFilter && !pluginId.includes(pluginFilter)) continue;
    const nodes: { ownerAbs: string; ownerLabel: string; surfaceAbs: string | null }[] = [
      ...surfaceDirsForPlugin(pluginRoot).map(({ abs, label }) => ({ ownerAbs: abs, ownerLabel: `surface "${label}"`, surfaceAbs: abs })),
      { ownerAbs: pluginRoot, ownerLabel: "plugin-root", surfaceAbs: null },
    ];
    for (const node of nodes) {
      if (!existsSync(join(node.ownerAbs, CONFIG_FACET_DIR))) continue;
      const componentAbs = node.surfaceAbs ? join(node.surfaceAbs, TAXONOMY_LEAF_FILENAME) : null;
      const componentText = componentAbs && existsSync(componentAbs) ? readFileSync(componentAbs, "utf8") : "";
      const configType = surfaceSchemaBinding(componentText, "Config");
      const presenceType = surfaceSchemaBinding(componentText, "Presence") ?? (configType ? policyAppPresenceTypeName(configType) : null);
      for (const lane of ["config", "presence"] as SurfaceSchemaLane[]) {
        const laneAbs = join(node.ownerAbs, lane === "config" ? CONFIG_FACET_DIR : PRESENCE_FACET_DIR);
        owners.push({
          pluginId, pluginRoot, ownerAbs: node.ownerAbs, ownerLabel: node.ownerLabel, surfaceAbs: node.surfaceAbs,
          lane, laneAbs, facetAbs: join(laneAbs, SCHEMA_FACET_DIR),
          typeName: lane === "config" ? configType : presenceType,
          appId: surfaceSchemaAppId(repoRoot, pluginId, node.ownerAbs),
        });
      }
    }
  }
  return owners;
}

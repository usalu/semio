/**
 * 🧬️ `surface-schema-projection` — the generator contract behind every surface and plugin-root
 * `🎚️config/🧬️schema/` and `👥️presence/🧬️schema/` lane.
 *
 * The taxonomy requires each such lane to carry one leaf per `schemaFacetKinds.🧬️data` format
 * (`🔣️.json` `🦀️.rs` `🟦️.ts` `🔗️.graphql` `🛰️.proto`), and `assertAppSchemaOwner`
 * (`🗿️taxonomy-validation/🟦️.ts`) enforces their presence. Hand-authoring them is ~2 600 files, so
 * they are a **projection**: exactly one Rust declaration per lane is the source of truth and the
 * five leaves are derived from it, byte-deterministically, with `🔣️.json` normative inside the facet
 * (`surfaceSchemaSpecFileKinds`) and the other four its mirrors — the same relation the repo
 * library's surface laws already police
 * (`📚️library/🧬️schema/🗺️surface/⚖️laws/{📏️field-parity,🪞️config-fidelity,💧️state-purity,🏷️type-name-parity}`).
 *
 * The source of truth is never invented. A lane is projected only when its bound Rust type resolves
 * to a real `pub struct` — the surface's own `🎚️config/🦀️.rs`, the plugin root's, the framework's
 * `NoConfig`/`NoPresence` sentinels, or a declaration under the owning plugin. Everything else is
 * reported and skipped.
 */
export const SURFACE_SCHEMA_CONTRACT_ID = "surface-schema-projection";

/** @emoji 🤖️ Ownership banner every projected leaf carries; a leaf without it is authored content the
 * projection never touches. Comment syntax differs per format, the marker text does not. */
export const SURFACE_SCHEMA_BANNER = `🤖️ Generated by \`bun ./📜️script.ts surface-schema\` (${SURFACE_SCHEMA_CONTRACT_ID}) — do not edit.`;

/** @emoji 🏷️ Framework sentinel state types: a surface that binds one of these owns no state of its
 * own, so its lane projects the sentinel's real (empty) declaration rather than an invented type. */
export const SURFACE_SCHEMA_SENTINEL_SOURCE = "🧰️framework/🛍️products/💻️os/🔨️modules/🔌️plugin/🦀️.rs";

/** @emoji 🧮️ The largest integer JSON and JavaScript both carry exactly (`Number.MAX_SAFE_INTEGER`).
 * The repo's one runtime integer law, `packValueToExactJson`, throws rather than rounds beyond it —
 * "JSON never learns to carry an integer carrier" — so a 64-bit lane declares that same bound in
 * schema, where Ajv and the authored TS guards enforce it before a value ever reaches the wire. */
const SAFE_INTEGER_BOUND = 9007199254740991;

/** @emoji 🔢️ Canonical scalar → per-format spelling. Keys are `policyCanonicalScalar` outputs, so a
 * round trip through the repo library's five field parsers reproduces the same shape.
 *
 * 32-bit integers need no explicit range: every `i32`/`u32` value is exactly representable in JSON
 * and in JavaScript. 64-bit ones are not, so `int64`/`uint64` carry {@link SAFE_INTEGER_BOUND}
 * explicitly and spell GraphQL `Long` — `Int` is 32-bit by GraphQL specification. This is the shape
 * the repo already authored by hand for its one live `u64` config field, `HomeConfig`
 * (`🪐️space/🗿️artifacts/🏠️home/…/🎚️config/🧬️schema/`): bounded `integer` + `Long` + proto `uint64`. */
const SCALARS: Readonly<Record<string, { json: { type: string; format?: string; minimum?: number; maximum?: number }; rust: string; typescript: string; graphql: string; proto: string }>> = {
  string: { json: { type: "string" }, rust: "String", typescript: "string", graphql: "String", proto: "string" },
  bool: { json: { type: "boolean" }, rust: "bool", typescript: "boolean", graphql: "Boolean", proto: "bool" },
  int32: { json: { type: "integer", format: "int32" }, rust: "i32", typescript: "number", graphql: "Int", proto: "int32" },
  uint32: { json: { type: "integer", format: "uint32" }, rust: "u32", typescript: "number", graphql: "Int", proto: "uint32" },
  int64: { json: { type: "integer", format: "int64", minimum: -SAFE_INTEGER_BOUND, maximum: SAFE_INTEGER_BOUND }, rust: "i64", typescript: "number", graphql: "Long", proto: "int64" },
  uint64: { json: { type: "integer", format: "uint64", minimum: 0, maximum: SAFE_INTEGER_BOUND }, rust: "u64", typescript: "number", graphql: "Long", proto: "uint64" },
  float32: { json: { type: "number", format: "float" }, rust: "f32", typescript: "number", graphql: "Float", proto: "float" },
  float64: { json: { type: "number", format: "double" }, rust: "f64", typescript: "number", graphql: "Float", proto: "double" },
  bytes: { json: { type: "string", format: "byte" }, rust: "Vec<u8>", typescript: "string", graphql: "String", proto: "bytes" },
};


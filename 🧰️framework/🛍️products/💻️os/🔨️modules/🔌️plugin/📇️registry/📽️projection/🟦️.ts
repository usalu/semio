/** @emoji 🗂️ The full generated catalog, rendered in memory once and consumed by both `generate`
 * (writes) and `check` (byte-compares) so the two can never disagree about what belongs in
 * `🤖️generated/`. */
export function renderCatalogFiles(repoRoot: string, view: RegistryCatalogInputView = registryCatalogInputView(repoRoot, TAXONOMY)): { files: Record<string, string>; entries: PluginRegistryEntry[]; playgrounds: PlaygroundEntry[]; frameworkPackages: FrameworkPackageEntry[]; componentLaunchers: { project: string; pluginId: string }[] } {
  const packages = discoverCatalogPackages(repoRoot, TAXONOMY, view);
  const entries = generatePluginRegistry(repoRoot, { packages, view });
  const playgrounds = generatePlaygroundRegistry(repoRoot, { packages, view });
  const frameworkPackages = generateFrameworkPackageRegistry(repoRoot, packages);
  const hostVariant = defaultHostVariant(entries, playgrounds);
  const componentLaunchers = entries.map((entry) => {
    const path = `${entry.cratePath}/📋️project.json`, kind = view.kind(path);
    if (kind && kind !== "file") throw new Error(`Invalid component Nx project: ${path}`);
    const project = kind ? JSON.parse(view.readText(path)).name : entry.packageName;
    if (typeof project !== "string" || !project.length) throw new Error(`Missing component Nx identity: ${path}`);
    return { project, pluginId: entry.pluginId };
  });
  return {
    componentLaunchers,
    entries,
    playgrounds,
    frameworkPackages,
    files: {
      "🔌️plugins.json": `${JSON.stringify(entries, null, 2)}\n`,
      "🧩️plugins/🟦️.ts": emitTypeScript(entries),
      "🎠️playgrounds.json": `${JSON.stringify(playgrounds, null, 2)}\n`,
      "🎮️playgrounds/🟦️.ts": emitPlaygroundsTypeScript(playgrounds, hostVariant),
      "🧰️framework.json": `${JSON.stringify(frameworkPackages, null, 2)}\n`,
      "🏗️framework/🟦️.ts": emitFrameworkPackagesTypeScript(frameworkPackages),
      "🖥️hosts/🦀️.rs": emitRustHosts(entries, playgrounds),
      "🗿️artifacts/🦀️.rs": emitRustArtifacts(entries, repoRoot),
      "trusted-stdio-catalog.json": encodeTrustedStdioCatalogV1(buildTrustedStdioCatalogV1(repoRoot, entries)),
    },
  };
}


export function catalogOutputShape(files: Readonly<Record<string, string>>): { directories: string[]; files: string[] } {
  const directories = new Set<string>();
  for (const path of Object.keys(files)) {
    const parts = path.split("/");
    for (let length = 1; length < parts.length; length += 1) directories.add(parts.slice(0, length).join("/"));
  }
  const compare = (left: string, right: string): number => Buffer.from(left).compare(Buffer.from(right));
  return { directories: [...directories].sort(compare), files: Object.keys(files).sort(compare) };
}


export function catalogOutputInventory(outDir: string): { directories: string[]; files: string[] } {
  const directories: string[] = [], files: string[] = [];
  const visit = (directory: string, prefix: string): void => {
    for (const entry of readdirSync(directory, { withFileTypes: true })) {
      const path = prefix ? `${prefix}/${entry.name}` : entry.name;
      if (entry.isDirectory()) { directories.push(path); visit(join(directory, entry.name), path); }
      else files.push(path);
    }
  };
  if (existsSync(outDir)) visit(outDir, "");
  const compare = (left: string, right: string): number => Buffer.from(left).compare(Buffer.from(right));
  return { directories: directories.sort(compare), files: files.sort(compare) };
}


export class GenerateScript extends BundleScript {
  run(_segments: string[]): void {
    const repoRoot = getWorkspaceRoot();
    const { files, entries, playgrounds, frameworkPackages, componentLaunchers } = renderCatalogFiles(repoRoot);
    const outDir = join(this.root, "🤖️generated");
    mkdirSync(outDir, { recursive: true });
    const expected = catalogOutputShape(files), actual = catalogOutputInventory(outDir);
    const expectedFiles = new Set(expected.files), expectedDirectories = new Set(expected.directories);
    for (const path of actual.files) if (!expectedFiles.has(path)) rmSync(join(outDir, path), { force: true });
    for (const path of actual.directories.sort((left, right) => right.split("/").length - left.split("/").length)) if (!expectedDirectories.has(path)) rmSync(join(outDir, path), { recursive: true, force: true });
    for (const path of expected.directories) mkdirSync(join(outDir, path), { recursive: true });
    for (const [name, content] of Object.entries(files)) { mkdirSync(dirname(join(outDir, name)), { recursive: true }); writeFileSync(join(outDir, name), content); }
    console.log(`plugin registry catalog refreshed (${entries.length} plugin crates, ${playgrounds.length} playgrounds, ${frameworkPackages.length} framework packages) -> ${outDir}`);
    // 🖥️ `.vscode/launch.json` is the second consumer of the very same playground catalog, so it is
    // regenerated here rather than from a separate entry point — `check` enforces its freshness. Written
    // last so a seed/devLaunchers problem can never leave the catalog itself unwritten.
    const launchPath = join(repoRoot, LAUNCH_OUTPUT_REL_PATH);
    writeFileSync(launchPath, generateLaunchJson(repoRoot, playgrounds, componentLaunchers));
    console.log(`${LAUNCH_OUTPUT_REL_PATH} regenerated -> ${launchPath}`);
  }
}


/** 🧾️ Emits exact registry/launch bytes and stale removals without touching either output root. */
export class PreviewGeneratedScript extends BundleScript {
  run(_segments: string[]): void {
    const repoRoot = getWorkspaceRoot();
    const protocol = process.env.SEMIO_GENERATOR_PREVIEW_PROTOCOL;
    const authority = TAXONOMY.generatorContracts["plugin-registry"].inputDiscovery!.previewInput;
    if (protocol && protocol !== authority.protocol) throw new Error("Unknown registry preview protocol");
    const native = registryCatalogInputView(repoRoot, TAXONOMY);
    const cancelFile = process.env.SEMIO_GENERATOR_PREVIEW_CANCEL_FILE;
    const cancelPath = cancelFile ? relative(repoRoot, cancelFile).replaceAll("\\", "/") : undefined;
    if (cancelPath) native.kind(cancelPath);
    const checkCancellation = (): void => {
      if (!cancelFile) return;
      try { lstatSync(cancelFile); } catch (error) { if ((error as NodeJS.ErrnoException).code === "ENOENT") return; throw error; }
      throw new Error("Registry preview cancelled");
    };
    const base: RegistryCatalogInputView = {
      entries(path) { checkCancellation(); return native.entries(path); },
      kind(path) { checkCancellation(); return native.kind(path); },
      readText(path) { checkCancellation(); return native.readText(path); },
    };
    let payload = "";
    if (protocol) {
      const chunks: Buffer[] = [];
      let size = 0;
      while (true) {
        checkCancellation();
        const chunk = Buffer.alloc(Math.min(65536, authority.maxBytes - size + 1));
        const length = readSync(0, chunk, 0, chunk.length, null);
        if (!length) break;
        size += length;
        if (size > authority.maxBytes) throw new Error("Registry preview input exceeds its declared byte limit");
        chunks.push(chunk.subarray(0, length));
      }
      payload = Buffer.concat(chunks).toString("utf8");
    }
    const view = protocol ? registryCatalogProjectedInputView(repoRoot, TAXONOMY, parseRegistryCatalogProjection(payload, TAXONOMY), base) : base;
    const { files, playgrounds, componentLaunchers } = renderCatalogFiles(repoRoot, view);
    const outDir = join(this.root, "🤖️generated");
    const rootPath = relative(repoRoot, outDir).replaceAll("\\", "/").normalize("NFC");
    const launchPath = join(repoRoot, LAUNCH_OUTPUT_REL_PATH);
    const expected = catalogOutputShape(files), actual = catalogOutputInventory(outDir);
    const nodes = [
      { bytesBase64: "", mode: 0o755, nodeKind: "directory" as const, path: rootPath },
      ...expected.directories.map((path) => ({ bytesBase64: "", mode: 0o755, nodeKind: "directory" as const, path: `${rootPath}/${path.normalize("NFC")}` })),
      ...Object.entries(files).map(([name, content]) => ({ bytesBase64: Buffer.from(content).toString("base64"), mode: 0o644, nodeKind: "file" as const, path: `${rootPath}/${name.normalize("NFC")}` })),
      { bytesBase64: Buffer.from(generateLaunchJson(repoRoot, playgrounds, componentLaunchers, (path) => view.readText(path))).toString("base64"), mode: 0o644, nodeKind: "file" as const, path: relative(repoRoot, launchPath).replaceAll("\\", "/").normalize("NFC") },
    ].sort((left, right) => Buffer.from(left.path).compare(Buffer.from(right.path)));
    const expectedPaths = new Set([...expected.directories, ...expected.files]);
    const staleRemovals = [...actual.directories, ...actual.files].filter((path) => !expectedPaths.has(path)).map((path) => `${rootPath}/${path.normalize("NFC")}`).sort((left, right) => Buffer.from(left).compare(Buffer.from(right)));
    process.stdout.write(`${JSON.stringify({ contractId: "plugin-registry", nodes, schemaVersion: 1, staleRemovals })}\n`);
  }
}




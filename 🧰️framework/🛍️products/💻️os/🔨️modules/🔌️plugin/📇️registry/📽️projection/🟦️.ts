/** 🧪️Checks every present playground against its own host metadata and component inventory. */
export function validatePlaygroundSessions(repoRoot: string, projection: GeneratedCatalogProjection = { entries: generatePluginRegistry(repoRoot), playgrounds: generatePlaygroundRegistry(repoRoot) }): string[] {
  const errors: string[] = [];
  const inventory = registryModuleDirectories(projection.entries);
  for (const playground of projection.playgrounds) {
    const owner = projection.entries.find(entry => entry.pluginId === playground.pluginId);
    if (!owner) { errors.push(`playground "${playground.variant}" has no declared component owner`); continue; }
    const session = buildPlaygroundSession(playground.variant, projection);
    const hostMode = owner.host !== undefined && playground.app === undefined;
    const selected = filterProjectedPluginRegistry(projection, hostMode ? undefined : playground.pluginId);
    if (session.registryPluginId !== owner.pluginId || session.defaultAppId !== playground.app || session.hostMode !== hostMode || !isDeepStrictEqual(session.host, owner.host) || !isDeepStrictEqual(session.plugins.map(entry => entry.pluginId), selected.map(entry => entry.pluginId))) errors.push(`playground "${playground.variant}" lost its owner selection or host metadata`);
    for (const entry of selected) {
      const actual = session.plugins.find(candidate => candidate.pluginId === entry.pluginId);
      const moduleUrl = `${entry.role === "extension" ? MODULE_EXTENSION_ROUTE : MODULE_PLUGIN_ROUTE}/${moduleDirectoryName(entry.pluginId, inventory)}/${MODULE_BRIDGE_FILE}`;
      const dependencies = entry.dependsOn.map(pluginId => ({ pluginId }));
      if (!actual || actual.moduleUrl !== moduleUrl || !isDeepStrictEqual(actual.dependencies, dependencies)) errors.push(`playground "${playground.variant}" lost the module route or dependencies of "${entry.pluginId}"`);
      for (const dependency of entry.dependsOn) if (!selected.some(candidate => candidate.pluginId === dependency)) errors.push(`playground "${playground.variant}" omits required dependency "${dependency}"`);
    }
  }
  return errors;
}

export function emitRustHosts(entries: DeployedRegistryEntryV1[], playgrounds: PlaygroundEntry[]): string {
  const hostRows = entries
    .filter((entry) => entry.host)
    .map((entry) => `    PluginHostConfig { plugin_id: ${JSON.stringify(entry.pluginId)}, landing_app_id: ${JSON.stringify(entry.host!.landingAppId)}, host_app_id: ${JSON.stringify(entry.host!.hostAppId)} },`)
    .join("\n");
  const variantRows = playgrounds.map((entry) => `    (${JSON.stringify(entry.variant)}, ${JSON.stringify(entry.pluginId)}),`).join("\n");
  const aliasRows = playgrounds.flatMap((entry) => entry.aliases.map((alias) => `    (${JSON.stringify(alias)}, ${JSON.stringify(entry.pluginId)}),`)).join("\n");
  const variantAppRows = playgrounds.filter((entry) => entry.app).map((entry) => `    (${JSON.stringify(entry.variant)}, ${JSON.stringify(entry.app)}),`).join("\n");
  const aliasAppRows = playgrounds.flatMap((entry) => entry.app ? entry.aliases.map((alias) => `    (${JSON.stringify(alias)}, ${JSON.stringify(entry.app)}),`) : []).join("\n");
  const ownerByArtifactKind = new Map<string, string>();
  for (const entry of [...entries].sort((left, right) => left.pluginId.localeCompare(right.pluginId))) {
    for (const event of entry.activationEvents) {
      if (!event.startsWith(ON_ARTIFACT_KIND_PREFIX)) continue;
      const kind = event.slice(ON_ARTIFACT_KIND_PREFIX.length);
      if (!ownerByArtifactKind.has(kind)) ownerByArtifactKind.set(kind, entry.pluginId);
    }
  }
  const artifactKindRows = [...ownerByArtifactKind]
    .sort(([leftKind], [rightKind]) => leftKind.localeCompare(rightKind))
    .map(([kind, pluginId]) => `    (${JSON.stringify(kind)}, ${JSON.stringify(pluginId)}),`)
    .join("\n");
  return `// @generated by framework/plugin/registry/script.ts — do not edit.

pub struct PluginHostConfig {
    pub plugin_id: &'static str,
    pub landing_app_id: &'static str,
    pub host_app_id: &'static str,
}

pub const PLUGIN_HOST_CONFIGS: &[PluginHostConfig] = &[
${hostRows}
];

const PLAYGROUND_VARIANT_REGISTRY_IDS: &[(&str, &str)] = &[
${variantRows}
${aliasRows}
];

const PLAYGROUND_VARIANT_APP_IDS: &[(&str, &str)] = &[
${variantAppRows}
${aliasAppRows}
];

pub fn resolve_registry_plugin_id(plugin_filter: &str) -> &str {
    for (variant, plugin_id) in PLAYGROUND_VARIANT_REGISTRY_IDS {
        if *variant == plugin_filter {
            return plugin_id;
        }
    }
    plugin_filter
}

pub fn resolve_playground_app_id(plugin_filter: &str) -> Option<&'static str> {
    PLAYGROUND_VARIANT_APP_IDS.iter().find_map(|(variant, app_id)| (*variant == plugin_filter).then_some(*app_id))
}

pub fn resolve_plugin_host_config(plugin_filter: &str) -> Option<&'static PluginHostConfig> {
    let registry_id = resolve_registry_plugin_id(plugin_filter);
    PLUGIN_HOST_CONFIGS.iter().find(|entry| entry.plugin_id == registry_id)
}

pub fn is_space_mode(plugin_filter: &str) -> bool {
    resolve_plugin_host_config(plugin_filter).is_some()
}

/// 🎬️ Every \`on-artifact-kind:<kind>\` the catalog declares, keyed by kind and owned by exactly one
/// plugin id (see \`claimOwnedArtifactKinds\` in \`📇️registry/🔎️discovery/🟦️.ts\`). Both kind namespaces a
/// descriptor declares are present: the crate's own \`ArtifactKindSpec.id\` and the artifact kind its app
/// surfaces name, which is what an opening coordinate parses to.
pub const PLUGIN_ARTIFACT_KIND_ACTIVATIONS: &[(&str, &str)] = &[
${artifactKindRows}
];

/// 🎬️ The plugin an artifact kind activates, resolved from declared activation events alone — no
/// manifest, no loaded module. The wgpu shell's opening relay calls this when the kind's owner is not
/// resident yet, exactly where the React shell calls \`artifactKindActivationOwner\`.
pub fn resolve_artifact_kind_activation_owner(artifact_kind: &str) -> Option<&'static str> {
    PLUGIN_ARTIFACT_KIND_ACTIVATIONS.iter().find_map(|(kind, plugin_id)| (*kind == artifact_kind).then_some(*plugin_id))
}
`;
}



/** 🪢️ Original typed-wire ownership and ordinary DOM controls share the staged form path. */
import { container, grant, leaf, nativeInstanceFixture, createTypedWireSupport, type TypedWireVitest, type TypedWireDependencies, type UiNodeRecord } from "../🪛️typedwire-helpers/🟦️.tsx";

export async function registerOwnedStagedControlTests(vitest: TypedWireVitest, dependencies: TypedWireDependencies): Promise<void> {
  const { describe, expect, it } = vitest;
  const { close, finish } = await createTypedWireSupport(vitest, dependencies);
  describe("TypedWire", () => {
    it("OwnedStagedBody renders original Form Field Input Select Button and read-only reads with accessible targets", async () => {
      const { OwnedUiInstance } = await import("@semio-tech/ui-contract/retained/instance");
      const { encodePackValue } = await import("@semio-tech/framework/packs");
      const { OwnedStagedControls } = await import("../../../🛠️ShellHelpers/🪟️window-panes/📝️staged-args/🛡️intents/owned.ts");
      const { StagedFormSession } = await import("../../../🛠️ShellHelpers/🪟️window-panes/📝️staged-args/🛡️intents/🟦️.ts");
      const { OwnedStagedBodyView } = await import("../../../🗣️Interpreter/🎛️control-port/owned.tsx");
      const { STAGED_FORM_STATUS_EXTENSION, STAGED_FORM_EVENT_ACTION, STAGED_FORM_PAGE_ACTION } = await import("@semio-tech/framework/manifest/staging");
      const { render, act, fireEvent } = await import("@semio-tech/ui-react/test");
      const { StrictMode } = await import("react");
      const { applyPatch } = await import("fast-json-patch");
      const user = (await import("@testing-library/user-event")).default.setup();
      const native = await nativeInstanceFixture();
      const owner = new OwnedUiInstance(native.activation, native.lifetime, dependencies.DEFAULT_UI_DOCUMENT_LIMITS, { usizeBits: 64 });
      native.lease.bindHostRetirement(owner);
      const lookup = owner.beginSurfaceLookup(native.activation, native.lifetime, "window")!;
      expect(finish(lookup)).toBe("ready");
      const source = lookup.takeResult()!;
      close(lookup);
      const token = { action: "ifc.edit", generation: "9007199254740993", revision: "source:1", window: "window" };
      const session = new StagedFormSession<number, number>({ token, locale: "de", controllerId: "ifc" }, { count: "0", axis: "x" });
      const changes: unknown[] = [];
      const controls = new OwnedStagedControls(source, "window", session, result => { changes.push(result); });
      const maintenance = async () => { await act(async () => { for (let turn = 0; owner.maintenancePending; turn++) { expect(turn).toBeLessThan(10000); const step = owner.advanceMaintenance(grant); expect(step.items).toBeLessThanOrEqual(1); expect(step.bytes).toBeLessThanOrEqual(4096); } }); };
      const nodes = (current: typeof token, ready: boolean): UiNodeRecord[] => {
        const binding = (name: string, trigger: "change" | "activate", args: unknown) => [{ trigger, action: { scope: "ifc", name, version: 1 }, args, capability: null }];
        const status = { ...leaf(0, "stage.status"), component: { type: "extension", extension: STAGED_FORM_STATUS_EXTENSION, props: { token: current, ready, diagnostics: [], diagnosticOffset: "0", diagnosticTotal: "0" } } };
        const input = { ...leaf(7, "stage.count"), accessibility: { label: "Wert / Value", description: null, live: "off", shortcut: null, hidden: false }, component: { type: "input", kind: "text", value: String(session.request()!.args.count), placeholder: null, commit: null, min: null, max: null, step: null, accept: null, precision: null, snaps: [], displayFactor: null, limits: null, draftTarget: "ifc.count", publicationRevision: null }, bindings: binding(STAGED_FORM_EVENT_ACTION, "change", { token: current, layout: "preserve", edits: [{ source: "text", path: ["count"] }] }) };
        const select = { ...leaf(8, "stage.axis"), accessibility: { label: "Achse / Axis", description: null, live: "off", shortcut: null, hidden: false }, component: { type: "select", value: String(session.request()!.args.axis), placeholder: null, appearance: "segmented", items: [{ value: "x", label: "X" }, { value: "y", label: "Y" }] }, bindings: binding(STAGED_FORM_EVENT_ACTION, "change", { token: current, layout: "replace", edits: [{ source: "choice", kind: "set", path: ["axis"], options: [{ key: "x", value: "x" }, { key: "y", value: "y" }] }] }) };
        const page = { ...leaf(9, "stage.page"), component: { type: "button", label: "Weiter / Next", icon: "arrow-right" }, bindings: binding(STAGED_FORM_PAGE_ACTION, "activate", { token: current, page: { fieldOffset: "16", diagnosticOffset: "0" } }) };
        const preview = { ...leaf(12, "stage.type"), component: { type: "text", value: "IfcLengthMeasure", emphasize: null, dataAttributes: null } };
        const field = (id: number, address: number, label: string, required = false, description: string | null = null, error: string | null = null) => ({ ...container(id, `stage.field.${address}`, [address]), component: { type: "container", role: "field", label, description, required, error, defaultOpen: null, dropOverlay: null } });
        const root = { ...container(10, "stage.form", ready ? [0, 17, 18, 19, 22] : [0, 18, 17, 19, 22]), component: { type: "container", role: "form", label: "Vorlage / Template", description: null, required: null, error: null, defaultOpen: null, dropOverlay: null } };
        return [status, input, select, page, preview, field(17, 7, "Wert / Value", true, "Exakter IFC-Wert / Exact IFC value", ready ? null : "Unvollständiger Wert / Incomplete value"), field(18, 8, "Achse / Axis"), field(19, 9, "Weiter / Next"), field(22, 12, "Datentyp / Data type"), root] as unknown as UiNodeRecord[];
      };
      const publish = async (current: typeof token, ready: boolean, revision: number) => {
        const operations: unknown[] = nodes(current, ready).map(node => ({ tag: "upsert", val: { node: encodePackValue(node) } }));
        operations.push({ tag: "set-root", val: 10n });
        const authority = await native.source(operations, source.view.revision, revision);
        const patch = owner.beginPatch(authority, source);
        for (let ordinal = 0; ordinal < authority.value.operationCount; ordinal++) { expect(patch.offer(ordinal)).toBe(true); expect(finish(patch), patch.failure ?? "staged control input").toBe("ready"); expect(patch.releaseInputReceipt(patch.peekInputReceipt()!)).toBe(true); }
        patch.finishInput();
        await act(async () => { expect(finish(patch), patch.failure ?? "staged control publication").toBe("ready"); });
        const receipt = await native.answer(native.lease.submitUiAcknowledgement(authority, patch.peekAcknowledgement()!, native.budget), { status: { tag: "idle" } });
        expect(patch.acceptAcknowledgement(receipt.receipt)).toBe(true);
        close(patch);
        await maintenance();
      };
      const mounted = render(<StrictMode><OwnedStagedBodyView owner={controls} /></StrictMode>);
      await publish(token, true, 1);
      expect(mounted.getByRole("form", { name: "Vorlage / Template" })).toBeTruthy();
      expect(mounted.container.textContent).not.toContain("framework.stagedFormStatus");
      expect(mounted.getByRole("group", { name: "Datentyp / Data type" }).textContent).toBe("IfcLengthMeasure");
      const input = mounted.getByRole("textbox", { name: "Wert / Value" }) as HTMLInputElement;
      expect(input.disabled).toBe(false);
      expect(input.getAttribute("aria-required")).toBe("true");
      const labels = () => Array.from(mounted.container.querySelectorAll<HTMLLabelElement>("label"));
      const inputLabel = labels().find(label => label.htmlFor === input.id)!;
      expect(inputLabel).toBeTruthy();
      expect(inputLabel.control).toBe(input);
      await act(async () => { await user.click(inputLabel); });
      expect(input.ownerDocument.activeElement).toBe(input);
      const description = input.getAttribute("aria-describedby")!;
      expect(input.ownerDocument.getElementById(description)?.textContent).toBe("Exakter IFC-Wert / Exact IFC value");
      const selected = mounted.getByRole("radio", { name: "X" }) as HTMLButtonElement;
      const choiceLabel = labels().find(label => label.htmlFor === selected.id)!;
      expect(choiceLabel.control).toBe(selected);
      await act(async () => { await user.click(choiceLabel); });
      expect(selected.ownerDocument.activeElement).toBe(selected);
      fireEvent.change(input, { target: { value: "-" } });
      fireEvent.change(input, { target: { value: "-1e" } });
      expect(input.value).toBe("-1e");
      expect(session.request()!.args).toEqual(applyPatch({ count: "0", axis: "x" }, [{ op: "replace", path: "/count", value: "-1e" }], true, false, true).newDocument);
      expect(session.canExecute()).toBe(false);
      expect((mounted.getByRole("button", { name: "Weiter / Next" }) as HTMLButtonElement).disabled).toBe(true);
      fireEvent.click(mounted.getByRole("radio", { name: "Y" }));
      expect(session.request()!.args).toEqual({ count: "-1e", axis: "y" });
      expect(input.disabled).toBe(true);
      const held = controls.reads.subscribeNode(7, () => {});
      await maintenance();
      const oldSnapshot = held.snapshot!;
      const oldPort = controls.control(held, oldSnapshot, source.view);
      const oldRecord = oldPort.read(7)!;
      await publish(session.request()!.token, false, 2);
      const refreshedInput = mounted.getByRole("textbox", { name: "Wert / Value" }) as HTMLInputElement;
      expect(refreshedInput).toBe(input);
      expect(refreshedInput.getAttribute("aria-invalid")).toBe("true");
      const error = refreshedInput.getAttribute("aria-errormessage")!;
      expect(refreshedInput.ownerDocument.getElementById(error)?.textContent).toBe("Unvollständiger Wert / Incomplete value");
      expect(refreshedInput.getAttribute("aria-describedby")?.split(" ")).toContain(error);
      expect(oldSnapshot.record).toBe(oldRecord);
      const before = session.request()!;
      oldPort.dispatch(oldRecord, "change", "stale");
      expect(session.request()!.args).toBe(before.args);
      const page = mounted.getByRole("button", { name: "Weiter / Next" }) as HTMLButtonElement;
      expect(page.disabled).toBe(false);
      fireEvent.click(page);
      expect(session.request()!.page?.fieldOffset).toBe("16");
      expect(session.request()!.args).toBe(before.args);
      expect((mounted.getByRole("textbox", { name: "Wert / Value" }) as HTMLInputElement).disabled).toBe(true);
      expect(changes).toHaveLength(4);
      mounted.unmount();
      controls.close();
      native.lease.beginClose();
      close(owner);
      expect(owner.takeRetirementWitness()).not.toBeNull();
      native.client.disposeAll();
    });
  });
}

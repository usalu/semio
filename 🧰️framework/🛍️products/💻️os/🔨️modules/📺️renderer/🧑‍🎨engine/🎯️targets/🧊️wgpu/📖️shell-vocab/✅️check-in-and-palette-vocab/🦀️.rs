//! ✅️ Check in and palette vocabulary: the check in, command and palette group chrome strings. See [`super`].

/// 🎼 Looks up the check in and palette chrome strings.
pub(super) fn shell_chrome_check_in_and_palette(key: &'static str, is_de: bool) -> Option<&'static str> {
    match (key, is_de) {
        ("checkIn.running", false) => Some("Checking in…"),
        ("checkIn.running", true) => Some("Wird eingecheckt…"),
        ("checkIn.ready", false) => Some("Checked in"),
        ("checkIn.ready", true) => Some("Eingecheckt"),
        ("checkIn.cancelled", false) => Some("Check-in cancelled"),
        ("checkIn.cancelled", true) => Some("Einchecken abgebrochen"),
        ("checkIn.unknownHead", false) => Some("Check-in refused: the hub does not know this version"),
        ("checkIn.unknownHead", true) => Some("Einchecken abgelehnt: Der Hub kennt diesen Stand nicht"),
        ("checkIn.staleHead", false) => Some("Already checked in: a newer check-in exists"),
        ("checkIn.staleHead", true) => Some("Bereits eingecheckt: Es gibt einen neueren Check-in"),
        ("checkIn.activeCheckpointChanged", false) => Some("Check-in collided with another check-in; try again"),
        ("checkIn.activeCheckpointChanged", true) => Some("Einchecken kollidierte mit einem anderen Check-in; bitte erneut versuchen"),
        ("checkIn.ledgerNotReplayable", false) => Some("Check-in refused: an approval in this range is checked in on its own"),
        ("checkIn.ledgerNotReplayable", true) => Some("Einchecken abgelehnt: Eine Freigabe in diesem Bereich wird separat eingecheckt"),
        ("checkIn.codecRefused", false) => Some("Check-in refused: the document could not be rebuilt"),
        ("checkIn.codecRefused", true) => Some("Einchecken abgelehnt: Das Dokument konnte nicht wiederhergestellt werden"),
        ("checkIn.authorityChanged", false) => Some("Check-in stopped: you can no longer edit this document"),
        ("checkIn.authorityChanged", true) => Some("Einchecken gestoppt: Sie dürfen dieses Dokument nicht mehr bearbeiten"),
        ("checkIn.unavailable", false) => Some("Check-in unavailable; try again"),
        ("checkIn.unavailable", true) => Some("Einchecken nicht verfügbar; bitte erneut versuchen"),
        ("command.moveWindow", false) => Some("Move Window"),
        ("command.moveWindow", true) => Some("Fenster verschieben"),
        ("command.splitWindow", false) => Some("Split Window"),
        ("command.splitWindow", true) => Some("Fenster teilen"),
        ("command.resizeWindow", false) => Some("Resize Window"),
        ("command.resizeWindow", true) => Some("Fenster anpassen"),
        ("palette.undo", false) => Some("Undo"),
        ("palette.undo", true) => Some("Rückgängig"),
        ("palette.redo", false) => Some("Redo"),
        ("palette.redo", true) => Some("Wiederholen"),
        ("palette.goHome", false) => Some("Go Home"),
        ("palette.goHome", true) => Some("Nach Hause"),
        ("palette.spawnPrefix", false) => Some("Spawn"),
        ("palette.spawnPrefix", true) => Some("Erzeugen"),
        ("palette.commitCheckpoint", false) => Some("Commit Checkpoint"),
        ("palette.commitCheckpoint", true) => Some("Prüfpunkt festschreiben"),
        ("palette.group.panels", false) => Some("Panels"),
        ("palette.group.panels", true) => Some("Panels"),
        ("window.focus.raised", false) => Some("{name} window focused"),
        ("window.focus.raised", true) => Some("Fenster {name} fokussiert"),
        ("window.focus.opened", false) => Some("{name} window opened and focused"),
        ("window.focus.opened", true) => Some("Fenster {name} geöffnet und fokussiert"),
        ("window.focus.refused", false) => Some("The {name} window cannot be shown here"),
        ("window.focus.refused", true) => Some("Das Fenster {name} kann hier nicht angezeigt werden"),
        ("window.focus.unavailable", false) => Some("The {name} window is not part of the {device} layout"),
        ("window.focus.unavailable", true) => Some("Das Fenster {name} gehört nicht zum Layout {device}"),
        ("window.focus.device.desktop", false) => Some("desktop"),
        ("window.focus.device.desktop", true) => Some("Desktop"),
        ("window.focus.device.mobile", false) => Some("mobile"),
        ("window.focus.device.mobile", true) => Some("Mobilgerät"),
        ("window.focus.device.tablet", false) => Some("tablet"),
        ("window.focus.device.tablet", true) => Some("Tablet"),
        ("row.control.refused", false) => Some("This row has nothing to edit"),
        ("row.control.refused", true) => Some("Diese Zeile lässt sich nicht bearbeiten"),
        ("palette.group.windows", false) => Some("Windows"),
        ("palette.group.windows", true) => Some("Fenster"),
        ("palette.group.catalogue", false) => Some("Catalogue"),
        ("palette.group.catalogue", true) => Some("Katalog"),
        ("palette.group.navigation", false) => Some("Navigation"),
        ("palette.group.navigation", true) => Some("Navigation"),
        ("palette.group.actions", false) => Some("Actions"),
        ("palette.group.actions", true) => Some("Aktionen"),
        ("palette.group.hostApp", false) => Some("Space"),
        ("palette.group.hostApp", true) => Some("Space"),
        _ => None,
    }
}

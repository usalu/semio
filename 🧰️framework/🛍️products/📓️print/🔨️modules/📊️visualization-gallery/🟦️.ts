/** 📊️ The visualization gallery sources: the product paths, the authored catalogue and schema loaders, the taxonomy leaves and the gallery template list that every generated artifact derives from.
 *
 * @see ./🏭️artifact-generation/🟦️.ts — the generated artifacts
 * @see ./🧾️api-reference/🟦️.ts — the machine-readable public API
 * @see ./🔑️implemented-keys/🟦️.ts — the implemented keys of the LaTeX packages
 * @see ./🗂️api-commands/🟦️.ts — the public API commands
 * @see ./📋️printed-key-tables/🟦️.ts — the printed key tables
 * @see ./🩺️coverage-verification/🟦️.ts — the catalogue coverage
 */
import { readFileSync, readdirSync } from "node:fs";
import { basename, join } from "node:path";
import { findWorkspaceRoot } from "@semio-tech/process/routing";
import { parseVizTaxonomy, type VizCatalog, type VizSchemaDocument } from "../../🧬️schema/🟦️.ts";

//#region 🔖️Sources
export const productRoot = join(findWorkspaceRoot(), "🧰️framework/🛍️products/📓️print");
export const VIZ_GALLERY_DIR = join(productRoot, "🧾️template/📊️viz-gallery");
export const VIZ_API_DIR = join(productRoot, "🧾️template/📊️viz-api");
export const VIZ_TAXONOMY_PATH = join(productRoot, "🖼️assets/📊️viz-taxonomy.md");
const VIZ_CATALOG_PATH = join(productRoot, "🖼️assets/🔣️viz-catalog.json");
const VIZ_SCHEMA_PATH = join(productRoot, "🧬️schema/🔣️.json");
export const VIZ_LATEX_DIR = join(productRoot, "🖋️latex");
export const VIZ_API_DOCUMENT = "🔓️viz-api.tex";
export const GENERATED_NOTE = "🤖 Generated by print/📜️script.ts generate viz from 🖼️assets/🔣️viz-catalog.json — do not edit.";
export const GENERATED_HEADER = `% ${GENERATED_NOTE}`;

/** 📚️ Reads the authored visualization catalog, the single source every generated artifact derives from. */
export function loadVizCatalog(): VizCatalog {
  return JSON.parse(readFileSync(VIZ_CATALOG_PATH, "utf8")) as VizCatalog;
}

/** 🧬️ Reads the visualization schema document, including its `x-semio-…` taxonomy and family vocabularies. */
export function loadVizSchema(): VizSchemaDocument & Readonly<Record<string, unknown>> {
  return JSON.parse(readFileSync(VIZ_SCHEMA_PATH, "utf8")) as VizSchemaDocument & Readonly<Record<string, unknown>>;
}

/** 🤖️ Reports whether a generated artifact carries the canonical do-not-edit note in its own comment syntax. */
export function marksItselfGenerated(path: string, content: string): boolean {
  return content.includes(path.endsWith(".json") ? JSON.stringify(GENERATED_NOTE) : GENERATED_HEADER);
}

/** 🍃️ Reads terminal visualization identifiers from the taxonomy source. */
export function parseVizTaxonomyLeaves(md: string): string[] {
  return parseVizTaxonomy(md).map((leaf) => `${leaf.section}/${leaf.slug}`);
}

/** 📑️ Enumerates the generated per-section gallery documents plus the hand-written API reference. */
export function visualizationTemplates(): readonly { readonly id: string; readonly texPath: string }[] {
  const documents = [
    ...readdirSync(VIZ_GALLERY_DIR).map((name) => ({ name, directory: "📊️viz-gallery" })),
    ...readdirSync(VIZ_API_DIR).map((name) => ({ name, directory: "📊️viz-api" })),
  ];
  return documents.filter(({ name }) => name.endsWith(".tex") && !name.includes("-dark"))
    .sort((left, right) => left.name.localeCompare(right.name))
    .map(({ name, directory }) => ({ id: basename(name, ".tex").replace(/^[^a-z]+/i, ""), texPath: `🧾️template/${directory}/${name}` }));
}
//#endregion 🔖️Sources

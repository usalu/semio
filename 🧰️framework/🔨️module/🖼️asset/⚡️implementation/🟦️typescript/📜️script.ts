function generatePy(icons: Record<string, string>, generatedDir: string): void {
  const literals = Object.keys(icons)
    .sort()
    .map((id) => `    "${id}": """${escapePythonString(icons[id]!)}""",`)
    .join("\n");
  const names = Object.keys(icons)
    .sort()
    .map((id) => `    "${id}",`)
    .join("\n");
  const body = `# Generated by asset/script.ts — do not edit.
from __future__ import annotations

from typing import Final, Literal

IconName = Literal[
${names}
]

ICONS: Final[dict[str, str]] = {
${literals}
}
`;
  writeFileSync(join(generatedDir, "🐍️icons.py"), body, "utf8");
}


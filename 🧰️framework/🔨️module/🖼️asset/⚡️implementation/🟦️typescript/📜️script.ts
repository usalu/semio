class GenerateCatalogScript extends BundleScript {
  async run(segments: string[]): Promise<void> {
    const target = (segments[0] ?? "all").toLowerCase();
    if (!["js", "net", "py", "rust", "all"].includes(target)) {
      throw new Error(`Unknown catalog generate target: ${target}`);
    }
    if (target === "all") {
      await runCatalogGenerateAll();
      return;
    }
    runGenerate(target);
  }
}

class BuildScript extends BundleScript {
  async run(): Promise<void> {
    await runCatalogGenerateAll();
    runMetabolismGenerate();
    console.log("@semio-tech/asset build complete.");
  }
}

const router = new ScriptRouter(import.meta.dir).register("generate", GenerateCatalogScript).register("generate-metabolism", GenerateMetabolismScript).register("build", BuildScript);


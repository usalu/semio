//#region 🚀️Commands
function catalogDirs(assetsDir: string): { iconsDir: string; generatedDir: string } {
  const iconsDir = join(assetsDir, "🔣️icon");
  const generatedDir = join(iconsDir, "🤖️generated");
  return { iconsDir, generatedDir };
}

function runGenerate(target: string): void {
  const assetsDir = import.meta.dir;
  const { iconsDir, generatedDir } = catalogDirs(assetsDir);
  mkdirSync(generatedDir, { recursive: true });
  const icons = readCatalogSvgs(iconsDir);
  writeCatalogReadme(assetsDir, Object.keys(icons));
  if (target === "js" || target === "all") generateJs(icons, generatedDir);
  if (target === "net" || target === "all") generateCs(icons, generatedDir);
  if (target === "py" || target === "all") generatePy(icons, generatedDir);
  if (target === "rust" || target === "all") generateRust(icons, generatedDir);
  console.log(`[asset] generated ${Object.keys(icons).length} icons → ${target}`);
}

async function runGenerateAll(): Promise<void> {
  const assetsDir = import.meta.dir;
  const { iconsDir, generatedDir } = catalogDirs(assetsDir);
  mkdirSync(generatedDir, { recursive: true });
  const icons = readCatalogSvgs(iconsDir);
  writeCatalogReadme(assetsDir, Object.keys(icons));
  generateJs(icons, generatedDir);
  generateCs(icons, generatedDir);
  generatePy(icons, generatedDir);
  generateRust(icons, generatedDir);
  await generateShortcodes(icons, generatedDir);
  console.log(`[asset] generated ${Object.keys(icons).length} icons + shortcodes → all`);
}


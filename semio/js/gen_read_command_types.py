#!/usr/bin/env python3
"""Emit semio/js/readCommandTypes.ts from semio/rs/read_module.rs (serde camelCase parity)."""

from __future__ import annotations

import re
from pathlib import Path

RS = Path(__file__).resolve().parent.parent / "rs" / "read_module.rs"
OUT = Path(__file__).resolve().parent / "readCommandTypes.ts"


def camel_field(rust_field: str) -> str:
    if rust_field == "r#type":
        return "type"
    if rust_field.startswith("r#"):
        rust_field = rust_field[2:]
    parts = rust_field.split("_")
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:] if p)


def rust_type_to_ts(rust: str, commands: set[str], outputs: set[str]) -> str:
    rust = rust.strip()
    if rust.startswith("Option<"):
        inner = rust[7:-1].strip()
        return f"({rust_type_to_ts(inner, commands, outputs)} | null | undefined)"
    if rust.startswith("Vec<"):
        inner = rust[4:-1].strip()
        inner_ts = rust_type_to_ts(inner, commands, outputs)
        return f"ReadonlyArray<{inner_ts}>"
    if rust in ("Id", "String"):
        return "string"
    if rust in ("f64", "f32", "i64", "i32", "usize", "i128"):
        return "number"
    if rust == "bool":
        return "boolean"
    if rust.endswith("IdDto"):
        return "IdDto"
    if rust in commands:
        return rust
    if rust in outputs:
        return rust
    return "unknown"


def split_fields(s: str) -> list[tuple[str, str]]:
    s = s.strip()
    if not s:
        return []
    out: list[tuple[str, str]] = []
    depth = 0
    start = 0
    for i, c in enumerate(s):
        if c == "<":
            depth += 1
        elif c == ">":
            depth -= 1
        elif c == "," and depth == 0:
            out.append(s[start:i].strip())
            start = i + 1
    out.append(s[start:].strip())
    res = []
    for p in out:
        if not p:
            continue
        m = re.match(r"^([a-zA-Z0-9#_]+)\s*:\s*(.+)$", p)
        if m:
            res.append((m.group(1), m.group(2).strip()))
        else:
            raise SystemExit(f"cannot parse field: {p!r}")
    return res


def extract_enums(src: str) -> dict[str, str]:
    """name -> body text (no outer braces)"""
    out: dict[str, str] = {}
    for m in re.finditer(r"pub enum (Read\w+) \{", src):
        name = m.group(1)
        i = m.end() - 1
        depth = 0
        j = i
        while j < len(src):
            c = src[j]
            if c == "{":
                depth += 1
            elif c == "}":
                depth -= 1
                if depth == 0:
                    out[name] = src[i + 1 : j]
                    break
            j += 1
    return out


def parse_variants(body: str) -> list[tuple[str, str | None]]:
    res: list[tuple[str, str | None]] = []
    for raw in body.splitlines():
        line = raw.split("//")[0].strip()
        if not line:
            continue
        if line.endswith(","):
            line = line[:-1].strip()
        if "{" not in line:
            m = re.match(r"^(\w+)$", line)
            if m:
                res.append((m.group(1), None))
            continue
        m = re.match(r"^(\w+)\s*\{(.*)\}\s*$", line)
        if not m:
            raise SystemExit(f"bad variant line: {line!r}")
        res.append((m.group(1), m.group(2).strip()))
    return res


def main() -> None:
    src = RS.read_text(encoding="utf-8")
    enums = extract_enums(src)
    commands = {n for n in enums if n.endswith("Command") and not n.endswith("CommandOutput")}
    outputs = {n for n in enums if n.endswith("CommandOutput")}

    out: list[str] = []
    out.append("/**")
    out.append(" * Read command + output types (serde **externally tagged**, `camelCase` keys).")
    out.append(" * @generated by gen_read_command_types.py from ../rs/read_module.rs")
    out.append(" */")
    out.append("")
    out.append("/** `{\"id\": string}` in JSON; all `*IdDto` use this shape. */")
    out.append("export type IdDto = { readonly id: string };")
    out.append("")
    out.append("/** One row of `readDesignFlattenMap` (camelCase fields). */")
    out.append("export type DesignFlattenMapEntryDto = {")
    out.append("  readonly pieceId: string;")
    out.append("  readonly plane: unknown;")
    out.append("  readonly center: unknown;")
    out.append("};")
    out.append("")

    order = sorted(
        enums.keys(),
        key=lambda s: (0, s) if s.endswith("CommandOutput") or s == "ReadKitCommandOutput" else (1, s),
    )
    read_kit_cmd_keys: list[str] = []
    # emit Command enums first, then CommandOutput
    for prefer_out in (False, True):
        for name in order:
            if name not in enums:
                continue
            is_out = name.endswith("CommandOutput")
            if is_out != prefer_out:
                continue
            body = enums[name]
            try:
                variants = parse_variants(body)
            except Exception as e:  # noqa: BLE001
                raise SystemExit(f"parse {name}: {e}") from e
            alts: list[str] = []
            for vname, inner in variants:
                key = vname[0].lower() + vname[1:]
                if name == "ReadKitCommand":
                    read_kit_cmd_keys.append(key)
                if inner is None:
                    alts.append(f"  | {{ readonly {key}: null }}")
                else:
                    parts = split_fields(inner)
                    flds: list[str] = []
                    for rfield, rtyp in parts:
                        ts = rust_type_to_ts(rtyp, commands, outputs)
                        cf = camel_field(rfield)
                        flds.append(f"readonly {cf}: {ts}")
                    inner_o = "; ".join(flds)
                    alts.append(f"  | {{ readonly {key}: {{ {inner_o} }} }}")
            out.append(f"export type {name} =")
            out.extend(alts)
            out.append("")

    out.append("/** Externally-tagged `ReadKitCommand` JSON keys (camelCase). */")
    qkeys = ", ".join(repr(k) for k in read_kit_cmd_keys)
    out.append(f"export const ALL_READ_KIT_COMMAND_KEYS = [{qkeys}] as const;")
    out.append("export type AllReadKitCommandKey = (typeof ALL_READ_KIT_COMMAND_KEYS)[number];")
    out.append("")

    out.append("export type ReadRootCommand = ReadKitCommand;")
    out.append("export type ReadCommandBatch = ReadonlyArray<ReadKitCommand>;")
    out.append("export type ReadCommandBatchResult = ReadonlyArray<ReadKitCommandOutput>;")
    out.append("")

    OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()

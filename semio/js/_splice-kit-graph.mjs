import fs from "fs";
const path = "c:/git/semio/semio/js/index.ts";
let idx = fs.readFileSync(path, "utf8");
let block = fs.readFileSync("c:/git/semio/semio/js/kitGraphCommandsRuntime.ts", "utf8");
block = "// #region Graph kit commands (semio.kit.* apply via KitStore)\n\n" + block.replace(/^\/\/ @semio\/js[^\n]*\n\n?/, "");
const benchMatch = idx.match(/\n\/\/ #region [^\n]*Benchmarks/);
if (!benchMatch) throw new Error("Benchmarks region not found");
const insertAt = benchMatch.index + 1;
const out = idx.slice(0, insertAt) + block + "\n" + idx.slice(insertAt);
fs.writeFileSync(path, out);
console.log("inserted lines", block.split("\n").length);

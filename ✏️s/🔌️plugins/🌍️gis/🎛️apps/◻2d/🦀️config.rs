//! 🧮️ GIS 2D play app — the view-state config artifact and its operation enum.
//!
//! Session-only but real, undoable config: it round-trips through the config `DocumentStore` exactly
//! like document content, with a true `backwards` per operation. Nothing here is document state — the
//! map's positions/routes/regions live in `crate::artifacts::gismap`.

use protocol::Operation;
use serde::{Deserialize, Serialize};
use std::collections::BTreeMap;

//#region 🔖️Config
/// 🧮️ gis2d's `DocumentApp::Config` — selection, per-layer visibility/stroke-weight, camera,
/// render/vector/LOD mode, feature selection/hover, selection method/mode, plus `locale`.
/// Per-layer maps are `BTreeMap` (not `HashMap`) because the DSL derive only binds string-keyed maps
/// through `dsl_schema::Shape::Map`'s `BTreeMap<String, V>` case.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize, dsl::DslDocument)]
#[serde(rename_all = "camelCase", default)]
#[dsl(extension = "gis2dcfg")]
#[dsl(layout = "lines")]
pub struct Gis2dConfig {
    /// 👁️ Selected document-tree layer ids.
    pub selected_ids: Vec<String>,
    /// 👁️ Per-layer visibility; a missing entry defaults to visible.
    #[dsl(block)]
    pub layer_visibility: BTreeMap<String, bool>,
    /// 🎥️ The free/live map camera (`{x,y,zoom}` JSON).
    pub camera_json: String,
    /// 🖼️ `"image" | "vector" | "combined"`.
    pub render_mode: String,
    /// 🎨️ `"colored" | "figureGround" | "invertedFigure"`.
    pub vector_style: String,
    /// 🔽️ Active LOD tier id.
    pub lod_mode: String,
    /// 👁️ `{positions:[id],routes:[id]}` feature selection JSON.
    pub feature_selection_json: String,
    /// 👁️ Hovered feature JSON (or `"null"`).
    pub hover_json: String,
    /// 🖱️ `"rectangle" | "lasso"` marquee method.
    pub selection_method: String,
    /// 🖱️ `"default" | "additive" | "subtractive" | "invertive"`.
    pub selection_mode: String,
    /// 👁️ Per-layer stroke-weight multiplier; a missing entry defaults to `1.0`.
    #[dsl(block)]
    pub layer_stroke_scale: BTreeMap<String, f64>,
    /// 🗣️ BCP-47 locale tag.
    pub locale: String,
}

fn default_gis2d_hover_json() -> String {
    "null".into()
}

fn default_gis2d_selection_method() -> String {
    "rectangle".into()
}

fn default_gis2d_selection_mode() -> String {
    "default".into()
}

fn default_gis2d_camera_json() -> String {
    r#"{"x":0,"y":0,"zoom":1}"#.into()
}

fn default_gis2d_render_mode() -> String {
    "combined".into()
}

fn default_gis2d_vector_style() -> String {
    "colored".into()
}

fn default_gis2d_feature_selection_json() -> String {
    r#"{"positions":[],"routes":[]}"#.into()
}

impl Default for Gis2dConfig {
    fn default() -> Self {
        Self {
            selected_ids: Vec::new(),
            layer_visibility: BTreeMap::new(),
            camera_json: default_gis2d_camera_json(),
            render_mode: default_gis2d_render_mode(),
            vector_style: default_gis2d_vector_style(),
            // 🔽️ Mirrors `framework_surface_tiled_map::GIS_MAP_LOD_MODE_AUTOMATIC`, spelled out here so
            // the config type stays independent of the tiled-map surface crate.
            lod_mode: "automatic".into(),
            feature_selection_json: default_gis2d_feature_selection_json(),
            hover_json: default_gis2d_hover_json(),
            selection_method: default_gis2d_selection_method(),
            selection_mode: default_gis2d_selection_mode(),
            layer_stroke_scale: BTreeMap::new(),
            locale: "en-US".into(),
        }
    }
}

store::impl_whole_record_config!(Gis2dConfig);

/// 👁️ Whether a map layer is currently shown; a layer with no explicit entry defaults to visible.
pub fn layer_visible(cfg: &Gis2dConfig, layer_id: &str) -> bool {
    cfg.layer_visibility.get(layer_id).copied().unwrap_or(true)
}
//#endregion 🔖️Config

//#region 🔖️ConfigOperations
/// 🧮️ `Gis2dConfig`'s operation enum — one variant per settled interaction, plus a generic `Snapshot`
/// every variant's `backwards()` returns ("whole-config snapshot is the simplest correct inverse").
/// `Operation::Diff` is the WHOLE `Gis2dConfig` (not a granular patch type): `diff()` returns "the full
/// config after this op", and `OperationDiff<Gis2dConfig>::apply` for `Gis2dConfig` itself (generated by
/// `store::impl_whole_record_config!`) just returns that snapshot verbatim, ignoring `base`.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize, dsl::DslOps)]
pub enum Gis2dConfigOperation {
    #[dsl(key = "snapshot")]
    Snapshot {
        #[dsl(block)]
        config: Gis2dConfig,
    },
    #[dsl(key = "selection")]
    SetSelection { ids: Vec<String> },
    #[dsl(key = "layer-visibility")]
    SetLayerVisibility { layer_id: String, visible: bool },
    #[dsl(key = "camera")]
    SetCamera { camera_json: String },
    #[dsl(key = "render-mode")]
    SetRenderMode { value: String },
    #[dsl(key = "vector-style")]
    SetVectorStyle { value: String },
    #[dsl(key = "lod-mode")]
    SetLodMode { value: String },
    #[dsl(key = "feature-selection")]
    SetFeatureSelection { value_json: String },
    #[dsl(key = "hover")]
    SetHover { value_json: String },
    #[dsl(key = "selection-method")]
    SetSelectionMethod { value: String },
    #[dsl(key = "selection-mode")]
    SetSelectionMode { value: String },
    #[dsl(key = "layer-stroke-scale")]
    SetLayerStrokeScale { layer_id: String, value: f64 },
    #[dsl(key = "locale")]
    SetLocale { value: String },
}

impl Operation<Gis2dConfig> for Gis2dConfigOperation {
    type Diff = Gis2dConfig;

    fn diff(&self, base: &Gis2dConfig) -> Gis2dConfig {
        let mut next = base.clone();
        match self {
            Gis2dConfigOperation::Snapshot { config } => return config.clone(),
            Gis2dConfigOperation::SetSelection { ids } => next.selected_ids = ids.clone(),
            Gis2dConfigOperation::SetLayerVisibility { layer_id, visible } => {
                next.layer_visibility.insert(layer_id.clone(), *visible);
            }
            Gis2dConfigOperation::SetCamera { camera_json } => next.camera_json = camera_json.clone(),
            Gis2dConfigOperation::SetRenderMode { value } => next.render_mode = value.clone(),
            Gis2dConfigOperation::SetVectorStyle { value } => next.vector_style = value.clone(),
            Gis2dConfigOperation::SetLodMode { value } => next.lod_mode = value.clone(),
            Gis2dConfigOperation::SetFeatureSelection { value_json } => next.feature_selection_json = value_json.clone(),
            Gis2dConfigOperation::SetHover { value_json } => next.hover_json = value_json.clone(),
            Gis2dConfigOperation::SetSelectionMethod { value } => next.selection_method = value.clone(),
            Gis2dConfigOperation::SetSelectionMode { value } => next.selection_mode = value.clone(),
            Gis2dConfigOperation::SetLayerStrokeScale { layer_id, value } => {
                next.layer_stroke_scale.insert(layer_id.clone(), *value);
            }
            Gis2dConfigOperation::SetLocale { value } => next.locale = value.clone(),
        }
        next
    }

    fn backwards(&self, base: &Gis2dConfig) -> Vec<Self> {
        vec![Gis2dConfigOperation::Snapshot { config: base.clone() }]
    }
}
//#endregion 🔖️ConfigOperations

//#region 🧪️Tests
#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn gis2d_config_default_matches_the_existing_action_arg_sticky_defaults() {
        let config = Gis2dConfig::default();
        assert_eq!(config.render_mode, "combined");
        assert_eq!(config.vector_style, "colored");
        assert_eq!(config.lod_mode, "automatic");
        assert_eq!(config.selection_method, "rectangle");
        assert_eq!(config.selection_mode, "default");
        assert_eq!(config.locale, "en-US");
    }

    #[test]
    fn gis2d_config_default_lod_mode_matches_the_tiled_map_surface_constant() {
        assert_eq!(Gis2dConfig::default().lod_mode, framework_surface_tiled_map::GIS_MAP_LOD_MODE_AUTOMATIC);
    }

    #[test]
    fn layer_visible_defaults_to_true_and_honours_explicit_entries() {
        let mut config = Gis2dConfig::default();
        assert!(layer_visible(&config, "water"), "a layer with no entry is visible");
        config.layer_visibility.insert("water".into(), false);
        assert!(!layer_visible(&config, "water"));
    }

    #[test]
    fn gis2d_config_dsl_round_trips_default_and_populated() {
        store::test_support::assert_dsl_round_trip(&Gis2dConfig::default());
        let mut populated = Gis2dConfig::default();
        populated.selected_ids = vec!["roads".into()];
        populated.layer_visibility.insert("water".into(), false);
        populated.layer_stroke_scale.insert("roads".into(), 1.5);
        store::test_support::assert_dsl_round_trip(&populated);
        store::test_support::assert_dsl_pack_equivalence(&populated);
    }

    #[test]
    fn gis2d_config_operation_diff_writes_the_targeted_field_and_leaves_the_rest() {
        let base = Gis2dConfig::default();
        let next = Gis2dConfigOperation::SetRenderMode { value: "vector".into() }.diff(&base);
        assert_eq!(next.render_mode, "vector");
        assert_eq!(next.vector_style, base.vector_style, "untouched fields survive the diff");
    }

    #[test]
    fn gis2d_config_operation_backwards_restores_the_pre_operation_snapshot() {
        let base = Gis2dConfig::default();
        let operation = Gis2dConfigOperation::SetLayerVisibility { layer_id: "water".into(), visible: false };
        let next = operation.diff(&base);
        assert_eq!(next.layer_visibility.get("water"), Some(&false));
        let backwards = operation.backwards(&base);
        assert_eq!(backwards, vec![Gis2dConfigOperation::Snapshot { config: base.clone() }]);
        let restored = backwards[0].diff(&next);
        assert_eq!(restored, base, "the snapshot inverse restores the exact pre-operation config");
    }

    #[test]
    fn gis2d_config_operation_lines_round_trip() {
        store::test_support::assert_op_line_round_trip(&Gis2dConfigOperation::SetSelection { ids: vec!["roads".into()] });
        store::test_support::assert_op_line_round_trip(&Gis2dConfigOperation::SetLayerVisibility { layer_id: "water".into(), visible: false });
        store::test_support::assert_op_line_round_trip(&Gis2dConfigOperation::SetCamera { camera_json: r#"{"x":1,"y":2,"zoom":3}"#.into() });
        store::test_support::assert_op_line_round_trip(&Gis2dConfigOperation::SetRenderMode { value: "vector".into() });
        store::test_support::assert_op_line_round_trip(&Gis2dConfigOperation::SetVectorStyle { value: "figureGround".into() });
        store::test_support::assert_op_line_round_trip(&Gis2dConfigOperation::SetLodMode { value: "automatic".into() });
        store::test_support::assert_op_line_round_trip(&Gis2dConfigOperation::SetFeatureSelection { value_json: r#"{"positions":[],"routes":[]}"#.into() });
        store::test_support::assert_op_line_round_trip(&Gis2dConfigOperation::SetHover { value_json: "null".into() });
        store::test_support::assert_op_line_round_trip(&Gis2dConfigOperation::SetSelectionMethod { value: "lasso".into() });
        store::test_support::assert_op_line_round_trip(&Gis2dConfigOperation::SetSelectionMode { value: "additive".into() });
        store::test_support::assert_op_line_round_trip(&Gis2dConfigOperation::SetLayerStrokeScale { layer_id: "roads".into(), value: 1.5 });
        store::test_support::assert_op_line_round_trip(&Gis2dConfigOperation::SetLocale { value: "de-DE".into() });
        store::test_support::assert_op_line_round_trip(&Gis2dConfigOperation::Snapshot { config: Gis2dConfig::default() });
    }
}

CREATE TABLE en1996_document (
  id INTEGER PRIMARY KEY CHECK (id = 1),
  annex TEXT NOT NULL CHECK (annex IN ('En','De')),
  masonry_class TEXT NOT NULL CHECK (masonry_class IN ('Class1','Class2','Class3','Class4','Class5')),
  design_situation TEXT NOT NULL CHECK (design_situation IN ('Persistent','Transient','Accidental','Seismic')),
  storeys INTEGER NOT NULL CHECK (storeys BETWEEN 0 AND 4294967295)
);
CREATE TABLE en1996_wall (
  id INTEGER PRIMARY KEY,
  document_id INTEGER NOT NULL REFERENCES en1996_document(id),
  ordinal INTEGER NOT NULL CHECK (ordinal >= 0),
  logical_id TEXT NOT NULL,
  label_en TEXT NOT NULL,
  label_de TEXT NOT NULL,
  wall_type TEXT NOT NULL CHECK (wall_type IN ('LoadBearing','Shear','NonLoadBearing')),
  thickness_m REAL,
  height_m REAL,
  length_m REAL,
  support_sides INTEGER NOT NULL CHECK (support_sides BETWEEN 0 AND 255),
  slab_bearing_depth_m REAL,
  eccentricity_top_m REAL,
  eccentricity_bottom_m REAL,
  unit_group TEXT NOT NULL CHECK (unit_group IN ('Group1','Group2','Group3','Group4')),
  unit_material TEXT NOT NULL CHECK (unit_material IN ('Clay','CalciumSilicate','Aerated','Concrete')),
  f_b_pa REAL,
  unit_length_m REAL,
  unit_width_m REAL,
  unit_height_m REAL,
  mortar_type TEXT NOT NULL CHECK (mortar_type IN ('GeneralPurpose','ThinLayer','Lightweight')),
  mortar_class TEXT NOT NULL CHECK (mortar_class IN ('M1','M2_5','M5','M10','M15','M20')),
  mortar_strength_pa REAL,
  bed_joint_thickness_m REAL,
  reinforced INTEGER NOT NULL CHECK (reinforced IN (0,1)),
  as_vertical_m2 REAL,
  as_horizontal_m2 REAL,
  f_yd_pa REAL,
  fire_rei_min INTEGER NOT NULL CHECK (fire_rei_min BETWEEN 0 AND 4294967295),
  exposure TEXT NOT NULL CHECK (exposure IN ('Mx1','Mx2','Mx3','Mx4','Mx5')),
  mu REAL,
  density_kg_m3 REAL,
  phi_infinity REAL,
  is_basement INTEGER NOT NULL CHECK (is_basement IN (0,1)),
  thickness_m_ieee754_bits INTEGER NOT NULL, thickness_m_ieee754_class TEXT NOT NULL,
  height_m_ieee754_bits INTEGER NOT NULL, height_m_ieee754_class TEXT NOT NULL,
  length_m_ieee754_bits INTEGER NOT NULL, length_m_ieee754_class TEXT NOT NULL,
  slab_bearing_depth_m_ieee754_bits INTEGER NOT NULL, slab_bearing_depth_m_ieee754_class TEXT NOT NULL,
  eccentricity_top_m_ieee754_bits INTEGER NOT NULL, eccentricity_top_m_ieee754_class TEXT NOT NULL,
  eccentricity_bottom_m_ieee754_bits INTEGER NOT NULL, eccentricity_bottom_m_ieee754_class TEXT NOT NULL,
  f_b_pa_ieee754_bits INTEGER NOT NULL, f_b_pa_ieee754_class TEXT NOT NULL,
  unit_length_m_ieee754_bits INTEGER NOT NULL, unit_length_m_ieee754_class TEXT NOT NULL,
  unit_width_m_ieee754_bits INTEGER NOT NULL, unit_width_m_ieee754_class TEXT NOT NULL,
  unit_height_m_ieee754_bits INTEGER NOT NULL, unit_height_m_ieee754_class TEXT NOT NULL,
  mortar_strength_pa_ieee754_bits INTEGER NOT NULL, mortar_strength_pa_ieee754_class TEXT NOT NULL,
  bed_joint_thickness_m_ieee754_bits INTEGER NOT NULL, bed_joint_thickness_m_ieee754_class TEXT NOT NULL,
  as_vertical_m2_ieee754_bits INTEGER NOT NULL, as_vertical_m2_ieee754_class TEXT NOT NULL,
  as_horizontal_m2_ieee754_bits INTEGER NOT NULL, as_horizontal_m2_ieee754_class TEXT NOT NULL,
  f_yd_pa_ieee754_bits INTEGER NOT NULL, f_yd_pa_ieee754_class TEXT NOT NULL,
  mu_ieee754_bits INTEGER NOT NULL, mu_ieee754_class TEXT NOT NULL,
  density_kg_m3_ieee754_bits INTEGER NOT NULL, density_kg_m3_ieee754_class TEXT NOT NULL,
  phi_infinity_ieee754_bits INTEGER NOT NULL, phi_infinity_ieee754_class TEXT NOT NULL
);
CREATE TABLE en1996_opening (
  id INTEGER PRIMARY KEY,
  wall_id INTEGER NOT NULL REFERENCES en1996_wall(id),
  ordinal INTEGER NOT NULL CHECK (ordinal >= 0),
  logical_id TEXT NOT NULL,
  width_m REAL, height_m REAL, sill_height_m REAL,
  width_m_ieee754_bits INTEGER NOT NULL, width_m_ieee754_class TEXT NOT NULL,
  height_m_ieee754_bits INTEGER NOT NULL, height_m_ieee754_class TEXT NOT NULL,
  sill_height_m_ieee754_bits INTEGER NOT NULL, sill_height_m_ieee754_class TEXT NOT NULL
);
CREATE TABLE en1996_load_case (
  id INTEGER PRIMARY KEY,
  wall_id INTEGER NOT NULL REFERENCES en1996_wall(id),
  ordinal INTEGER NOT NULL CHECK (ordinal >= 0),
  logical_id TEXT NOT NULL, design_situation TEXT NOT NULL, imposed_category TEXT NOT NULL,
  g_k_slab_n REAL, q_k_imposed_pa REAL, tributary_area_m2 REAL, slab_span_m REAL,
  q_k_snow_pa REAL, q_p_wind_pa REAL, c_pe REAL, h_k_earth_n REAL,
  g_k_slab_n_ieee754_bits INTEGER NOT NULL, g_k_slab_n_ieee754_class TEXT NOT NULL,
  q_k_imposed_pa_ieee754_bits INTEGER NOT NULL, q_k_imposed_pa_ieee754_class TEXT NOT NULL,
  tributary_area_m2_ieee754_bits INTEGER NOT NULL, tributary_area_m2_ieee754_class TEXT NOT NULL,
  slab_span_m_ieee754_bits INTEGER NOT NULL, slab_span_m_ieee754_class TEXT NOT NULL,
  q_k_snow_pa_ieee754_bits INTEGER NOT NULL, q_k_snow_pa_ieee754_class TEXT NOT NULL,
  q_p_wind_pa_ieee754_bits INTEGER NOT NULL, q_p_wind_pa_ieee754_class TEXT NOT NULL,
  c_pe_ieee754_bits INTEGER NOT NULL, c_pe_ieee754_class TEXT NOT NULL,
  h_k_earth_n_ieee754_bits INTEGER NOT NULL, h_k_earth_n_ieee754_class TEXT NOT NULL
);
CREATE TABLE en1996_concentrated_load (
  id INTEGER PRIMARY KEY,
  load_case_id INTEGER NOT NULL REFERENCES en1996_load_case(id),
  ordinal INTEGER NOT NULL CHECK (ordinal >= 0),
  logical_id TEXT NOT NULL,
  force_n REAL, bearing_area_m2 REAL, bearing_length_m REAL,
  force_n_ieee754_bits INTEGER NOT NULL, force_n_ieee754_class TEXT NOT NULL,
  bearing_area_m2_ieee754_bits INTEGER NOT NULL, bearing_area_m2_ieee754_class TEXT NOT NULL,
  bearing_length_m_ieee754_bits INTEGER NOT NULL, bearing_length_m_ieee754_class TEXT NOT NULL
);

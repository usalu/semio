CREATE TABLE en1995_document (
  id INTEGER PRIMARY KEY CHECK (id = 1),
  annex TEXT NOT NULL CHECK (annex IN ('En','De'))
);
CREATE TABLE en1995_member (
  id INTEGER PRIMARY KEY,
  document_id INTEGER NOT NULL REFERENCES en1995_document(id),
  ordinal INTEGER NOT NULL CHECK (ordinal >= 0),
  logical_id TEXT NOT NULL, label_en TEXT NOT NULL, label_de TEXT NOT NULL,
  role TEXT NOT NULL CHECK (role IN ('beam','column','floor','bridge')),
  strength_class TEXT NOT NULL,
  service_class INTEGER NOT NULL CHECK (service_class BETWEEN 0 AND 255),
  support TEXT NOT NULL CHECK (support IN ('simplySupported','cantilever','continuousTwoSpan')),
  b_m REAL, h_m REAL, span_m REAL, support_length_m REAL, bearing_length_m REAL,
  buckling_length_y_m REAL, buckling_length_z_m REAL, lateral_restraint_spacing_m REAL,
  notch_depth_m REAL, notch_distance_m REAL, m_crit_nm REAL,
  mass_kg_per_m REAL, mass_kg_per_m2 REAL, damping_xi REAL, fire_duration_s REAL,
  bridge_n_obs REAL, bridge_t_l_years REAL, bridge_beta REAL, bridge_a REAL, bridge_b REAL, bridge_crowd_per_m2 REAL,
  b_m_ieee754_bits INTEGER NOT NULL, b_m_ieee754_class TEXT NOT NULL,
  h_m_ieee754_bits INTEGER NOT NULL, h_m_ieee754_class TEXT NOT NULL,
  span_m_ieee754_bits INTEGER NOT NULL, span_m_ieee754_class TEXT NOT NULL,
  support_length_m_ieee754_bits INTEGER NOT NULL, support_length_m_ieee754_class TEXT NOT NULL,
  bearing_length_m_ieee754_bits INTEGER NOT NULL, bearing_length_m_ieee754_class TEXT NOT NULL,
  buckling_length_y_m_ieee754_bits INTEGER NOT NULL, buckling_length_y_m_ieee754_class TEXT NOT NULL,
  buckling_length_z_m_ieee754_bits INTEGER NOT NULL, buckling_length_z_m_ieee754_class TEXT NOT NULL,
  lateral_restraint_spacing_m_ieee754_bits INTEGER NOT NULL, lateral_restraint_spacing_m_ieee754_class TEXT NOT NULL,
  notch_depth_m_ieee754_bits INTEGER NOT NULL, notch_depth_m_ieee754_class TEXT NOT NULL,
  notch_distance_m_ieee754_bits INTEGER NOT NULL, notch_distance_m_ieee754_class TEXT NOT NULL,
  m_crit_nm_ieee754_bits INTEGER NOT NULL, m_crit_nm_ieee754_class TEXT NOT NULL,
  mass_kg_per_m_ieee754_bits INTEGER NOT NULL, mass_kg_per_m_ieee754_class TEXT NOT NULL,
  mass_kg_per_m2_ieee754_bits INTEGER NOT NULL, mass_kg_per_m2_ieee754_class TEXT NOT NULL,
  damping_xi_ieee754_bits INTEGER NOT NULL, damping_xi_ieee754_class TEXT NOT NULL,
  fire_duration_s_ieee754_bits INTEGER NOT NULL, fire_duration_s_ieee754_class TEXT NOT NULL,
  bridge_n_obs_ieee754_bits INTEGER NOT NULL, bridge_n_obs_ieee754_class TEXT NOT NULL,
  bridge_t_l_years_ieee754_bits INTEGER NOT NULL, bridge_t_l_years_ieee754_class TEXT NOT NULL,
  bridge_beta_ieee754_bits INTEGER NOT NULL, bridge_beta_ieee754_class TEXT NOT NULL,
  bridge_a_ieee754_bits INTEGER NOT NULL, bridge_a_ieee754_class TEXT NOT NULL,
  bridge_b_ieee754_bits INTEGER NOT NULL, bridge_b_ieee754_class TEXT NOT NULL,
  bridge_crowd_per_m2_ieee754_bits INTEGER NOT NULL, bridge_crowd_per_m2_ieee754_class TEXT NOT NULL
);
CREATE TABLE en1995_member_action (
  id INTEGER PRIMARY KEY,
  member_id INTEGER NOT NULL REFERENCES en1995_member(id),
  ordinal INTEGER NOT NULL CHECK (ordinal >= 0),
  logical_id TEXT NOT NULL, kind TEXT NOT NULL, category TEXT NOT NULL, load_duration TEXT NOT NULL,
  q_line_n_per_m REAL, f_point_n REAL, m_k_nm REAL, v_k_n REAL, n_k_n REAL, n_t_k_n REAL, f_c90_k_n REAL,
  q_line_n_per_m_ieee754_bits INTEGER NOT NULL, q_line_n_per_m_ieee754_class TEXT NOT NULL,
  f_point_n_ieee754_bits INTEGER NOT NULL, f_point_n_ieee754_class TEXT NOT NULL,
  m_k_nm_ieee754_bits INTEGER NOT NULL, m_k_nm_ieee754_class TEXT NOT NULL,
  v_k_n_ieee754_bits INTEGER NOT NULL, v_k_n_ieee754_class TEXT NOT NULL,
  n_k_n_ieee754_bits INTEGER NOT NULL, n_k_n_ieee754_class TEXT NOT NULL,
  n_t_k_n_ieee754_bits INTEGER NOT NULL, n_t_k_n_ieee754_class TEXT NOT NULL,
  f_c90_k_n_ieee754_bits INTEGER NOT NULL, f_c90_k_n_ieee754_class TEXT NOT NULL
);
CREATE TABLE en1995_connection (
  id INTEGER PRIMARY KEY,
  document_id INTEGER NOT NULL REFERENCES en1995_document(id),
  ordinal INTEGER NOT NULL CHECK (ordinal >= 0),
  logical_id TEXT NOT NULL, label_en TEXT NOT NULL, label_de TEXT NOT NULL,
  fastener_type TEXT NOT NULL, strength_class TEXT NOT NULL,
  service_class INTEGER NOT NULL CHECK (service_class BETWEEN 0 AND 255),
  diameter_m REAL,
  number INTEGER NOT NULL CHECK (number BETWEEN 0 AND 4294967295),
  rows INTEGER NOT NULL CHECK (rows BETWEEN 0 AND 4294967295),
  spacing_m REAL, edge_distance_m REAL, end_distance_m REAL, t1_m REAL, t2_m REAL,
  steel_plate INTEGER NOT NULL CHECK (steel_plate IN (0,1)),
  steel_plate_thickness_m REAL,
  shear_planes INTEGER NOT NULL CHECK (shear_planes BETWEEN 0 AND 4294967295),
  f_u_k REAL,
  diameter_m_ieee754_bits INTEGER NOT NULL, diameter_m_ieee754_class TEXT NOT NULL,
  spacing_m_ieee754_bits INTEGER NOT NULL, spacing_m_ieee754_class TEXT NOT NULL,
  edge_distance_m_ieee754_bits INTEGER NOT NULL, edge_distance_m_ieee754_class TEXT NOT NULL,
  end_distance_m_ieee754_bits INTEGER NOT NULL, end_distance_m_ieee754_class TEXT NOT NULL,
  t1_m_ieee754_bits INTEGER NOT NULL, t1_m_ieee754_class TEXT NOT NULL,
  t2_m_ieee754_bits INTEGER NOT NULL, t2_m_ieee754_class TEXT NOT NULL,
  steel_plate_thickness_m_ieee754_bits INTEGER NOT NULL, steel_plate_thickness_m_ieee754_class TEXT NOT NULL,
  f_u_k_ieee754_bits INTEGER NOT NULL, f_u_k_ieee754_class TEXT NOT NULL
);
CREATE TABLE en1995_connection_action (
  id INTEGER PRIMARY KEY,
  connection_id INTEGER NOT NULL REFERENCES en1995_connection(id),
  ordinal INTEGER NOT NULL CHECK (ordinal >= 0),
  logical_id TEXT NOT NULL, kind TEXT NOT NULL, load_duration TEXT NOT NULL,
  f_k_n REAL,
  f_k_n_ieee754_bits INTEGER NOT NULL, f_k_n_ieee754_class TEXT NOT NULL
);

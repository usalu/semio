    /// 🔩️ The document with the joints of an example frame in its first building: `joint-1` at the first and `joint-2` at the second storey (ΣM_Rc ≥ 1.3 ΣM_Rb, or a weak column at `joint-1` when `weak_lower_joint`) and `joint-3` under the roof, which the top-storey exemption of EN 1998-1 4.4.2.3 leaves unchecked although its column is weaker than the beam.
    pub fn with_example_joints(mut self, weak_lower_joint: bool) -> Self {
        let building = &self.buildings[0];
        let role = |kind: MemberKind| building.members.iter().find(|m| m.role == kind).map(|m| m.id.clone()).unwrap_or_default();
        let (column, beam, top) = (role(MemberKind::Column), role(MemberKind::Beam), building.storeys.len().saturating_sub(1));
        let joint = |id: &str, storey: usize, x_m: f64, y_m: f64, column_moment_rd_nm: f64, beam_moment_rd_nm: f64| En1998Joint {
            id: id.into(),
            building_id: building.id.clone(),
            storey_id: building.storeys[storey].id.clone(),
            column_id: column.clone(),
            beam_id: beam.clone(),
            x_m,
            y_m,
            column_moment_rd_nm,
            beam_moment_rd_nm,
        };
        self.joints = vec![
            joint("joint-1", 0, 6.0, 4.0, if weak_lower_joint { 4.0e6 } else { 9.0e6 }, 4.0e6),
            joint("joint-2", 1, 12.0, 4.0, 7.5e6, 4.0e6),
            joint("joint-3", top, 12.0, 12.0, 3.5e6, 4.0e6),
        ];
        self
    }


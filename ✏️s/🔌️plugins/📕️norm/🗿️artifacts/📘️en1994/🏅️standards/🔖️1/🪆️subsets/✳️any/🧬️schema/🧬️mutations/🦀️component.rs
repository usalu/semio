//! 🧬️ En1994 artifact — document mutation dispatch. Semantic vocabulary derived from
//! `📸️snapshot/🦀️component.rs`'s `En1994Snapshot` shape (a flat set of persistent scalar
//! calculation inputs — national annex choice, design actions, resistances, fire/fatigue
//! parameters; no id-keyed or ordered collections in this artifact) per
//! `.🦑️repo/🎫️tickets/🎆️26/🌙️08/☀️12/SEMANTIC-MUTATIONS-OVERHAUL/📓️taxonomy.md`/
//! `📓️derivation-rules.md` rule 1 (document-level scalars). Every persistent field gets its own
//! `change-<field>` mutation — none of these 22 fields forms an inseparable multi-field facet
//! that's "never meaningfully set one-field-at-a-time" (derivation-rules rule 1's `update`
//! exception), so no `update-*` grouping was introduced. `impl protocol::Mutation`/
//! `SemanticMutation` below are generated by `#[derive(dsl::Mutations)]` — never hand-written.
//!
//! Every triad leaf is self-wired directly below (`#[path]`, `🔖️LeafWiring` region) rather than in
//! `📦️glue.rs` — this facet's fan-out (26/08/12/SEMANTIC-MUTATIONS-OVERHAUL) is scoped to files
//! inside this artifact directory only; `📦️glue.rs` is plugin-shared and out of that scope. The old
//! generic `📄set-snapshot` leaf stays physically present as an orphan stub (see its own doc
//! comments) because `📦️glue.rs` still `#[path]`-wires it — cleanup tracked as a `sharedFileRequests`
//! entry in this ticket's wave2 report.


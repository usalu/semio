"""🔍️ Library coverage introspection: walks the installed oracle libraries and writes a markdown matrix of the Eurocode clauses each one implements.

Usage: python -I 🐍️.py OUTPUT.md
"""

import importlib
import importlib.metadata
import importlib.util
import inspect
import pkgutil
import re
import sys
from pathlib import Path

LIBRARIES = {
    "structuralcodes": ["structuralcodes.codes"],
    "concreteproperties": ["concreteproperties"],
    "sectionproperties": ["sectionproperties.analysis", "sectionproperties.pre.library"],
    "blueprints": ["blueprints.codes", "blueprints.structural_sections"],
    "groundhog": ["groundhog"],
    "sympy": ["sympy"],
    "pynite": ["Pynite"],
    "anastruct": ["anastruct"],
}
DISTRIBUTIONS = {"structuralcodes": "structuralcodes", "concreteproperties": "concreteproperties", "sectionproperties": "sectionproperties", "blueprints": "blue-prints", "groundhog": "groundhog", "sympy": "sympy", "pynite": "PyNiteFEA", "anastruct": "anastruct"}
CLAUSE = re.compile(r"(?:EN\s?)?(?:19\d\d-\d(?:-\d)?\s*)?(?:§|Eq\.?|Equation|Formula|Table|clause|Cl\.)?\s*\(?\b(\d{1,2}\.\d{1,2}(?:\.\d{1,2}){0,3}|[A-Z]\.\d{1,2}(?:\.\d{1,2})?)\b\)?")
PART = re.compile(r"(?:ec|en|eurocode)[_ -]?(?:19)?(\d)|(\d{4})[_-](\d)", re.I)


def stub_plotting():
    """🔇️ Load the groundhog adapter, which installs the inert plotly, pyproj and jinja2 finder groundhog 0.15.0 needs at import."""
    spec = importlib.util.spec_from_file_location("coverage_groundhog_adapter", Path(__file__).resolve().parent.parent / "🔌️adapters" / "groundhog" / "🐍️.py")
    spec.loader.exec_module(importlib.util.module_from_spec(spec))


def walk(root):
    """🚶️ Yield every importable submodule under `root`, tolerating import failures."""
    try:
        package = importlib.import_module(root)
    except Exception as error:
        yield root, None, error
        return
    yield root, package, None
    for info in pkgutil.walk_packages(getattr(package, "__path__", []), root + "."):
        try:
            yield info.name, importlib.import_module(info.name), None
        except Exception as error:
            yield info.name, None, error


def public(module):
    """🔎️ Public functions and classes defined in `module` itself."""
    for name, member in inspect.getmembers(module):
        if name.startswith("_") or not (inspect.isfunction(member) or inspect.isclass(member)):
            continue
        if getattr(member, "__module__", None) == module.__name__:
            yield name, member


def order(clause):
    """🔢️ Sort key that orders numeric and lettered clause segments without mixing types."""
    return [(0, int(p), "") if p.isdigit() else (1, 0, p) for p in clause.split(".")]


def summarise(member):
    """📝️ First docstring line plus the clause citations found in the whole docstring."""
    doc = inspect.getdoc(member) or ""
    first = doc.strip().splitlines()[0] if doc.strip() else ""
    clauses = sorted(set(m.group(1) for m in CLAUSE.finditer(doc)), key=order)
    return first, clauses


def scan(library):
    """📚️ Rows `(module, name, first line, clauses)` and failures for one library."""
    rows, failures = [], []
    for root in LIBRARIES[library]:
        for name, module, error in walk(root):
            if error is not None:
                failures.append((name, f"{type(error).__name__}: {error}"))
                continue
            for member, obj in public(module):
                rows.append((name, member, *summarise(obj)))
    return rows, failures


def code_part(module):
    """🏷️ The Eurocode part a module path refers to, or `-`."""
    m = re.search(r"ec(\d)(?:_(\d{4}))?|(?:en)?(199\d)", module.replace(".", "_"))
    if not m:
        return "-"
    return f"EN 199{m.group(1)}" if m.group(1) else f"EN {m.group(3)}"


def render(out):
    """🧾️ Render the markdown report."""
    lines = ["# Oracle Library Coverage", "", "Generated by `✏️s/🔌️plugins/📕️norm/🔮️oracles/🏃️harness/🔍️coverage/🐍️.py`; introspection of the installed packages, no network.", ""]
    summary, detail = [], []
    for library in LIBRARIES:
        try:
            version = importlib.metadata.version(DISTRIBUTIONS[library])
        except importlib.metadata.PackageNotFoundError:
            summary.append(f"| {library} | NOT INSTALLED | - | - | - |")
            continue
        rows, failures = scan(library)
        per_part = {}
        for module, name, first, clauses in rows:
            per_part.setdefault(code_part(module), []).append((module, name, first, clauses))
        for part, items in sorted(per_part.items()):
            cited = sorted({c for *_, cl in items for c in cl}, key=order)
            summary.append(f"| {library} {version} | {part} | {len(items)} | {len(cited)} | {', '.join(cited[:12])}{' ...' if len(cited) > 12 else ''} |")
        detail += ["", f"## {library} {version}", ""]
        if failures:
            detail += ["Import failures:", ""] + [f"- `{n}`: {e}" for n, e in failures] + [""]
        eurocode = [r for r in rows if code_part(r[0]) != "-"]
        detail += ["| module | symbol | summary | cited clauses |", "|---|---|---|---|"]
        detail += [f"| `{m}` | `{n}` | {f.replace('|', '/')} | {', '.join(c)} |" for m, n, f, c in (eurocode or rows)]
    lines += ["| library | part | public symbols | distinct clause citations | clauses |", "|---|---|---|---|---|"] + summary + detail
    Path(out).write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    stub_plotting()
    render(sys.argv[1])

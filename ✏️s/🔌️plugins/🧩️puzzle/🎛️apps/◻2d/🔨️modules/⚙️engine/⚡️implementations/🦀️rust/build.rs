//! @emoji 📎️ Build script: metabolism SVG icon table for `include_str!`.

use std::path::PathBuf;

fn main() {
    let manifest_dir = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let out_dir = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR"));
    let emoji_font = manifest_dir.join("asset/🔤️NotoColorEmoji-subset.ttf");
    println!("cargo:rerun-if-changed={}", emoji_font.display());

    let icons_src = manifest_dir.join("../../../../../../../../../🧰️framework/🔨️modules/🖼️assets/⚡️implementations/🟦️typescript/🌱️metabolism/🔣️icons");
    println!("cargo:rerun-if-changed={}", icons_src.display());

    let mut arms = String::new();
    if icons_src.is_dir() {
        for ent in std::fs::read_dir(&icons_src).unwrap_or_else(|e| panic!("read_dir {}: {e}", icons_src.display())) {
            let ent = ent.unwrap_or_else(|e| panic!("dir entry: {e}"));
            let path = ent.path();
            if path.extension().and_then(|x| x.to_str()) != Some("svg") {
                continue;
            }
            let stem = path.file_stem().and_then(|s| s.to_str()).unwrap_or_else(|| panic!("bad file name {:?}", path));
            let safe = stem.chars().map(|c| if c.is_ascii_alphanumeric() { c } else { '_' }).collect::<String>();
            let dest = out_dir.join(format!("icon_{safe}.svg"));
            std::fs::copy(&path, &dest).unwrap_or_else(|e| panic!("copy {:?} -> {:?}: {e}", path, dest));
            arms.push_str(&format!("\t\t\"{stem}\" => Some(include_str!(concat!(env!(\"OUT_DIR\"), \"/icon_{safe}.svg\"))),\n"));
        }
    }

    let gen = format!(
        r#"// @emoji 🖼️ Auto-generated by 📦️build.rs — metabolism board icon SVG strings.

pub fn board_metabolism_icon_svg(key: &str) -> Option<&'static str> {{
	let k = key.trim();
	match k {{
{arms}		_ => None,
	}}
}}
"#
    );
    let gen_path = out_dir.join("board_metabolism_icon_match.rs");
    std::fs::write(&gen_path, gen).unwrap_or_else(|e| panic!("write {}: {e}", gen_path.display()));
}

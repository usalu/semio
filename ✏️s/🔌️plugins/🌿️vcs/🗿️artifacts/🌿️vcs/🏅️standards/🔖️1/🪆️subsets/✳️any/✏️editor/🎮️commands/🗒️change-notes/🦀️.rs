//! 🗒️ VCS editor command — `change-notes`: one concrete `change_notes` mutation for the demo document.

use crate::editor::vcs::config::{VcsDemoConfig, VcsDemoConfigMutation};
use crate::{op::VcsDemoMutation, VcsSnapshot};
use semio_framework_plugin::{ArtifactView, ConfigView, Emit, Fault};
use semio_framework_value_derive::{FromValue, ToValue};

#[derive(Clone, Debug, PartialEq, ToValue, FromValue, semio_framework_dsl_record_derive::DslRecord)]
#[dsl(keyword = "change-notes")]
pub struct ChangeNotes {
    pub notes: String,
}

pub fn handle(payload: &ChangeNotes, _doc: &ArtifactView<'_, VcsSnapshot>, _cfg: &ConfigView<'_, VcsDemoConfig>) -> Result<Emit<VcsDemoMutation, VcsDemoConfigMutation>, Fault> {
    use crate::mutations::change_notes;
    Ok(Emit::mutations(vec![change_notes(payload.notes.clone())]))
}


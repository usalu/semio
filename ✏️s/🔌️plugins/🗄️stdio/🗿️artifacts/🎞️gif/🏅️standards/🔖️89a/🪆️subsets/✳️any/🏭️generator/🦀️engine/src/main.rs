//! 🏭️ Generates `pattern-strip.gif`, a small, deliberately varied, fully deterministic GIF89a —
//! built entirely through the real `gif` 0.13 encoder (the same crate registered as
//! `gif-89a-any-mutate` in `../../🔣️oracle.json`), never through this repository's own
//! `encode_gif`. No wall-clock, no randomness: byte-for-byte reproducible on every run, which is
//! what `test fixture reproduce` checks.
//!
//! Deliberately exercises the surface `gif@89a`'s 21 mutation kinds touch: an 8-colour global
//! colour table, three 4x4 frames (frame 1 carries its OWN local palette overriding the global
//! one, frame 2 is interlaced), three different disposal methods, a transparent index on frame 2,
//! a NETSCAPE2.0 loop-count extension (loops twice), one comment extension and one custom
//! application extension.
//!
//! Usage: `generate <output.gif>`.

use std::env;

fn main() {
    let out_path = env::args().nth(1).expect("usage: generate <output.gif>");
    let bytes = build_gif();
    std::fs::write(&out_path, &bytes).unwrap_or_else(|error| panic!("writing {out_path}: {error}"));
    eprintln!("wrote {} bytes to {out_path}", bytes.len());
}

fn build_gif() -> Vec<u8> {
    const W: u16 = 4;
    const H: u16 = 4;
    // 🎨️ Global colour table: 8 flat RGB triples (red, green, blue, yellow, cyan, magenta, black, white).
    let global_palette: &[u8] = &[255, 0, 0, 0, 255, 0, 0, 0, 255, 255, 255, 0, 0, 255, 255, 255, 0, 255, 0, 0, 0, 255, 255, 255];

    let mut out = Vec::new();
    {
        let mut encoder = gif::Encoder::new(&mut out, W, H, global_palette).expect("gif header");
        encoder.set_repeat(gif::Repeat::Finite(2)).expect("loop extension");
        encoder.write_raw_extension(gif::AnyExtension(0xFE), &[b"pattern-strip fixture, generated by the gif crate"]).expect("comment extension");
        let mut app_header = [0u8; 11];
        app_header[..8].copy_from_slice(b"SEMIOFIX");
        app_header[8..11].copy_from_slice(b"1.0");
        encoder.write_raw_extension(gif::AnyExtension(0xFF), &[&app_header[..], &[7u8, 0, 0]]).expect("application extension");

        // 🖼️ Frame 0: uses the global palette, indices 0..15 checkerboard-ish, no transparency,
        // disposal "keep" (do not dispose).
        let frame0_indices: Vec<u8> = (0..16u8).map(|i| i % 4).collect();
        let mut frame0 = gif::Frame::from_indexed_pixels(W, H, frame0_indices, None);
        frame0.delay = 50;
        frame0.dispose = gif::DisposalMethod::Keep;
        encoder.write_frame(&frame0).expect("frame 0");

        // 🖼️ Frame 1: its OWN local palette (distinct from the global one), disposal "restore to
        // background", transparent index 3.
        let frame1_indices: Vec<u8> = vec![0, 1, 2, 3, 1, 2, 3, 0, 2, 3, 0, 1, 3, 0, 1, 2];
        let local_palette: Vec<u8> = vec![10, 10, 10, 90, 90, 90, 170, 170, 170, 250, 250, 250];
        let mut frame1 = gif::Frame::from_indexed_pixels(W, H, frame1_indices, Some(3));
        frame1.palette = Some(local_palette);
        frame1.delay = 75;
        frame1.dispose = gif::DisposalMethod::Background;
        frame1.transparent = Some(3);
        encoder.write_frame(&frame1).expect("frame 1");

        // 🖼️ Frame 2: interlaced, global palette, disposal "restore to previous".
        let frame2_indices: Vec<u8> = (0..16u8).rev().map(|i| i % 4).collect();
        let mut frame2 = gif::Frame::from_indexed_pixels(W, H, frame2_indices, None);
        frame2.delay = 100;
        frame2.dispose = gif::DisposalMethod::Previous;
        frame2.interlaced = true;
        encoder.write_frame(&frame2).expect("frame 2");
    }
    out
}

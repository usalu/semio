#[derive(Clone, Debug, PartialEq, value_derive::ToValue, value_derive::FromValue, dsl::Mutations)]
#[mutations(snapshot = SemioObjectSnapshot, diff = SemioObjectDiff, schema = "s.stdio.semio.object")]
pub enum SemioObjectMutation {
    MoveObject(move_object::MoveObject),
    RotateObject(rotate_object::RotateObject),
    ScaleObject(scale_object::ScaleObject),
    CreateBrep(create_brep::CreateBrep),
    DeleteBrep(delete_brep::DeleteBrep),
    CreateMesh(create_mesh::CreateMesh),
    DeleteMesh(delete_mesh::DeleteMesh),
    CreateProperties(create_properties::CreateProperties),
    DeleteProperties(delete_properties::DeleteProperties),
}

/// 🏷️ Kebab-case spelling of every `SemioObjectMutation` variant, in declaration order — the
/// vocabulary the `semio-v1-object` mutation catalog (`../../🧪️oracle/🔣️.json`) declares
/// and `mutate-semio-object`'s exhaustive test case measures itself against. `kinds_match_the_enum_
/// and_the_catalog` below is what keeps this list honest against the enum, since the framework
/// never parses Rust.
pub const KINDS: &[&str] = &["move-object", "rotate-object", "scale-object", "create-brep", "delete-brep", "create-mesh", "delete-mesh", "create-properties", "delete-properties"];
//#endregion 🔖️Mutations

//#region 🔖️Apply
/// ▶️ Applies a mutation to `snapshot` in place, returning the diff — kept from the pre-wave facet
/// (consumed by `../🦀️component.rs`'s `SemioObjectBuilderConstruction::mutate`).
// 🚫️async: E1 pure codec/computation helper (file verified I/O-free, consumed via Fn-bound combinator/Display) — see R9
pub fn apply_semio_object_mutation(snapshot: &mut SemioObjectSnapshot, mutation: &SemioObjectMutation) -> protocol::MutationOutcome<SemioObjectDiff> {
    use protocol::Mutation;
    let outcome = <SemioObjectMutation as Mutation<SemioObjectSnapshot>>::diff(mutation, snapshot);
    outcome.apply_to(snapshot)
}

/// ↩️ Computes `mutation`'s own inverse against `base` — a thin wrapper around
/// `protocol::Mutation::inverse` so external Rust callers that cannot name this crate's private
/// `protocol` extern-crate item (the `mutate-semio-object` test adapter, whose `inverse-<kind>` scenarios
/// need a mutation's own computed inverse) can still reach the inverse law that
/// [`apply_semio_object_mutation`] alone cannot. Same shape as `✳️kit`'s `inverse_semio_kit_mutation`.
// 🚫️async: E1 pure codec/computation helper (file verified I/O-free, consumed via Fn-bound combinator/Display) — see R9
pub fn inverse_semio_object_mutation(mutation: &SemioObjectMutation, base: &SemioObjectSnapshot) -> Vec<SemioObjectMutation> {
    use protocol::Mutation;
    <SemioObjectMutation as Mutation<SemioObjectSnapshot>>::inverse(mutation, base)
}

/// 📥️ Decodes this facet's own externally-tagged (`{"<VariantName>": {<snake_case payload>}}`)
/// JSON projection — no `#[value(rename_all)]` sits on this enum or its payload structs, which is
/// exactly the shape the committed `<kind>/🧪️tests/<fixture>/🦠️mutation/🔣️component.json` vectors
/// carry — into a real [`SemioObjectMutation`]. `create-brep`/`create-mesh`/`create-properties` carry a `store::os_io::ArtifactRef` `target`
/// field, the exact value an external caller cannot construct by hand; decoding the committed vector
/// is what turns those six child-lifecycle kinds from unreachable into exercisable.
// 🚫️async: E1 pure codec/computation helper (file verified I/O-free, consumed via Fn-bound combinator/Display) — see R9
pub fn decode_semio_object_mutation_json(text: &str) -> Result<SemioObjectMutation, String> {
    serde_json::from_str(text).map_err(|error| error.to_string())
}

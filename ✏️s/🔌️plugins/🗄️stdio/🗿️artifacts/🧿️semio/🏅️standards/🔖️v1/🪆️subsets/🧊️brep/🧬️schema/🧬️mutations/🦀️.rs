/// 🧬️ Every variant wraps exactly one `protocol::MutationKind<SemioBrepSnapshot, SemioBrepMutation>`
/// payload struct declared in the corresponding triad leaf's `🦠️mutation/🦀️.rs`. Thirteen
/// triads: vertex lifecycle (`create-vertex`/`delete-vertex`), edge lifecycle
/// (`create-edge`/`delete-edge`), face lifecycle (`create-face`/`delete-face`), shell lifecycle
/// (`create-shell`/`delete-shell`), solid lifecycle (`create-solid`/`delete-solid`), then the two
/// structured-payload replacements (`replace-curve`/`replace-surface`) and the one scalar
/// reposition (`move-vertex`).
#[derive(Clone, Debug, PartialEq, value_derive::ToValue, value_derive::FromValue, dsl::Mutations)]
#[mutations(snapshot = SemioBrepSnapshot, diff = SemioBrepDiff, schema = "s.stdio.semio.brep")]
pub enum SemioBrepMutation {
    CreateVertex(create_vertex::CreateVertex),
    DeleteVertex(delete_vertex::DeleteVertex),
    CreateEdge(create_edge::CreateEdge),
    DeleteEdge(delete_edge::DeleteEdge),
    CreateFace(create_face::CreateFace),
    DeleteFace(delete_face::DeleteFace),
    CreateShell(create_shell::CreateShell),
    DeleteShell(delete_shell::DeleteShell),
    CreateSolid(create_solid::CreateSolid),
    DeleteSolid(delete_solid::DeleteSolid),
    ReplaceCurve(replace_curve::ReplaceCurve),
    ReplaceSurface(replace_surface::ReplaceSurface),
    MoveVertex(move_vertex::MoveVertex),
}


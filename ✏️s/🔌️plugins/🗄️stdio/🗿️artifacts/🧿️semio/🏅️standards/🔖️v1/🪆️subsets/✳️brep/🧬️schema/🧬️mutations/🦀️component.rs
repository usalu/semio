//! 🧬️ SemioBrepMutation — document mutation dispatch. Semantic vocabulary is EXACTLY SMO's
//! approved verb table (`📌️important.md`, verb rulings), authored fresh for this wave — not
//! derived, not invented: `create-vertex`/`delete-vertex`, `create-edge`/`delete-edge`,
//! `create-face`/`delete-face`, `create-shell`/`delete-shell`, `create-solid`/`delete-solid`,
//! `replace-curve{edge_id,new_curve}`, `replace-surface{face_id,new_surface}`,
//! `move-vertex{vertex_id,new_point}`. Thirteen triads, in dispatch order below.
//!
//! `create-loop`/`delete-loop` are DELIBERATELY absent: `Loop`/`Coedge` carry no `PersistentLabel`
//! and framework-3d's arena ids are generational and reused after deletion, so those verbs would
//! have no valid stable address (see `📓️wave3a-design/brep-dissolution-design.md` §2). SMO approved
//! them before this was known and has wound down without a corrected ruling — leaving them
//! unauthored is the sanctioned outcome per `📌️important.md`, not an oversight.
//!
//! Booleans/Euler ops/sweep/offset/fillet are NOT verbs here — they are `group_id`-batched sets of
//! the primitives above, with diffs computed by pure engine fns against `base`, per doctrine. This
//! facet exposes only the entity-level primitives those batches would be built from.
//!
//! `impl protocol::Mutation`/`SemanticMutation` are generated by `#[derive(dsl::Mutations)]` — never
//! hand-written (same convention `✳️text`/`✳️graph` already establish in this codebase). `OpText`/
//! `OpBinary` are NOT covered by that derive (it only generates `Mutation`/`SemanticMutation`) and
//! stay hand-rolled below, reusing the sibling `🔺️diff` facet's already-`pub(crate)` hex/bracket
//! value-codec primitives — this mirrors the SHAPE this file already used before this wave's
//! rewrite, just re-pointed at the new 13-verb vocabulary instead of the old 22-variant
//! `Add*`/`Remove*`/`Set*` one.
//!
//! `📸️set-snapshot` is DELETED, with no replacement, per the locked decision
//! (`📌️important.md`): whole-document replace goes through `ArtifactStore::reset`, outside history.


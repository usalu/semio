//! 🧬️ SemioMeshMutation — document mutation dispatch. Semantic vocabulary derived from the
//! subset's real snapshot fields (meshes/primitives/materials/textures), checked against SMO's
//! taxonomy+derivation-rules docs, authored fresh for this wave — not derived from memory, not
//! invented: `create-mesh`/`delete-mesh`, `create-primitive`/`delete-primitive`,
//! `set-primitive-topology`, `replace-primitive-geometry{mesh_id,primitive_id,positions,normals,
//! uvs,colors,indices}`, `set-primitive-material`, `create-material`/`delete-material`,
//! `change-material-base-color`, `change-material-metallic`, `change-material-roughness`,
//! `create-texture`/`delete-texture`, `change-texture-mime`, `replace-texture-bytes`,
//! `move-vertex{mesh_id,primitive_id,vertex_index,new_point}`. Seventeen triads, in dispatch order
//! below.
//!
//! **`replace-primitive-geometry`** is the SMO-approved rename of the old `set-primitive-geometry`
//! (`📌️important.md`'s verb rulings table: "mesh `set-primitive-geometry`→`replace-primitive-geometry`
//! | ✅ reasoning approved, ❌ but it is SMO's to do, not ours"). SMO approved the reasoning — a
//! positions/normals/uvs/colors/indices blob is a structured sub-payload, so `set` is the wrong
//! verb — and reserved the edit for themselves. **SMO has since wound down without doing it.** DKM
//! completes it here under the user's explicit instruction to finish the stdio mutation vocabulary
//! end to end, per this ticket's provenance note: SMO-approved in reasoning, SMO-reserved in
//! execution, completed by DKM after SMO ended. This is SMO's rename, not DKM's.
//!
//! **`change-material-metallic`/`change-material-roughness`** decompose the old bundled
//! `SetMaterialPbr{metallic,roughness}`: unlike `base_color` (grouped into one `SemioRgba` value
//! type on `SemioMaterial`), `metallic`/`roughness` are two independent top-level scalar fields,
//! each independently settable (every real PBR editor exposes two separate sliders) — the same
//! decompose test SMO's `StrokeStyle` ruling already applies to drawing's stroke fields.
//! **`change-texture-mime`/`replace-texture-bytes`** decompose the old bundled
//! `SetTextureBytes{mime,bytes}` the same way (derivation-rules.md rule 2: `change-<field>` per
//! remaining scalar, `replace-<payload>` per large structured field — `mime` is the scalar,
//! `bytes` is the large payload).
//!
//! **`create-mesh`/`create-primitive`/`create-material`/`create-texture` (and their `delete-*`
//! partners) keep the pre-existing `add`/`remove`-shaped verb spelling renamed to `create`/`delete`**
//! — matching the strong cross-subset precedent this repo already establishes for full id-keyed
//! entities with their own lifecycle (`🕸️graph`'s `create-node`/`delete-node` vs its OWN
//! `add-node-port`/`add-node-property` for genuinely set-like members; `📊️table`'s
//! `create-column`/`delete-column`; brep's own `create-vertex`/…/`create-solid` rename from the
//! identical `Add*`/`Remove*` shape this file itself used before this wave). None of this
//! subset's four collections (meshes/primitives/materials/textures) are set-like members
//! (attribute/tag/connector) — each is a full structured entity with its own field set — so
//! derivation-rules.md rule 2 ("Per id-keyed collection: create-<singular>, delete-<singular>")
//! governs, not taxonomy's narrower `add`/`remove`.
//!
//! **`create-loop`/`insert-vertex`/`remove-vertex`-shaped verbs on `positions` are NOT authored.**
//! `positions`/`normals`/`uvs`/`colors`/`indices` are strictly parallel buffers with no per-element
//! id; growing/shrinking one element without touching the others (and without renumbering
//! `indices`) has no honest single-verb expression at this layer. Only `move-vertex` (a same-length
//! reposition by BASE-state index) and the whole-buffer `replace-primitive-geometry` are authored.
//!
//! `impl protocol::Mutation`/`SemanticMutation` are generated by `#[derive(dsl::Mutations)]` —
//! never hand-written (same convention `🔤️text`/`🕸️graph`/`🧊️brep` already establish). `OpText`/
//! `OpBinary` are NOT covered by that derive and stay hand-rolled below, reusing the sibling
//! `🔺️diff` facet's now-`pub(crate)` hex/bracket value-codec primitives — this mirrors the SHAPE
//! this file already used before this wave's rewrite, just re-pointed at the new 17-verb
//! vocabulary instead of the old 16-variant `Add*`/`Remove*`/`Set*` one.
//!
//! `📸️set-snapshot` is DELETED, with no replacement, per the locked decision
//! (`📌️important.md`): whole-document replace goes through `ArtifactStore::reset`, outside history.


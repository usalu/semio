pub fn inverse_semio_mesh_mutation(mutation: &SemioMeshMutation, base: &SemioMeshSnapshot) -> Vec<SemioMeshMutation> {
    use protocol::Mutation;
    <SemioMeshMutation as Mutation<SemioMeshSnapshot>>::inverse(mutation, base)
}


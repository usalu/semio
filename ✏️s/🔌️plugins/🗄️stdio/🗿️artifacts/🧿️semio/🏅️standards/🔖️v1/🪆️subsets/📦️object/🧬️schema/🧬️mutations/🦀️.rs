//! 🧬️ SemioObjectMutation — document mutation dispatch. Vocabulary derived from
//! `📸️snapshot/🦀️.rs`'s `SemioObjectSnapshot` shape: one composite value field
//! (`transform`, split into `move`/`rotate`/`scale` per `📌️important.md`'s domain-verb table) and
//! three singular CHILD slots (`brep`/`mesh`/`properties`), each a `create`/`delete` pair per the
//! ticket's approved composition verbs (child lifecycle). `object` has no LINK slots, so
//! `bind`/`unbind`/`change`/`extract`/`inline` are unused here — see `🧰️kit` for those.
//!
//! `impl protocol::Mutation`/`SemanticMutation` below are generated by `#[derive(dsl::Mutations)]`

#[derive(Clone, Debug, PartialEq, Serialize, Deserialize, dsl::Mutations)]
#[mutations(snapshot = SemioObjectSnapshot, diff = SemioObjectDiff, schema = "s.stdio.semio.object")]
pub enum SemioObjectMutation {
    MoveObject(move_object::mutation::MoveObject),
    RotateObject(rotate_object::mutation::RotateObject),
    ScaleObject(scale_object::mutation::ScaleObject),
    CreateBrep(create_brep::mutation::CreateBrep),
    DeleteBrep(delete_brep::mutation::DeleteBrep),
    CreateMesh(create_mesh::mutation::CreateMesh),
    DeleteMesh(delete_mesh::mutation::DeleteMesh),
    CreateProperties(create_properties::mutation::CreateProperties),
    DeleteProperties(delete_properties::mutation::DeleteProperties),
}

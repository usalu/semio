#!/usr/bin/env python3
"""Stages the proctor-as-a-cached-product change onto the frozen manifests (x-proctor).

Usage: python3 apply.py [--root <repository>] [--check]

Edits, each anchored on structure (a target block, a named-input array), idempotent, and followed by post-condition
asserts on the parsed JSON:
  1. 🎓️teaching/🛂️proctor/📦️packages/🦀️rust/📋️project.json
     - namedInputs.proctorRust  = the Cargo closure globs generated by inputs.ts (never hand-listed)
     - namedInputs.cargoSources = cargo, proctorRust, sharedGlobals, the build script and its TypeScript/JSON closure
     - build.outputs            = both mode directories of the product
     - build.cache true; dev, check, rebuild, health, backup, restore, erase, prune, capacity dependOn build
     - check.inputs             = the receipt of the product instead of the Rust and course globs
  2. 🎓️teaching/🏛️architecture/📚️course/📦️packages/🟦️typescript/📋️project.json
     - dev, check, test-e2e, docker-image-build, deploy-check dependOn @teaching/proctor:build
     - check.inputs: the whole-repo proctor glob and the root Cargo globs are replaced by the receipt of the product
  3. 🎓️teaching/🛂️proctor/🏗️bootstrap/🧾️product/🟦️.ts: PROCTOR_ACQUISITION_DEFAULT = "product"

With --check nothing is written; the exit status says whether the files are already in the target state.
"""
import json
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PROCTOR = "🎓️teaching/🛂️proctor/📦️packages/🦀️rust/📋️project.json"
COURSE = "🎓️teaching/🏛️architecture/📚️course/📦️packages/🟦️typescript/📋️project.json"
PRODUCT = "🎓️teaching/🛂️proctor/🏗️bootstrap/🧾️product/🟦️.ts"
RECEIPT = {"dependentTasksOutputFiles": "**/receipt.json", "transitive": False}


def die(message):
    print("apply.py: " + message, file=sys.stderr)
    sys.exit(2)


def span_of_bracket(text, start, opening, closing):
    depth, in_string, escaped = 0, False, False
    for index in range(start, len(text)):
        char = text[index]
        if in_string:
            if escaped:
                escaped = False
            elif char == "\\":
                escaped = True
            elif char == '"':
                in_string = False
            continue
        if char == '"':
            in_string = True
        elif char == opening:
            depth += 1
        elif char == closing:
            depth -= 1
            if depth == 0:
                return start, index + 1
    die("unbalanced " + opening)


def find_member(text, key, indent, within=(0, None), opening="{", closing="}"):
    """The span of the value of `"key": <opening> … <closing>` written at `indent` spaces inside `within`."""
    end = len(text) if within[1] is None else within[1]
    for match in re.finditer(r"^" + " " * indent + re.escape(json.dumps(key, ensure_ascii=False)) + r": ", text[within[0]:end], re.M):
        position = within[0] + match.end()
        if position < len(text) and text[position] == opening:
            return span_of_bracket(text, position, opening, closing)
    return None


def dump(item):
    text = json.dumps(item, ensure_ascii=False)
    return "{ " + text[1:-1] + " }" if isinstance(item, dict) else text


def render_items(items, indent):
    pad = " " * indent
    return "[\n" + ",\n".join(pad + "  " + dump(item) for item in items) + "\n" + pad + "]"


def set_array(text, target_span, key, indent, items):
    """Replaces the array `key` of an object (at `indent`) by `items`, one per line; inserts it before the closing brace when absent."""
    found = find_member(text, key, indent, target_span, "[", "]")
    rendered = render_items(items, indent)
    if found:
        return text[: found[0]] + rendered + text[found[1] :]
    close = target_span[1] - 1
    line = text.rfind("\n", 0, close)
    before = text[:line].rstrip()
    comma = "" if before.endswith(("{", ",")) else ","
    return before + comma + "\n" + " " * indent + json.dumps(key) + ": " + rendered + text[line:]


def ensure_depends_on(text, target, dependency):
    block = find_member(text, target, 4, find_member(text, "targets", 2))
    if not block:
        die("target " + target + " not found")
    found = find_member(text, "dependsOn", 6, block, "[", "]")
    if found:
        current = json.loads(text[found[0] : found[1]])
        if dependency in current:
            return text
        body = text[found[0] : found[1]]
        if "\n" in body:
            last = body.rstrip().rstrip("]").rstrip()
            return text[: found[0]] + last + ",\n" + " " * 8 + json.dumps(dependency) + "\n" + " " * 6 + "]" + text[found[1] :]
        return text[: found[0]] + body[:-1] + ", " + json.dumps(dependency) + "]" + text[found[1] :]
    executor = re.search(r'^      "executor": "repo:script",\n', text[block[0] : block[1]], re.M)
    if not executor:
        die("target " + target + " has no executor line")
    at = block[0] + executor.end()
    return text[:at] + "      " + '"dependsOn": [' + json.dumps(dependency) + "],\n" + text[at:]


def load(path):
    with open(path, encoding="utf8") as handle:
        return handle.read()


def save(path, text, check):
    if check:
        return
    with open(path, "w", encoding="utf8") as handle:
        handle.write(text)


def proctor_manifest(text, globs):
    targets = find_member(text, "targets", 2)
    named = find_member(text, "namedInputs", 2)
    if not targets or not named:
        die("proctor manifest shape")
    for verb in ["dev", "check", "rebuild", "health", "backup", "restore", "erase", "prune", "capacity"]:
        text = ensure_depends_on(text, verb, "build")
    named = find_member(text, "namedInputs", 2)
    found = find_member(text, "proctorRust", 4, named, "[", "]")
    if found:
        text = text[: found[0]] + render_items(globs, 4) + text[found[1] :]
    else:
        at = named[0] + re.search(r'^    "cargoSources": \[', text[named[0] : named[1]], re.M).start()
        text = text[:at] + '    "proctorRust": ' + render_items(globs, 4) + ",\n" + text[at:]
    named = find_member(text, "namedInputs", 2)
    sources = [
        "cargo",
        "proctorRust",
        "sharedGlobals",
        "{projectRoot}/📜️script.ts",
        "{workspaceRoot}/🎓️teaching/🛂️proctor/🏗️bootstrap/**/*.ts",
        "{workspaceRoot}/🎓️teaching/🛂️proctor/🏗️bootstrap/**/*.json",
        "!{workspaceRoot}/🎓️teaching/🛂️proctor/**/target/**",
    ]
    found = find_member(text, "cargoSources", 4, named, "[", "]")
    text = text[: found[0]] + render_items(sources, 4) + text[found[1] :]
    targets = find_member(text, "targets", 2)
    build = find_member(text, "build", 4, targets)
    text = set_array(text, build, "outputs", 6, ["{projectRoot}/dist/build/prototype", "{projectRoot}/dist/build/release"])
    targets = find_member(text, "targets", 2)
    check = find_member(text, "check", 4, targets)
    inputs = [
        "{projectRoot}/📜️script.ts",
        "sharedGlobals",
        RECEIPT,
        {"env": "SEMIO_TEST_LEVEL"},
        {"env": "SEMIO_TEST_BUDGET_MS"},
        {"env": "SEMIO_BUILD_BUDGET_MS"},
        "{workspaceRoot}/🎓️teaching/🏛️architecture/📚️course/**/*",
        {"env": "PROCTOR_COURSE"},
    ]
    found = find_member(text, "inputs", 6, check, "[", "]")
    rendered = "[\n" + ",\n".join("        " + dump(item) for item in inputs) + "\n      ]"
    return text[: found[0]] + rendered + text[found[1] :]


def course_manifest(text):
    for verb in ["dev", "check", "test-e2e", "docker-image-build", "deploy-check"]:
        text = ensure_depends_on(text, verb, "@teaching/proctor:build")
    targets = find_member(text, "targets", 2)
    check = find_member(text, "check", 4, targets)
    found = find_member(text, "inputs", 6, check, "[", "]")
    items = json.loads(text[found[0] : found[1]])
    drop = {
        "{workspaceRoot}/🎓️teaching/🛂️proctor/**/*",
        "{workspaceRoot}/Cargo.toml",
        "{workspaceRoot}/Cargo.lock",
        "{workspaceRoot}/.cargo/config.toml",
        "{workspaceRoot}/rust-toolchain.toml",
    }
    items = [item for item in items if not (isinstance(item, str) and item in drop)]
    if RECEIPT not in items:
        items.insert(1, RECEIPT)
    rendered = "[\n" + ",\n".join("        " + dump(item) for item in items) + "\n      ]"
    return text[: found[0]] + rendered + text[found[1] :]


def post_conditions(proctor, course):
    p, c = json.loads(proctor), json.loads(course)
    assert p["namedInputs"]["proctorRust"][0].startswith("{workspaceRoot}/")
    assert "^cargo" not in p["namedInputs"]["cargoSources"] and "proctorRust" in p["namedInputs"]["cargoSources"]
    assert p["targets"]["build"]["cache"] is True and "cargoSources" in p["targets"]["build"]["inputs"]
    assert p["targets"]["build"]["outputs"] == ["{projectRoot}/dist/build/prototype", "{projectRoot}/dist/build/release"]
    for verb in ["dev", "check", "rebuild", "health", "backup", "restore", "erase", "prune", "capacity"]:
        assert "build" in p["targets"][verb]["dependsOn"], verb
    assert RECEIPT in p["targets"]["check"]["inputs"]
    for verb in ["dev", "check", "test-e2e", "docker-image-build", "deploy-check"]:
        assert "@teaching/proctor:build" in c["targets"][verb]["dependsOn"], verb
    assert RECEIPT in c["targets"]["check"]["inputs"]
    assert not any(isinstance(i, str) and "🛂️proctor/**/*" in i for i in c["targets"]["check"]["inputs"])


def main():
    arguments = sys.argv[1:]
    check = "--check" in arguments
    root = os.path.abspath(arguments[arguments.index("--root") + 1]) if "--root" in arguments else os.path.abspath(os.path.join(HERE, *[".."] * 9))
    checkout = os.path.abspath(os.path.join(HERE, *[".."] * 9))
    generated = subprocess.run(["bun", os.path.join(HERE, "inputs.ts"), checkout], capture_output=True, text=True, cwd=checkout)
    if generated.returncode:
        die("inputs.ts failed: " + generated.stderr)
    globs = json.loads(generated.stdout)["globs"]
    old_proctor, old_course, old_product = (load(os.path.join(root, name)) for name in (PROCTOR, COURSE, PRODUCT))
    new_proctor, new_course = proctor_manifest(old_proctor, globs), course_manifest(old_course)
    product = re.sub(r'(PROCTOR_ACQUISITION_DEFAULT: "product" \| "build" = )"(?:build|product)"', r'\1"product"', old_product)
    if product == old_product and 'PROCTOR_ACQUISITION_DEFAULT: "product" | "build" = "product"' not in product:
        die("PROCTOR_ACQUISITION_DEFAULT anchor not found")
    post_conditions(new_proctor, new_course)
    changed = [name for name, old, new in ((PROCTOR, old_proctor, new_proctor), (COURSE, old_course, new_course), (PRODUCT, old_product, product)) if old != new]
    for name, new in ((PROCTOR, new_proctor), (COURSE, new_course), (PRODUCT, product)):
        save(os.path.join(root, name), new, check)
    print(("would change: " if check else "changed: ") + (", ".join(changed) if changed else "nothing (already applied)"))
    sys.exit(1 if check and changed else 0)


main()

def glances(seed, count, margin):
    """🌠️ Segments scattered over the quarter-pixel lattice around three scattered boxes; a segment whose verdict hangs on less than a sample is left out."""
    stream = Stream(seed)
    rects = [keepout(stream.below(800) / 4, stream.below(800) / 4, 0 if stream.below(9) == 0 else stream.below(480) / 4, 0 if stream.below(9) == 0 else stream.below(480) / 4) for _ in range(3)]
    segments = []
    while len(segments) < count:
        start = point(stream.below(1200) / 4 - 20, stream.below(1200) / 4 - 20)
        kind = stream.below(8)
        end = point(start["x"], stream.below(1200) / 4 - 20) if kind == 0 else point(stream.below(1200) / 4 - 20, start["y"]) if kind == 1 else point(stream.below(1200) / 4 - 20, stream.below(1200) / 4 - 20)

def ladders():
    """🪜️ The vectors of case 🪜️ladder-geometry."""
    placements = []
    for entry in PLACEMENTS:
        expected, verdict = LADDERS.placement(entry)
        if verdict != entry["verdict"]:
            raise AssertionError("placements/%s: composed as %s, the oracle says %s" % (entry["id"], entry["verdict"], verdict))
        placements.append(dict(entry, expected=expected))
    if {entry["verdict"] for entry in placements} != {"granted", "no-rim", "too-short", "too-tall", "off-the-pitch", "no-footing", "too-steep", "too-flat", "blocked"}:
        raise AssertionError("the placements do not cover every verdict")
    leans = []
    for entry in LEANS:
        expected, verdict = LADDERS.lean(entry)
        if verdict != entry["verdict"]:
            raise AssertionError("leans/%s: composed as %s, the oracle says %s" % (entry["id"], entry["verdict"], verdict))
        leans.append(dict(entry, expected=expected))
    if {entry["verdict"] for entry in leans} != {"granted", "too-short", "too-tall", "off-the-pitch", "no-footing", "too-steep", "blocked", "no-grip"}:
        raise AssertionError("the leans do not cover every verdict")
    climbs = [dict(entry, expected=LADDERS.climb(entry)) for entry in RUNS]

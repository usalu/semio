class Stream:
    """🎰️ A 32-bit linear congruential generator, so that the composed stages do not depend on a library's stream."""

    def __init__(self, seed):
        """🌱️ Starts the stream."""
        self.state = seed & 0xFFFFFFFF

    def below(self, bound):
        """🎲️ The next integer in ``[0, bound)``."""
        self.state = (self.state * 1664525 + 1013904223) & 0xFFFFFFFF
        return (self.state * bound) >> 32



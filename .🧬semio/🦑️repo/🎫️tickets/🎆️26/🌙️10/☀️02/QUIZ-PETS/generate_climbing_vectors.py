def walls():
    """🧗️ The vectors of case 🧗️wall-climbing."""
    layouts = [dict(entry, expected=WALLS.pitches(LATTICE, entry)) for entry in LAYOUTS]
    if not any(len(entry["expected"]) > 3 for entry in layouts if entry["id"].startswith("scattered")):
        raise AssertionError("the scattered layouts cut no stage into several pitches")
    stretches = [dict(entry, expected=WALLS.stretches(LATTICE, entry)) for entry in STRETCHES]
    nearests = [dict(entry, expected=WALLS.nearest(LATTICE, entry)) for entry in NEARESTS]
    sights = [dict(entry, expected=WALLS.sight(entry)) for entry in SIGHTS]
    verdicts = [answer["clear"] for entry in sights if entry["id"].startswith("scattered") for answer in entry["expected"]]
    if min(verdicts.count(True), verdicts.count(False)) < len(verdicts) // 8:
        raise AssertionError("the scattered sights are nearly all clear or nearly all blocked")
    holds = [dict(entry, expected=WALLS.holds(entry)) for entry in HOLDS]
    surveys = [dict(entry, expected=WALLS.survey(entry)) for entry in SURVEYS]
    climbs = [dict(entry, expected=WALLS.climb(entry)) for entry in CLIMBS]
    if not {0, WALLS.GRIP_BUDGET + 1} <= {entry["expected"]["ticks"] for entry in climbs}:
        raise AssertionError("the climbs do not cover a climb of no tick and one beyond a rested grip")
    grips = [dict(entry, expected=WALLS.grip(entry)) for entry in GRIPS]
    slides = [dict(entry, expected=WALLS.slide(entry)) for entry in SLIDES]
    mantles = [dict(entry, expected=WALLS.mantle(entry)) for entry in MANTLES]
    hoists = [dict(entry, expected=WALLS.hoist("hoists/%s" % entry["id"], entry["from"], entry["to"], entry["height"], entry["ticks"])) for entry in HOISTS]
    routes = [dict(entry, expected=WALLS.route(entry)) for entry in WAYS]
    if not any(leg["exit"] != leg["pitch"] for entry in routes if entry["expected"] for leg in entry["expected"]):
        raise AssertionError("no route lunges from one pitch of a wall line to the next")
    crossings = [dict(entry, expected=WALLS.crossing(entry)) for entry in CROSSINGS]
    lunges = [step for entry in crossings for way in entry["expected"]["ways"] for step in way["path"] if step[3] == "lunge"]
    if not lunges or not any(len(chain) == 3 for entry in crossings for chain in entry["expected"]["chains"]):
        raise AssertionError("the crossings neither lunge nor join three pitches into one line")
    document = {"$comment": GENERATED % "🧗️wall-climbing", "lattice": LATTICE, "constants": WALLS.CONSTANTS, "layouts": unique(layouts), "stretches": unique(stretches), "nearests": unique(nearests), "sights": unique(sights), "holds": unique(holds), "surveys": unique(surveys), "climbs": unique(climbs), "grips": unique(grips), "slides": unique(slides), "mantles": unique(mantles), "hoists": unique(hoists), "routes": unique(routes), "crossings": unique(crossings)}
    unique(mantles + hoists)
    write("🧗️wall-climbing", document)
    return {"layouts": len(layouts), "pitches": sum(len(entry["expected"]) for entry in layouts), "stretches": sum(len(entry["queries"]) for entry in stretches), "nearests": sum(len(entry["points"]) for entry in nearests), "sights": sum(len(entry["segments"]) * len(entry["rects"]) for entry in sights), "holds": sum(len(entry["perches"]) * len(entry["pitches"]) for entry in holds), "surveys": len(surveys), "climbs": [entry["expected"]["ticks"] for entry in climbs], "grips": len(grips), "slides": len(slides), "mantles": len(mantles) + len(hoists), "routes": [None if entry["expected"] is None else len(entry["expected"]) for entry in routes], "crossings": [[len(way["path"]) for way in entry["expected"]["ways"]] for entry in crossings], "lunges": len(lunges)}



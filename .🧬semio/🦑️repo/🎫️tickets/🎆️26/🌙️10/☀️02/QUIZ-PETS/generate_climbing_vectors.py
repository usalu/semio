def ropes():
    """🎣️ The vectors of case 🎣️grapple-reach."""
    shots = []
    for entry in AIMS:
        expected, verdicts = GRAPPLE.shot_for("shots/%s" % entry["id"], entry["feet"], entry["perches"], entry["keepouts"], entry["size"])
        shots.append(dict(entry, verdicts=verdicts, expected=expected))
    reasons = {verdict for entry in shots for found in entry["verdicts"] for verdict in found}
    if reasons != {"granted", "too-low", "too-short", "too-long", "too-flat", "blocked"}:
        raise AssertionError("the shots do not cover every verdict: %r" % sorted(reasons))
    if {entry["expected"]["reel"] for entry in shots if entry["expected"]} != {"zip", "swing"}:
        raise AssertionError("the shots do not cover both ways of reeling")
    flights = [dict(entry, expected=GRAPPLE.flight(entry)) for entry in FLIGHTS]
    for entry in ZIPS + SWINGS:
        if entry["shot"]["reel"] != ("zip" if entry in ZIPS else "swing"):
            raise AssertionError("%s is reeled in the other way" % entry["id"])
    zips = [dict(entry, expected=GRAPPLE.zipped(entry)) for entry in ZIPS]
    swings, deviations = [], {}
    for entry in SWINGS:
        expected, deviation = GRAPPLE.swung(entry)
        if not deviation <= entry["tolerance"]:
            raise AssertionError("swings/%s leaves the pendulum by %r°" % (entry["id"], deviation))
        deviations[entry["id"]] = round(deviation, 4)
        swings.append(dict(entry, expected=expected))
    surveys = [dict(entry, expected=GRAPPLE.shot_holds("surveys/%s" % entry["id"], entry["shot"], entry["perches"], entry["keepouts"])) for entry in HELD]
    landings = [dict(entry, expected=GRAPPLE.landing(entry)) for entry in LANDINGS]
    routes = [dict(entry, expected=GRAPPLE.route(entry)) for entry in ROUTES]
    if {leg["means"] for entry in routes if entry["expected"] for leg in entry["expected"]} != {"ladder", "wall", "raise", "grapple"}:
        raise AssertionError("the routes do not cover every means")
    write("🎣️grapple-reach", {"$comment": GENERATED % "🎣️grapple-reach", "constants": GRAPPLE.CONSTANTS, "shots": unique(shots), "flights": unique(flights), "zips": unique(zips), "swings": unique(swings), "surveys": unique(surveys), "landings": unique(landings), "routes": unique(routes)})
    return {"shots": len(shots), "granted": sum(1 for entry in shots if entry["expected"] is not None), "flights": [entry["expected"]["ticks"] for entry in flights], "zips": [entry["expected"]["ticks"] for entry in zips], "swings": [entry["expected"]["ticks"] for entry in swings], "degrees": deviations, "surveys": len(surveys), "holding": sum(1 for entry in surveys if entry["expected"] is not None), "landings": len(landings), "routes": [None if entry["expected"] is None else "+".join(leg["means"] for leg in entry["expected"]) for entry in routes]}



def ballistics():
    """🦘️ The vectors of case 🦘️hop-ballistics."""
    falls = []
    for entry in FALLS:
        heights, speeds = BALLISTICS.fall(entry["y"], entry["vy"], entry["ticks"])
        falls.append(dict(entry, expected={"heights": [float(height) for height in heights], "speeds": [float(speed) for speed in speeds]}))
    landings = [dict(entry, expected=[BALLISTICS.landing(entry["perches"], sweep["x"], sweep["fromY"], sweep["toY"]) for sweep in entry["sweeps"]]) for entry in LANDINGS]
    drops = [dict(entry, expected=BALLISTICS.drop("drops/%s" % entry["id"], entry["perches"], entry["start"], entry["limit"])) for entry in DROPS]
    hops = []
    for name, start, end, verdict in HOPS:
        launch, found = BALLISTICS.hop(start, end)
        if found != verdict:
            raise AssertionError("hops/%s: composed as %s, the oracle says %s" % (name, verdict, found))
        hops.append({"id": name, "from": start, "to": end, "verdict": verdict, "expected": launch})
    if {entry["verdict"] for entry in hops} != {"granted", "too-high", "too-far", "too-long", "too-fast"}:
        raise AssertionError("the hops do not cover every verdict")
    if max(entry["expected"]["ticks"] for entry in hops if entry["expected"]) != BALLISTICS.HOP_TICKS:
        raise AssertionError("no hop flies for the longest time")
    ends = {name: (start, end) for name, start, end, _verdict in HOPS}
    flights = [{"id": name, "from": ends[name][0], "to": ends[name][1], "expected": BALLISTICS.flight(*ends[name])} for name in FLIGHTS]
    routes = [dict(entry, expected=BALLISTICS.route(entry)) for entry in ROUTES]
    write("🦘️hop-ballistics", {"$comment": GENERATED % "🦘️hop-ballistics", "constants": BALLISTICS.CONSTANTS, "falls": unique(falls), "landings": unique(landings), "drops": unique(drops), "hops": unique(hops), "flights": unique(flights), "routes": unique(routes)})
    return {"falls": len(falls), "landings": sum(len(entry["sweeps"]) for entry in landings), "drops": len(drops), "hops": len(hops), "flights": len(flights), "routes": len(routes)}



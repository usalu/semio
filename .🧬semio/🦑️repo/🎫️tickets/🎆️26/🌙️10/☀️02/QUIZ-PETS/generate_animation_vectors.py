def scalar(value):
    """🔹️ Whether a value is a leaf of the document."""
    return not isinstance(value, (list, dict))


def inline(value):
    """➖️ Whether a value is written on one line: leaves, lists of leaves, and short objects of leaves and lists of leaves."""
    if scalar(value):
        return True
    if isinstance(value, list):
        return all(scalar(entry) for entry in value)
    return all(scalar(entry) or (isinstance(entry, list) and all(scalar(leaf) for leaf in entry)) for entry in value.values()) and len(json.dumps(value, ensure_ascii=False)) <= 200


def render(value, depth):
    """🖨️ Indented UTF-8 JSON in which every row of numbers stays on one line."""
    if inline(value):
        return json.dumps(value, ensure_ascii=False)
    pad = "  " * (depth + 1)
    if isinstance(value, list):
        rows = [pad + render(entry, depth + 1) for entry in value]
        return "[\n" + ",\n".join(rows) + "\n" + "  " * depth + "]"
    rows = [pad + json.dumps(key, ensure_ascii=False) + ": " + render(entry, depth + 1) for key, entry in value.items()]
    return "{\n" + ",\n".join(rows) + "\n" + "  " * depth + "}"


def write(directory, document):
    """💾️ Writes one fixture with a trailing newline, after proving that it reads back as the same document."""
    path = os.path.join(PETS, "🧫️fixtures", directory, "🔣️.json")
    text = render(document, 0) + "\n"
    if json.loads(text) != document:
        raise AssertionError("the rendered fixture %s does not read back as its document" % directory)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "wb") as handle:
        handle.write(text.encode("utf-8"))



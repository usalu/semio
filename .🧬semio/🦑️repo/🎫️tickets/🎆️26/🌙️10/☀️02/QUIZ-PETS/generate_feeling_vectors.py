def stage(rng, document, tick):
    """🎬️ A random stage: two to six actors close together, each species at most once most of the time, sometimes twice, sometimes a stranger."""
    names = [species["id"] for species in document["species"]]
    count = int(rng.integers(2, 7))
    chosen = [names[index] for index in rng.permutation(len(names))][:count]
    while len(chosen) < count:
        chosen.append(str(rng.choice(names + ["ghost"])))
    sightings = []
    for name in chosen:
        kind = next((species for species in document["species"] if species["id"] == name), None)
        states = [entry["id"] for entry in kind["states"]] if kind is not None else ["bright"]
        tricks = [entry["id"] for entry in kind["tricks"]] if kind is not None else ["flare"]
        floats = name in ("glow", "mist") and rng.random() < 0.6
        activity = str(rng.choice(["idle", "idle", "trick", "sleep", "walk", "purr"]))
        performed = str(rng.choice(tricks)) if activity == "trick" and rng.random() < 0.8 else None
        sightings.append(sight(name, str(rng.choice(states)), (MOODS[int(rng.integers(0, len(MOODS)))], int(rng.integers(0, 9)) / 8), float(rng.integers(0, 361)) / 2, float(rng.integers(300, 420)) / 2 if floats else 300, activity, int(rng.integers(0, 4)) * 320, performed))
    return sightings


def cooled(rng, document, tick):
    """🧊️ Random coolings: some over, some still running, some for reactions and pairs that are not on stage."""
    names = [species["id"] for species in document["species"]]
    coolings = []
    for _ in range(int(rng.integers(0, 4))):
        chosen = document["chemistry"][int(rng.integers(0, len(document["chemistry"])))]
        strange = rng.random() < 0.2
        when = str(rng.choice(names)) if strange or "species" not in chosen["when"] else chosen["when"]["species"]
        near = chosen["near"]["species"] if "species" in chosen["near"] else str(rng.choice([name for name in names if name != when]))
        coolings.append({"reaction": chosen["id"], "when": when, "near": near, "until": tick + int(rng.integers(-2, 3)) * 32})
    return coolings



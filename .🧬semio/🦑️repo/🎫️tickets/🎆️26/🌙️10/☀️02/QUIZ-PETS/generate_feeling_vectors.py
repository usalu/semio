def load(path, name):
    """📦️ Loads one Python file as a module."""
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def case(name):
    """🧪️ The Python adapter of one case, loaded with the harness shim it imports."""
    sys.modules.setdefault("semio_repo_test", load(HOST, "semio_repo_test"))
    return load(os.path.join(PETS, "🧪️tests", name, "🐍️.py"), "pets_" + "".join(letter for letter in name if letter.isascii()).replace("-", "_"))


def label(number):
    """🔤️ An id fragment of a number: ``minus-0-45`` for −0.45, ``1`` for 1."""
    text = ("%d" % abs(number) if float(number).is_integer() else repr(abs(number))).replace(".", "-")
    return "minus-" + text if number < 0 else text


def dump(path, document):
    """💾️ Writes one document as indented UTF-8 JSON with a trailing newline, only when it changed."""
    os.makedirs(os.path.dirname(path), exist_ok=True)
    payload = (json.dumps(document, ensure_ascii=False, indent=1, allow_nan=False) + "\n").encode("utf-8")
    if os.path.exists(path) and open(path, "rb").read() == payload:
        print("unchanged %s" % os.path.relpath(path, ROOT))
        return
    for _ in range(20):
        try:
            with open(path, "wb") as handle:
                handle.write(payload)
            break
        except OSError as error:
            print("retrying %s after %s" % (os.path.relpath(path, ROOT), error))
            time.sleep(0.5)
    else:
        raise OSError("cannot write %s" % path)
    print("wrote %s (%d bytes)" % (os.path.relpath(path, ROOT), len(payload)))


def write(directory, document):
    """📁️ Writes one fixture of the pets product."""
    dump(os.path.join(PETS, "🧫️fixtures", directory, "🔣️.json"), document)


def comment(name, source):
    """🏷️ The provenance note every fixture starts with."""
    return "Generated by `%s` from %s in 🧪️tests/%s/🐍️.py — never edit by hand." % (COMMAND, source, name)


def unique(vectors):
    """🆔️ Refuses a list of vectors in which an id repeats."""
    seen = set()
    for vector in vectors:
        if vector["id"] in seen:
            raise AssertionError("duplicate vector id %s" % vector["id"])
        seen.add(vector["id"])
    return vectors


def felt(mood, intensity, since=0):
    """🫀️ One feeling."""
    return {"mood": mood, "intensity": intensity, "since": since}



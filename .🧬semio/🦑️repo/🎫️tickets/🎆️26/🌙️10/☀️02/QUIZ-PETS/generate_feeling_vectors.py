def named(english, german):
    """🌍️ A text in both languages."""
    return {"en": english, "de": german}


def state(name, english, german, **more):
    """🔦️ One state."""
    return {"id": name, "name": named(english, german), **more}


def trick(name, english, german, clip, cues, **more):
    """🪄️ One trick; ``source`` is written as ``from``."""
    if "source" in more:
        more["from"] = more.pop("source")
    return {"id": name, "name": named(english, german), "clip": clip, "cues": cues, **more}


def kind(reference, name, english, german, thing, width, height, palette, temperament, mood, states, tricks):
    """🐣️ One species of the case: the reference rig with its own name, box, colours, character, states and tricks."""
    document = copy.deepcopy(reference)
    document.pop("$schema", None)
    document["id"] = name
    document["name"] = named(english, german)
    document["thing"] = thing
    document["grounds"] = []
    document["size"] = {"width": width, "height": height}
    document["palette"] = {"body": palette[0], "accent": palette[1], "detail": palette[2]}
    document["temperament"] = {"energy": temperament[0], "sociability": temperament[1], "curiosity": temperament[2]}
    document["states"] = states
    document["tricks"] = tricks
    document["grip"] = round(height * 0.9, 1)
    document["reach"] = round(width * 0.25, 1)
    document["mood"] = mood
    return document


def reaction(name, when, near, within, every, then, where=None, chance=None, unless=None, affinity=None):
    """⚗️ One reaction."""
    document = {"id": name, "when": when, "near": near, "within": within}
    if where is not None:
        document["where"] = where
    if unless is not None:
        document["unless"] = unless
    if affinity is not None:
        document["affinity"] = affinity
    document["every"] = every
    if chance is not None:
        document["chance"] = chance
    document["then"] = then
    return document



def sight(species, state_, feeling, x, y, activity="idle", held=0, trick_=None):
    """👀️ One actor as the chemistry sees it: ``feeling`` is ``(mood, intensity)``, ``held`` the ticks it has been in its state, ``trick_`` the trick it performs, the body is the size box of its species."""

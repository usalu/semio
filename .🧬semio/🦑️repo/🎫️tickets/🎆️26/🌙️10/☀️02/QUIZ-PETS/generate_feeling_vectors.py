def decay_vectors(feeling_case):
    """📉️ Feelings over ticks: every mood strong, middling and faint beside a resting mood of content; resting moods above, at and below their rest."""
    offsets = [0, 1, 64, 127, 128, 129, 192, 256, 512, 1024, 2048, 4096, 8192, 8320, 8321, 9000, 20000]
    vectors = []
    for mood in MOODS[1:]:
        for intensity in [1, 0.6, 0.07]:
            feeling = felt(mood, intensity, 1000)
            fade = feeling_case.fade_tick(feeling)
            ticks = sorted(set([1000 + offset for offset in offsets] + [fade - 1, fade, fade + 1, fade + 256, fade + 511, fade + 512, fade + 513]))
            vectors.append({"id": "%s-at-%s" % (mood, label(intensity)), "feeling": feeling, "resting": "content", "ticks": ticks})
    for mood, intensity in [("scared", 0.02), ("sad", 0), ("happy", 0.05), ("happy", 0.049)]:
        vectors.append({"id": "faint-%s-at-%s" % (mood, label(intensity)), "feeling": felt(mood, intensity, 1000), "resting": "proud", "ticks": [900, 1000, 1001, 1064, 1128, 1256, 1511, 1512, 1513, 3000]})
    for resting in ["content", "proud", "sleepy", "grumpy", "scared"]:
        for intensity in [1, 0.5, 0.26, 0.25, 0.1, 0]:
            feeling = felt(resting, intensity, 1000)
            rest = feeling_case.settles(feeling, resting)
            ticks = sorted(set([1000 + offset for offset in offsets] + [rest - 1, rest, rest + 1]))
            vectors.append({"id": "resting-%s-at-%s" % (resting, label(intensity)), "feeling": feeling, "resting": resting, "ticks": ticks})
    return vectors


def jump_vectors(rng):
    """⏭️ Feelings with dyadic intensities and cuts of time: their arithmetic is exact, so both ways must agree to the bit."""
    vectors = []
    for index in range(48):
        mood = MOODS[int(rng.integers(0, len(MOODS)))]
        resting = mood if index % 4 == 0 else MOODS[int(rng.integers(0, len(MOODS)))]
        since = int(rng.integers(0, 500))
        cuts = sorted(set(since + int(offset) for offset in rng.integers(0, [200, 2000, 20000][index % 3], size=int(rng.integers(2, 7)))))
        vectors.append({"id": "cut-%d" % index, "feeling": felt(mood, int(rng.integers(0, 65)) / 64, since), "resting": resting, "cuts": cuts})
    return vectors


def crowd(name, restings, feelings, sociabilities, affinity, near, beats):
    """👥️ One crowd; ``affinity`` and ``near`` are functions of the two places."""
    count = len(feelings)
    return {
        "id": name,
        "restings": restings,
        "feelings": feelings,
        "sociabilities": sociabilities,
        "affinities": [[0 if giver == catcher else affinity(giver, catcher) for catcher in range(count)] for giver in range(count)],
        "near": [[giver != catcher and bool(near(giver, catcher)) for catcher in range(count)] for giver in range(count)],
        "beats": beats,
    }



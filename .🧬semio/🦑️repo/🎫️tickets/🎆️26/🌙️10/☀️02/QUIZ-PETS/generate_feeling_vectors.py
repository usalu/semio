def body(x, y, width, height):
    """⬜️ A bare body for the relations: only its box matters."""
    return {"species": "glow", "state": "bright", "held": 0, "mood": "content", "intensity": 0.25, "activity": "idle", "trick": None, "x": x, "y": y, "width": width, "height": height}


def drifts(rng, names):
    """💞️ A random rapport history: none, or a drift for a few pairs of species, in sixteenths."""
    rapports = []
    for _ in range(int(rng.integers(0, 3))):
        pair = [str(name) for name in rng.choice(names, size=2, replace=False)]
        if not any(sorted(entry["between"]) == sorted(pair) for entry in rapports):
            rapports.append({"between": pair, "drift": int(rng.integers(-8, 9)) / 16})
    return rapports



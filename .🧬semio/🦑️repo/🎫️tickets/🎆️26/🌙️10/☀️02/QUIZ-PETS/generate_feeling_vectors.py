# region 🔖️Replay
class Replay:
    """🎞️ Stands in for the context of the harness: hands the documents under construction to the handlers of an oracle."""

    def __init__(self, documents):
        self.documents = documents

    def fixture_bytes(self, uri):
        """📨️ The bytes a handler would read from a committed fixture."""
        return json.dumps(self.documents[uri], ensure_ascii=False).encode("utf-8")


def replayed(handler, context):
    """🔁️ What a handler produces for vectors that carry no expectation yet: its own comparison is switched off for the call."""
    scope = handler.__globals__
    kept = scope["close"]
    scope["close"] = lambda produced, expected: True
    try:
        return handler(context).projection
    finally:
        scope["close"] = kept



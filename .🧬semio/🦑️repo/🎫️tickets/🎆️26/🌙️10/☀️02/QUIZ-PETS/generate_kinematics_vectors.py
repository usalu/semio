def posed(species, changes):
    """🤸️ A full pose of a species: rest everywhere except the bones named in ``changes``."""
    pose = []
    for bone in species["bones"]:
        entry = dict(RIG.REST)
        entry.update(changes.get(bone["id"], {}))
        pose.append(entry)
    unknown = set(changes) - {bone["id"] for bone in species["bones"]}
    if unknown:
        raise AssertionError("pose names unknown bones %s" % sorted(unknown))
    return pose


def scattered(species, generator):
    """🌪️ A pose with every bone moved: offsets within ±6 px, rotations within ±180°, scales within 0.6 … 1.4, all in short decimals."""
    return [{"x": round(float(generator.uniform(-6, 6)), 2), "y": round(float(generator.uniform(-6, 6)), 2), "rotation": round(float(generator.uniform(-180, 180)), 1), "scaleX": round(float(generator.uniform(0.6, 1.4)), 2), "scaleY": round(float(generator.uniform(0.6, 1.4)), 2)} for _ in species["bones"]]



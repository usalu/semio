def quanta(pixels):
    """🔬️ Pixels as whole quanta; refused when they are no multiple of a quarter pixel."""
    scaled = pixels * QUANTUM
    if scaled != int(scaled):
        raise AssertionError("%r px is no multiple of a quarter pixel" % pixels)
    return int(scaled)


def event(at, kind, x=None, y=None, pointer=None, guards=None):
    """🖲️ One event of a press vector."""
    entry = {"at": at, "kind": kind}
    if x is not None:
        entry.update(x=quanta(x), y=quanta(y))
    if pointer is not None:
        entry["pointer"] = pointer
    if guards:
        entry["guards"] = list(guards)
    return entry



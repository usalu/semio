def bodies(seed, count):
    """🧍️ The pets of the page: bodies of every size on a jittered grid, never touching."""
    dice, placed = Dice(seed, 1), []
    columns = int(math.ceil(math.sqrt(count * PAGE[0] / PAGE[1])))
    rows = int(math.ceil(count / columns))
    for index in range(count):
        column, row = index % columns, index // columns
        x = (column + 0.5 + dice.between(-0.25, 0.25)) * PAGE[0] / columns
        y = (row + 0.75 + dice.between(-0.15, 0.15)) * PAGE[1] / rows
        placed.append(box(dice, x, y))
    return placed


def somewhere(dice, pets, near):
    """📍️ A target of ordinary travel: beside or on a pet, or anywhere on the page."""
    if dice.chance(near):
        x, y = centre(dice.pick(pets))
        angle, distance = dice.between(0, 2 * math.pi), dice.between(0, 150)
        return min(max(x + distance * math.cos(angle), 4), PAGE[0] - 4), min(max(y + distance * math.sin(angle), 4), PAGE[1] - 4)
    return dice.between(4, PAGE[0] - 4), dice.between(4, PAGE[1] - 4)


def roam(mover, dice, count, memory, speed, left, right, top, bottom):
    """🦋️ A persistent random walk of some events inside a box: the velocity forgets itself after ``memory`` seconds and bounces off the sides."""
    keep = math.exp(-1 / (memory * mover.rate))
    kicks = dice.normal((count, 2)) * speed * math.sqrt(1 - keep * keep)
    px, py, vx, vy = mover.x, mover.y, 0.0, 0.0
    xs, ys = numpy.empty(count), numpy.empty(count)
    for index in range(count):
        vx, vy = vx * keep + kicks[index, 0], vy * keep + kicks[index, 1]
        px, py = px + vx / mover.rate, py + vy / mover.rate
        if px < left or px > right:
            px, vx = min(max(px, left), right), -vx
        if py < top or py > bottom:
            py, vy = min(max(py, top), bottom), -vy
        xs[index], ys[index] = px, py
    mover.put(xs, ys, 0.5)


def travel(mover, dice, pets, seconds):
    """🧭️ Going about a page: reaches to targets, half of them beside or on a pet, with dwells of every length between them."""
    until = mover.seconds() + seconds
    while mover.seconds() < until:
        mover.aim(*somewhere(dice, pets, 0.5), pace=dice.between(0.7, 2.5), tremor=dice.between(0.2, 0.8))
        kind = dice.below(10)
        if kind < 3:
            mover.rest(dice.between(0.1, 1.5))
        elif kind < 9:
            mover.hover(dice.between(0.15, 2.5), dice.between(0.4, 1.2), dice.between(0, 4))
        else:
            mover.hover(dice.between(2, 6), dice.between(0.4, 1.5), dice.between(0, 3))


def sweep(mover, dice, pets, seconds):
    """🧹️ Wiping the pointer left and right over, above or under a pet, wider than the pet."""
    until = mover.seconds() + seconds
    while mover.seconds() < until:
        x, y = centre(dice.pick(pets))
        swing, hertz = dice.between(50, 220), dice.between(0.5, 3)
        hertz = min(hertz, 2500 / (2 * math.pi * swing))
        middle, level = x + dice.between(-40, 40), y + dice.between(-60, 60)
        phase = dice.between(0, 2 * math.pi)
        mover.aim(middle + swing * math.sin(phase), level, pace=dice.between(0.8, 1.6))
        count = mover.events(dice.between(2, 7))
        time = numpy.arange(1, count + 1) / mover.rate
        wander = numpy.cumsum(dice.normal(count)) * 0.15
        mover.put(middle + swing * numpy.sin(phase + 2 * math.pi * hertz * time * (1 + 0.05 * numpy.sin(time * 1.7))), level + wander + 6 * numpy.sin(2 * math.pi * hertz * time * dice.between(0.4, 2.2)), dice.between(0.4, 1.0))
        mover.hover(dice.between(0.2, 1.0), 0.6)


def read(mover, dice, pets, seconds):
    """📖️ Following text with the pointer: short hops along a line with pauses, and a return sweep to the next line."""
    until = mover.seconds() + seconds
    while mover.seconds() < until:
        x, y = centre(dice.pick(pets))
        left, width = x - dice.between(60, 300), dice.between(200, 500)
        line, spacing = y + dice.between(-90, 60), dice.between(18, 30)
        mover.aim(left, line, pace=dice.between(0.8, 1.5))
        for _ in range(3 + dice.below(6)):
            while mover.x < left + width:
                mover.reach(mover.x + dice.between(30, 100), line + dice.between(-2, 2), dice.between(1.2, 2.2), 0.5)
                mover.hover(dice.between(0.08, 0.35), 0.6)
            line += spacing
            mover.reach(left + dice.between(-6, 6), line, dice.between(0.9, 1.4), 0.5)
            mover.hover(dice.between(0.1, 0.4), 0.6)


def select(mover, dice, pets, seconds):
    """🖍️ Selecting text beside or under a pet: a slow drag along a line, sometimes adjusted back and forth, sometimes on to the next line."""
    until = mover.seconds() + seconds
    while mover.seconds() < until:
        x, y = centre(dice.pick(pets))
        mover.aim(x + dice.between(-150, 60), y + dice.between(-50, 50), pace=dice.between(0.8, 1.6))
        mover.hover(dice.between(0.1, 0.4), 0.5)
        mover.reach(mover.x + dice.between(40, 400), mover.y + dice.between(-3, 3), dice.between(1.5, 4), 0.5)
        if dice.chance(0.4):
            mover.reach(mover.x - dice.between(8, 40), mover.y + dice.between(-2, 2), dice.between(1.2, 2), 0.5)
            if dice.chance(0.5):
                mover.reach(mover.x + dice.between(5, 20), mover.y, dice.between(1.2, 2), 0.5)
        if dice.chance(0.2):
            mover.reach(mover.x - dice.between(60, 300), mover.y + dice.between(18, 30), dice.between(1.5, 3), 0.5)
        mover.hover(dice.between(0.2, 1.0), 0.6)


def linger(mover, dice, pets, seconds):
    """🫧️ Resting the pointer on or right beside a pet for a long while, with tremor, drift and small adjustments."""
    until = mover.seconds() + seconds
    while mover.seconds() < until:
        body = dice.pick(pets)
        x, y = centre(body)
        mover.aim(x + dice.between(-0.9, 0.9) * body[2] / QUANTUM, y + dice.between(-0.9, 0.9) * body[3] / QUANTUM)
        for _ in range(1 + dice.below(5)):
            mover.hover(dice.between(1, 4), dice.between(0.5, 1.5), dice.between(0, 6))
            if dice.chance(0.6):
                mover.reach(mover.x + dice.between(-15, 15), mover.y + dice.between(-15, 15), dice.between(1, 2), 0.6)


def wander(mover, dice, pets, seconds):
    """☁️ Idle wandering: the pointer drifts about a part of the page, as a hand does that waits or thinks — a slow persistent random walk (80 to 400 px/s) in a box of 300 to 600 pixels."""
    until = mover.seconds() + seconds
    while mover.seconds() < until:
        x, y = somewhere(dice, pets, 0.5)
        left, top = x - dice.between(100, 300), y - dice.between(100, 300)
        mover.aim(x, y, pace=dice.between(0.8, 1.6))
        roam(mover, dice, mover.events(dice.between(4, 12)), dice.between(0.25, 0.7), dice.between(80, 400), left, left + dice.between(300, 600), top, top + dice.between(300, 600))
        mover.hover(dice.between(0.3, 2.0), 0.6)


def fidget(mover, dice, pets, seconds):
    """🌪️ Vigorous aimless wiggling right at a pet: a persistent random walk (150 to 900 px/s) that bounces about in a box the pet stands somewhere in, within 220 pixels of it. A stress, not ordinary travel."""
    until = mover.seconds() + seconds
    while mover.seconds() < until:
        x, y = centre(dice.pick(pets))
        left, right = x - dice.between(20, 220), x + dice.between(20, 220)
        top, bottom = y - dice.between(20, 220), y + dice.between(20, 220)
        mover.aim(dice.between(left, right), dice.between(top, bottom))
        roam(mover, dice, mover.events(dice.between(4, 12)), dice.between(0.15, 0.4), dice.between(150, 900), left, right, top, bottom)
        mover.hover(dice.between(0.2, 1.0), 0.6)


ORDINARY = {"travel": travel, "sweep": sweep, "read": read, "select": select, "linger": linger, "wander": wander, "fidget": fidget}
KINDS = ["travel", "sweep", "read", "select", "linger", "wander"]
MIX = ["travel", "travel", "travel", "travel", "sweep", "read", "select", "linger", "wander", "fidget"]


def ordinary(seed, kind, pets, seconds):
    """🚶️ One stretch of pointer travel of a kind, as an encoded path."""
    dice = Dice(seed, 2)
    mover = hand(dice, dice.between(4, PAGE[0] - 4), dice.between(4, PAGE[1] - 4))
    ORDINARY[kind](mover, dice, pets, seconds)
    return encoded(*mover.ticks())



def clicking(seed):
    """👇️ A synthesised press vector — a click, a double click, a long press, a slow drag or a quick drag by a hand with jitter — and the kinds of signals the hand means."""
    dice = Dice(seed, 7)
    pointer = dice.pick(["mouse", "mouse", "mouse", "pen", "touch"])
    jitter = 5.0 if pointer == "touch" else 2.0
    x, y = dice.below(1200) + 40.0, dice.below(640) + 40.0
    kind = dice.pick(["click", "double", "long", "slow", "quick"])
    events, meant, tick = [], [], 5 + dice.below(10)

    def wobble(until, every):
        """〰️ Small moves inside the slop until a tick."""
        nonlocal tick
        while tick + every < until:
            tick += every
            events.append(event(tick, "dragged", x + round(dice.between(-jitter, jitter) / 1.5 * 4) / 4, y + round(dice.between(-jitter, jitter) / 1.5 * 4) / 4))

    def press():
        """⬇️ The press itself."""
        events.append(event(tick, "pressed", x, y, pointer))
        return tick

    if kind in ("click", "double"):
        for _ in range(2 if kind == "double" else 1):
            down = press()
            wobble(down + 3 + dice.below(10), 2)
            tick += 1 + dice.below(2)
            events.append(event(tick, "released", x, y))
            meant.append("click")
            tick += 6 + dice.below(14)
    elif kind == "long":
        down = press()
        wobble(down + 36 + dice.below(110), 4 + dice.below(8))
        tick += 1 + dice.below(4)
        events.append(event(tick, "released", x, y))
        meant.extend(["hold", "unhold"])
    else:
        down = press()
        speed = dice.between(0.15, 1.2) if kind == "slow" else dice.between(2.5, 12)
        angle = dice.between(0, 2 * math.pi)
        while speed * (tick - down) < 40:
            tick += 1 + dice.below(2)
            gone = speed * (tick - down)
            events.append(event(tick, "dragged", x + round(gone * math.cos(angle) * 4) / 4, y + round(gone * math.sin(angle) * 4) / 4))
        tick += 1 + dice.below(6)
        events.append(event(tick, "released", events[-1]["x"] / QUANTUM, events[-1]["y"] / QUANTUM))
        slop = ORACLE.SLOP_COARSE if pointer == "touch" else ORACLE.SLOP_FINE
        beyond = [entry["at"] for entry in events[1:-1] if math.hypot(entry["x"] / QUANTUM - x, entry["y"] / QUANTUM - y) >= slop]
        meant.extend((["hold"] if beyond[0] >= down + ORACLE.HOLD_TICKS else []) + ["lift", "drop"])
    return {"id": "%s-%d" % (kind, seed), "ticks": tick + 10, "events": events}, meant



def judged(name, corpus):
    """⚖️ What the TypeScript subject answers to a corpus: written to the scratch folder, judged by ``judge_gesture_traces.ts``."""
    os.makedirs(SCRATCH, exist_ok=True)
    inputs, outputs = os.path.join(SCRATCH, name + "-corpus.json"), os.path.join(SCRATCH, name + "-verdicts.json")
    with open(inputs, "w", encoding="utf-8") as handle:
        json.dump(dict(corpus, quantum=QUANTUM, hold=HOLD, page=[PAGE[0] * QUANTUM, PAGE[1] * QUANTUM]), handle)
    subprocess.run(["bun", os.path.join(TICKET, "judge_gesture_traces.ts"), inputs, outputs], check=True, cwd=ROOT)
    with open(outputs, "r", encoding="utf-8") as handle:
        return json.load(handle)


def surveyed(hours, seed, kinds):
    """🗃️ A large corpus: that many hours of pointer travel of some kinds past 24 pets, 1 200 circles, 600 strokes, 600 shakes and 600 carries, every trace with its group and its label."""
    pets = bodies(seed, 24)
    hovers, helds, ticks, index = [], [], 0, 0
    while ticks < hours * 3600 * TICKS_PER_SECOND:
        kind = kinds[index % len(kinds)]
        path = ordinary(seed * 1000003 + index, kind, pets, 60)
        ticks += len(ORACLE.trail(path, HOLD)[0])
        hovers.append({"id": "%s-%d" % (kind, index), "group": kind, "label": "ordinary", "bodies": pets, "path": path})
        index += 1
    for name, maker, count in (("circle", circle, 600), ("stroke", stroke, 300)):
        for hard in (False, True):
            for number in range(count):
                trace = maker(seed * 7919 + number + (500000 if hard else 0), hard)
                group = "%s-%s" % (name, "hard" if hard else "plain")
                hovers.append({"id": "%s-%d" % (group, number), "group": group, "label": trace["label"], "bodies": [trace["body"]], "path": trace["path"]})
    for hard in (False, True):
        for number in range(300):
            group = "shake-%s" % ("hard" if hard else "plain")
            helds.append(dict(shake(seed * 104729 + number + (500000 if hard else 0), hard), id="%s-%d" % (group, number), group=group))
    for number in range(600):
        helds.append(dict(carry(seed * 15485863 + number), id="carry-%d" % number, group="carry"))
    return {"hovers": hovers, "helds": helds}



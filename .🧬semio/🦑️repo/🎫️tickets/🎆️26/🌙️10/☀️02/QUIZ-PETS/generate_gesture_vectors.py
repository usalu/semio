def scalar(value):
    """🔹️ Whether a value is a leaf of the document."""
    return not isinstance(value, (list, dict))


def inline(value):
    """➖️ Whether a value is written on one line: leaves, lists of leaves, lists of short rows, and short objects of leaves and lists of leaves."""
    if scalar(value):
        return True
    if isinstance(value, list):
        return all(scalar(entry) for entry in value) or (all(isinstance(entry, list) and all(scalar(leaf) for leaf in entry) for entry in value) and len(json.dumps(value, ensure_ascii=False)) <= 200)
    return all(scalar(entry) or (isinstance(entry, list) and all(scalar(leaf) for leaf in entry)) for entry in value.values()) and len(json.dumps(value, ensure_ascii=False)) <= 200


def render(value, depth):
    """🖨️ Indented UTF-8 JSON in which every row of numbers stays on one line."""
    if inline(value):
        return json.dumps(value, ensure_ascii=False)
    pad = "  " * (depth + 1)
    if isinstance(value, list):
        rows = [pad + render(entry, depth + 1) for entry in value]
        return "[\n" + ",\n".join(rows) + "\n" + "  " * depth + "]"
    rows = [pad + json.dumps(key, ensure_ascii=False) + ": " + render(entry, depth + 1) for key, entry in value.items()]
    return "{\n" + ",\n".join(rows) + "\n" + "  " * depth + "}"


def write(document):
    """💾️ Writes the fixture with a trailing newline, after proving that it reads back as the same document; answers whether the file changed."""
    path = os.path.join(PETS, "🧫️fixtures", CASE, "🔣️.json")
    text = (render(document, 0) + "\n").encode("utf-8")
    if json.loads(text.decode("utf-8")) != document:
        raise AssertionError("the rendered fixture does not read back as its document")
    before = None
    if os.path.exists(path):
        with open(path, "rb") as handle:
            before = handle.read()
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "wb") as handle:
        handle.write(text)
    return len(text), before != text


def unique(vectors):
    """🆔️ Refuses two vectors with the same id."""
    ids = [vector["id"] for vector in vectors]
    if len(set(ids)) != len(ids):
        raise AssertionError("duplicate vector ids in %r" % ids)
    return vectors



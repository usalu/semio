def circle(seed, hard):
    """⭕️ A deliberate circle round a pet: its label (clockwise as seen on screen is ``circle``), the body, the path and the ticks between which the circle is drawn.

    The plain ones stay well inside what a person does on purpose; the ``hard`` ones go to the edges — slow or
    fast, flat, far off centre, small or wide, with more wobble and fewer turns.
    """
    dice = Dice(seed, 3)
    body = box(dice, dice.between(300, PAGE[0] - 300), dice.between(330, PAGE[1] - 250))
    x, y = centre(body)
    size = max(body[2], body[3]) / QUANTUM
    way = dice.pick([1, -1])
    if hard:
        radius, hertz, flat = size * dice.between(0.85, 2.9), dice.between(0.45, 3.5), dice.between(0.55, 1.0)
        off, wobble, turns, tremor = dice.between(0, 0.35), dice.between(0, 0.15), dice.between(1.5, 3.5), dice.between(0.6, 1.6)
    else:
        radius, hertz, flat = size * dice.between(1.1, 2.4), dice.between(0.7, 2.4), dice.between(0.75, 1.0)
        off, wobble, turns, tremor = dice.between(0, 0.2), dice.between(0, 0.1), dice.between(2.2, 3.5), dice.between(0.4, 1.2)
    angle, tilt, lean = dice.between(0, 2 * math.pi), dice.between(0, math.pi), dice.between(0, 2 * math.pi)
    middle = (x + off * radius * math.cos(lean), y + off * radius * math.sin(lean))
    start = dice.between(0, 2 * math.pi)
    mover = hand(dice, middle[0] + dice.between(180, 320) * math.cos(angle), middle[1] + dice.between(180, 320) * math.sin(angle))
    mover.rest(dice.between(0.1, 0.4))

    def ellipse(phase, scale):
        """🥚️ The points of the tilted ellipse at some phases."""
        along, across = radius * scale * numpy.cos(phase), radius * scale * flat * numpy.sin(phase)
        return middle[0] + along * math.cos(tilt) - across * math.sin(tilt), middle[1] + along * math.sin(tilt) + across * math.cos(tilt)

    first = ellipse(numpy.array([start]), numpy.ones(1))
    mover.aim(float(first[0][0]), float(first[1][0]), pace=dice.between(0.8, 1.5))
    count = mover.events(turns / hertz)
    time = numpy.arange(1, count + 1) / mover.rate
    speed = hertz * (1 + 0.2 * numpy.sin(2 * math.pi * time * dice.between(0.3, 1.0) + dice.between(0, 2 * math.pi)))
    phase = start + way * 2 * math.pi * numpy.cumsum(speed) / mover.rate
    swell = 1 + wobble * numpy.sin(phase * dice.between(0.3, 1.7) + dice.between(0, 2 * math.pi))
    begin = mover.tick()
    mover.put(*ellipse(phase, swell), tremor)
    end = mover.tick() - 1
    mover.reach(mover.x + dice.between(-300, 300), mover.y + dice.between(-200, 200), dice.between(0.8, 1.5))
    mover.rest(0.2)
    return {"label": "circle" if way > 0 else "countercircle", "span": [begin, end], "body": body, "path": encoded(*mover.ticks())}


def stroke(seed, hard):
    """🐈️ A deliberate petting: the pointer goes left and right over a pet, one to four times a second, along a slight arch and a slight slope (up to 11°, the hard ones up to 23°)."""
    dice = Dice(seed, 4)
    body = box(dice, dice.between(200, PAGE[0] - 200), dice.between(250, PAGE[1] - 200))
    x, y = centre(body)
    width, height = body[2] / QUANTUM, body[3] / QUANTUM
    swing = width * (dice.between(0.3, 0.7) if hard else dice.between(0.4, 0.62))
    hertz = dice.between(0.8, 4.2) if hard else dice.between(1.2, 3.4)
    aside = dice.between(-1, 1) * max(width / 2 + 8 - swing, 0)
    level = y + dice.between(-0.4, 0.4) * height
    angle = dice.between(0, 2 * math.pi)
    mover = hand(dice, x + dice.between(150, 300) * math.cos(angle), y + dice.between(150, 300) * math.sin(angle))
    mover.rest(dice.between(0.1, 0.4))
    phase = dice.between(0, 2 * math.pi)
    mover.aim(x + aside + swing * math.sin(phase), level, pace=dice.between(0.9, 1.6))
    count = mover.events(dice.between(2.5, 3.5))
    time = numpy.arange(1, count + 1) / mover.rate
    pace = hertz * (1 + 0.1 * numpy.sin(2 * math.pi * time * dice.between(0.2, 0.8)))
    wave = numpy.sin(phase + 2 * math.pi * numpy.cumsum(pace) / mover.rate)
    arch = dice.between(-0.3, 0.3) * swing * wave * wave
    slope = math.tan(dice.between(-0.4, 0.4) if hard else dice.between(-0.2, 0.2))
    begin = mover.tick()
    mover.put(x + aside + swing * wave, level + arch + slope * swing * wave + dice.between(0, 0.08) * height * numpy.sin(2 * math.pi * time * dice.between(0.3, 1.5)), dice.between(0.4, 1.0))
    end = mover.tick() - 1
    mover.reach(mover.x + dice.between(-250, 250), mover.y + dice.between(-200, 200), dice.between(0.8, 1.5))
    mover.rest(0.2)
    return {"label": "stroke", "span": [begin, end], "body": body, "path": encoded(*mover.ticks())}


def shake(seed, hard):
    """🫨️ A deliberate shake of a held pet: the grip goes to and fro two to five times a second, in any direction, while it drifts."""
    dice = Dice(seed, 5)
    height = dice.pick(SIZES)[1]
    mover = hand(dice, dice.between(300, PAGE[0] - 300), dice.between(250, PAGE[1] - 250))
    mover.hover(dice.between(0.1, 0.3), 0.4)
    mover.reach(mover.x + dice.between(-60, 60), mover.y - dice.between(10, 80), dice.between(1, 2))
    swing = dice.between(25, 70) if hard else dice.between(32, 70)
    hertz = dice.between(2, 5) if hard else dice.between(2.4, 4.6)
    hertz = min(hertz, 1900 / (2 * math.pi * swing))
    angle = dice.between(0, 2 * math.pi) if dice.chance(0.4) else dice.between(-0.5, 0.5)
    count = mover.events(dice.between(1.2, 2.5))
    time = numpy.arange(1, count + 1) / mover.rate
    wave = numpy.sin(2 * math.pi * hertz * time * (1 + 0.05 * numpy.sin(time * 2.3)))
    side = 0.15 * swing * numpy.sin(2 * math.pi * hertz * time * dice.between(0.7, 2.1))
    slide = numpy.cumsum(dice.normal((count, 2)), axis=0) * 0.25
    begin = mover.tick()
    mover.put(mover.x + swing * wave * math.cos(angle) - side * math.sin(angle) + slide[:, 0], mover.y + swing * wave * math.sin(angle) + side * math.cos(angle) + slide[:, 1], dice.between(0.3, 1.0))
    end = mover.tick() - 1
    mover.hover(dice.between(0.2, 0.5), 0.5)
    return {"label": "shake", "span": [begin, end], "height": height * QUANTUM, "path": encoded(*mover.ticks())}



def robust(vector):
    """🧐️ Whether the oracle finds a deliberate trace clean."""
    xs, ys = ORACLE.trail(vector["path"], HOLD)
    if "height" in vector:
        return ORACLE.clean_shake(xs, ys, QUANTUM, vector["height"] / QUANTUM, vector["span"]) is not None
    across, down, width, height = ORACLE.offsets(xs, ys, vector["body"], QUANTUM)
    if vector["label"] == "stroke":
        return ORACLE.clean_petting(across, down, ORACLE.zone(across, down, width, height), width, vector["span"]) is not None
    turns, distance, live = ORACLE.winding(xs, ys, vector["body"], QUANTUM)
    return ORACLE.clean_circle(turns, distance, live, vector["span"], vector["body"], QUANTUM) is not None


def guarded(vectors, guards):
    """🚧️ The first robust vector of a list once more per guard, with the guard up throughout."""
    twin = next(vector for vector in vectors if vector["robust"])
    return [dict(twin, id="%s-on-a-%s-stage" % (twin["id"], guard) if guard in ("quiet", "still") else "%s-%s" % (twin["id"], "over-a-control" if guard == "control" else "while-the-page-scrolls"), guard=guard, of=twin["id"]) for guard in guards]


def build():
    """🏗️ The vectors of the case and a summary of what they hold."""
    document = {"$comment": GENERATED, "constants": ORACLE.CONSTANTS, "quantum": QUANTUM, "hold": HOLD, "page": [PAGE[0] * QUANTUM, PAGE[1] * QUANTUM], "variants": VARIANTS, "floors": FLOORS}
    presses, meanings = composed(), {}
    for seed in range(24):
        vector, meant = clicking(seed)
        presses.append(vector)
        meanings[vector["id"]] = meant
    warmths = histories()
    circles = [dict(circle(100 + number, False), id="circle-plain-%02d" % number) for number in range(32)] + [dict(circle(200 + number, True), id="circle-hard-%02d" % number) for number in range(16)]
    strokes = [dict(stroke(300 + number, False), id="stroke-plain-%02d" % number) for number in range(16)] + [dict(stroke(400 + number, True), id="stroke-hard-%02d" % number) for number in range(8)]
    shakes = [dict(shake(500 + number, False), id="shake-plain-%02d" % number) for number in range(12)] + [dict(shake(600 + number, True), id="shake-hard-%02d" % number) for number in range(6)] + [dict(carry(700 + number), id="carry-%02d" % number) for number in range(18)]
    for vector in circles + strokes + shakes:
        vector["robust"] = robust(vector)
    circles += guarded(circles, ["control", "quiet", "still", "scrolled"])
    strokes += guarded(strokes, ["control", "quiet", "still", "scrolled"])
    shakes += guarded(shakes, ["control", "quiet", "still", "scrolled"])
    pets = bodies(9, 40)
    travels = [{"id": "%s-%d" % (kind, lap), "kind": kind, "sample": lap == 0, "path": ordinary(900 + lap * len(KINDS) + index, kind, pets, 30)} for lap in range(3) for index, kind in enumerate(KINDS)]
    verdicts = judged(
        "vectors",
        {
            "hovers": [{"id": vector["id"], "bodies": [vector["body"]], "path": vector["path"], "guard": vector.get("guard")} for vector in circles + strokes] + [{"id": travel["id"], "bodies": pets, "path": travel["path"], "variants": VARIANTS} for travel in travels],
            "helds": [{"id": vector["id"], "height": vector["height"], "path": vector["path"], "guard": vector.get("guard")} for vector in shakes],
            "presses": presses,
            "warmths": warmths,
        },
    )
    for vector in presses:
        vector["expected"] = ORACLE.press_signals(vector, QUANTUM)
        if verdicts["presses"][vector["id"]] != vector["expected"]:
            raise AssertionError("presses/%s: the oracle answers %r, the TypeScript subject %r" % (vector["id"], vector["expected"], verdicts["presses"][vector["id"]]))
        if vector["id"] in meanings and [signal for _tick, signal in vector["expected"]] != meanings[vector["id"]]:
            raise AssertionError("presses/%s: the hand meant %r, the oracle answers %r" % (vector["id"], meanings[vector["id"]], vector["expected"]))
    for vector in warmths:
        vector["expected"] = ORACLE.warmth_answers(vector["caresses"])
        if not ORACLE.close(verdicts["warmths"][vector["id"]], vector["expected"]):
            raise AssertionError("warmth/%s: the oracle answers %r, the TypeScript subject %r" % (vector["id"], vector["expected"], verdicts["warmths"][vector["id"]]))
    for vector in circles + strokes:
        vector["expected"] = [[tick, cue] for _variant, _body, tick, cue in verdicts["hovers"][vector["id"]]]
    for vector in shakes:
        vector["expected"] = verdicts["helds"][vector["id"]]
    offences = [[travel["id"]] + row for travel in travels for row in verdicts["hovers"][travel["id"]]]
    if offences:
        raise AssertionError("ordinary travel set off %d cues in the TypeScript subject, the first %r" % (len(offences), offences[:5]))
    ordered = ["id", "label", "robust", "span", "guard", "of", "body", "height", "path", "expected"]
    document.update(
        presses=unique(presses),
        warmths=unique(warmths),
        circles=unique([{key: vector[key] for key in ordered if key in vector} for vector in circles]),
        strokes=unique([{key: vector[key] for key in ordered if key in vector} for vector in strokes]),
        shakes=unique([{key: vector[key] for key in ordered if key in vector} for vector in shakes]),
        bodies=pets,
        travels=unique(travels),
    )
    produced = {"circles": {vector["id"]: ORACLE.judged_hover("circles", document, vector) for vector in document["circles"]}, "strokes": {vector["id"]: ORACLE.judged_hover("strokes", document, vector) for vector in document["strokes"]}}
    produced["shakes"] = ORACLE.twins("shakes", {vector["id"]: ORACLE.judged_held(document, vector) for vector in document["shakes"]}, document["shakes"])
    detection = {kind: ORACLE.tally(document[kind], FLOORS[kind], kind) for kind in ("circles", "strokes", "shakes")}
    watched = ORACLE.travelled(document, False)
    summary = {"presses": len(presses), "warmths": len(warmths), "caresses": sum(len(vector["caresses"]) for vector in warmths), "bodies": len(pets)}
    for kind in ("circles", "strokes", "shakes"):
        plain = [vector for vector in document[kind] if "guard" not in vector]
        summary[kind] = {
            group: "%d of %d recognised, %d of them clean" % (sum(1 for vector in plain if group in vector["id"] and vector["expected"]), sum(1 for vector in plain if group in vector["id"]), sum(1 for vector in plain if group in vector["id"] and vector["robust"]))
            for group in ("plain", "hard", "carry")
            if any(group in vector["id"] for vector in plain)
        }
        summary[kind]["detection"] = detection[kind]
    summary["travel"] = {
        "stretches": len(travels),
        "pointerMinutes": round(sum(len(ORACLE.trail(travel["path"], HOLD)[0]) for travel in travels) / TICKS_PER_SECOND / 60, 2),
        "samplePointerMinutes": round(sum(len(ORACLE.trail(travel["path"], HOLD)[0]) for travel in travels if travel["sample"]) / TICKS_PER_SECOND / 60, 2),
        "variants": VARIANTS,
        "pointerHoursInEveryVariant": round(watched["pointerTicks"] / TICKS_PER_SECOND / 3600, 2),
        "petHoursInEveryVariant": round(watched["petTicks"] / TICKS_PER_SECOND / 3600, 1),
        "cues": len(offences),
    }
    return document, summary



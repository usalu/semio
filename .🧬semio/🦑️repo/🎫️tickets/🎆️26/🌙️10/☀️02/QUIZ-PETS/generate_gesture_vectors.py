class Dice:
    """🎲️ The random stream of one trace: PCG64 behind numpy's generator, seeded by a list of integers."""

    def __init__(self, *key):
        """🌱️ Starts the stream of a key."""
        self.generator = numpy.random.Generator(numpy.random.PCG64(numpy.random.SeedSequence(list(key))))

    def between(self, low, high):
        """📏️ A number between two bounds."""
        return float(low + (high - low) * self.generator.random())

    def chance(self, odds):
        """🪙️ Whether something with these odds happens."""
        return bool(self.generator.random() < odds)

    def below(self, bound):
        """🔢️ An integer in ``[0, bound)``."""
        return int(self.generator.integers(0, bound))

    def pick(self, options):
        """🃏️ One of some options."""
        return options[self.below(len(options))]

    def normal(self, count=None):
        """🔔️ Standard normal numbers."""
        return self.generator.standard_normal(count)


def minimum_jerk(count):
    """📈️ The progress of a minimum-jerk reach after each of ``count`` equal time steps: ``10 τ³ − 15 τ⁴ + 6 τ⁵``."""
    tau = numpy.arange(1, count + 1) / count
    return tau * tau * tau * (10 - 15 * tau + 6 * tau * tau)


class Hand:
    """✋️ A hand on a pointing device: the events it reports at the rate of the device, and how much tremor every event carries."""

    def __init__(self, dice, rate, x, y, whole):
        """🖐️ A hand at rest at a point; ``whole`` rounds to whole pixels like a mouse."""
        self.dice, self.rate, self.whole = dice, rate, whole
        self.xs, self.ys, self.tremors = [numpy.array([float(x)])], [numpy.array([float(y)])], [numpy.zeros(1)]
        self.x, self.y, self.count = float(x), float(y), 1

    def put(self, xs, ys, tremor):
        """➕️ Appends events."""
        if len(xs) == 0:
            return
        self.xs.append(numpy.asarray(xs, dtype=float))
        self.ys.append(numpy.asarray(ys, dtype=float))
        self.tremors.append(numpy.full(len(xs), float(tremor)))
        self.x, self.y, self.count = float(xs[-1]), float(ys[-1]), self.count + len(xs)

    def events(self, seconds):
        """⏱️ How many events a duration takes, at least one."""
        return max(1, int(round(seconds * self.rate)))

    def seconds(self):
        """⌛️ How long the hand has been moving."""
        return self.count / self.rate

    def tick(self):
        """🕰️ The first tick that reads an event not yet reported."""
        return -(-self.count * TICKS_PER_SECOND // self.rate)

    def rest(self, seconds):
        """🛑️ Exact stillness: the hand is off the device."""
        count = self.events(seconds)
        self.put(numpy.full(count, self.x), numpy.full(count, self.y), 0.0)

    def hover(self, seconds, tremor=0.8, drift=0.0):
        """🫳️ Holding the pointer in place: tremor, and a slow drift of ``drift`` pixels per second in a random direction."""
        count = self.events(seconds)
        angle = self.dice.between(0, 2 * math.pi)
        along = numpy.arange(1, count + 1) / self.rate * drift
        self.put(self.x + along * math.cos(angle), self.y + along * math.sin(angle), tremor)

    def reach(self, x, y, pace=1.0, tremor=0.5, bend=None):
        """🏹️ A minimum-jerk reach to a point with a slight bend; its duration follows Fitts' law, stretched by ``pace``."""
        dx, dy = x - self.x, y - self.y
        distance = math.hypot(dx, dy)
        if distance < 0.5:
            return
        seconds = (0.10 + 0.105 * math.log2(distance / 16 + 1)) * pace * self.dice.between(0.85, 1.25)
        progress = minimum_jerk(max(2, self.events(seconds)))
        bow = (self.dice.normal() * 0.05 if bend is None else bend) * distance * numpy.sin(math.pi * progress)
        self.put(self.x + dx * progress - dy / distance * bow, self.y + dy * progress + dx / distance * bow, tremor)

    def aim(self, x, y, pace=1.0, tremor=0.5):
        """🎯️ A reach as a hand really makes it: sometimes past the target, followed by a corrective submovement."""
        dx, dy = x - self.x, y - self.y
        distance = math.hypot(dx, dy)
        if distance > 40 and self.dice.chance(0.3):
            past = self.dice.between(0.03, 0.09)
            self.reach(x + dx * past, y + dy * past, pace, tremor)
            self.hover(self.dice.between(0.03, 0.12), tremor)
            self.reach(x, y, self.dice.between(0.9, 1.5), tremor)
        else:
            self.reach(x, y, pace, tremor)

    def ticks(self):
        """🎞️ The pointer of every tick in quanta: the tremor is added to the events, a tick reads the latest event, and the device rounds."""
        xs, ys, tremors = numpy.concatenate(self.xs), numpy.concatenate(self.ys), numpy.concatenate(self.tremors)
        keep = math.exp(-2 * math.pi * 9.0 / self.rate)
        gain = math.sqrt((1 + keep) / (1 - keep))
        for values in (xs, ys):
            values += scipy.signal.lfilter([1 - keep], [1, -keep], self.dice.normal(len(values))) * gain * tremors
        numpy.clip(xs, 0, PAGE[0], out=xs)
        numpy.clip(ys, 0, PAGE[1], out=ys)
        index = (numpy.arange(len(xs) * TICKS_PER_SECOND // self.rate) * self.rate) // TICKS_PER_SECOND
        grid = QUANTUM if self.whole else 1
        return (numpy.rint(xs[index] * QUANTUM / grid).astype(int) * grid, numpy.rint(ys[index] * QUANTUM / grid).astype(int) * grid)


def encoded(xs, ys):
    """🗜️ A path as the vectors write it: the first point, then per tick the step to the next point, or ``HOLD + n`` for ``n`` ticks without a step."""
    path, still = [int(xs[0]), int(ys[0])], 0
    for dx, dy in zip(numpy.diff(xs).tolist(), numpy.diff(ys).tolist()):
        if dx == 0 and dy == 0:
            still += 1
            continue
        if still:
            path.append(HOLD + still)
            still = 0
        path.extend([dx, dy])
    if still:
        path.append(HOLD + still)
    return path


def box(dice, x, y):
    """🐾️ A body of a random size that stands with its feet at a point, in quanta."""
    width, height = dice.pick(SIZES)
    return [int((x - width / 2) * QUANTUM), int((y - height) * QUANTUM), width * QUANTUM, height * QUANTUM]


def centre(body):
    """🧿️ The centre of a body in pixels."""
    return (body[0] + body[2] / 2) / QUANTUM, (body[1] + body[3] / 2) / QUANTUM


def hand(dice, x, y):
    """🖱️ A hand on a device of a random kind: a mouse at 60, 120 or 144 Hz in whole pixels, a slow or busy page at 30 Hz, a pen or a dense screen in quarter pixels."""
    rate, whole = dice.pick([(60, True), (60, True), (60, False), (120, True), (144, True), (30, True), (64, False)])
    return Hand(dice, rate, x, y, whole)



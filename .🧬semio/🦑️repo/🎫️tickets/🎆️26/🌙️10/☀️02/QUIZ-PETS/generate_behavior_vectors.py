def bonds(menagerie):
    """🤝️ The vectors of the bond-dynamics case."""
    oracle = case("🤝️bond-dynamics")
    ids = [kind["id"] for kind in menagerie["species"]] + ["stranger"]
    pairs = [[a, b] for a in ids for b in ids]
    tables = [
        ("authored-only", menagerie["bonds"], []),
        ("with-history", menagerie["bonds"], [{"between": ["mossy", "sparky"], "drift": 0.35}, {"between": ["mossy", "thorny"], "drift": -0.15}, {"between": ["pebble", "stranger"], "drift": 0.05}, {"between": ["misty", "sparky"], "drift": 0.2}]),
        ("at-the-bounds", [{"between": ["mossy", "sparky"], "affinity": 0.9}, {"between": ["thorny", "mossy"], "affinity": -0.7}, {"between": ["pebble", "misty"], "affinity": -1}], [{"between": ["sparky", "mossy"], "drift": 0.5}, {"between": ["mossy", "thorny"], "drift": -0.5}, {"between": ["misty", "pebble"], "drift": 0.5}]),
        ("no-bonds", [], [{"between": ["mossy", "sparky"], "drift": -0.5}]),
    ]
    affinities = [{"id": name, "bonds": authored, "rapports": rapports, "pairs": pairs, "expected": [oracle.affinity(authored, rapports, pair[0], pair[1]) for pair in pairs]} for name, authored, rapports in tables]
    drifts = [-0.5, -0.45, -0.1, 0, 0.05, 0.42, 0.45, 0.5]
    steps = [{"id": "drift-%s" % label(drift), "drift": drift, "expected": {activity: oracle.stepped(drift, activity) for activity in ACTIVITIES}} for drift in drifts]
    spans = [0, 1, 64, 3840, 19200, 38400, 38401, 100000, 192000]
    fading = [{"id": "drift-%s" % label(drift), "drift": drift, "ticks": spans, "expected": [oracle.faded(drift, ticks) for ticks in spans]} for drift in [0.5, 0.1, 0.05, 0, -0.15, -0.5]]
    stories = [
        ("friends-keep-cuddling", 0.8, [{"after": 6000, "activity": "cuddle"}] * 8),
        ("rivals-squabble-sulk-and-mend", -0.5, [{"after": 6000, "activity": "squabble"}, {"after": 400, "activity": "sulk"}] * 6),
        ("squabbles-without-mending-hit-the-floor", -0.7, [{"after": 2000, "activity": "squabble"}] * 6),
        ("strangers-forget", 0, [{"after": 0, "activity": "greet"}, {"after": 38400, "activity": "greet"}, {"after": 100, "activity": "greet"}, {"after": 6400, "activity": "squabble"}, {"after": 300, "activity": "sulk"}, {"after": 200000, "activity": "greet"}]),
        ("a-friendship-tested", 0.4, [{"after": 3000, "activity": "cuddle"}, {"after": 3000, "activity": "greet"}, {"after": 3000, "activity": "squabble"}, {"after": 350, "activity": "sulk"}, {"after": 3000, "activity": "cuddle"}, {"after": 60000, "activity": "idle"}, {"after": 10, "activity": "walk"}]),
    ]
    histories = []
    for name, authored, events in stories:
        drift = 0.0
        trail = []
        feelings = []
        for event in events:
            drift = oracle.stepped(oracle.faded(drift, event["after"]), event["activity"])
            trail.append(drift)
            feelings.append(oracle.affinity([{"between": ["a", "b"], "affinity": authored}], [{"between": ["a", "b"], "drift": drift}], "b", "a"))
        histories.append({"id": name, "affinity": authored, "events": events, "expected": {"drifts": trail, "affinities": feelings}})
    temperaments = {"energetic": {"energy": 0.9, "sociability": 0.6, "curiosity": 0.9}, "sleepy": {"energy": 0.2, "sociability": 0.5, "curiosity": 0.3}, "sociable": {"energy": 0.6, "sociability": 0.8, "curiosity": 0.6}}
    needs = []
    for name, temperament in temperaments.items():
        for activity in ACTIVITIES:
            for ticks in [0, 64, 1280, 64000]:
                start = {"energy": 0.5, "sociability": 0.5, "curiosity": 0.5}
                needs.append({"id": "%s-%s-%d" % (name, activity, ticks), "needs": start, "activity": activity, "ticks": ticks, "temperament": temperament, "expected": oracle.spent(start, activity, ticks, temperament)})

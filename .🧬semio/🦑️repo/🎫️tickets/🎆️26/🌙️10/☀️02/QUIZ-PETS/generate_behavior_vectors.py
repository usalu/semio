def behavior(menagerie):
    """🧠️ The vectors of the behavior-choice case."""
    oracle = case("🧠️behavior-choice")
    limits = [{"id": mode, "expected": oracle.LIMITS[mode]} for mode in ["still", "calm", "lively"]]
    weights = [{**vector, "expected": oracle.weights(vector)} for vector in situations()]
    lists = [
        ("single", [1]),
        ("last-of-three", [0, 0, 3]),
        ("ascending", [1, 2, 3, 4]),
        ("halves-and-quarters", [0.5, 0, 0.25, 0, 0.25]),
        ("even-thirds", [1, 1, 1]),
        ("empty", []),
        ("all-zero", [0, 0]),
        ("negatives-skipped", [-1, 2, -3, 4]),
        ("tiny-first", [0.000000001, 1]),
        ("trailing-zero", [3, 1, 0]),
        ("calm-rested-weights", oracle.weights(situation("calm-rested", "calm", 0.9, 0.6))),
        ("lively-tired-weights", oracle.weights(situation("lively-tired", "lively", 0.25, 0.6))),
    ]
    marks = [0, 0.1, 0.25, 0.3, 1 / 3, 0.5, 0.6, 2 / 3, 0.75, 0.9, 0.999999, 1 - 2**-32]
    picks = [{"id": name, "weights": amounts, "units": marks, "expected": [oracle.pick(amounts, mark) for mark in marks]} for name, amounts in lists]
    decisions = []
    for index, vector in enumerate(situations()):
        keyed = {**vector, "seed": 20261002 + index, "stream": index % 5, "count": 256}
        amounts = oracle.weights(keyed)
        chosen = [ACTIVITIES[oracle.pick(amounts, oracle.unit([keyed["seed"], keyed["stream"], counter]))] for counter in range(keyed["count"])]
        decisions.append({**keyed, "expected": {"activities": chosen, "counts": {activity: chosen.count(activity) for activity in ACTIVITIES}}})
    rested = next(vector for vector in decisions if vector["id"] == "calm-rested")["expected"]["counts"]
    if not (rested["idle"] > 128 and rested["fidget"] > 0 and rested["walk"] > 0 and rested["sleep"] == 0):
        raise AssertionError("a rested pet in calm must stay idle in more than half of its decisions and still fidget and walk now and then: %r" % rested)
    dwells = [{"id": "%s-%s" % (activity, mode), "activity": activity, "mode": mode, "units": UNITS, "expected": [oracle.dwell(activity, mode, mark) for mark in UNITS]} for activity in ACTIVITIES for mode in ["still", "calm", "lively"]]
    moods = [{"id": activity, "expected": oracle.MOODS[index]} for index, activity in enumerate(ACTIVITIES)]
    sixteenths = [index / 16 + 1 / 32 for index in range(16)]
    affinities = [-1, -0.6, -0.45, -0.3, -0.29, -0.2, -0.1, 0, 0.1, 0.16, 0.3, 0.39, 0.4, 0.6, 0.8, 0.9, 1]
    encounters = []
    for affinity in affinities:
        parts = oracle.shares(affinity)
        encounters.append({"id": "affinity-%s" % label(affinity), "affinity": affinity, "units": sixteenths, "expected": {"shares": parts, "kinds": [oracle.ENCOUNTERS[oracle.pick(parts, mark)] for mark in sixteenths]}})
    graph = [{"id": "activity-graph", "expected": {"followers": oracle.FOLLOWERS, **oracle.reach(oracle.FOLLOWERS)}}]
    if graph[0]["expected"]["components"] != 1:
        raise AssertionError("the activity graph must be one strongly connected component")
    casts = []
    lineups = [("home", menagerie["casts"][0]), ("meadow", menagerie["casts"][1]), ("overlapping", {"scene": "overlapping", "core": ["mossy", "sparky", "mossy"], "rotation": ["sparky", "thorny", "pebble", "thorny", "misty"]}), ("core-only", {"scene": "core-only", "core": ["mossy", "thorny"], "rotation": []})]
    for name, lineup in lineups:
        for capacity in [0, 1, 2, 3, 4, 6]:
            for seed in [1, 20261002, 4294967295]:
                vector = {"id": "%s-capacity-%d-seed-%d" % (name, capacity, seed), "cast": lineup, "capacity": capacity, "seed": seed, "epochs": [0, 1, 2, 3, 4, 5, 1000]}
                casts.append({**vector, "expected": [oracle.cast(vector, epoch) for epoch in vector["epochs"]]})
    write(
        "🧠️behavior-choice",
        {
            "$comment": comment("🧠️behavior-choice", "numpy (cumsum, searchsorted, SeedSequence, roll) and scipy.sparse.csgraph"),
            "limits": unique(limits),
            "weights": unique(weights),
            "picks": unique(picks),
            "decisions": unique(decisions),
            "dwells": unique(dwells),
            "moods": unique(moods),
            "encounters": unique(encounters),
            "graph": unique(graph),
            "casts": unique(casts),
        },
    )



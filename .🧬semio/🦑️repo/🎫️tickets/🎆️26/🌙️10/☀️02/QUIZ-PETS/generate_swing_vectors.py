def scalar(value):
    """🔹️ Whether a value is a leaf of the document."""
    return not isinstance(value, (list, dict))


def inline(value):
    """➖️ Whether a value is written on one line: leaves, lists of leaves, and short objects and lists whose members are leaves or lists of leaves."""
    if scalar(value):
        return True
    members = value if isinstance(value, list) else list(value.values())
    if all(scalar(entry) for entry in members):
        return isinstance(value, list) or len(json.dumps(value, ensure_ascii=False)) <= 240
    return all(scalar(entry) or (isinstance(entry, (list, dict)) and all(scalar(leaf) for leaf in (entry if isinstance(entry, list) else entry.values()))) for entry in members) and len(json.dumps(value, ensure_ascii=False)) <= 240


def render(value, depth):
    """🖨️ Indented UTF-8 JSON in which every row of numbers and every point stays on one line."""
    if inline(value):
        return json.dumps(value, ensure_ascii=False, allow_nan=False)
    pad = "  " * (depth + 1)
    if isinstance(value, list):
        rows = [pad + render(entry, depth + 1) for entry in value]
        return "[\n" + ",\n".join(rows) + "\n" + "  " * depth + "]"
    rows = [pad + json.dumps(key, ensure_ascii=False) + ": " + render(entry, depth + 1) for key, entry in value.items()]
    return "{\n" + ",\n".join(rows) + "\n" + "  " * depth + "}"


def write(directory, document):
    """💾️ Writes one fixture with a trailing newline, after proving that it reads back as the same document: beside the old file first, then renamed over it, because a file a running test watcher holds cannot be truncated on Windows."""
    path = os.path.join(PETS, "🧫️fixtures", directory, "🔣️.json")
    text = render(document, 0) + "\n"
    if json.loads(text) != document:
        raise AssertionError("the rendered fixture %s does not read back as its document" % directory)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    payload = text.encode("utf-8")
    if os.path.exists(path) and open(path, "rb").read() == payload:
        print("unchanged %s" % os.path.relpath(path, ROOT))
        return
    for _ in range(20):
        try:
            with open(path + ".new", "wb") as handle:
                handle.write(payload)
            os.replace(path + ".new", path)
            break
        except OSError as error:
            print("retrying %s after %s" % (os.path.relpath(path, ROOT), error))
            time.sleep(0.5)
    else:
        raise OSError("cannot write %s" % path)
    print("wrote %s" % os.path.relpath(path, ROOT))


def comment(case, oracle):
    """🏷️ The provenance note every fixture starts with."""
    return "Generated by `%s` from %s in 🧪️tests/%s/🐍️.py — never edit by hand." % (COMMAND, oracle, case)


def unique(vectors):
    """🆔️ Refuses a list of vectors in which an id repeats."""
    seen = set()
    for vector in vectors:
        if vector["id"] in seen:
            raise AssertionError("duplicate vector id %s" % vector["id"])
        seen.add(vector["id"])
    return vectors


def point(x, y):
    """📍️ A point."""
    return {"x": x, "y": y}



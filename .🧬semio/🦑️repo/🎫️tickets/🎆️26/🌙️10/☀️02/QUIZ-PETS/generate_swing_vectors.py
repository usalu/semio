def ring(start, velocity, thrust, count):
    """🖱️ A ring of pointer samples, one per tick, oldest first: ``start + velocity·k + thrust·k²`` pixels."""
    return [point(start["x"] + velocity["x"] * tick + thrust["x"] * tick * tick, start["y"] + velocity["y"] * tick + thrust["y"] * tick * tick) for tick in range(count)]



def march(x, y, dx, dy, ticks, width=40, height=50):
    """🛤️ The boxes of a body that moves by a fixed step per tick."""
    return [[x + dx * tick, y + dy * tick, x + dx * tick + width, y + dy * tick + height] for tick in range(ticks)]



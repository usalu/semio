def render(value, depth):
    """🖨️ Indented UTF-8 JSON in which every value that fits into 150 characters stays on one line."""
    flat = json.dumps(value, ensure_ascii=False)
    if not isinstance(value, (list, dict)) or len(flat) <= 150 or not value:
        return flat
    pad = "  " * (depth + 1)
    if isinstance(value, list):
        return "[\n" + ",\n".join(pad + render(entry, depth + 1) for entry in value) + "\n" + "  " * depth + "]"
    return "{\n" + ",\n".join(pad + json.dumps(key, ensure_ascii=False) + ": " + render(entry, depth + 1) for key, entry in value.items()) + "\n" + "  " * depth + "}"


def write(document):
    """💾️ Writes the fixture with a trailing newline, after proving that it reads back as the same document."""
    path = os.path.join(PETS, "🧫️fixtures", CASE, "🔣️.json")
    text = render(document, 0) + "\n"
    if json.loads(text) != json.loads(json.dumps(document)):
        raise AssertionError("the rendered fixture does not read back as its document")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "wb") as handle:
        handle.write(text.encode("utf-8"))


def answered(name, vectors):
    """🆔️ Every vector with the answer of its reference; two vectors with one id are refused."""
    ids = [vector["id"] for vector in vectors]
    if len(set(ids)) != len(ids):
        raise AssertionError("duplicate vector ids in %s: %r" % (name, ids))
    return [dict(vector, expected=ORACLE.REFERENCES[name](vector)) for vector in vectors]



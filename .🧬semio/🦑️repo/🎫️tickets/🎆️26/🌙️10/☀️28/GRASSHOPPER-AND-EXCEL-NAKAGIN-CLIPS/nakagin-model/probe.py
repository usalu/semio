import rhino3dm as r
print(r.__version__)
p = r.Plane(r.Point3d(1, 2, 3), r.Vector3d(1, 0, 0), r.Vector3d(0, 1, 0))
print(p.Origin, p.XAxis, p.YAxis, p.ZAxis)
t = r.Transform.PlaneToPlane(r.Plane.WorldXY(), p)
print(t.TransformPoint if hasattr(t, "TransformPoint") else dir(t))
pt = r.Point3d(1, 1, 1)
pt.Transform(t)
print(pt)
b = r.Box(r.BoundingBox(0, 0, 0, 1, 2, 3))
print(b.Volume, b.Area if hasattr(b, "Area") else "")
print([n for n in dir(r.Plane) if not n.startswith("_")])

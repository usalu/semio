const fs = require("fs");
const assert = require("node:assert/strict");
const path = require("path");
const root = process.cwd();
const ticket = __dirname;
const fixture = JSON.parse(fs.readFileSync(path.join(ticket, "ledger-geometry.case.json"), "utf8"));
const source = fs.readFileSync(path.join(root, "🧰️framework/🛍️products/📓️print/🧾️template/📝️assignment/parametrization-geometry.tex"), "utf8");
assert.match(source, /\\newcommand\{\\AssignmentLedgerEntry\}\[3\]/);
assert.match(source, /\\newcommand\{\\AssignmentBlankLedgerEntry\}\[2\]/);
assert.match(source, /\\newcommand\{\\AssignmentLedger\}\[2\]/);
assert.match(source, /\\AssignmentLedger\{10\}\{\\AssignmentSelectedEdges\{\\AssignmentBlankLedgerEntry\}\}/);
assert.match(source, /\\newcommand\{\\AssignmentWorkedExampleLedger\}\[6\]/);
assert.match(source, /\\AssignmentLedger\{3\}/);
const worked = source.slice(source.indexOf("\\newcommand{\\AssignmentWorkedExampleLedger}"), source.indexOf("\\newcommand{\\AssignmentBox}"));
const entries = [...worked.matchAll(/\\AssignmentLedgerEntry\{(\d+)\}\{(\d+)\}\{#(\d)\}/g)].map(match => match.slice(1).map(Number));
assert.deepEqual(entries.map(entry => entry[2]), fixture.ledger.exampleArgumentOrder);
assert.deepEqual(entries.map(([from,to]) => [from,to]), [[1,2],[2,3],[3,1],[2,1],[3,2],[1,3]]);
assert.match(source, /\\newcommand\{\\AssignmentWorkedExampleGraphPicture\}\{/);
assert.match(source, /\\newcommand\{\\AssignmentWorkedExampleGraph\}\{/);
assert.doesNotMatch(source, /\\newcommand\{\\AssignmentWorkedExampleGraphEdge\}/);
const picture = source.slice(source.indexOf("\\newcommand{\\AssignmentWorkedExampleGraphPicture}"), source.indexOf("\\newcommand{\\AssignmentWorkedExampleGraph}"));
const edges = [...picture.matchAll(/\\AssignmentSelectedGraphEdge\{(\d)\}\{(\d)\}/g)].map(match => match.slice(1).map(Number));
assert.deepEqual(edges, fixture.graph.directedEdges);
assert.equal((picture.match(/\\AssignmentWorkedExampleGraphVertex/g)||[]).length, fixture.graph.vertexCount);
assert.equal((picture.match(/node\[/g)||[]).length, fixture.graph.captionCount);
assert.match(source, /\\AssignmentGraphRadiusY=32mm/);
assert.equal(fixture.ledger.columnWidthMm*(fixture.ledger.ruleEnd-fixture.ledger.ruleStart),64.6);
assert.match(source, /\\fontsize\{9\}\{10\}\\selectfont/);
assert.match(source, /parameter-rows=8,header-height=16mm/);
process.stdout.write("[DEBUG] Shared ledger fixture and geometry contracts passed.\n");

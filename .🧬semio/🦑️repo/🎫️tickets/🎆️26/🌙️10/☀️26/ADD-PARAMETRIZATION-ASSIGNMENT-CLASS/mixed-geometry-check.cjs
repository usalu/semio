const fs = require("node:fs");
const path = require("node:path");
const assert = require("node:assert/strict");
const fixture = JSON.parse(fs.readFileSync(path.join(__dirname, "mixed-example.json"), "utf8"));
const geometry = fs.readFileSync("🧰️framework/🛍️products/📓️print/🧾️template/📝️assignment/parametrization-geometry.tex", "utf8");
for (const macro of ["AssignmentWorkedExampleTable", "AssignmentWorkedExampleGraph", "AssignmentWorkedExampleLedger", "AssignmentPyramid", "AssignmentEllipticalCylinder"]) assert.ok(geometry.includes("\\newcommand{\\" + macro + "}"), macro);
assert.ok(!geometry.includes("AssignmentWorkedBox"));
assert.ok(geometry.includes("type-columns=3,parameter-rows=4"));
for (const [index, parameter] of ["L", "B", "H"].entries()) assert.ok(geometry.includes("\\AssignmentParameterMatrixRow{#" + (index + 1) + "}{" + fixture.map(shape => shape[parameter]).join(",") + "}"));
assert.ok(geometry.includes("\\AssignmentParameterMatrixRow{#4}{#5,#6,#7}"));
for (const shape of fixture) assert.ok(geometry.includes("\\" + shape.macro + "{" + shape.L + "}{" + shape.B + "}{" + shape.H + "}"));
assert.ok(geometry.includes("\\AssignmentGraphRadiusY=32mm"));
assert.ok(geometry.includes("\\AssignmentSelectedEdges{\\AssignmentSelectedGraphEdge}"));
assert.ok(geometry.includes("\\AssignmentTypesOne{\\AssignmentGraphVertex}"));
assert.ok(geometry.includes("\\AssignmentTypesTwo{\\AssignmentGraphVertex}"));
assert.ok(geometry.includes("\\AssignmentWorkedExampleLedgerEntry{0}{1}{2}{#1}"));
assert.ok(geometry.includes("\\AssignmentWorkedExampleLedgerEntry{1}{2}{3}{#2}"));
assert.ok(geometry.includes("\\AssignmentWorkedExampleLedgerEntry{2}{1}{3}{#3}"));
console.log("Mixed geometry source contracts passed.");

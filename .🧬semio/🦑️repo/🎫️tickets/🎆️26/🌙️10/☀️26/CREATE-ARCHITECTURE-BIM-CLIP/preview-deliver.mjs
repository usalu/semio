import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import {fileURLToPath} from "node:url";
const ticket=path.dirname(fileURLToPath(import.meta.url)),root=process.cwd();
const work=path.join(ticket,"🗑️generated","preview");
const result=JSON.parse(fs.readFileSync(path.join(work,"verification.json"),"utf8"));
const origin=path.resolve(result.path);
if(!origin.startsWith(work+path.sep)||!fs.statSync(origin).isFile())throw Error("Unexpected preview input");
const target=path.resolve(root,".🧬semio/🎓️teaching/⚡️cache/bim-preview/de/speaker/BIM_information.mp4");
if(target.length>256)throw Error("Preview path too long");
fs.mkdirSync(path.dirname(target),{recursive:true});
fs.copyFileSync(origin,target);
const hash=f=>crypto.createHash("sha256").update(fs.readFileSync(f)).digest("hex");
if(hash(origin)!==hash(target))throw Error("Preview copy changed bytes");
const url=target.replaceAll(path.sep,"/");
const report="\n## Verified Playback Deliverable\n\n["+path.basename(target)+"]("+url+")\n\nThe canonical renderer exited successfully. PyAV decoded every frame: "+result.frames+" frames at "+result.fps+" fps, "+result.width+" × "+result.height+", "+result.duration.toFixed(3)+" seconds, "+result.bytes+" bytes. The delivered copy has the same SHA-256 as the verified render. No prerecorded narration has been supplied. The final MP4 is retained for the explicitly requested playback; temporary media and logs are removed from this ticket.\n";
fs.appendFileSync(path.join(ticket,"preview.md"),report);
fs.appendFileSync(path.join(ticket,"summary.md"),"\n## Requested Playback Preview\n\nA 720p/24 fps German Speaker preview of the first video is now retained for playback. [Play video]("+url+"). [Verification](preview.md).\n");
console.log("[DEBUG] Verified delivery: "+url);

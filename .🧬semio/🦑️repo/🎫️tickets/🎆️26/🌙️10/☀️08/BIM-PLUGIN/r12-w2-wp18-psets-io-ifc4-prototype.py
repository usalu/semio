import sys
import ifcopenshell
import ifcopenshell.validate

f = ifcopenshell.file(schema="IFC4")
c = f.create_entity
person = c("IfcPerson", None, "a", None, None, None, None, None, None)
org = c("IfcOrganization", None, "o", None, None, None)
pao = c("IfcPersonAndOrganization", person, org, None)
app = c("IfcApplication", org, "1", "semio BIM", "semio.bim")
owner = c("IfcOwnerHistory", pao, app, None, "ADDED", None, None, None, 0)
origin = c("IfcAxis2Placement3D", c("IfcCartesianPoint", (0.0, 0.0, 0.0)), None, None)
ctx = c("IfcGeometricRepresentationContext", None, "Model", 3, 1e-6, origin, c("IfcDirection", (0.0, 1.0)))
units = c("IfcUnitAssignment", [c("IfcSIUnit", None, "LENGTHUNIT", None, "METRE")])
project = c("IfcProject", "0" * 21 + "1", owner, "P", None, None, None, None, [ctx], units)
library = c("IfcProjectLibrary", "0" * 21 + "2", owner, "P Library", None, None, None, None, [ctx], units)
simple_single = c("IfcSimplePropertyTemplate", "0" * 21 + "3", owner, "FireRating", "description=Rating;required=true;", "P_SINGLEVALUE", "IfcLabel", None, None, None, None, None, None)
enum = c("IfcPropertyEnumeration", "Class", [c("IfcLabel", "A"), c("IfcLabel", "B")], None)
simple_enum = c("IfcSimplePropertyTemplate", "0" * 21 + "4", owner, "Class", None, "P_ENUMERATEDVALUE", "IfcLabel", None, enum, None, None, None, None)
simple_real = c("IfcSimplePropertyTemplate", "0" * 21 + "5", owner, "U", "minimum=0;", "P_SINGLEVALUE", "IfcReal", None, None, None, None, None, None)
template = c("IfcPropertySetTemplate", "0" * 21 + "6", owner, "Pset_X", None, "PSET_OCCURRENCEDRIVEN", "IfcWall,IfcSlab", [simple_single, simple_enum, simple_real])
typed = c("IfcPropertySetTemplate", "0" * 21 + "7", owner, "Pset_T", None, "PSET_TYPEDRIVENONLY", "IfcWallType", [simple_single])
mixed = c("IfcPropertySetTemplate", "0" * 21 + "8", owner, "Pset_M", None, "PSET_TYPEDRIVENOVERRIDE", "IfcWall,IfcWallType", [simple_single])
c("IfcRelDeclares", "0" * 21 + "9", owner, None, None, project, [library])
c("IfcRelDeclares", "0" * 21 + "A", owner, None, None, library, [template, typed, mixed])
system = c("IfcClassification", "Src", "2015", None, "Uniclass", None, None, None)
r1 = c("IfcClassificationReference", None, "EF", "Walls", system, None, None)
r2 = c("IfcClassificationReference", None, "EF_25", "Sub", r1, None, None)
c("IfcRelAssociatesClassification", "0" * 21 + "B", owner, None, None, [library], system)
log = ifcopenshell.validate.json_logger()
ifcopenshell.validate.validate(f, log, express_rules=True)
print(len(log.statements), [s["message"] for s in log.statements][:20])
open(sys.argv[1], "w", encoding="utf-8").write(f.to_string())
print(f.to_string()[-1800:])

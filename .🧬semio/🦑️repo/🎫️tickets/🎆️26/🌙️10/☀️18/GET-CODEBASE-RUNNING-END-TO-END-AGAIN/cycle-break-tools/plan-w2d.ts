/** 🎫️ W2d: the local-session broker client is a dev-server client; it moves to os-dev so the OS core stops depending on os-dev at runtime. */
import { Plan } from "./plan.ts";
import { planMoves } from "./moves.ts";
import { finish } from "./direct.ts";
import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import { ROOT, model } from "./lib.ts";
const W = "w2d-broker-client";
const OS = "🧰️framework/🛍️products/💻️os";
const B = `${OS}/🔨️modules/📇️directory/🎫️local-session/🗄️broker`;
const DEV = `${OS}/🔨️modules/🧑‍💻dev/🚀️local-hub/🎫️session`;
const plan = new Plan();
planMoves(plan, W, "the broker client belongs to the dev server that talks to the hub", [{ from: `${B}/🟦️.ts`, to: `${DEV}/🗄️broker/🟦️.ts` }]);
plan.edits = plan.edits.filter(e => !(e.file === `${B}/🟦️.ts`));
const f = `${B}/🟦️.ts`;
plan.edit({ file: f, from: "@semio-tech/framework-os-dev/local-hub/session/io", to: "../📥️io/🟦️.ts", mode: "specifier", wave: W, why: "same package after the move" });
plan.edit({ file: f, from: "@semio-tech/framework-os-dev/local-hub/session/data", to: "../📋️data/🟦️.ts", mode: "specifier", wave: W, why: "same package after the move" });
plan.edit({ file: f, from: "./🧬️schema/🟦️.ts", to: "@semio-tech/framework-os/modules/directory/local-session/broker/schema", mode: "specifier", wave: W, why: "the protocol schema stays with the OS core" });
const routing = readFileSync(resolve(ROOT, f), "utf8").match(/"([^"]*🧭️routing\/🟦️\.ts)"/u)?.[1];
if (!routing) throw Error("routing import not found");
plan.edit({ file: f, from: routing, to: "@semio-tech/process/routing", mode: "specifier", wave: W, why: "bare key of the process package" });
plan.edit({ file: `${DEV}/🟦️.ts`, from: "@semio-tech/framework-os/modules/directory/local-session/broker", to: "./🗄️broker/🟦️.ts", mode: "specifier", wave: W, why: "the client is a module of the dev session now" });
const os = model.byName.get("@semio-tech/framework-os")!;
const dev = model.byName.get("@semio-tech/framework-os-dev")!;
const rm = (p: typeof os, key: string): void => { const value = p.exports[key] as string | undefined; if (value) { plan.manifest({ op: "remove", packageJson: p.packageJson, package: p.name, field: "exports", key, value, wave: W, why: "the key moved with the module" }); plan.del(`${p.dir}/${value.slice(2)}`, W, "dead glue"); } };
rm(os, "./modules/directory/local-session/broker");
rm(dev, "./local-hub/session/data");
rm(dev, "./local-hub/session/io");
plan.manifest({ op: "remove", packageJson: os.packageJson, package: os.name, field: "dependencies", key: "@semio-tech/framework-os-dev", value: os.deps["@semio-tech/framework-os-dev"] ?? "workspace:*", wave: W, why: "the OS core no longer imports os-dev at runtime" });
plan.manifest({ op: "add", packageJson: os.packageJson, package: os.name, field: "devDependencies", key: "@semio-tech/framework-os-dev", value: "workspace:*", wave: W, why: "renderer and directory tests drive the dev host" });
finish(plan, "w2d", process.argv);

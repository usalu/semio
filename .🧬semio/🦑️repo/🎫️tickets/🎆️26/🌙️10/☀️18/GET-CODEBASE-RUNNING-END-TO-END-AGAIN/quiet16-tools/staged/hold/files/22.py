"""🤫️ Independent Python oracle of how a forecast-aware run is learned once the quiet forecast holds: a run executed work when an executor of the run asked for it or when its peak exceeded the quiet size the forecast named before it started (the quiet reservation, which the holder grows past), else it was quiet; the next forecast follows the run's own last outcome through the forecast port of the upgrade oracle (decayed quiet and busy weights, the follow-up window, the quiet size from the quiet class's own peaks). Writes the replay sequences of `../🧫️fixtures/🔣️.json`; `--check` exits 1 when the stored fixture differs.
usage: python3 -I 🐍️.py [--check]"""
import copy,importlib.util,json,os,random,sys

HERE=os.path.dirname(os.path.abspath(__file__))
TARGET=os.path.join(HERE,"..","🧫️fixtures","🔣️.json")
POLICY=os.path.join(HERE,"..","..","..","..","🔣️policy.json")
UPGRADE=os.path.join(HERE,*[".."]*9,"🔨️modules","🏃️process","🏗️build","🌡️host-capacity","🧪️tests","🔼️upgrade","🐍️oracle","🐍️.py")
LEAF="run:build:@x/y:build"
START=1_900_000_000_000

def load(path,name):
    spec=importlib.util.spec_from_file_location(name,path);module=importlib.util.module_from_spec(spec);spec.loader.exec_module(module);return module
UP=load(UPGRADE,"upgrade_oracle")
EST=UP.load_estimates()

def run_row(executed,peak,ended):return {"executed":executed,"peakMegabytes":peak,"activeMilliseconds":0,"peakAtMilliseconds":0,"endedAtMs":ended}

def seeded(policy,peaks,last):
    store={"version":1,"classes":{}}
    for index,(executed,peak) in enumerate(peaks):store=UP.record_forecast(policy,EST,store,LEAF,run_row(executed,peak,last-(len(peaks)-1-index)*600_000))
    return store

def replay(policy,name,store,start,steps):
    rows=[];now=start
    for gap,asked,peak in steps:
        now+=gap;before=UP.forecast(policy,EST,store,LEAF,now)
        executed=asked or peak>before["megabytes"]
        rows.append({"nowMs":now,"asked":asked,"peakMegabytes":peak,"expect":{"forecast":before,"executed":executed}})
        store=UP.record_forecast(policy,EST,store,LEAF,run_row(executed,peak,now))
    return {"name":name,"store":copy.deepcopy(seed_of[name]),"steps":rows,"after":{"nowMs":now+60_000,"forecast":UP.forecast(policy,EST,store,LEAF,now+60_000)}}

seed_of={}
def generate():
    policy=json.load(open(POLICY,encoding="utf8"))["hostCapacity"];rng=random.Random(1627);sequences=[]
    live=[(True,500),(True,1587),(True,511),(True,608),(True,2019),(True,2947),(True,1629),(True,500)]
    stories=[
     ("live store of 14:50 (every run learned busy), then hot no-ops of 500 MB a minute apart",seeded(policy,live,START-120_000),[(60_000,False,500)]*6),
     ("live store, a course edit that outgrows the quiet size between no-ops",seeded(policy,live,START-120_000),[(60_000,False,520),(30_000,False,3409),(20_000,False,544),(60_000,False,517),(60_000,False,552)]),
     ("live store, a refresh whose executor asks, then no-ops after a long pause",seeded(policy,live,START-120_000),[(60_000,True,2156),(30_000,False,511),(2_400_000,False,511),(60_000,False,505),(3_600_000,False,498)]),
     ("an empty store: the first run of a class",{"version":1,"classes":{}},[(0,False,480),(60_000,False,470),(60_000,False,490)]),
    ]
    for name,store,steps in stories:seed_of[name]=store;sequences.append(replay(policy,name,store,START,steps))
    for index in range(10):
        name=f"random {index+1}";history=[(rng.random()<rng.choice([0.0,0.3,0.9]),rng.choice([300,480,700,1500,2800,4200])) for _ in range(rng.choice([0,0,2,5,9]))]
        store=seeded(policy,history,START-rng.choice([5_000,600_000,4_000_000])) if history else {"version":1,"classes":{}}
        steps=[(rng.choice([5_000,60_000,600_000,1_900_000,8_000_000]),rng.random()<0.25,rng.choice([300,480,700,1100,1500,2600,4200,9000])) for _ in range(rng.choice([4,6,8]))]
        seed_of[name]=store;sequences.append(replay(policy,name,store,START,steps))
    steps=[step for sequence in sequences for step in sequence["steps"]]
    coverage={"askedBusy":sum(1 for step in steps if step["asked"]),"outgrownBusy":sum(1 for step in steps if not step["asked"] and step["expect"]["executed"]),"quiet":sum(1 for step in steps if not step["expect"]["executed"]),"forecastQuiet":sum(1 for step in steps if step["expect"]["forecast"]["quiet"]),"forecastFull":sum(1 for step in steps if not step["expect"]["forecast"]["quiet"]),"followUp":sum(1 for step in steps if "followUpMilliseconds" in step["expect"]["forecast"]),"history":sum(1 for step in steps if step["expect"]["forecast"]["quiet"] and "followUpMilliseconds" not in step["expect"]["forecast"])}
    return {"version":1,"about":"Generated by 🐍️oracle/🐍️.py from the library build policy and the forecast port of the framework upgrade oracle; do not edit.","leaf":LEAF,"sequences":sequences,"coverage":coverage}

def dump(value):return json.dumps(value,ensure_ascii=False,indent=1)+"\n"

if __name__=="__main__":
    text=dump(generate())
    if "--check" in sys.argv:
        stored=open(TARGET,encoding="utf8").read()

"""Rebuilds plan.json from the live tree in one go: overlay copy (never symlinks) -> hand plan -> relative-import plan -> help snapshot -> merged plan; usage: rebuild.py [--root LIVE] [--overlay DIR] [--keep]. Stdlib only; spawns bun for the planners."""
import argparse, json, os, shutil, subprocess, sys
here = os.path.dirname(os.path.abspath(__file__))
parser = argparse.ArgumentParser()
parser.add_argument("--root", default=os.getcwd())
parser.add_argument("--overlay", default=os.path.join(os.path.realpath(os.environ.get("TMPDIR", "/tmp")), "cli-zt", "plan"))
parser.add_argument("--keep", action="store_true")
args = parser.parse_args()
root, overlay = os.path.abspath(args.root), os.path.abspath(args.overlay)
out = os.path.join(here, "plan.json")
scratch = os.path.join(here, "plan-scratch")
os.makedirs(scratch, exist_ok=True)
run = lambda *cmd: subprocess.run(list(cmd), check=True, cwd=root)
shutil.rmtree(overlay, ignore_errors=True)
os.makedirs(overlay)
L = "🧰️framework/🛍️products/🦑️repo/🔨️modules/📚️library"
run(sys.executable, os.path.join(here, "make-overlay.py"), root, overlay, "🧰️framework", "🧪️tests/🧭️entrypoint", ".storybook")
hand, rel, snapshot = (os.path.join(scratch, name) for name in ("hand.json", "rel.json", "help-snapshot.json"))
run(sys.executable, os.path.join(here, "build-plan.py"), "--root", root, "--out", hand)
run(sys.executable, os.path.join(here, "apply.py"), "--root", overlay, "--plan", hand, "--apply", "--ignore-running")
run("bun", os.path.join(here, "rel-plan.ts"), overlay, os.path.join(here, "entries2.json"), rel)
run("bun", os.path.join(here, "snap-help.ts"), overlay, snapshot)
run(sys.executable, os.path.join(here, "merge-plan.py"), hand, rel, out, "--root", root, f"{L}/🏗️build/⚙️operations/🧪️tests/🧫️fixtures/📖️help/🔣️.json={snapshot}")
if not args.keep: shutil.rmtree(overlay, ignore_errors=True)
shutil.rmtree(scratch, ignore_errors=True)

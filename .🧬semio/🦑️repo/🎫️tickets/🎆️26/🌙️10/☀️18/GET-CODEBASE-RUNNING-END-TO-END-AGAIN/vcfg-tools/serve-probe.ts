import { mkdtempSync, mkdirSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { createFrameworkOsDevConfig } from "../../../../../../../../🧰️framework/🛍️products/💻️os/🔨️modules/🧑‍💻dev/🏗️builder/🌐️vite/🟦️.ts";
import { nextActivationReceipt, publishActivationReceipt } from "../../../../../../../../🧰️framework/🛍️products/💻️os/🔨️modules/🧑‍💻dev/♻️activation/🟦️.ts";
import { specificOsDevBuildInventoryV1 } from "../../../../../../../../✏️s/🧑‍💻dev/🧩️catalog/📦️packages/🟦️typescript/🏗️builder/🟦️.ts";
const root = mkdtempSync(join(tmpdir(), "vcfg-"));
const activationRoot = join(root, "activation"), moduleRoot = join(root, "modules"), extensionsRoot = join(root, "extensions");
for (const d of [activationRoot, moduleRoot, extensionsRoot]) mkdirSync(d, { recursive: true });
publishActivationReceipt(activationRoot, nextActivationReceipt("draw", "prototype", [], undefined));
const inventory = { ...specificOsDevBuildInventoryV1(), browserHost: () => ({ moduleRoot, activationRoot, extensionsRoot }) };
const factory = createFrameworkOsDevConfig({ inventory, brands: [], browserSessionFactories: [], browserEntry: "/probe/🟦️.ts" });
const config = await factory({ command: "serve", mode: "prototype" } as never);
const flat = (config.plugins ?? []).flat(Infinity) as { name: string; configureServer?: (s: unknown) => unknown; closeBundle?: () => void }[];
console.log("[DEBUG] serve plugins", flat.length, flat.map((p) => p.name).filter((n) => /activation|extension|freshness/.test(n)).join(","));
const activation = flat.find((p) => p.name === "semio-activation")!;
const listeners: Record<string, (() => void)[]> = {};
const server = { middlewares: { use() {} }, httpServer: { listening: false, once: (e: string, l: () => void) => { (listeners[e] ??= []).push(l); }, on() {} }, ws: { send() {} } };
const t0 = Date.now();
const result = await activation.configureServer!(server);
console.log("[DEBUG] configureServer resolved", result, "ms", Date.now() - t0, "listeners", Object.keys(listeners).join(","));
activation.closeBundle!();
console.log("[DEBUG] closeBundle ok");
process.exit(0);

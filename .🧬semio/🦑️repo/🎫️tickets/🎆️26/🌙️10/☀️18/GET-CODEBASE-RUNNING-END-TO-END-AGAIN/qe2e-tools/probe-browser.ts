import { createRequire } from "node:module";
import { realpathSync } from "node:fs";
import { serveStaticSite } from "../../../../../../../../🎓️teaching/🏛️architecture/❓️quiz/🧱️stack/🟦️.ts";
const root = process.env.SEMIO_REPO_ROOT!;
const require = createRequire(realpathSync(root + "/node_modules/playwright/cli.js"));
const { chromium } = require("playwright-core");
const served = await serveStaticSite(process.env.PROBE_DIR!, 6162);
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const logs: string[] = [];
page.on("console", (m: any) => logs.push(m.type() + ": " + m.text().slice(0, 200)));
page.on("pageerror", (e: any) => logs.push("pageerror: " + String(e).slice(0, 300)));
await page.goto(served.origin, { waitUntil: "load", timeout: 60000 });
await page.waitForTimeout(4000);
console.log("[DEBUG] title", await page.title());
console.log("[DEBUG] text", (await page.locator("body").innerText()).slice(0, 400).replaceAll("\n", " | "));
console.log("[DEBUG] logs", JSON.stringify(logs.slice(0, 8)));
await page.screenshot({ path: process.env.PROBE_SHOT! });
await browser.close();
await served.close();

#!/usr/bin/env python3
"""Regenerates the verdict table of result-plugc-d.md between the markers <!--T--> and <!--/T--> from verdicts3.tsv (+ notes.tsv: group TAB note)."""
import os
os.chdir("/Users/ueli/Documents/semio")
C=".🧬semio/🦑️repo/🎫️tickets/🎆️26/🌙️10/☀️18/GET-CODEBASE-RUNNING-END-TO-END-AGAIN"
V=C+"/🗑️generated/plugc-d/verdicts3.tsv"; N=C+"/plugc-d-tools/notes.tsv"; R=C+"/result-plugc-d.md"
notes={}
if os.path.exists(N):
    for l in open(N):
        k,_,v=l.rstrip("\n").partition("\t"); notes[k]=v
rows=[]
last={}
for l in open(V):
    f=l.rstrip("\n").split("\t")
    if len(f)<6: continue
    last[f[0]]=f
for k,f in last.items():
    rows.append("| %s | %s | %s | %s | %s | %s |"%(k,f[1].replace("semio-s-artifact-","").replace(",",", "),f[2].split("=")[1],f[3].split("=")[1],f[4].split("=")[1],notes.get(k,"")))
tbl="<!--T-->\n| group | packages | passed | failed | compile errors | note |\n|---|---|---|---|---|---|\n"+"\n".join(rows)+"\n<!--/T-->"
t=open(R).read()
if "<!--T-->" in t:
    a=t.index("<!--T-->"); b=t.index("<!--/T-->")+len("<!--/T-->")
    t=t[:a]+tbl+t[b:]
else:
    t=t.rstrip("\n")+"\n\n## Verdict table (generated by plugc-d-tools/table.py)\n"+tbl+"\n"
open(R,"w").write(t)

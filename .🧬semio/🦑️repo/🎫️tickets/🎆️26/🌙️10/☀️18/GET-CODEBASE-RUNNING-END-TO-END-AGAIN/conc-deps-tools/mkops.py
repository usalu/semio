def exact(key, old):
    found = text(key).count(old)
    if found != 1:
        raise SystemExit("anchor of the operation must occur once, found %d in %s:\n%s" % (found, key, old[:240]))
    return old


def between(key, start, end):
    body = text(key)
    if body.count(start) != 1:
        raise SystemExit("start marker must occur once in %s: %s" % (key, start[:160]))
    first = body.index(start)
    last = body.index(end, first) + len(end)
    return exact(key, body[first:last])


def line(key, prefix):
    body = text(key)
    if body.count(prefix) != 1:
        raise SystemExit("line prefix must occur once in %s: %s" % (key, prefix[:160]))
    first = body.index(prefix)
    return exact(key, body[first:body.index("\n", first)])


def operation(identifier, key, old, new, marker):
    exact(key, old)
    OPERATIONS.append({"id": identifier, "target": key, "marker": marker, "old": old, "new": new, "group": GROUP})



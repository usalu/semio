#!/usr/bin/env python3
# Writes C/result-lawcov-cli.md and staged/tests-manifest.json from the current filesystem state.
import json, os, re, time
ROOT = "/Users/ueli/Documents/semio"
HERE = os.path.dirname(os.path.abspath(__file__))
C = os.path.dirname(HERE)
sel = json.load(open(os.path.join(HERE, "units-sel.json")))
LIB = [os.path.join(ROOT, e) for e in os.listdir(ROOT) if e.replace("\ufe0f", "") == "🧰framework"][0]
for part in ["🛍products", "🦑repo", "🔨modules", "📚library"]:
    LIB = [os.path.join(LIB, e) for e in os.listdir(LIB) if e.replace("\ufe0f", "") == part][0]
os.chdir(LIB)
now = time.time()
rows, manifest = [], []
third = re.compile(r'from "((?:@[^/"]+/)?[^./"][^"]*)"')
core = {"bun:test", "ajv"}
for u in sel:
    d = u["dir"]
    t = os.path.join(d, "🧪️tests")
    f = os.path.join(t, "🔣️.json")
    s = os.path.join(t, "🧬️schema", "🔣️.json")
    ts = os.path.join(t, "🟦️.ts")
    if not (os.path.exists(f) and os.path.exists(s) and os.path.exists(ts) and now - os.path.getmtime(ts) < 12 * 3600):
        continue
    text = open(ts, encoding="utf8").read()
    imports = sorted({m for m in third.findall(text) if not m.startswith(("node:", "bun:")) and m not in ("ajv",)})
    py = os.path.exists(os.path.join(t, "🐍️oracle.py"))
    oracle = ", ".join(imports + (["python"] if py else []))
    tests = len(re.findall(r"\btest(?:\.failing)?\(", text))
    failing = len(re.findall(r"\btest\.failing\(", text))
    rows.append((u["lines"], u["unit"].replace("️", ""), u["cls"], tests, failing, oracle))
    manifest.append(os.path.relpath(os.path.abspath(ts), ROOT))
rows.sort(reverse=True)
json.dump(sorted(manifest), open(os.path.join(HERE, "staged", "tests-manifest.json"), "w", encoding="utf8"), ensure_ascii=False, indent=1)
tot = sum(r[0] for r in rows)
scope = sum(u["lines"] for u in sel)
out = ["# result-lawcov-cli", "", "Executor lawcov-cli, wave 1021a, ticket GET-CODEBASE-RUNNING-END-TO-END-AGAIN. Generated by `lawcov-cli-tools/report.py`.", "",
       "READY: %d units have their own `🧪️tests/` (corpus + closing schema + TS test over the real code + independent oracle); registries, production and taxonomy untouched (see Staged)." % len(rows), "",
       "## Coverage", "", "- Scope units (1-NOTEST + 2-NOCORPUS, excluding ⚖️laws, 🏗️build, ⚡️caching): %d units, %d production lines." % (len(sel), scope),
       "- Done: %d units, %d production lines (%.1f%% of scope lines)." % (len(rows), tot, 100.0 * tot / scope),
       "- Every unit: `🧪️tests/🔣️.json` corpus (language-agnostic), `🧪️tests/🧬️schema/🔣️.json` closing it (ajv strict), `🧪️tests/🟦️.ts` running the real code, and an oracle: a third-party library (ajv, typescript API, minimatch, @iarna/toml, protobufjs, graphql, web-tree-sitter + tree-sitter-rust, graphlib, fast-json-patch, resolve.exports, git CLI) and/or an independent `🐍️oracle.py` (stdlib only).",
       "- Real defects are encoded as `test.failing` witnesses with the corpus holding the true expectation (they flip red when the defect is fixed); none was weakened.", "",
       "## Units (production lines, class before, tests, of which defect witnesses, oracle)", "", "| lines | unit | was | tests | defects | oracle |", "|---:|---|---|---:|---:|---|"]
for r in rows:
    out.append("| %d | `%s` | %s | %d | %d | %s |" % r)
out += ["", "## Findings (file:line, each has a test.failing witness unless noted)", ""]
out += open(os.path.join(HERE, "findings.md"), encoding="utf8").read().split("\n")[1:]
out += ["", "## Not done / risks", "",
        "- The remaining %d scope units (%d lines) are untouched; the largest are the Rust-source codemods of 🏗️authoring/📦️crate-tree (mutation-families, sandbox, testkit, unmirror, render, test-closure, verify), 🎛️commands/✅️verify lanes and gates, 🗄️stdio-ledger, 🔮️oracles, 🏃️process, the library root nx plugin and 🧩 root, 📦️packages re-export stubs (2-3 lines each, nothing to test)." % (len(sel) - len(rows), scope - tot),
        "- Weak oracles: 🧼️workspace-cleanup/🗑️removal (invariant model only), 🎛️commands/📝️commit/📈️attribution (git + own sums), the `🐍️oracle.py` of units whose logic is a thin regex wrapper re-implements the same regex in Python (independent engine, not independent algorithm).",
        "- Git-backed tests build scratch repositories in the OS temp directory; each captured git call in the library goes through a `bun -e` child (see PERF finding), so the attribution suite needs ~55 s under load. `setDefaultTimeout(120000)` is set in every generated test file.",
        "- Run each file with `bun test ./<path>` (a path without `./` makes bun scan the whole checkout as a filter: 7M files, 80 s). Paths are listed in `lawcov-cli-tools/staged/tests-manifest.json`.", "",
        "## Staged", "", "- `lawcov-cli-tools/staged/tests-manifest.json`: every new test file (repo-relative). `lawcov-cli-tools/staged/apply.py` verifies the manifest (dry-run default) and has nothing to write: no registry, project.json, taxonomy or production file was edited. integrate2 may wire the manifest into whichever test target should own it.",
        "- Generators: `lawcov-cli-tools/gen/u*.py` (re-runnable, deterministic; `lib.py` scaffolds the files), `spec_metrics.py`, `pyemoji.py`.", ""]
open(os.path.join(C, "result-lawcov-cli.md"), "w", encoding="utf8").write("\n".join(out))
print(len(rows), tot, scope)

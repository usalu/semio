#!/usr/bin/env python3
"""Monolith census 8 at HEAD: hand-authored source files over 1,000 lines, census-7 comparison, bulk-commit touch, owners, paths over 256 chars."""
import json, os, re, subprocess, sys
from collections import defaultdict

ROOT = "/Users/ueli/Documents/semio"
HERE = os.path.dirname(os.path.abspath(__file__))
EXT = (".rs", ".ts", ".tsx", ".cjs", ".mjs", ".js", ".py", ".cs", ".wit", ".go")
C7_COMMIT = "4dab415ed905e2287ad0b651448171c619cbb1c7"
BULK = ["8f91299152c", "bd9e4e02bd0"]
GEN_RE = re.compile(r"@generated|DO NOT EDIT|auto-generated|GENERATED FILE|generated by", re.I)


def git(*args):
    return subprocess.run(["git", "-C", ROOT, *args], capture_output=True, check=True).stdout


def ls_tree(rev):
    out = git("ls-tree", "-r", "-z", "--full-tree", rev)
    res = {}
    for rec in out.split(b"\0"):
        if not rec:
            continue
        meta, path = rec.split(b"\t", 1)
        mode, typ, sha = meta.decode().split()
        if typ != "blob" or mode == "120000":
            continue
        res[path.decode("utf-8")] = sha
    return res


def excluded(path):
    segs = path.split("/")
    if path.startswith(".🧬semio/"):
        return "semio"
    if any(s in ("node_modules", "dist", "target") for s in segs):
        return "build-dir"
    if any("🤖" in s and s.endswith("generated") for s in segs):
        return "generated-dir"
    if any("🪞" in s and "vendor" in s for s in segs) or any("♻" in s and "mit-bestand" in s for s in segs):
        return "vendored-dir"
    if ".storybook" in segs:
        return "storybook"
    if any(s.startswith("extension-host-build-") for s in segs):
        return "ext-host-build"
    if path.endswith(".d.ts"):
        return "dts"
    return None


class Blobs:
    def __init__(self):
        self.p = subprocess.Popen(["git", "-C", ROOT, "cat-file", "--batch"], stdin=subprocess.PIPE, stdout=subprocess.PIPE)

    def get(self, sha):
        self.p.stdin.write((sha + "\n").encode())
        self.p.stdin.flush()
        header = self.p.stdout.readline().decode().split()
        size = int(header[2])
        data = self.p.stdout.read(size)
        self.p.stdout.read(1)
        return data

    def close(self):
        self.p.stdin.close()
        self.p.wait()


def main():
    head = ls_tree("HEAD")
    c7 = ls_tree(C7_COMMIT)
    owners = json.load(open(os.path.join(ROOT, "📋️build-owners.json"), encoding="utf-8"))["owners"]
    owner_roots = sorted(((o["root"].rstrip("/") + "/", o["name"]) for o in owners if o["root"]), key=lambda t: -len(t[0]))

    def owner_of(path):
        for root, name in owner_roots:
            if path.startswith(root):
                return name
        return "(no owner)"

    excl_counts = defaultdict(int)
    inscope = {}
    for path, sha in head.items():
        if not path.endswith(EXT):
            continue
        reason = excluded(path)
        if reason:
            excl_counts[reason] += 1
            continue
        inscope[path] = sha

    blobs = Blobs()
    rows = {}
    big_content = {}
    for path, sha in inscope.items():
        data = blobs.get(sha)
        lines = data.count(b"\n")
        rows[path] = {"lines": lines, "bytes": len(data), "sha": sha}
        if lines > 1000:
            text = data.decode("utf-8", "replace")
            head25 = "\n".join(text.split("\n")[:25])
            rows[path]["gen_header"] = bool(GEN_RE.search(head25))
            rows[path]["sig"] = ("validateAgainst" in text) or ("(value: unknown)" in text)
            rows[path]["use_components"] = text.lstrip().startswith('"use components"')
    # census-7 commit state for over-1000 HEAD files and census-7 membership for all over-1000 files
    c7_big = {}
    for path in rows:
        if rows[path]["lines"] > 1000 and path in c7:
            pass
    over_head = [p for p, r in rows.items() if r["lines"] > 1000]
    c7_lines = {}
    for path in over_head:
        if path in c7:
            c7_lines[path] = blobs.get(c7[path]).count(b"\n")
    blobs.close()

    # the eight-line rule: census 7 over-1000 list parsed from its section 4 table
    c7_doc = open(os.path.join(HERE, "..", "audit-monolith-census-7.md"), encoding="utf-8").read()
    c7_list = set()
    in4 = False
    for line in c7_doc.split("\n"):
        if line.startswith("## 4."):
            in4 = True
            continue
        if in4 and line.startswith("## "):
            break
        if in4 and line.startswith("| ") and "`" in line:
            m = re.findall(r"`([^`]+)`", line)
            if m:
                c7_list.add(m[-1])

    bulk_touch = {}
    for rev in BULK:
        names = git("diff-tree", "--no-commit-id", "--name-only", "-r", "-z", "--no-renames", rev + "^", rev).decode("utf-8").split("\0")
        bulk_touch[rev] = set(n for n in names if n)

    over_gen = [p for p in over_head if rows[p].get("gen_header")]
    over = [p for p in over_head if not rows[p].get("gen_header")]
    over.sort(key=lambda p: -rows[p]["lines"])

    summary = {
        "head": git("rev-parse", "--short", "HEAD").decode().strip(),
        "tracked_blobs_head": len(head),
        "inscope_files": len(inscope),
        "inscope_lines": sum(r["lines"] for r in rows.values()),
        "excluded": dict(excl_counts),
        "over1000_all": len(over_head),
        "over1000_generated_header": len(over_gen),
        "over1000_hand_authored": len(over),
        "over1000_sig": sum(1 for p in over if rows[p].get("sig")),
        "over1000_use_components": [p for p in over if rows[p].get("use_components")],
        "c7_list_size": len(c7_list),
        "new_vs_c7_list": len([p for p in over if p not in c7_list]),
        "dropped_from_c7_list": len([p for p in c7_list if p not in over_head]),
        "bulk_touch_counts": {rev: sum(1 for p in over if p in bulk_touch[rev]) for rev in BULK},
    }

    out_rows = []
    for p in over:
        r = rows[p]
        out_rows.append({
            "path": p,
            "lines": r["lines"],
            "owner": owner_of(p),
            "in_c7_list": p in c7_list,
            "c7_commit_lines": c7_lines.get(p),
            "c7_commit_exists": p in c7,
            "sig": bool(r.get("sig")),
            "use_components": bool(r.get("use_components")),
            "bulk": [rev for rev in BULK if p in bulk_touch[rev]],
            "ext": os.path.splitext(p)[1],
        })

    gen_rows = [{"path": p, "lines": rows[p]["lines"]} for p in over_gen]

    # paths over 256 characters among tracked files at HEAD (character count, and utf-8 byte count)
    long_paths = []
    for p in head:
        if len(p) > 256:
            long_paths.append({"path": p, "chars": len(p), "bytes": len(p.encode("utf-8"))})
    long_paths.sort(key=lambda r: -r["chars"])

    # packages: group hand-authored over-1000 files by owner, disjoint by construction
    pk = defaultdict(list)
    for r in out_rows:
        pk[r["owner"]].append(r)
    packages = []
    for owner, files in sorted(pk.items(), key=lambda kv: -sum(f["lines"] for f in kv[1])):
        packages.append({"owner": owner, "files": len(files), "lines": sum(f["lines"] for f in files),
                         "new_vs_c7": sum(1 for f in files if not f["in_c7_list"])})

    json.dump({"summary": summary, "over": out_rows, "generated_over": gen_rows, "long_paths": long_paths,
               "packages": packages, "c7_list": sorted(c7_list)}, open(os.path.join(HERE, "census8.json"), "w", encoding="utf-8"),
              ensure_ascii=False, indent=1)
    print(json.dumps(summary, ensure_ascii=False, indent=1))
    print("long paths", len(long_paths))


if __name__ == "__main__":
    main()

const RS_DEF = new Set(["function_item", "closure_expression", "impl_item", "trait_item", "struct_item", "enum_item", "union_item", "macro_definition", "function_signature_item"]);

function rsScan(text: string): { comments: { c: Cmt; inDef: boolean; inErr: boolean }[]; leaves: string[]; errors: number } {
  const tree = parser.parse(text);
  const cur = tree.walk();
  const comments: { c: Cmt; inDef: boolean; inErr: boolean }[] = [];
  const leaves: string[] = [];
  let errors = 0;
  const defStack: boolean[] = [];
  const errStack: boolean[] = [];
  let defDepth = 0;
  let errDepth = 0;
  let descend = true;
  for (;;) {
    const n = typeof cur.currentNode === "function" ? cur.currentNode() : cur.currentNode;
    const ty = n.type;
    let entered = false;
    if (ty === "line_comment" || ty === "block_comment") {
      const raw = n.text as string;
      const body = ty === "line_comment" ? raw.replace(/[\r\n]+$/, "") : raw;
      comments.push({ c: { s: n.startIndex, e: n.startIndex + body.length, kind: ty === "line_comment" ? "line" : "block" }, inDef: defDepth > 0, inErr: errDepth > 0 });
      descend = false;
    } else {
      if (ty === "ERROR" || (typeof n.isMissing === "function" ? n.isMissing() : n.isMissing)) errors++;
      if (n.childCount === 0) leaves.push(`${ty}:${n.text}`);
      descend = true;
      defStack.push(RS_DEF.has(ty));
      errStack.push(ty === "ERROR");
      if (RS_DEF.has(ty)) defDepth++;
      if (ty === "ERROR") errDepth++;
      entered = true;
    }
    if (descend && n.childCount > 0 && cur.gotoFirstChild()) continue;
    if (entered) {
      if (defStack.pop()) defDepth--;
      if (errStack.pop()) errDepth--;
    }
    for (;;) {
      if (cur.gotoNextSibling()) break;
      if (!cur.gotoParent()) return { comments, leaves, errors };
      if (defStack.pop()) defDepth--;
      if (errStack.pop()) errDepth--;
    }
  }
}

function analyzeRs(text: string): Result {
  const sc = rsScan(text);
  const res: Result = { removed: [], kept: {}, outside: 0 };
  const cs = sc.comments;
  const keepSet = new Set<number>();
  const verdicts = cs.map(({ c }) => classifyRs(text.slice(c.s, c.e), c));
  for (let i = 0; i < cs.length; i++) {
    if (verdicts[i].rule !== "safety") continue;
    keepSet.add(i);
    for (let j = i - 1; j >= 0; j--) {
      const a = cs[j].c;
      const b = cs[j + 1].c;
      if (a.kind !== "line" || b.kind !== "line" || !/^[ \t]*\n[ \t]*$/.test(text.slice(a.e, b.s)) || !/^[ \t]*$/.test(text.slice(text.lastIndexOf("\n", a.s - 1) + 1, a.s))) break;
      keepSet.add(j);
    }
    for (let j = i + 1; j < cs.length; j++) {
      const a = cs[j - 1].c;
      const b = cs[j].c;
      if (a.kind !== "line" || b.kind !== "line" || !/^[ \t]*\n[ \t]*$/.test(text.slice(a.e, b.s)) || !/^[ \t]*$/.test(text.slice(text.lastIndexOf("\n", b.s - 1) + 1, b.s))) break;
      keepSet.add(j);
    }
  }
  for (let i = 0; i < cs.length; i++) {
    const { inDef, inErr, c } = cs[i];
    if (!inDef) {
      res.outside++;
      continue;
    }
    if (inErr) {
      res.kept["parse-error-region"] = (res.kept["parse-error-region"] ?? 0) + 1;
      continue;
    }
    const v = verdicts[i];
    if (!v.remove) {
      res.kept[v.rule] = (res.kept[v.rule] ?? 0) + 1;
      continue;
    }
    if (keepSet.has(i)) {
      res.kept["safety-block-continuation"] = (res.kept["safety-block-continuation"] ?? 0) + 1;
      continue;
    }
    res.removed.push(c);
  }
  return res;
}

function applyRemovals(text: string, removed: Cmt[]): string {
  let out = text;
  const sorted = [...removed].sort((a, b) => b.s - a.s);
  for (const c of sorted) {
    const { s, e } = c;
    const ls = out.lastIndexOf("\n", s - 1) + 1;
    let le = out.indexOf("\n", e);
    if (le < 0) le = out.length;
    const before = out.slice(ls, s);
    let afterEnd = le;
    if (out[afterEnd - 1] === "\r") afterEnd--;
    const after = out.slice(e, afterEnd);
    const multi = out.slice(s, e).includes("\n");
    if (before.trim() === "" && after.trim() === "") {
      const from = ls;
      const to = le < out.length ? le + 1 : le;
      let o = out.slice(0, from) + out.slice(to);
      const pStart = o.lastIndexOf("\n", from - 2) + 1;
      const prevLine = from > 0 ? o.slice(pStart, from - 1) : null;
      let nEnd = o.indexOf("\n", from);
      if (nEnd < 0) nEnd = o.length;
      const nextLine = from < o.length ? o.slice(from, nEnd) : null;
      const prevBlank = prevLine !== null && prevLine.trim() === "";
      const nextBlank = nextLine !== null && nextLine.trim() === "";
      const prevOpen = prevLine !== null && /[{(\[]\s*$/.test(prevLine);
      const nextClose = nextLine !== null && /^\s*[})\]]/.test(nextLine);
      const pair = prevLine !== null && nextLine !== null && /([{(\[])\s*$/.test(prevLine) && nextLine.trimStart()[0] === ({ "{": "}", "(": ")", "[": "]" } as Record<string, string>)[/([{(\[])\s*$/.exec(prevLine)![1]];
      if (pair) o = o.slice(0, pStart) + prevLine!.trimEnd() + nextLine!.trimStart() + o.slice(nEnd);
      else if (nextBlank && (prevBlank || prevOpen)) o = o.slice(0, from) + o.slice(Math.min(nEnd + 1, o.length));
      else if (prevBlank && nextClose && prevLine !== null) o = o.slice(0, pStart) + o.slice(from);
      out = o;
    } else if (after.trim() === "") {
      let st = s;
      while (st > ls && (out[st - 1] === " " || out[st - 1] === "\t")) st--;
      out = out.slice(0, st) + out.slice(afterEnd);
    } else if (multi && before.trim() !== "") {
      out = out.slice(0, s) + "\n" + out.slice(e);
    } else {
      const prevWs = s === 0 || /[\s(\[{]/.test(out[s - 1]);
      let to = e;
      if (prevWs && /[ \t]/.test(out[e] ?? "")) to = e + 1;
      let from = s;
      if (to === e && prevWs && /[)\]},;.]/.test(out[e] ?? "")) while (from > ls && /[ \t]/.test(out[from - 1])) from--;
      out = out.slice(0, from) + out.slice(to);
    }
  }
  return out;
}

function lineOf(text: string, idx: number): number {
  let n = 1;
  for (let i = text.indexOf("\n"); i >= 0 && i < idx; i = text.indexOf("\n", i + 1)) n++;
  return n;
}

function verifyRs(oldText: string, newText: string, expectedKept: string[]): string | null {
  const a = rsScan(oldText);
  const b = rsScan(newText);
  if (b.errors > a.errors) return `errors ${a.errors}->${b.errors}`;
  if (a.leaves.length !== b.leaves.length) return `leaf-count ${a.leaves.length}->${b.leaves.length}`;
  for (let i = 0; i < a.leaves.length; i++) if (a.leaves[i] !== b.leaves[i]) return `leaf-mismatch at ${i}: ${a.leaves[i].slice(0, 60)} vs ${b.leaves[i].slice(0, 60)}`;
  const nc = b.comments.map(({ c }) => newText.slice(c.s, c.e));
  if (nc.length !== expectedKept.length) return `comment-count ${expectedKept.length}!=${nc.length}`;
  for (let i = 0; i < nc.length; i++) if (nc[i] !== expectedKept[i]) return `kept-comment-mismatch at ${i}`;
  return null;
}


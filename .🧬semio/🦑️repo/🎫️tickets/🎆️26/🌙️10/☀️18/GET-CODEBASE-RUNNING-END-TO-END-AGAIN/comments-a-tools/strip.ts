function bodyIntervalsTs(sf: ts.SourceFile): [number, number][] {
  const iv: [number, number][] = [];
  const visit = (n: ts.Node) => {
    switch (n.kind) {
      case ts.SyntaxKind.FunctionDeclaration:
      case ts.SyntaxKind.FunctionExpression:
      case ts.SyntaxKind.ArrowFunction:
      case ts.SyntaxKind.MethodDeclaration:
      case ts.SyntaxKind.Constructor:
      case ts.SyntaxKind.GetAccessor:
      case ts.SyntaxKind.SetAccessor:
      case ts.SyntaxKind.ClassStaticBlockDeclaration:
        iv.push([n.getStart(sf), n.end]);
        break;
      case ts.SyntaxKind.ClassDeclaration:
      case ts.SyntaxKind.ClassExpression:
      case ts.SyntaxKind.InterfaceDeclaration:
      case ts.SyntaxKind.EnumDeclaration:
      case ts.SyntaxKind.TypeLiteral: {
        const m = (n as any).members as ts.NodeArray<ts.Node>;
        iv.push([m.pos, n.end]);
        break;
      }
    }
    ts.forEachChild(n, visit);
  };
  visit(sf);
  return mergeIntervals(iv);
}

const TEST_BASES = new Set(["it", "test", "describe", "suite", "bench", "beforeEach", "afterEach", "beforeAll", "afterAll", "specify", "context", "fit", "xit", "fdescribe", "xdescribe"]);
function isTestDefinition(n: ts.Node): boolean {
  if (n.kind !== ts.SyntaxKind.ExpressionStatement) return false;
  let e: ts.Node = (n as ts.ExpressionStatement).expression;
  for (;;) {
    if (ts.isCallExpression(e)) e = e.expression;
    else if (ts.isPropertyAccessExpression(e)) e = e.expression;
    else if (ts.isNonNullExpression(e)) e = e.expression;
    else break;
  }
  return ts.isIdentifier(e) && TEST_BASES.has(e.text);
}

function docPositionsTs(sf: ts.SourceFile): Set<number> {
  const set = new Set<number>();
  const visit = (n: ts.Node) => {
    if (DECL.has(n.kind) || isTestDefinition(n)) for (const d of (n as any).jsDoc ?? []) set.add(d.pos);
    ts.forEachChild(n, visit);
  };
  visit(sf);
  return set;
}

function tokensOf(node: ts.Node, sf: ts.SourceFile, out: ts.Node[]) {
  const kids = node.getChildren(sf);
  if (kids.length === 0) {
    out.push(node);
    return;
  }
  for (const k of kids) {
    if (k.kind >= ts.SyntaxKind.FirstJSDocNode && k.kind <= ts.SyntaxKind.LastJSDocNode) continue;
    tokensOf(k, sf, out);
  }
}

function commentsTs(text: string, sf: ts.SourceFile): Cmt[] {
  const toks: ts.Node[] = [];
  tokensOf(sf, sf, toks);
  const seen = new Map<number, Cmt>();
  const add = (rs: ts.CommentRange[] | undefined) => {
    for (const r of rs ?? []) seen.set(r.pos, { s: r.pos, e: r.end, kind: r.kind === ts.SyntaxKind.SingleLineCommentTrivia ? "line" : "block" });
  };
  for (let i = 0; i < toks.length; i++) {
    const t = toks[i];
    if (t.kind === ts.SyntaxKind.JsxText) continue;
    if (toks[i - 1]?.kind !== ts.SyntaxKind.JsxText) add(ts.getLeadingCommentRanges(text, t.pos));
    if (toks[i + 1]?.kind !== ts.SyntaxKind.JsxText) add(ts.getTrailingCommentRanges(text, t.end));
  }
  return [...seen.values()].filter((c) => !(c.kind === "line" && text.startsWith("#!", c.s)));
}

function dropEmptyJsx(sf: ts.SourceFile): ts.SourceFile {
  const tr = ts.transform(sf, [
    (ctx) => {
      const visit = (n: ts.Node): ts.Node | undefined => {
        if (n.kind === ts.SyntaxKind.JsxText) {
          const t = (n as ts.JsxText).text;
          if (t.trim() === "" && t.includes("\n")) return undefined;
        }
        if (n.kind === ts.SyntaxKind.JsxExpression && !(n as ts.JsxExpression).expression && (n.parent?.kind === ts.SyntaxKind.JsxElement || n.parent?.kind === ts.SyntaxKind.JsxFragment)) return undefined;
        return ts.visitEachChild(n, visit as any, ctx);
      };
      return (root) => ts.visitEachChild(root, visit as any, ctx) as ts.SourceFile;
    },
  ]);
  return tr.transformed[0] as ts.SourceFile;
}

const printer = ts.createPrinter({ removeComments: true });
function canonTs(path: string, text: string, kind: ts.ScriptKind): string | null {
  const sf = ts.createSourceFile(path, text, ts.ScriptTarget.ESNext, true, kind);
  if ((sf as any).parseDiagnostics.length) return null;
  const sf2 = dropEmptyJsx(sf);
  return printer.printFile(sf2).replace(/\{\s+\}/g, "{}");
}

function scriptKind(path: string): ts.ScriptKind {
  if (path.endsWith(".tsx")) return ts.ScriptKind.TSX;
  if (path.endsWith(".jsx")) return ts.ScriptKind.JSX;
  if (/\.(js|mjs|cjs)$/.test(path)) return ts.ScriptKind.JS;
  return ts.ScriptKind.TS;
}

function jsxContainerRange(sf: ts.SourceFile, text: string, c: Cmt): [number, number] | null {
  let found: [number, number] | null = null;
  const visit = (n: ts.Node) => {
    if (found || n.end < c.e || n.pos > c.s) return;
    if (n.kind === ts.SyntaxKind.JsxExpression && !(n as ts.JsxExpression).expression && n.getStart(sf) < c.s && c.e <= n.end) found = [n.getStart(sf), n.end];
    ts.forEachChild(n, visit);
  };
  visit(sf);
  return found;
}

function analyzeTs(path: string, text: string): Result {
  const kind = scriptKind(path);
  const isJs = kind === ts.ScriptKind.JS || kind === ts.ScriptKind.JSX;
  const sf = ts.createSourceFile(path, text, ts.ScriptTarget.ESNext, true, kind);
  if ((sf as any).parseDiagnostics.length) return { removed: [], kept: {}, outside: 0, error: "parse-diagnostics" };
  const iv = bodyIntervalsTs(sf);
  const docPos = docPositionsTs(sf);
  const cs = commentsTs(text, sf);
  const res: Result = { removed: [], kept: {}, outside: 0 };
  const jsxSeen = new Set<number>();
  for (const c of cs) {
    if (!inIntervals(iv, c.s, c.e)) {
      res.outside++;
      continue;
    }
    const v = classifyTs(text, c, docPos, isJs);
    if (!v.remove) {
      res.kept[v.rule] = (res.kept[v.rule] ?? 0) + 1;
      continue;
    }
    const jr = jsxContainerRange(sf, text, c);
    if (jr) {
      if (jsxSeen.has(jr[0])) continue;
      jsxSeen.add(jr[0]);
      res.removed.push({ s: jr[0], e: jr[1], kind: "block" });
      continue;
    }
    res.removed.push(c);
  }
  return res;
}


import { existsSync } from "node:fs";
import { initParser, findWasm } from "./parse.ts";
import { buildTree } from "./tree.ts";
import { loadPackage } from "./cargo.ts";
import { setTreeBuilder, resolvePath, lookup } from "./resolve.ts";
import { ROOT } from "./checks.ts";
await initParser(findWasm(ROOT)!);
const [dir, kind, name, modpath, ...segs] = process.argv.slice(2);
const pkg = loadPackage(dir)!;
const trees = new Map<any, any>();
const tf = (p: any, t: any) => { const k = p.dir + t.kind + t.name; if (!trees.has(k)) trees.set(k, buildTree(p, t, p.name)); return trees.get(k); };
setTreeBuilder((p) => { const t = p.targets.find((x: any) => x.kind === "lib"); return t ? tf(p, t) : null; });
const t = pkg.targets.find((x) => x.kind === kind && (name === "-" || x.name === name))!;
const tree = tf(pkg, t);
let m = tree.root;
for (const s of modpath === "-" ? [] : modpath.split("::")) m = m.kids.find((k: any) => k.name === s)!;
const r = resolvePath(m, segs, "code", { env: { test: kind === "test", wasm: false }, home: tree });
console.log(JSON.stringify({ err: r.err && { ...r.err, at: r.err.at?.path(), entry: undefined }, defs: r.defs.map((d: any) => d.kind) }));
console.log("entries:", m.entries.map((e: any) => e.name + ":" + e.kind).slice(0, 30).join(" "));

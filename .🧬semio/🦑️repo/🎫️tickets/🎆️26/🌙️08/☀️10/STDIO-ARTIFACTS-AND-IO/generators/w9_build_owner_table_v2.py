#!/usr/bin/env python3
"""W9: re-key 🧪owner-table.json (artifact-level io matrix) onto standard+subset
coordinates using w9_standards_table.json. Read-only inputs, writes
w9_owner_table_v2.json in this same generators/ folder. Idempotent: re-running
overwrites deterministically from the same inputs.
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
TICKET = os.path.dirname(HERE)

with open(os.path.join(TICKET, "🧪owner-table.json"), encoding="utf-8") as f:
    owner_table = json.load(f)

with open(os.path.join(HERE, "w9_standards_table.json"), encoding="utf-8") as f:
    standards = json.load(f)

domain_default = standards["domain_default"]
stdio_standards = standards["stdio"]

SUBSET_ID = "*"
SUBSET_DIR = "✳️any"


def stdio_entry(kind, roster_entry):
    std = stdio_standards[kind]
    return {
        **roster_entry,
        "standard": std["slug"],
        "standard_dir": std["dir"],
        "rust_mod": std["rust_mod"],
        "subset": SUBSET_ID,
        "subset_dir": SUBSET_DIR,
    }


stdio_roster_v2 = {
    kind: stdio_entry(kind, entry)
    for kind, entry in owner_table["stdio_roster"].items()
}

domain_roster_v2 = {}
for owner in owner_table["owners"]:
    key = f"{owner['plugin']}::{owner['artifact']}"
    domain_roster_v2[key] = {
        "plugin": owner["plugin"],
        "artifact": owner["artifact"],
        "path": owner["path"],
        "kind_id": owner["kind_id"],
        "standard": domain_default["slug"],
        "standard_dir": domain_default["dir"],
        "rust_mod": domain_default["rust_mod"],
        "subset": SUBSET_ID,
        "subset_dir": SUBSET_DIR,
    }

# io matrix: one row per (owner, stdio target) pair -- matches the original
# owner-table's "curated_io_pairs" semantics (285), which counts pairs, not
# directions. Every pair here supports both directions in the source data
# (import list == export list for every owner), so direction is carried as
# two explicit booleans rather than doubling the row count.
io_matrix_v2 = []
for owner in owner_table["owners"]:
    key = f"{owner['plugin']}::{owner['artifact']}"
    import_set = set(owner["import"])
    export_set = set(owner["export"])
    for stdio_kind in sorted(import_set | export_set):
        target = stdio_roster_v2[stdio_kind]
        io_matrix_v2.append({
            "owner": key,
            "owner_path": owner["path"],
            "target_kind": stdio_kind,
            "target_dir": target["dir"],
            "target_standard": target["standard"],
            "target_standard_dir": target["standard_dir"],
            "target_subset": SUBSET_ID,
            "target_subset_dir": SUBSET_DIR,
            "import": stdio_kind in import_set,
            "export": stdio_kind in export_set,
        })

out = {
    "_comment": "W9: standard+subset-aware re-keying of 🧪owner-table.json. Generated by w9_build_owner_table_v2.py -- do not hand-edit, re-run the generator instead.",
    "stdio_roster": stdio_roster_v2,
    "stdio_dag_edges": owner_table["stdio_dag_edges"],
    "domain_roster": domain_roster_v2,
    "io_matrix": io_matrix_v2,
    "counts": {
        "stdio_artifacts": len(stdio_roster_v2),
        "domain_artifacts": len(domain_roster_v2),
        "curated_io_pairs": len(io_matrix_v2),
    },
}

out_path = os.path.join(HERE, "w9_owner_table_v2.json")
with open(out_path, "w", encoding="utf-8") as f:
    json.dump(out, f, ensure_ascii=False, indent=2)
    f.write("\n")

print(f"wrote {out_path}")
print(f"stdio_artifacts={out['counts']['stdio_artifacts']} "
      f"domain_artifacts={out['counts']['domain_artifacts']} "
      f"curated_io_pairs={out['counts']['curated_io_pairs']}")
assert out['counts']['stdio_artifacts'] == 29, "stdio roster count drifted from 29"
assert out['counts']['domain_artifacts'] == 54, "domain roster count drifted from 54"
assert out['counts']['curated_io_pairs'] == 285, "curated io pair count drifted from 285"
print("OK: counts match the W0-W8 baseline (29 / 54 / 285)")

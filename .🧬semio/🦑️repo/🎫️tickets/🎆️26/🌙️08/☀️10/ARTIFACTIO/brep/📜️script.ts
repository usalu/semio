import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
const ticket = dirname(dirname(import.meta.path));
const root = "✏️s/🔌️plugins/🗄️stdio/🗿️artifacts/🧿️semio/🏅️standards/🔖️v1/🪆️subsets/🧊️brep";
const ioFile = root + "/🚪️io/🦀️.rs";
const schemaFile = root + "/🧬️schema/🦀️.rs";
let io = readFileSync(ioFile, "utf8");
const start = io.indexOf("    /// 🔗️ Real cross-collection");
const end = io.indexOf("    static VALIDATOR_ENTRY", start);
if (start < 0 || end < 0) throw new Error("BREP validator extraction source unavailable");
const helper = io.slice(start, end).split("\n").map(line => line.startsWith("    ") ? line.slice(4) : line).join("\n");
io = io.slice(0, start) + io.slice(end);
io = io.replace("    use std::collections::HashSet;", "    use crate::standards::v1::subsets::brep::schema::check_brep_referential_integrity;");
writeFileSync(ioFile, io);
writeFileSync(schemaFile, readFileSync(schemaFile, "utf8") + "\nuse std::collections::HashSet;\n\n" + helper);
const inference = root + "/🧬️schema/💡️inferences/✅validation-report/🦀️.rs";
writeFileSync(inference, readFileSync(inference, "utf8").replace("::brep::io::check_brep_referential_integrity", "::brep::schema::check_brep_referential_integrity"));
writeFileSync(join(ticket,"brep-semantic-referential-validation.md"), "# BREP Semantic Referential Validation\n\nCross-collection BREP identity validation belongs to canonical schema. The unchanged typed validator now lives there, while physical payload decoding and validator registration remain IO and invoke it privately. Semantic validation-report inference imports the canonical helper directly. Existing composition tests use the canonical private import from IO. No new IO facade export was added. Native verification is pending.\n\n" + [schemaFile,ioFile,inference].map(file => `- ${file}`).join("\n") + "\n");
console.log("[DEBUG] BREP referential validation restored to canonical schema");

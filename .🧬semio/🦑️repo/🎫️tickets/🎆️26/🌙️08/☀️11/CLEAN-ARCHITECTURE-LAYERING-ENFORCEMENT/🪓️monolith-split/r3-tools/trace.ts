import {existsSync, readFileSync} from "node:fs";
import {dirname, resolve} from "node:path";
import {buildSlices, collectDecls} from "/Users/ueli/Documents/semio/🧰️framework/🛍️products/🦑️repo/🔨️modules/📚️library/🏗️authoring/📦️crate-tree/🧱️decl-tree/🟦️.ts";
import {readCargoLib} from "/Users/ueli/Documents/semio/🧰️framework/🛍️products/🦑️repo/🔨️modules/📚️library/🏗️authoring/📦️crate-tree/🗺️plan/🟦️.ts";
import {transformTestClosure} from "/Users/ueli/Documents/semio/🧰️framework/🛍️products/🦑️repo/🔨️modules/📚️library/🏗️authoring/📦️crate-tree/🧪️test-closure/🟦️.ts";
import {convertMutationLeaves} from "/Users/ueli/Documents/semio/🧰️framework/🛍️products/🦑️repo/🔨️modules/📚️library/🏗️authoring/📦️crate-tree/🧬️mutation-families/🟦️.ts";
import {parseRustSourceTree} from "/Users/ueli/Documents/semio/🧰️framework/🛍️products/🦑️repo/🔨️modules/📚️library/🏗️authoring/📦️crate-tree/🌳️module-tree/🟦️.ts";
import {topLevelNames} from "/Users/ueli/Documents/semio/🧰️framework/🛍️products/🦑️repo/🔨️modules/📚️library/🏗️authoring/📦️crate-tree/🗺️plan/🟦️.ts";
const root = "/Users/ueli/Documents/semio";
const [pkg, convertArg, only] = process.argv.slice(2);
const lib = readCargoLib(resolve(root, pkg!, "Cargo.toml"));
const original = readFileSync(lib.entry, "utf8");
const tree0 = parseRustSourceTree(original);
const names = new Set<string>([...topLevelNames(original, tree0.items)].filter(([, i]) => i.kind !== "use").map(([n]) => n));
for (const n of tree0.modules) if (!n.inline) names.add(n.name);
const transform = transformTestClosure(root, lib.entry, original, names, {fixtures: true, aggregate: true, hoist: true, detach: true});
const rootSource = transform.rootSource;
const overlay = new Map<string, string>([...transform.edits, ...transform.creates]);
const readText = (a: string) => a === lib.entry ? rootSource : overlay.get(a) ?? (existsSync(a) ? readFileSync(a, "utf8") : null);
const family = convertArg === "on" ? convertMutationLeaves(lib.entry, rootSource, readText) : null;
for (const [f, t] of family?.edits ?? []) overlay.set(f, t);
if (family) console.log("converted", family.converted.length, JSON.stringify(family.notes ?? family.reasons ?? "").slice(0, 600));
const detaching = new Set<string>((family?.aggregates ?? []).map(a => a.name));
const decls = collectDecls(lib.entry, rootSource, readText);
const lines: string[] = [];
buildSlices(decls, readText, m => lines.push(m), {detachTestsMentioning: detaching, detachAllTests: true});
for (const l of lines) if (!only || l.includes(only)) console.log(l);
if (process.env.SHOW) for (const [f, t] of overlay) if (f.includes(process.env.SHOW)) console.log("=== " + f + "\n" + t);

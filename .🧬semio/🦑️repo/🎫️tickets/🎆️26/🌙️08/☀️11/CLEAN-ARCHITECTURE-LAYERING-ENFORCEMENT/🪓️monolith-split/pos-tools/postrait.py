"""🧷 POS trait-path neutraliser. rustc aborts before body type-check when any TRAIT path (bound, dyn, impl Trait, supertrait, impl header) fails to resolve,
while unresolved TYPE paths are harmless. Trait paths that the stub layer cannot know (items generated by external macros, names behind neutralised globs) are therefore
rewritten, in the sandbox only, to a generic stub trait `crate::__ext::__unresolved::Tr<n>`; every rewrite is reported so a real carve defect is never hidden."""
import re

HEAD_CODES = {"E0433", "E0405", "E0404", "E0412", "E0432", "E0574", "E0425", ""}
PATHCH = re.compile(r"[A-Za-z0-9_]")
UNRESOLVED_STUB = "pub mod __unresolved {\n" + "\n".join(f"    pub trait Tr{n}<{', '.join(f'A{i} = ()' for i in range(6))}> {{}}" for n in range(1)) + "\n}\n"


def stub_text():
    return "pub mod __unresolved {\n    pub trait Tr<A0 = (), A1 = (), A2 = (), A3 = (), A4 = (), A5 = ()> {}\n}\n"


def trait_context(before, after):
    b = before.rstrip()
    if re.search(r"\b(dyn|impl)$", b):
        return True
    if re.search(r"<[^<>]*\bas$", b) or re.search(r"<\s*[\w:<>&\[\]\s,']*\s+as$", b):
        return True
    if b.endswith("+") and not b.endswith("++"):
        return True
    if re.search(r"(^|[\s;{}\)])(unsafe\s+)?impl\s*(<.*>)?\s*!?$", b):
        return bool(re.match(r"^\s+for\b", after))
    if b.endswith(":") and not b.endswith("::"):
        head = b[:-1]
        depth = 0
        for i, ch in enumerate(head):
            if ch == "<":
                depth += 1
            elif ch == ">" and (i == 0 or head[i - 1] != "-"):
                depth -= 1
        if depth > 0:
            return True
        if re.search(r"\bwhere\b", head):
            return True
        if re.match(r"^\s*(for\s*<[^>]*>\s*)?[A-Z][A-Za-z0-9_]*\s*$", head):
            return True
        if re.match(r"^\s*(for\s*<[^>]*>\s*)?[A-Za-z_][A-Za-z0-9_:<>, '&]*$", head) and re.search(r"(,|>|\{|where)\s*$", b[:-1]) is None and re.match(r"^\s*(pub|\w+\s*:|\w+\s*\))", head) is None and False:
            return True
    return False


def split_path(line, hs):
    """Given the line text and the 0-based start of the highlighted segment, return (start, end) of the whole path incl. generic args, or None."""
    s = hs
    while s > 0 and (PATHCH.match(line[s - 1]) or (line[s - 1] == ":" and s > 1 and line[s - 2] == ":") or (line[s - 1] == ":" and s < len(line) and line[s] == ":")):
        s -= 1
    while s < len(line) and line[s] == ":" and not (s + 1 < len(line) and line[s + 1] == ":"):
        s += 1
    e = hs
    while e < len(line) and (PATHCH.match(line[e]) or line[e] == ":"):
        e += 1
    while e > s and line[e - 1] == ":":
        e -= 1
    if e < len(line) and line[e] == "<":
        depth = 0
        j = e
        while j < len(line):
            if line[j] == "<":
                depth += 1
            elif line[j] == ">" and line[j - 1] != "-":
                depth -= 1
                if depth == 0:
                    e = j + 1
                    break
            j += 1
        else:
            return None
    return s, e


def split_args(argtext):
    out, cur, depth = [], "", 0
    for ch in argtext:
        if ch in "<([":
            depth += 1
        elif ch in ">)]":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur)
            cur = ""
        else:
            cur += ch
    if cur.strip():
        out.append(cur)
    return [a.strip() for a in out if a.strip()]


COUNTER = [0]


def reset():
    COUNTER[0] = 0


def next_name():
    COUNTER[0] += 1
    return f"crate::__ext::__unresolved::Tr{COUNTER[0]}"


def replacement(path_text):
    m = re.match(r"^(.*?)(<.*>)?$", path_text, re.S)
    args = []
    if m and m.group(2):
        for a in split_args(m.group(2)[1:-1]):
            if a.startswith("'") or re.match(r"^[A-Za-z_]\w*\s*=", a):
                continue
            args.append(a)
    args = args[:6]
    return next_name() + ("<" + ", ".join(args) + ">" if args else "")


def fix_from_diag(d):
    """d carries line_text/hs from the primary span. Returns (line_text, path_text) or None when the position is not a trait context."""
    lt, hs = d.get("line_text"), d.get("hs")
    if lt is None or hs is None or d["code"] not in HEAD_CODES:
        return None
    r = split_path(lt, hs)
    if r is None:
        return None
    s, e = r
    path = lt[s:e]
    if not re.match(r"^(::)?[A-Za-z_]", path):
        return None
    if not (d["code"] == "E0405" or trait_context(lt[:s], lt[e:])):
        return None
    return lt, path


def apply(text, fixes):
    """fixes: set of (line_text, path_text). Returns (new_text, applied_count)."""
    if not fixes:
        return text, 0
    by = {}
    for lt, pt in fixes:
        by.setdefault(lt, []).append(pt)
    out, n = [], 0
    for line in text.split("\n"):
        if line in by:
            for pt in by[line]:
                if pt in line:
                    line = line.replace(pt, replacement(pt), 1)
                    n += 1
        out.append(line)
    return "\n".join(out), n


from posstub import mask, trait_position_spans, Stub

USE_LINE = re.compile(r"^\s*(?:pub(?:\s*\([^)]*\))?\s+)?use\b")


def use_statement_at(text, line_no):
    """(start_offset, end_offset, tree_text) of the `use` statement that covers 1-based line `line_no`, or None."""
    lines = text.split("\n")
    if line_no < 1 or line_no > len(lines):
        return None
    k = line_no - 1
    while k >= 0 and not USE_LINE.match(lines[k]):
        if lines[k].strip().endswith(";") or lines[k].strip().endswith("}") and k < line_no - 1:
            return None
        k -= 1
    if k < 0:
        return None
    start = sum(len(x) + 1 for x in lines[:k])
    m = mask(text)
    um = re.compile(r"\buse\b").search(m, start)
    if not um:
        return None
    depth, j = 0, um.end()
    while j < len(m):
        if m[j] in "{(":
            depth += 1
        elif m[j] in "})":
            depth -= 1
        elif m[j] == ";" and depth <= 0:
            break
        j += 1
    return start, j, text[um.end():j]


def broken_aliases(text, lines_and_names):
    """lines_and_names: {line_no: set(names) or None(all)} of failed use statements -> set of broken local names."""
    out = set()
    st = Stub()
    for ln, names in lines_and_names.items():
        r = use_statement_at(text, ln)
        if not r:
            continue
        tree = re.sub(r"^\s*(?:::)?", "", r[2]).strip()
        for alias, segs in st._aliases(tree):
            if names is None or alias in names or (names & set(segs)):
                out.add(alias)
    return out


def neutralize_aliases(text, broken):
    """Rewrite trait paths whose head segment is a broken use alias to the generic stub trait. Returns (text, count)."""
    if not broken:
        return text, 0
    m = mask(text)
    edits = []
    for s, e, p in trait_position_spans(m):
        head = p.lstrip(":").split("::")[0]
        if head in broken:
            edits.append((s, e, next_name()))
    out, last, n = [], 0, 0
    for s, e, rep in sorted(edits):
        if s < last:
            continue
        out.append(text[last:s])
        out.append(rep)
        last = e
        n += 1
    out.append(text[last:])
    return "".join(out), n

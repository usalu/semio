# 📝️ Applies the WP0 edits to PLAN-PLUGIN-CRATES.md in place (anchored, idempotent: refuses when the marker section already exists).
# usage: plan_edit.py dry|apply   (reads ../🗑️generated/pwp0-results.json for the measured numbers and the oracle text)
import json, os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import plan_text as T, plan_appendix as A, crates as C
PLAN = C.PLAN
res = json.load(open(C.GEN + '/pwp0-results.json', encoding='utf-8'))

def once(t, anchor, new, mode='after'):
    assert t.count(anchor) == 1, ('anchor count', t.count(anchor), anchor[:80])
    i = t.index(anchor)
    return t[:i + len(anchor)] + new + t[i + len(anchor):] if mode == 'after' else t[:i] + new + t[i:]

def replace_once(t, old, new):
    assert t.count(old) == 1, ('replace count', t.count(old), old[:80])
    return t.replace(old, new)

def main():
    mode = sys.argv[1]
    t = open(PLAN, encoding='utf-8').read()
    assert '### 12.5 WP0 hand-off contract' not in t, 'plan already edited'
    t = once(t, '\n## 0. Verdict in twelve lines\n', '\n' + T.INTRO + '\n', 'before')
    # 1.1 re-measure
    t = once(t, '\n### 1.2 Per-crate budget', '\n' + res['s11'] + '\n', 'before')
    # 1.3
    t = once(t, '\n## 2. Inventory\n', '\n' + res['s13'] + '\n', 'before')
    # 6.1 note
    t = once(t, '\n### 6.2 Notes per tight or unusual crate', '\n' + res['s61'] + '\n', 'before')
    # 8
    t = once(t, '\n## 9. cfg targets: guest wasip2 vs native\n', '\n' + res['s8'] + '\n', 'before')
    # 12.2 phase 0 note
    t = once(t, '**Phase 0 (WP0, serial):**\n', res['s122'] + '\n', 'after')
    # 12.4 and 12.5 before section 13
    t = once(t, '\n## 13. Verification and gates', '\n' + T.S12_4 + '\n' + T.S12_5.replace('{BLOCKED}', res['blocked']) + '\n', 'before')
    # 15.2
    t = once(t, '(default is Option A).\n', T.S15_RESOLVED, 'after') if '(default is Option A).\n' in t else t
    # Appendix A
    t = replace_once(t, '| `🦀️.rs` | 940 | 55 | facade |', '| `🦀️.rs` | 960 | 58 | facade `[WP0 change]` (was 940 / 55; now the root with the hub `include!`s, 12.5) |')
    t = replace_once(t, '| `🪟️window-kits/🌍️world3d/🦀️.rs` | 652 | 33 | window-kits-rich; window-kits 19 |', '| `🪟️window-kits/🌍️world3d/🦀️.rs` | 653 | 33 | window-kits-rich; window-kits 19 `[WP0 change]` (was 652) |')
    t = replace_once(t, '| `🏗️builder/🧩️app/🦀️.rs` | 1572 | 88 | app-builder |', '| `🏗️builder/🧩️app/🦀️.rs` | 1572 | 89 | app-builder `[WP0 change]` (was 88 KB) |')
    t = once(t, '| `⚖️authoring-law/🦀️.rs` | 91 | 7 | facade (testing law) |\n', res['a_rows'], 'after')
    # appendices H to K
    h = A.appendix_h(); i, n = A.appendix_i(); j1, j2, cn, cl, inn, il = A.appendix_j(); k, kn = A.appendix_k()
    app = f"""

## Appendix H. Crate registry (frozen by WP0, generated by `pwp0-tools/crates.py`; rank = the topological order, a crate may depend only on lower ranks)

80 crates. `stub` A: the stub is the real root (`[lib] path = "../../🦀️.rs"`); B: the stub is package-local until the carve flips `[lib] path` (12.5.2). `root` is relative to `PLUG/`; the package is `<root>/📦️packages/🦀️rust`. Companion bins list their hosts (11.3).

{h}

## Appendix I. Mount units of the root and their hubs (generated by `pwp0-tools/rootunits.py`; {n} units)

The `module` is the name the monolith knows; carving a crate replaces the unit by `extern crate semio_framework_plugin_<key> as <module>;` (12.5.4). Units marked `root` stay in the root.

{i}

## Appendix J. Lift files of the item moves of 5.2 (generated by `pwp0-tools/liftgroups.py`)

{cn} cross-package lift files ({cl:,} lines) have a docstring-only stub in the destination crate's directory (folder `🛬️lifted/<source module>`); the source package fills it (12.5.3 rule 3). the rows for I3 (`editor_surface` and three more items) and I6 (`drive_framework_reserved_registry_job`) are manual additions; I4 is internal to the instance family (WP6).

{j1}

The {inn} groups below are inside one package (their sum is {il:,} lines); the owner moves them while carving and needs no lift file.

{j2}

## Appendix K. Mount lines in a foreign parent file (generated by `pwp0-tools/crossmounts.py`; {kn} edges)

The root's own mounts are in Appendix I. For the edges below the child's owner edits the one named line of the parent's file when the child leaves (12.5.3 rule 2a); an `include!` edge disappears when the last item of the included file has been lifted.

{k}
"""
    t = t.rstrip('\n') + '\n' + app
    if mode == 'apply':
        cur = open(PLAN, encoding='utf-8').read()
        n0 = len(cur.split('\n'))
        open(PLAN, 'w', encoding='utf-8').write(t)
        print('applied;', n0, '->', len(t.split('\n')), 'lines')
    else:
        print('dry;', len(t.split('\n')), 'lines')

if __name__ == '__main__': main()

import fs from "node:fs";
import path from "node:path";
const R = "/Users/ueli/Documents/semio/";
const SDK = "🧰️framework/📦️packages/🟦️typescript";
const [sub, file, emoji, src, valuesArg, typesArg] = process.argv.slice(2);
const values = (valuesArg ?? "").split(",").filter(Boolean).sort(), types = (typesArg ?? "").split(",").filter(Boolean).sort();
const abs = R + SDK + "/" + file;
if (!fs.existsSync(R + src)) throw new Error("missing source " + src);
if (fs.existsSync(abs)) throw new Error("facade exists " + file);
const rel = path.relative(path.dirname(abs), R + src).normalize("NFC");
const spec = rel.startsWith(".") ? rel : "./" + rel;
const lines = [];
if (values.length) lines.push(`export { ${values.join(", ")} } from "${spec}";`);
if (types.length) lines.push(`export type { ${types.join(", ")} } from "${spec}";`);
fs.mkdirSync(path.dirname(abs), { recursive: true });
fs.writeFileSync(abs, `/** ${emoji} SDK entry \`@semio-tech/framework${sub.slice(1)}\`: explicit public surface of the framework module that plugins build on. */\n` + lines.join("\n") + "\n");
const pkgPath = R + SDK + "/package.json";
const pkg = JSON.parse(fs.readFileSync(pkgPath, "utf8"));
if (sub in pkg.exports) throw new Error("export exists " + sub);
pkg.exports[sub] = "./" + file;
fs.writeFileSync(pkgPath, JSON.stringify(pkg, null, 2) + "\n");
console.log("CREATED", sub, file);

#!/usr/bin/env python3
# 🧵️ One-shot: registers the lopdf READER for pdf@1.7/vt and repoints its 16 witnessable kinds onto it.
# The two encryption kinds are recorded `-uncarried` with the writer-side reason. Replaces the 18 old
# fixtureManifests (whose `after` bytes came from our own engine) with the 16 lopdf-written ones.
import json, subprocess

V = "✏️s/🔌️plugins/🗄️stdio/🗿️artifacts/📄️pdf/🏅️standards/🔖️1.7/🪆️subsets/✳️vt"
ORACLE = f"{V}/🧪️oracle/🔣️.json"
BIN = f"{V}/🏭️generator/🦀️lopdf-engine/target/release/reader"
CAP = "pdf-1-7-vt-mutate-reader"
UNC = "pdf-1-7-vt-mutate-uncarried"
OID = "lopdf-pdf-1-7-vt-mutate-reader"
UNCARRIED = {"insert-encryption-dictionary", "remove-encryption-dictionary"}

d = json.load(open(ORACLE))

d["oracles"].append({
    "id": OID, "kind": "third-party-library", "ecosystem": "rust", "package": "lopdf", "version": "0.44",
    "source": {"repository": "https://github.com/J-F-Liu/lopdf", "license": "MIT"},
    "engine": {"family": "lopdf", "implementation": "lopdf 0.44 COS object graph", "version": "0.44"},
    "capabilities": [CAP], "comparisonProfiles": ["semantic-pdf-conformance-vt-v1"],
    "license": "MIT", "testOnly": True, "productionReachable": False, "networkDuringExecution": False,
    "platforms": ["darwin-arm64", "darwin-x64", "linux-x64", "linux-arm64", "win32-x64"],
    "homepage": "https://github.com/J-F-Liu/lopdf",
    "rationale": (
        "📖️ A READER — and the reason this subset needed one is worth stating exactly, because the "
        "sibling entry looked qualifying and was not.\n\n"
        "The previous fixture corpus was generated by a binary that imported `oracle_apply_mutation` and "
        "`project_conformance` from `semio-s-plugin-stdio-test-oracle`, this repository's OWN crate. The "
        "mutated bytes and the expected projection of them were therefore both ours, and `lopdf` was "
        "reduced to a codec for our own answer: a shared misreading of the PDF specification would have "
        "produced two agreeing wrong answers and the test would still have passed. Registering a reader "
        "beside that corpus would have changed the label and nothing else.\n\n"
        "So the corpus was REBUILT. `🦀️lopdf-engine` depends on `lopdf` and nothing else: it lays out the "
        "seed, performs each mutation through lopdf's own public COS API, and reads the conformance axes "
        "back through it. Nothing in this repository predicts what this reader judges.\n\n"
        "Two of the eighteen kinds are registered `-uncarried` rather than routed around: lopdf 0.44's "
        "writer takes its encryption path whenever the trailer carries `/Encrypt` and then requires the "
        "encryption state a genuine decryption would have recorded, so a synthetic encryption dictionary "
        "can be neither written nor read back. That is a writer-side limit, not a reader gap."
    ),
})

EVIDENCE = (
    "Validated BOTH ways for all 16 witnessable kinds, per-fixture: (base,base) -> equal:true for 16/16; "
    "(base,mutated) -> equal:false for 16/16 — 32/32 directions correct. Observability is additionally "
    "enforced at GENERATION time: 🦀️lopdf-engine refuses to write a pair whose projection does not move, "
    "so a no-op mutation cannot be committed as a passing fixture. The two encryption kinds were caught "
    "by exactly that check failing to even read its own output (`object ID 8 0 not found`) and are "
    "registered -uncarried."
)
CRITERIA = [
    {"id": "accepts-a-known-good-pair", "met": True, "detail": "16/16 kinds: identical (base,base) compares equal:true"},
    {"id": "rejects-a-known-bad-pair", "met": True, "detail": "16/16 kinds: the kind's own (base,mutated) compares equal:false"},
    {"id": "reads-only", "met": True, "detail": "The reader binary projects and compares; it neither applies a mutation nor computes an expected state. The expected state is the committed mutated.pdf."},
    {"id": "deterministic", "met": True, "detail": "All 16 pairs regenerate byte-identically (aggregate sha256 unchanged across a full regeneration); no wall-clock and no randomness in the seed"},
    {"id": "offline", "met": True, "detail": "lopdf 0.44.0 is vendored in the cargo registry cache; the crate builds and runs with --offline"},
]

d.setdefault("probes", []).extend([
    {"id": "pdf-vt-project", "kind": "external-process", "ecosystem": "rust", "package": "lopdf", "version": "0.44",
     "engine": {"family": "lopdf", "implementation": "lopdf 0.44 COS object graph", "version": "0.44"},
     "capabilities": ["pdf.vt.project"], "outputSchema": "semio.repository-test.probe-report/v2",
     "deterministic": True, "license": "MIT", "testOnly": True, "productionReachable": False,
     "networkDuringExecution": False, "command": [BIN, "project"],
     "qualification": {"status": "qualified", "evidence": EVIDENCE, "checkedAt": "2026-08-28", "criteria": CRITERIA}},
    {"id": "pdf-vt-compare", "kind": "external-process", "ecosystem": "rust", "package": "lopdf", "version": "0.44",
     "engine": {"family": "lopdf", "implementation": "lopdf 0.44 COS object graph", "version": "0.44"},
     "capabilities": ["pdf.vt.compare"], "outputSchema": "semio.repository-test.probe-report/v2",
     "deterministic": True, "license": "MIT", "testOnly": True, "productionReachable": False,
     "networkDuringExecution": False, "command": [BIN, "compare"],
     "qualification": {"status": "qualified", "evidence": EVIDENCE, "checkedAt": "2026-08-28", "criteria": CRITERIA}},
])

d.setdefault("comparisonPipelines", []).append({
    "id": "pdf-1-7-vt-lopdf-compare-v1",
    "description": "Conformance-axis equality read back through lopdf's own COS API. GATING.",
    "stages": [
        {"probe": "pdf-vt-project", "description": "An independent reader accepts both files.",
         "inputs": ["base-pdf", "mutated-pdf"], "assertions": {"bothImport": True}},
        {"probe": "pdf-vt-compare", "description": "Equality over the vt conformance axes — the operative equality.",
         "inputs": ["base-pdf", "mutated-pdf"], "assertions": {"equal": True}},
    ],
})

repointed = uncarried = 0
for m in d["mutationManifests"][0]["mutations"]:
    if m["id"] in UNCARRIED:
        m["oracleRequirements"] = [{"capability": UNC, "qualifyingKind": "third-party-library"}]
        uncarried += 1
    else:
        m["oracleRequirements"] = [{"capability": CAP, "qualifyingKind": "third-party-library", "oracle": OID}]
        repointed += 1

manifests = json.loads(subprocess.run(["bun", f"{V}/🏭️generator/📜️script.ts", "manifests"], capture_output=True, text=True).stdout)
for entry in manifests:
    entry["comparisonPipeline"] = "pdf-1-7-vt-lopdf-compare-v1"
d["fixtureManifests"] = manifests

json.dump(d, open(ORACLE, "w"), ensure_ascii=False, indent=2)
open(ORACLE, "a").write("\n")
print(f"repointed {repointed}, uncarried {uncarried}, fixtureManifests {len(manifests)}")

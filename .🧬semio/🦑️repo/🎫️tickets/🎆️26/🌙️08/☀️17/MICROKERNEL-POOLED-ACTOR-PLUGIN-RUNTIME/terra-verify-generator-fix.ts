// Isolated verification of the crossMirrorImportLine logic against the REAL committed
// manifest.ts and ui-contract.ts, since the actual `generate` pipeline is blocked by an
// unrelated pre-existing Rust compile failure (protocol_core TS trait-bound errors).
import { readFileSync, writeFileSync } from "node:fs";

const manifestPath = "🧰️framework/🔨️modules/🛂️manifest/🤖️generated/🟦️manifest.ts";
const uiContractPath = "🧰️framework/🔨️modules/🛂️manifest/🤖️generated/🟦️ui-contract.ts";

function declaredTypeNames(mirrorPath: string): Set<string> {
  const source = readFileSync(mirrorPath, "utf8");
  const names = new Set<string>();
  for (const match of source.matchAll(/^export (?:type|interface) (\w+)/gm)) names.add(match[1]);
  return names;
}

function stripBlockComments(body: string): string {
  return body.replace(/\/\*\*[\s\S]*?\*\//g, "");
}

function crossMirrorImportLine(body: string, declaredHere: Set<string>, mirrorPath: string, importSpecifier: string): string {
  const mirrorNames = declaredTypeNames(mirrorPath);
  const codeOnly = stripBlockComments(body);
  const needed = [...mirrorNames].filter((name) => !declaredHere.has(name) && new RegExp(`\\b${name}\\b`).test(codeOnly)).sort();
  return needed.length === 0 ? "" : `import type { ${needed.join(", ")} } from "${importSpecifier}";\n\n`;
}

const manifestSource = readFileSync(manifestPath, "utf8");
// Strip the existing @generated header comment to recover the raw body, matching what
// consolidateBindings's blocks.join("\n\n") would have produced.
const bodyText = manifestSource.replace(/^\/\*\* @generated[\s\S]*?\*\/\n\n/, "");
const declaredHere = declaredTypeNames(manifestPath);

const importLine = crossMirrorImportLine(bodyText, declaredHere, uiContractPath, "./🟦️ui-contract.ts");
console.log("COMPUTED IMPORT LINE:");
console.log(JSON.stringify(importLine));

const fixed = `/** @generated by \`bun nx run @semio-tech/framework:generate\` from framework/📦️packages/🦀️rust/📦️glue.rs via ts-rs. Do not edit. */\n\n${importLine}${bodyText}`;
writeFileSync(process.argv[2], fixed);
console.log("Wrote fixed manifest to", process.argv[2]);

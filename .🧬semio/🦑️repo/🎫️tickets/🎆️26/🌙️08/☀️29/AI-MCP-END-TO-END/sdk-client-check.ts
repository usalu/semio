import { Client } from "@modelcontextprotocol/sdk/client/index.js";
import { StdioClientTransport } from "@modelcontextprotocol/sdk/client/stdio.js";
import { readFileSync } from "node:fs";
const entry = JSON.parse(readFileSync(".mcp.json", "utf8")).mcpServers.semio;
const errors: string[] = [], changes: string[] = [];
const transport = new StdioClientTransport({ command: entry.command, args: entry.args, env: { ...process.env, SEMIO_LANGUAGE: "en" } as Record<string, string>, cwd: process.cwd(), stderr: "ignore" });
const client = new Client({ name: "sdk-client-check", version: "1" }, { capabilities: {}, listChanged: { tools: { onChanged: () => changes.push("tools") }, resources: { onChanged: () => changes.push("resources") }, prompts: { onChanged: () => changes.push("prompts") } } } as never);
client.onerror = error => errors.push(String(error.message ?? error));
const t = performance.now();
await client.connect(transport);
const since = () => ((performance.now() - t) / 1000).toFixed(2);
console.log("connected", since(), client.getServerVersion());
const tools = await client.listTools(); console.log("tools", tools.tools.length, since());
console.log("resources", (await client.listResources()).resources.length, "prompts", (await client.listPrompts()).prompts.length, "templates", (await client.listResourceTemplates()).resourceTemplates.length, since());
let progress = 0;
const call = async (name: string, args: Record<string, unknown>) => {
  const reply = await client.callTool({ name, arguments: args }, undefined, { timeout: 120_000, onprogress: () => { progress++; } });
  return { isError: reply.isError ?? false, code: (reply.structuredContent as { code?: string } | undefined)?.code };
};
for (let n = 0; n < 30; n++) await call("context_resolve", { locale: n % 2 ? "de" : "en" });
for (let n = 0; n < 30; n++) await call("capabilities_search", { query: "add block", limit: 5 });
const id = `sdk-${Date.now()}`;
console.log("create", await call("artifact_create", { artifactId: id, kind: "os.agent.probe/v1" }));
for (let n = 0; n < 20; n++) await call("artifact_validate", { artifactId: id });
console.log("validate/snapshot", await call("artifact_snapshot", { artifactId: id }));
console.log("read resource", (await client.readResource({ uri: "semio://workspace" })).contents.length);
console.log("bad", await call("capabilities_search", { query: "x", limit: 0 }));
console.log("progress rows", progress, "client errors", errors.length, errors.slice(0, 3), "list changes", changes);
await client.close();

def thigh(listing, ident, rows, mirror):
    entry = lib.solid(listing, ident)
    rotation = entry["sections"][0]["rotation"]
    exponent = entry["sections"][0]["exponent"]
    first = rows[0][0]
    kept = [section for section in entry["sections"] if section["at"][0] < first - 1e-6]
    entry["sections"] = kept + lib.sections(rows, rotation, exponent, mirror)


def main():
    document = lib.load(SOURCE)
    for scale, volume in document["volumes"].items():
        body = volume["body"]
        lib.reloft(body, "withers", WITHERS[scale], 2.0)
        if scale in BREAST:
            lib.pair(body, "breast", BREAST[scale], 2.3)
        arm = "fore-upper" if scale == "500" else "arm"
        dome = [(-0.088, 0.008, -0.158, 0.024, 0.022)] if scale in ("50", "100") else []
        lib.pair(body, arm, dome + [(u, v, w + ARM_INSET, a, b * ARM_FLAT) for u, v, w, a, b in ARM[scale]], 2.1)
        if scale == "50":
            lib.pair(body, "elbow", ELBOW, 2.0)
        lib.pair(body, "forearm", [(u, v, w + (FOREARM_INSET if u < 0.1 else 0), a, b) for u, v, w, a, b in FOREARM[scale]], 2.15)
        lib.pair(body, "fore-lower" if scale == "500" else "fore-cannon", FORE_CANNON[scale])
        upper = "hind-upper" if scale == "500" else "thigh"
        thigh(body, "near-" + upper, STIFLE[scale], False)
        thigh(body, "far-" + upper, STIFLE[scale], True)
        lib.pair(body, "gaskin", GASKIN[scale])
    lib.save(SOURCE, document)
    print("[DEBUG] horse body re-cut")


if __name__ == "__main__":
    sys.exit(main())

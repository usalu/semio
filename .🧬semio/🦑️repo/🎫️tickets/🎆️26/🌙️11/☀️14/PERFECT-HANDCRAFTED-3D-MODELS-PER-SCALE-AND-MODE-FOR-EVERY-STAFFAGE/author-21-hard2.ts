import { entryOf, loadSource, merged } from "./volumes-lib.ts";
const P = "../../../../../../../🎓️teaching/🏛️architecture/🧍️staffage/🔨️modules/🗂️catalog/🧊️volumes/🌓️silhouette/🟦️.ts";
const { measureAsset } = (await import(P)) as any;
const [spec, sc, view = "elevation", mode = "base"] = process.argv.slice(2);
const { entry, asset } = entryOf(spec!);
const src = loadSource(entry)!;
const m = merged(asset, src);
const vol = m.volumes[sc!];
const geo = m.representations[sc!].geometry;
const count = (g: any) => Object.fromEntries(Object.entries(g).map(([k, v]: any) => [k, v.length]));
console.log("shapes before", JSON.stringify(count(geo)));
if (mode === "nostroke") for (const v of Object.keys(geo)) geo[v] = geo[v].filter((s: any) => /Z\s*$/i.test(s.d ?? "") || s.kind !== "path");
if (mode === "bodyonly") for (const v of Object.keys(geo)) geo[v] = geo[v].filter((s: any) => s.role === "body" && /Z\s*$/i.test(s.d ?? ""));
console.log("shapes after", JSON.stringify(count(geo)));
const soft = new Set<string>(vol.thermal.filter((s: any) => s.of && ["leaf-sun", "leaf-shade"].includes(s.region)).map((s: any) => s.of));
const r = measureAsset(m, Number(sc), m.presentation.defaultPose, undefined, 0.15e-3 * Number(sc), soft);
const v = r.views[view];
const hh = (h: number[]) => h.map((x, k) => (x ? `${k}:${x}` : "")).filter(Boolean).join(" ");
console.log("p95", v.p95M, "softp95", v.p95SoftM, "iou", v.iou);
console.log("hard", hh(v.spread.hard));
console.log("soft", hh(v.spread.soft));

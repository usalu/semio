"""📐 Stage 4 of the seated office worker: the body lists of 1:100, 1:200 and 1:500 restated by hand for their smallest feature (15, 30, 75 mm) with the proportions, bones and ids of the 1:50 model.

Run: `python3 rework-03-seated-office-worker-4-coarse.py` rewrites `volumes["100"|"200"|"500"].body` of the source; solids that are not restated here keep their earlier statement.
"""
from rework_03_lib import *

A = "humans/seated-office-worker"
src = read(source_path(A))
V = src["volumes"]
FINE = by_id(V["50"]["body"])


def restate(scale, rows, remove=()):
    body = V[scale]["body"]
    old = by_id(body)
    new = []
    for kind, id, bone, data, *more in rows:
        ref = old.get(id) or FINE.get(id) or FINE.get(id.replace("-r", "-l")) or FINE["chair-stem-front"]
        extra = more[0] if more else {}
        if kind == "loft":
            new.append(loft(id, bone, ref["material"], ref["tone"], data, **extra))
        elif kind == "box":
            new.append(box(id, bone, ref["material"], ref["tone"], data[0], data[1], data[2]))
        elif kind == "cap":
            new.append(cap(id, bone, ref["material"], ref["tone"], data[0], data[1], data[2]))
        elif kind == "ext":
            new.append(ext(id, bone, ref["material"], ref["tone"], data[0], "xy", data[1], data[2]))
    full = []
    for s in new:
        full.append(s)
        if s["id"].endswith("-l") and s["bone"] != "lumbar":
            full.append(mirror(s))
    N = by_id(full)
    out, seen = [], set()
    for s in body:
        if s["id"] in remove:
            continue
        out.append(N.get(s["id"], s))
        seen.add(s["id"])
    for s in full:
        if s["id"] not in seen:
            last = max((i for i, o in enumerate(out) if o["bone"] == s["bone"]), default=None)
            if last is None:
                last = max(i for i, o in enumerate(out) if o["bone"] == "pelvis")
            out.insert(last + 1, s)
    V[scale]["body"] = rnd(out)
    print(scale, len(out))



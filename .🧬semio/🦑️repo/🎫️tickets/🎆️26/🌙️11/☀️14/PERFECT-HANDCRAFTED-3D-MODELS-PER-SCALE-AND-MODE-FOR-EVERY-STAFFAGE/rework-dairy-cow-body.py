def rounded(rows, exponent):
    first, last = rows[0], rows[-1]
    head = [(first[0] - d * max(first[3], first[4]), first[1], first[2], first[3] * k, first[4] * k) for d, k in ((0.62, 0.34), (0.42, 0.66), (0.2, 0.9))]
    tail = [(last[0] + d * max(last[3], last[4]), last[1], last[2], last[3] * k, last[4] * k) for d, k in ((0.2, 0.9), (0.42, 0.66), (0.62, 0.34))]
    return head + list(rows) + tail


def sections(rows, exponent, sign):
    return [{"at": [round(row[0], 4), round(row[1], 4), round(sign * row[2], 4)], "rx": round(row[3], 4), "ry": round(row[4], 4), "rotation": list(LIMB), "exponent": row[5] if len(row) > 5 else exponent} for row in rows]


def main():
    path = sys.argv[1]
    document = json.load(open(path, encoding="utf-8"))
    volumes = document["asset"]["volumes"]
    for scale, table in BODY.items():
        listing = {entry["id"]: entry for entry in volumes[scale]["body"]}
        for name, (bone, exponent, domed, rows) in table.items():
            for prefix, side, sign in (("near-", "n", 1), ("far-", "f", -1)):
                entry = listing.get(prefix + name)
                if entry is None:
                    raise SystemExit("missing solid " + prefix + name + " at 1:" + scale)
                entry["bone"] = bone + side
                entry["sections"] = sections(rounded(rows, exponent) if domed else rows, exponent, sign)
                entry["capStart"], entry["capEnd"] = True, True
        for name, (centre, radii) in ELLIPSOIDS.get(scale, {}).items():
            for prefix, sign in (("near-", 1), ("far-", -1)):
                entry = listing.get(prefix + name)
                if entry is None:
                    raise SystemExit("missing solid " + prefix + name + " at 1:" + scale)
                entry["radii"] = list(radii)
                entry["transform"] = {"translation": [centre[0], centre[1], sign * centre[2]]}
    coarse = volumes["500"]
    for entry in coarse["body"]:
        if entry["id"] == "trunk":
            for section in entry["sections"]:
                station = section["at"][0]
                if abs(station - 1.13) < 1e-6:
                    section["ry"] = 0.25
                elif station >= 1.27:
                    scale = section["ry"] / 0.13 if station > 1.27 else 1.0
                    section["rx"], section["ry"] = round(0.26 * (section["rx"] / 0.22 if station > 1.27 else 1.0), 5), round(0.19 * scale, 5)
    for prefix in ("near-", "far-"):
        for limb, centre in (("hind", 0.175), ("fore", 0.150)):
            sign = -1 if prefix == "near-" else 1
            inner, outer, whole = prefix + limb + "-claw-inner", prefix + limb + "-claw-outer", prefix + limb + "-claw"
            for entry in coarse["body"]:
                if entry["id"] == inner:
                    entry["id"] = whole
                    for section in entry["sections"]:
                        section["at"][2] = sign * centre
                        section["rx"], section["ry"] = round(section["rx"] * 1.7, 5), round(section["ry"] * 2.3, 5)
            coarse["body"] = [entry for entry in coarse["body"] if entry["id"] != outer]
            for entry in coarse["thermal"]:
                if entry.get("of") == inner:
                    entry["id"], entry["of"] = "th-" + whole, whole
            coarse["thermal"] = [entry for entry in coarse["thermal"] if entry.get("of") != outer]
    with open(path, "w", encoding="utf-8") as handle:
        json.dump(document, handle, ensure_ascii=False, indent=2)
        handle.write("\n")


main()

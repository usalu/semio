const tree = await page.evaluate(() => {
  const details = [...document.querySelectorAll("#course-main details")].find((d) => !d.closest("[inert]") && d.getBoundingClientRect().height > 0);
  if (!details) return { text: "no details found", clip: null };
  let option = details;
  while (option.parentElement && !option.parentElement.hasAttribute("data-shared-border-group") && option.parentElement.id !== "course-main") option = option.parentElement;
  const container = option.parentElement;
  const lines = [];
  const box = (e) => { const r = e.getBoundingClientRect(); return [r.x, r.y, r.width, r.height].map((v) => Math.round(v * 10) / 10).join(","); };
  const name = (e) => e.tagName.toLowerCase() + [...e.attributes].filter((a) => a.name.startsWith("data-")).map((a) => `[${a.name}${a.value ? "=" + a.value.slice(0, 30) : ""}]`).join("") + (typeof e.className === "string" && e.className ? "." + e.className.slice(0, 80) : "");
  const style = (e) => { const s = getComputedStyle(e); const b = ["Top", "Right", "Bottom", "Left"].map((k) => s["border" + k + "Width"] + " " + s["border" + k + "Style"]).join("|"); return ` border=${b} outline=${s.outlineWidth} ${s.outlineStyle} shadow=${s.boxShadow.slice(0, 60)} bg=${s.backgroundColor}`; };
  for (let e = details; e && e.id !== "course-main"; e = e.parentElement) lines.push("up " + box(e) + " " + name(e) + style(e));
  const walk = (e, level) => { if (level > 9) return; for (const c of e.children) { const r = c.getBoundingClientRect(); if (r.height < 1 && r.width < 1) continue; if (c.closest("svg") && c.tagName.toLowerCase() !== "svg") continue; lines.push("  ".repeat(level) + box(c) + " " + name(c) + style(c)); walk(c, level + 1); } };
  lines.push("OPTION-CONTAINER " + box(container) + " " + name(container) + style(container));
  walk(option, 0);
  const overlays = [...document.querySelectorAll("[data-shared-border-overlay]")].filter((o) => !o.closest("[inert]")).map((o) => "overlay " + box(o) + " paths=" + o.querySelectorAll("path,line,rect").length + " parent=" + name(o.parentElement));
  lines.push(...overlays);
  const r = option.getBoundingClientRect();
  return { text: lines.join("\n"), clip: { x: Math.max(0, r.x - 12), y: Math.max(0, r.y - 12), width: r.width + 24, height: r.height + 24 } };
});

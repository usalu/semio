import {chromium} from "@playwright/test";
const b = await chromium.launch({args:["--enable-unsafe-webgpu","--enable-features=Vulkan,WebGPU","--use-angle=swiftshader","--use-vulkan=swiftshader","--use-webgpu-adapter=swiftshader","--enable-unsafe-swiftshader","--ignore-gpu-blocklist"]});
const p = await b.newPage({viewport:{width:1280,height:720}});
p.on("console", m => { if (m.type()==="error") console.log("CONSOLE", m.text().slice(0,300)); });
await p.goto(`http://localhost:6010/iframe.html?id=${process.argv[2]}&viewMode=story`);
const host = p.locator(".semio-board-2d-host");
await host.waitFor({timeout:60000});
await p.waitForFunction(()=>document.querySelector(".semio-board-2d-host")?.getAttribute("data-board-snapshot-parsed")==="true",null,{timeout:60000});
const cv = p.locator('.semio-board-2d-host canvas:not([aria-hidden="true"])');
const box = await cv.boundingBox();
const dbg = JSON.parse(await p.getByTestId("puzzle2d-board-debug").innerText());
const sel = async()=>p.evaluate(()=>{const h=document.querySelector(".semio-board-2d-host");return [...h.attributes].filter(a=>/selection|interaction|utility|lasso|method/.test(a.name)).map(a=>a.name+"="+a.value.slice(0,200)).join("\n")});
const pts=[[-80,-80],[360,-80],[360,200],[-80,200],[-80,-80]].map(([wx,wy])=>[box.x+(wx-dbg.camera.x)*dbg.camera.zoom+box.width/2, box.y+(wy-dbg.camera.y)*dbg.camera.zoom+box.height/2]);
console.log("BOX", JSON.stringify(box), JSON.stringify(dbg), JSON.stringify(pts));
await p.mouse.move(...pts[0]); await p.mouse.down();
for (const q of pts.slice(1)) await p.mouse.move(...q,{steps:8});
console.log("MIDDOWN", await sel());
await p.mouse.up(); await p.waitForTimeout(3000);
console.log("AFTER", await sel(), await p.getByTestId("puzzle2d-board-debug").innerText());
await b.close();

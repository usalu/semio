#!/bin/sh
# 🏁️ The closing runs of the memory repair inside ONE capacity grant, one process tree at a time: final.sh <memory MB> <step…>
# Every step runs under guarded.sh with the grant as its limit (a tree above the reservation is stopped) and under `timeout`; its log <generated>/f-<step>.log ends with the peak of the process tree, the seconds and the exit code.
# Steps: resume (interrupt-resume.py on a quick and a slow asset), pair (the matrix of the two reference assets, --jobs 1), heads (a merge over the whole catalog without records: the memory and the time of the generator itself), matrix:<id> (the matrix of one asset to its end), prof:<id>:<scale>:<subjects> (phases.ts under the sampling profiler), suite (the multiview coverage suite), check:<id> (the check CLI of one asset), trial:<id> (the same from the trial copy $CHECK_TRIAL), cmd:<label> (the command in $CMD).
# Do not edit this file while a run of it is in flight.
set -u
R=/Users/ueli/Documents/semio
S="$R/🎓️teaching/🏛️architecture/🧍️staffage"
T="$S/🧪️tests/🔭️multiview-coverage"
U="$R/.🧬semio/🦑️repo/🎫️tickets/🎆️26/🌙️11/☀️22/GET-STAFFAGE-RUNNING-END-TO-END-AND-FINISH-ALL-STAFFAGE-TICKETS"
M="$U/🧰️matrix/MM"
G="$U/🗑️generated/matrix/MM"
BUN=$(ls ~/Library/Caches/semio/runtimes/bun/*/bun | head -1)
if [ "${1:-}" != "--inside" ]; then
  cd "$R" || exit 1
  memory=$1; shift
  exec repo capacity run --memory="$memory" -- sh "$M/final.sh" --inside "$memory" "$@"
fi
limit=$2; shift 2
mkdir -p "$G"
cd "$R" || exit 1
for step in "$@"; do
  label=$(echo "$step" | tr ':' '-')
  log="$G/f-$label.log"
  case "$step" in
    resume) rm -rf "$G/f-resume"; sh "$M/guarded.sh" "$limit" "$log" timeout 1200 python3 "$U/🧰️matrix/interrupt-resume.py" "$BUN" "$T" "$G/f-resume" finned-heat-exchanger,olive-tree ;;
    pair) sh "$M/guarded.sh" "$limit" "$log" timeout 5400 "$BUN" "$T/📊️matrix.ts" --language en --out "$G/f-pair" --jobs 1 --assets finned-heat-exchanger,jogger ;;
    heads) sh "$M/guarded.sh" "$limit" "$log" timeout 900 "$BUN" "$T/📊️matrix.ts" --language en --out "$G/f-heads" --merge-only ;;
    matrix:*) id=${step#matrix:}; sh "$M/guarded.sh" "$limit" "$log" timeout "${LIMIT_S:-14400}" "$BUN" "$T/📊️matrix.ts" --language en --out "$G/f-matrix-$id" --jobs 1 --timeout-s "${LIMIT_S:-14400}" --assets "$id" ;;
    prof:*) rest=${step#prof:}; id=${rest%%:*}; rest=${rest#*:}; scale=${rest%%:*}; subjects=${rest#*:}; sh "$M/guarded.sh" "$limit" "$log" timeout 1800 "$BUN" --cpu-prof --cpu-prof-dir "$G/f-prof-$id-$scale" "$M/phases.ts" --snapshot "$S/🗂️catalog/🌳️vegetation/$id/🔣️.json" --scale "$scale" --subjects "$subjects" --every 20 ;;
    suite) sh "$M/guarded.sh" "$limit" "$log" timeout 1800 "$BUN" node_modules/vitest/vitest.mjs run --configLoader native --reporter=verbose --config "$S/🧪️tests/🎚️config/🟦️.ts" "🔭️multiview-coverage" ;;
    check:*) id=${step#check:}; sh "$M/guarded.sh" "$limit" "$log" timeout "${LIMIT_S:-3600}" "$BUN" "$S/🔨️modules/🗂️catalog/🩺️check/🟦️.ts" --asset "$id" ;;
    trial:*) id=${step#trial:}; sh "$M/guarded.sh" "$limit" "$log" timeout "${LIMIT_S:-3600}" "$BUN" "$CHECK_TRIAL" --asset "$id" ;;
    cmd:*) sh "$M/guarded.sh" "$limit" "$log" timeout "${LIMIT_S:-3600}" sh -c "$CMD" ;;
  esac
done

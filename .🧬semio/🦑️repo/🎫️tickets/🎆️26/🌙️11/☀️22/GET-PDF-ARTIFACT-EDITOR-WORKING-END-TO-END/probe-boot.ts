import { createRequire } from "node:module";
import { join } from "node:path";
const root = process.cwd();
const osDev = "🧰️framework/🛍️products/💻️os/🔨️modules/🧑‍💻dev";
const { ensureRepositoryBrowserPathV1 } = await import(join(root, "🧰️framework/🛍️products/🦑️repo/🔨️modules/📚️library/🧪️testing/🌐️browser/🧰️preparation/🟦️.ts"));
const { awaitBeacon, dismissIntroduction, unfoldActionsRail } = await import(join(root, osDev, "🧪️tests/🧮️program-matrix/🟦️.ts"));
const require = createRequire(join(root, osDev, "📦️packages/🟦️typescript/package.json"));
ensureRepositoryBrowserPathV1(root, process.env);
const { chromium } = require("playwright") as typeof import("playwright");
const browser = await chromium.launch();
const page = await browser.newPage({ locale: "en-US", viewport: { width: 1600, height: 1000 } });
const log: string[] = [];
page.on("pageerror", e => log.push("pageerror: " + e.message.slice(0, 400)));
page.on("console", m => { log.push(`${m.type()}: ${m.text().slice(0, 3000)}`); });
page.on("requestfailed", r => log.push("reqfail: " + r.url().slice(0, 200)));
page.on("response", r => { if (r.status() >= 400) log.push(`http ${r.status()}: ${r.url().slice(0, 200)}`); });
await page.goto(process.env.PDF_PANE_URL ?? "http://127.0.0.1:6260/");
const beacon = await awaitBeacon(page, Date.now() + 240_000).catch(e => "ERR " + e);
console.log("beacon", beacon);
await dismissIntroduction(page).catch(() => undefined);
await unfoldActionsRail(page).catch(e => console.log("unfold", String(e).slice(0,200)));
const ids = await page.evaluate(() => [...document.querySelectorAll("[id^='action.']")].map(e => e.id + "|" + (e.getAttribute("aria-label") ?? e.textContent ?? "").trim().slice(0, 40)));
console.log("actions", JSON.stringify(ids));
const inputs = await page.evaluate(() => [...document.querySelectorAll("input,textarea")].map(e => (e.getAttribute("aria-label") ?? e.id ?? "") + "|" + (e as HTMLInputElement).value).slice(0, 40));
console.log("inputs", JSON.stringify(inputs));
await page.screenshot({ path: join(import.meta.dir, "🗑️generated", "probe.png") });
console.log(log.join("\n"));
await browser.close();

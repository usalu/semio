import { S } from "./lib.ts";
const sil = await import(`${S}/🔨️modules/🗂️catalog/🧊️volumes/🌓️silhouette/🟦️.ts`);
const { featureOf } = await import(`${S}/🔨️modules/🗂️catalog/🧊️volumes/🟦️.ts`);
const [file, sc, view, xs, ys] = process.argv.slice(2);
const asset = (await Bun.file(file!).json()).asset;
const m = sil.measureAsset(asset, Number(sc), undefined, undefined, featureOf(Number(sc))).views[view!];
const P = { x: Number(xs), y: Number(ys) };
const inside = (ring: any[]) => { let c = false; for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) { const [p, q] = [ring[i], ring[j]]; if ((p.y > P.y) !== (q.y > P.y) && P.x < ((q.x - p.x) * (P.y - p.y)) / (q.y - p.y) + p.x) c = !c; } return c; };
m.filled.forEach((g: any, i: number) => { if (g.some(inside)) console.log("filled", i, JSON.stringify(g[0].slice(0, 6))); });
m.outlines.forEach((g: any, i: number) => { if (g.some(inside)) console.log("outline", i, JSON.stringify(g[0])); });

/** 📝 Turns matrix-v3 JSONL results into the markdown matrix. Usage: node report.mjs [out.md] [--inventory feature-inventory-v3.md] [--apps 2d,3d,viewer2d,viewer3d] */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const argv = process.argv.slice(2);
const T22 = fileURLToPath(new URL("../", import.meta.url));
const gen = `${T22}🗑️generated/matrix-v3/`;
const opt = (n, d) => { const i = argv.indexOf(`--${n}`); return i < 0 ? d : argv[i + 1]; };
const outPath = argv.find(a => a.endsWith(".md") && !a.startsWith("--")) ?? `${T22}feature-matrix-v3.md`;
const invPath = opt("inventory", `${T22}feature-inventory-v3.md`);
const apps = opt("apps", "2d,3d,viewer2d,viewer3d").split(",");
const TITLES = { "2d": "2D Editor (http://127.0.0.1:6086/)", "3d": "3D Editor (http://127.0.0.1:6087/)", viewer2d: "2D Viewer (http://127.0.0.1:6088/)", viewer3d: "3D Viewer (http://127.0.0.1:6089/)" };
const cell = s => String(s ?? "").replace(/\|/g, "\\|").replace(/\r?\n/g, " ").slice(0, 260);
const rel = p => (p ? String(p).replace(T22, "").replace(/\\/g, "/") : "");

const inventory = {};
if (existsSync(invPath)) for (const line of readFileSync(invPath, "utf8").split("\n")) { const m = /^\| ([EV][23]D-\d+) \| (.*?) \| (.*?) \| (.*?) \| (.*?) \|$/.exec(line); if (m) inventory[m[1]] = { feature: m[2], last: m[5] }; }

const data = {};
for (const a of apps) {
  const f = `${gen}${a}/results.jsonl`;
  data[a] = existsSync(f) ? readFileSync(f, "utf8").split("\n").filter(Boolean).map(l => JSON.parse(l)) : [];
}
const counts = rows => ({ total: rows.length, pass: rows.filter(r => r.status === "PASS").length, fail: rows.filter(r => r.status === "FAIL").length, skip: rows.filter(r => r.status === "SKIP").length, hang: rows.filter(r => r.status === "BOOT-HANG").length });

let md = `# FEM Feature Matrix v3 (headless Chromium, re-runnable harness)\n\nGenerated by \`matrix-v3/report.mjs\` from \`🗑️generated/matrix-v3/<app>/results.jsonl\` (run with \`node matrix-v3/run.mjs <2d|3d|viewer2d|viewer3d>\`). Each row is one check with an asserted DOM/aria/console effect; screenshots are linked in the Shot column. Inventory column maps to \`feature-inventory-v3.md\` IDs.\n\n`;
md += "| App | Checks | PASS | FAIL | SKIP | BOOT-HANG |\n|---|---|---|---|---|---|\n";
for (const a of apps) { const c = counts(data[a]); md += data[a].length ? `| ${TITLES[a]} | ${c.total} | ${c.pass} | ${c.fail} | ${c.skip} | ${c.hang} |\n` : `| ${TITLES[a]} | not run | | | | |\n`; }

const covered = new Set(); const result = {};
for (const a of apps) for (const r of data[a]) for (const id of r.inv ?? []) { covered.add(id); (result[id] ??= []).push(r); }

md += "\n## FAIL summary\n\n";
let anyFail = false;
for (const a of apps) {
  const fails = data[a].filter(r => r.status === "FAIL" || r.status === "BOOT-HANG");
  if (!fails.length) continue; anyFail = true;
  md += `### ${TITLES[a]}\n\n| ID | Inventory | Action | Expected | Observed |\n|---|---|---|---|---|\n`;
  for (const r of fails) md += `| ${r.id} | ${(r.inv ?? []).join(", ")} | ${cell(r.action)} | ${cell(r.expected)} | ${cell(r.observed)} |\n`;
  md += "\n";
}
if (!anyFail) md += "No failures recorded.\n\n";

for (const a of apps) {
  md += `## ${TITLES[a]}\n\n`;
  if (!data[a].length) { md += "Not run.\n\n"; continue; }
  const forced = data[a].some(r => r.forced);
  if (forced) md += "> Run was forced past a boot hang: rows that need the model are expected to FAIL and do not describe the product.\n\n";
  md += "| ID | Area | Action | Expected | Observed | Result | ms | Inventory | Console errors | Shot |\n|---|---|---|---|---|---|---|---|---|---|\n";
  for (const r of data[a]) md += `| ${r.id} | ${r.area} | ${cell(r.action)} | ${cell(r.expected)} | ${cell(r.observed)} | ${r.status} | ${r.ms} | ${(r.inv ?? []).join(", ")} | ${r.console ? `${r.console.errors ?? 0}${r.console.fatal ? ` (fatal ${r.console.fatal})` : ""}` : ""} | ${rel(r.shot)} |\n`;
  md += "\n";
}

const ids = Object.keys(inventory);
if (ids.length) {
  const ran = apps.filter(a => data[a].length);
  const relevant = ids.filter(id => ran.some(a => (id.startsWith("E2D") && id !== "E2D-138" && a === "2d") || (id.startsWith("E3D") && a === "3d") || ((id.startsWith("V2D") || id === "E2D-138") && (a === "viewer2d" || a === "2d")) || (id.startsWith("V3D") && (a === "viewer3d" || a === "3d"))));
  const gaps = relevant.filter(id => !covered.has(id));
  md += `## Coverage against feature-inventory-v3.md\n\n${relevant.length - gaps.length} of ${relevant.length} inventory rows (of the apps that were run) are asserted by at least one check.\n\n`;
  const roll = id => { const rs = result[id] ?? []; if (!rs.length) return "NO CHECK"; if (rs.some(r => r.status === "FAIL" || r.status === "BOOT-HANG")) return "FAIL"; if (rs.every(r => r.status === "SKIP")) return "SKIP"; return "PASS"; };
  md += "| Inventory ID | Feature | v3 result | Checks |\n|---|---|---|---|\n";
  for (const id of relevant) md += `| ${id} | ${cell(inventory[id].feature)} | ${roll(id)} | ${(result[id] ?? []).map(r => r.id).join(", ")} |\n`;
  md += `\n### Inventory rows without a check (known gaps)\n\n${gaps.length ? gaps.map(g => `- ${g}: ${inventory[g].feature}`).join("\n") : "None."}\n`;
}
writeFileSync(outPath, md);
console.log(`wrote ${outPath}`);

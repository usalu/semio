    "Unit axes land at +-30 degrees in the isometric picture: (1,0,0) -> (cos 30, -sin 30), (0,1,0) -> (0, 1), (0,0,1) -> (cos 30, sin 30). Numbers generated by the formulas above in float64 (T/axonometric-fixture.py)."

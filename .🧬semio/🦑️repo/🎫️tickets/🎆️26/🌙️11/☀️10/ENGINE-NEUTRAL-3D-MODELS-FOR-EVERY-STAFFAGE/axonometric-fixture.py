def camera(azimuth, elevation):
    a, e = math.radians(azimuth), math.radians(elevation)
    right = [math.sin(a), 0, math.cos(a)]
    up = [-math.sin(e) * math.cos(a), math.cos(e), math.sin(e) * math.sin(a)]
    toward = [math.cos(e) * math.cos(a), math.sin(e), -math.cos(e) * math.sin(a)]
    nu = 1 / math.cos(e)

    def axis(v):
        return nu * math.hypot(sum(r * c for r, c in zip(right, v)), sum(r * c for r, c in zip(up, v)))

    return dict(right=right, up=up, toward=toward, normalisation=nu, axisScale=dict(x=axis([1, 0, 0]), y=axis([0, 1, 0]), z=axis([0, 0, 1])))


iso = (45, math.degrees(math.atan(1 / math.sqrt(2))))
dim = (90 - math.degrees(math.asin(1 / (2 * math.sqrt(2)))), math.degrees(math.asin(1 / 3)))
cases = [
    dict(name="isometric", spec={"kind": "isometric"}, azimuthDeg=iso[0], elevationDeg=iso[1], **camera(*iso)),
    dict(name="dimetric", spec={"kind": "dimetric"}, azimuthDeg=dim[0], elevationDeg=dim[1], **camera(*dim)),
    dict(name="free-30-20", spec={"kind": "free", "azimuthDeg": -30, "elevationDeg": 20}, azimuthDeg=-30, elevationDeg=20, **camera(-30, 20)),
    dict(name="side-elevation", spec={"kind": "free", "azimuthDeg": 90, "elevationDeg": 0}, azimuthDeg=90, elevationDeg=0, **camera(90, 0)),
    dict(name="front-elevation", spec={"kind": "free", "azimuthDeg": 0, "elevationDeg": 0}, azimuthDeg=0, elevationDeg=0, **camera(0, 0)),
]
points = []
for c in cases:
    for p in ([1, 0, 0], [0, 1, 0], [0, 0, 1], [0.5, 1.8, -0.25]):
        nu = c["normalisation"]
        points.append(dict(camera=c["name"], world=p, paper=[nu * sum(a * b for a, b in zip(c["right"], p)), nu * sum(a * b for a, b in zip(c["up"], p))], depth=nu * sum(a * b for a, b in zip(c["toward"], p))))

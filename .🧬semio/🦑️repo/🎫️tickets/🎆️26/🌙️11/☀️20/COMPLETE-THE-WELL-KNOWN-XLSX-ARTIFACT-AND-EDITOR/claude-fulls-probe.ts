import {mkdirSync} from "node:fs";
import {createRequire} from "node:module";
import {join} from "node:path";

const root = "/Users/ueli/Documents/semio";
const osDev = "🧰️framework/🛍️products/💻️os/🔨️modules/🧑‍💻dev";
const url = process.argv[2] ?? "http://127.0.0.1:6070/";
const locale = process.argv[3] ?? "en-US";
const seconds = Number(process.argv[4] ?? 90);
const out = join(import.meta.dir, "🗑️generated/claude-full-s");
mkdirSync(out, {recursive: true});
const {ensureRepositoryBrowserPathV1} = await import(join(root, "🧰️framework/🛍️products/🦑️repo/🔨️modules/📚️library/🧪️testing/🌐️browser/🧰️preparation/🟦️.ts"));
const require = createRequire(join(root, osDev, "📦️packages/🟦️typescript/package.json"));
ensureRepositoryBrowserPathV1(root, process.env);
const {chromium} = require("playwright") as typeof import("playwright");
const browser = await chromium.launch({args: ["--js-flags=--experimental-wasm-jspi"]});
const page = await browser.newPage({locale, viewport: {width: 1440, height: 900}});
const logs: string[] = [];
page.on("pageerror", e => logs.push("[pageerror] " + e.message.slice(0, 400)));
page.on("console", m => { if (["error", "warning"].includes(m.type()) || /\[DEBUG\]|refused|stalled/i.test(m.text())) logs.push(`[${m.type()}] ${m.text().slice(0, 400)}`); });
page.on("requestfailed", r => logs.push("[requestfailed] " + r.url().slice(0, 200)));
page.on("response", r => { if (r.status() >= 400) logs.push(`[http ${r.status()}] ${r.url().slice(0, 200)}`); });
await page.goto(url);
await page.waitForTimeout(seconds * 1000);
await page.screenshot({path: join(out, `probe-${locale}.png`)});
console.log("[DEBUG] title:", await page.title());
console.log("[DEBUG] body:", (await page.locator("body").innerText()).slice(0, 1500).replace(/\s+/g, " "));
console.log("[DEBUG] logs:\n" + [...new Set(logs)].slice(0, 60).join("\n"));
await browser.close();

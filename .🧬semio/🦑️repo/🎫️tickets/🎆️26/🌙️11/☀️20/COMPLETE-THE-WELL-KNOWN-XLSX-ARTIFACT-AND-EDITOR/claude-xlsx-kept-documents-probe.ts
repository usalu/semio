import { mkdir } from "node:fs/promises";
import { createRequire } from "node:module";
import { join } from "node:path";

/** 🧮️ Opens the full S shell on a data folder that already keeps many documents and reports the Actions rail: which rows exist, which are visible, and what the rail's box and scroll metrics are. Usage: `repo <this file> [url] [locale]`. */
const root = "/Users/ueli/Documents/semio";
const osDev = join(root, "🧰️framework/🛍️products/💻️os/🔨️modules/🧑‍💻dev");
const [url = "http://127.0.0.1:6070/", locale = "de-DE"] = process.argv.slice(2);
const out = join(import.meta.dir, "🗑️generated", "kept-documents-probe");
await mkdir(out, { recursive: true });
const { ensureRepositoryBrowserPathV1 } = await import(join(root, "🧰️framework/🛍️products/🦑️repo/🔨️modules/📚️library/🧪️testing/🌐️browser/🧰️preparation/🟦️.ts"));
const { awaitBeacon, dismissIntroduction, unfoldActionsRail, readShell, clickUncovered, windowIds } = await import(join(osDev, "🧪️tests/🧮️program-matrix/🟦️.ts"));
ensureRepositoryBrowserPathV1(root, process.env);
const { chromium } = createRequire(join(osDev, "📦️packages/🟦️typescript/package.json"))("playwright") as typeof import("playwright");
const browser = await chromium.launch({ args: ["--js-flags=--experimental-wasm-jspi", "--use-angle=swiftshader", "--in-process-gpu", "--disable-accelerated-2d-canvas"] });
const page = await (await browser.newContext({ locale, viewport: { width: 1440, height: 900 } })).newPage();
await page.goto(url);
console.log("beacon", await awaitBeacon(page, Date.now() + 180_000));
await dismissIntroduction(page);
await unfoldActionsRail(page).catch(() => undefined);
await page.waitForTimeout(3000);
const shell = await readShell(page);
console.log("rail actions", JSON.stringify(shell.actions));
console.log("rail", JSON.stringify(await page.evaluate(() => {
  const pane = document.querySelector('[data-slot="window-action-pane"]') as HTMLElement | null;
  const row = document.querySelector('[data-slot="window-action-pane"] [id="action.openArtifactFile"]') as HTMLElement | null;
  const box = (el: HTMLElement | null) => el === null ? null : { rect: el.getBoundingClientRect().toJSON(), scrollH: el.scrollHeight, clientH: el.clientHeight, overflowY: getComputedStyle(el).overflowY };
  return { pane: box(pane), row: box(row), rows: pane?.querySelectorAll('[id^="action."]').length ?? 0, listItems: document.querySelectorAll('[role="listitem"], [role="row"]').length };
})));
await page.screenshot({ path: join(out, `rail-${locale}.png`) });
const messages: string[] = [];
page.on("console", message => { if (message.type() !== "debug" && !/cft0|lcsj|store (?:replacement|initializer)/u.test(message.text())) messages.push(`${message.type()}: ${message.text()}`.slice(0, 400)); });
let choosers = 0;
page.on("filechooser", () => { choosers += 1; });
await page.keyboard.press(process.platform === "darwin" ? "Meta+p" : "Control+p");
const input = page.locator("[role='dialog'] [data-slot='command-input']").first();
await input.waitFor({ state: "visible", timeout: 15_000 });
await input.fill("xlsx");
const item = page.locator('[data-slot="command-item"][data-command-item-id^="spawn."][data-command-item-id*="xlsx"]').first();
await item.waitFor({ state: "visible", timeout: 8_000 });
const before = await windowIds(page);
await item.click();
for (const deadline = Date.now() + 60_000; (await windowIds(page)).filter(id => !before.includes(id)).length === 0 && Date.now() < deadline; await page.waitForTimeout(300));
await page.waitForTimeout(3500);
await unfoldActionsRail(page).catch(() => undefined);
const selector = '[data-slot="window-action-pane"] [id="action.openArtifactFile"]';
console.log("open row count", await page.locator(selector).count());
console.log("row metrics", JSON.stringify(await page.evaluate(sel => { const el = document.querySelector(sel) as HTMLElement | null; if (!el) return null; const r = el.getBoundingClientRect(); const top = document.elementFromPoint(r.x + r.width / 2, r.y + r.height / 2); return { rect: r.toJSON(), disabled: el.getAttribute("aria-disabled"), topElement: top === null ? null : `${top.tagName}#${top.id}.${top.getAttribute("data-slot")}`, pane: (document.querySelector('[data-slot="window-action-pane"]') as HTMLElement).getBoundingClientRect().toJSON() }; }, selector)));
const cursor = messages.length;
await clickUncovered(page, selector).catch(error => console.log("click error", String(error).slice(0, 200)));
await page.waitForTimeout(8000);
console.log("choosers after click", choosers);
console.log("console after click", JSON.stringify(messages.slice(cursor)));
await page.screenshot({ path: join(out, `after-open-click-${locale}.png`) });
await browser.close();

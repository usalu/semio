# 🧾 Renders the norm audit JSON into the fleet-1108 audit-norm markdown report
import json, os
TICKET = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(TICKET, "🗑️generated", "audit-norm", "result.json")
OUT = os.path.join(TICKET, "🔍️audits", "fleet-1108-audit-norm.md")
ORDER = ["en1990", "en1991", "en1992", "en1993", "en1994", "en1995", "en1996", "en1997", "en1998", "en1999"]
NAMES = {"en1990": "⚖️en1990 (EN 1990)", "en1991": "🏋️en1991 (EN 1991)", "en1992": "🏛️en1992 (EN 1992)", "en1993": "🔩️en1993 (EN 1993)",
         "en1994": "🧩️en1994 (EN 1994)", "en1995": "🪵️en1995 (EN 1995)", "en1996": "🪨️en1996 (EN 1996)", "en1997": "🌍️en1997 (EN 1997)",
         "en1998": "🫨️en1998 (EN 1998)", "en1999": "🪶️en1999 (EN 1999)"}
SPECFILE = {"en1990": "en1990-en1991-target.md", "en1991": "en1990-en1991-target.md", "en1992": "en1992-target.md", "en1993": "en1993-target.md",
            "en1994": "en1994-en1999-target.md", "en1999": "en1994-en1999-target.md", "en1995": "en1995-en1996-target.md",
            "en1996": "en1995-en1996-target.md", "en1997": "en1997-en1998-target.md", "en1998": "en1997-en1998-target.md"}
data = json.load(open(SRC, encoding="utf-8"))
def agn(rel): return rel.endswith((".feature", ".json", ".toml", ".csv"))
def impl_cell(r):
    if r["kind"] == "not-modelled": return "no (not-modelled): " + (r["reason"] or "")[:140]
    if r["kind"] == "data":
        ok = r["data_path_exists"]
        return "data: " + ("path exists" if ok else ("path missing" if ok is False else "declared, not a path (unknown)"))
    if r["impl"]:
        rel, ln, n = r["impl"][0]
        return "yes: `%s:%d`" % (rel, ln)
    return "no id/check hit"
def test_cell(r):
    if not r["test"]: return "no hit"
    rel, ln, _ = r["test"][0]
    return ("agnostic" if agn(rel) else "specific") + ": `%s:%d`" % (rel, ln)
def orc_cell(r):
    if not r["oracle"]: return "no hit"
    rel, ln, _ = r["oracle"][0]
    dep = r["oracle_deps"][0] if r["oracle_deps"] else "unknown"
    return "`%s:%d`; %s" % (rel, ln, dep)
def esc(s): return str(s).replace("|", "\\|")
def cd(rows): return [r for r in rows if r["kind"] in ("check", "design-case")]
L = []
L.append("# 🔍 Fleet 1108 Audit: Norm Artifacts vs Target Specs (lane `audit-norm`)\n")
L.append("Read-only audit, 2026-11-08, ticket `26/11/01/NORM-COMPLETE-VISUAL-EUROCODE-PLUGINS`. Generated by `🧰️scripts/fleet-1108-audit-norm.py` and `🧰️scripts/fleet-1108-audit-norm-report.py`. No tests or builds were run.\n")
L.append("## Method\n")
L.append("- Spec items: the `items` of each artifact's `🧭️spec-trace/🔣️.json` (795 items in 10 artifacts). The check list per item (`checks` prefixes, design-case `entry`, data `path`) is the claimed realisation. The spec-trace is the repo's self-declaration; this audit verifies it against the source.")
L.append("- Implemented: the check prefix or entry id occurs as a token (or, for field-path references such as `.profile.siteResponse`, as a substring) in a non-test, non-oracle, non-spec-trace file of that artifact. Hit = `file:line` of the first occurrence. Data items: declared path checked for existence under the subset root.")
L.append("- Language-agnostic test: the id occurs in a `.feature`, `.json`, `.toml` or `.csv` under a test/fixture path. A `specific` hit = only in a `.rs`/`.ts`/`.py` test file. Only the first 2 hits per item are stored by the script, so a `specific` label can hide a later agnostic hit.")
L.append("- Third-party oracle: the id occurs in a file under an `oracle` path. Python oracles are classified by their imports (stdlib-only / third-party names). Other languages: unknown.")
L.append("- Limits: string presence, not behaviour. `no hit` means the id string does not occur in that category. Fixture or catalogue JSON containing an id is counted as a test hit even if no test executes it. Clause-number coverage is not checked.")
L.append("- Spec-trace vs target spec: see the section `Spec-trace ids versus target markdown`.\n")
L.append("## Summary\n")
L.append("| Artifact | Items | check/design | implemented (id hit) | not-modelled | data | test hit | oracle hit |")
L.append("|---|---|---|---|---|---|---|---|")
for k in ORDER:
    rows = data[k]["rows"]; c = cd(rows)
    L.append("| %s | %d | %d | %d | %d | %d | %d | %d |" % (NAMES[k], len(rows), len(c), sum(1 for r in c if r["impl"]),
        sum(1 for r in rows if r["kind"] == "not-modelled"), sum(1 for r in rows if r["kind"] == "data"),
        sum(1 for r in c if r["test"]), sum(1 for r in c if r["oracle"])))
L.append("")
L.append("## Ranked gaps (top of report)\n")
L.append("Ranking per artifact: (1) declared not-modelled, (2) no implementation hit or missing data path, (3) implemented but no test hit, (4) implemented and tested but no oracle hit. Counts:\n")
L.append("| Rank | Artifact | not-modelled | no impl hit | data path missing | no test hit | no oracle hit |")
L.append("|---|---|---|---|---|---|---|")
agg = []
for k in ORDER:
    rows = data[k]["rows"]; c = cd(rows)
    nm = [r for r in rows if r["kind"] == "not-modelled"]
    ni = [r for r in c if not r["impl"]]
    dm = [r for r in rows if r["kind"] == "data" and r["data_path_exists"] is False]
    nt = [r for r in c if r["impl"] and not r["test"]]
    no = [r for r in c if r["impl"] and r["test"] and not r["oracle"]]
    agg.append((k, nm, ni, dm, nt, no))
    L.append("| - | %s | %d | %d | %d | %d | %d |" % (NAMES[k], len(nm), len(ni), len(dm), len(nt), len(no)))
L.append("")
for k, nm, ni, dm, nt, no in agg:
    top = [("not modelled", r["id"]) for r in nm] + [("no impl hit", r["id"]) for r in ni] + [("data path missing", r["id"]) for r in dm] + [("no test hit", r["id"]) for r in nt] + [("no oracle hit", r["id"]) for r in no]
    L.append("- **%s**: %s" % (NAMES[k], ", ".join("`%s` (%s)" % (i, why) for why, i in top[:10]) if top else "no gaps by these criteria"))
L.append("")
L.append("## Spec-trace ids versus target markdown\n")
L.append("- Every spec-trace id of all 10 artifacts occurs as a boundary-delimited string in its target spec file (checked by substring match, 795 of 795).")
L.append("- Bold-heading check for EN 1990/1991 (`**ID` at line start): trace ids without a bold heading are E16.04, E16.05, E16.06, E17.10, E3.06, E4.05, E4.06, E4.07, E4.08. They occur in the target text, but not as headings. Each needs a manual look at the target clause.")
L.append("- A heading-level scan of the other target specs found no trace id missing from the headings, except false positives from table rows and hand-check notes. The reverse direction (heading ids missing from the trace) was not verified exhaustively for EN 1997/1998 (`GI-17` is the only heading-level candidate) or for EN 1993 (`V-029`, `V-255`-`V-260`, `V-301`-`V-305`, `V-424`-`V-427`, `V-806` occur inline, not as headings).\n")
for k in ORDER:
    rows = data[k]["rows"]; c = cd(rows)
    L.append("---\n")
    L.append("## %s\n" % NAMES[k])
    L.append("Target spec: `📐️specs/%s`. Spec-trace: `%s/🏅️standards/🔖️1/🪆️subsets/✳️any/🧭️spec-trace/🔣️.json`. Items: %d (check %d, design-case %d, data %d, not-modelled %d).\n" % (
        SPECFILE[k], data[k]["dir"], len(rows), sum(1 for r in rows if r["kind"] == "check"), sum(1 for r in rows if r["kind"] == "design-case"),
        sum(1 for r in rows if r["kind"] == "data"), sum(1 for r in rows if r["kind"] == "not-modelled")))
    L.append("| Spec item | Clause | Kind | Implemented? (file:line) | Language-agnostic test? | Third-party oracle? |")
    L.append("|---|---|---|---|---|---|")
    for r in rows:
        is_c = r["kind"] in ("check", "design-case")
        L.append("| `%s` | %s | %s | %s | %s | %s |" % (r["id"], esc(r["clause"]), r["kind"], esc(impl_cell(r)),
            esc(test_cell(r)) if is_c else "n/a", esc(orc_cell(r)) if is_c else "n/a"))
    L.append("")
open(OUT, "w", encoding="utf-8").write("\n".join(L) + "\n")
print("wrote", OUT, len(L))

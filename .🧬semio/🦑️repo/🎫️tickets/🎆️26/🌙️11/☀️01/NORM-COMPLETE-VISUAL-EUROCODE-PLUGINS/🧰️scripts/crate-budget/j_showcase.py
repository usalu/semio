"""🎪️ Crate-budget J: the full-showcase accessor and its fixture leave the snapshot model crate for the crate `<artifact>-showcase` (root `✳️any/🎪️showcase`); consumers call the free function `full_showcase()`. Usage: j_showcase.py <enXXXX> (idempotent)."""
import bisect, glob, os, re, sys
sys.path.insert(0, os.path.dirname(__file__))
from g_lib import *

CONSUMERS = {
    "en1992": [("✏️editor", "dependencies")],
    "en1997": [("✏️editor", "dependencies")],
    "en1993": [("✏️editor", "dependencies"), ("🎬️scene", "dev-dependencies"), ("🧬️schema/💡️inferences/⚖️checks", "dev-dependencies")],
}
PACK = "semio-framework-pack-json"


def lock_add(consumer, new, deps):
    for p in lock_files(consumer):
        head, pk = lock_blocks(rd(p))
        pk = [b.rstrip("\n") for b in pk]
        names = [pkg_name(b) for b in pk]
        if consumer not in names:
            continue
        if new not in names:
            j = bisect.bisect_left(names, new)
            pk.insert(j, '[[package]]\nname = "%s"\nversion = "0.1.0"\ndependencies = [\n%s]' % (new, "".join(' "%s",\n' % d for d in sorted(deps))))
            names.insert(j, new)
        i = names.index(consumer)
        m = re.search(r"dependencies = \[\n(.*?)\]", pk[i], re.S)
        cur = re.findall(r'"([^"]+)"', m.group(1))
        if new not in cur:
            body = "dependencies = [\n" + "".join(' "%s",\n' % d for d in sorted(set(cur) | {new})) + "]"
            pk[i] = pk[i][: m.start()] + body + pk[i][m.end():]
        wr(p, head + "\n\n".join(pk) + "\n")
        print("lock", p[len(SEMIO):])


def main(key):
    art = [d for d in glob.glob(NORM + "/🗿️artifacts/*") if d.endswith(key)][0]
    sub = art + "/🏅️standards/🔖️1/🪆️subsets/✳️any"
    model_dir = sub + "/🧬️schema/📸️snapshot"
    model = "semio-s-artifact-norm-%s-model" % key
    name = "semio-s-artifact-norm-%s-showcase" % key
    ty = key.capitalize() + "Snapshot"
    crate = sub + "/🎪️showcase"
    mf = model_dir + "/🦀️.rs"
    src = rd(mf)
    m = re.search(r"    /// 🎪️ The full showcase:[^\n]*\n    pub fn full_showcase\(\) -> Self \{\n[^\n]*\n    \}\n\n", src)
    if not m:
        assert os.path.exists(crate + "/🦀️.rs"), "nothing to move"
        return print("done", key)
    doc = re.search(r"/// 🎪️ (.*?), decoded from the committed fixture", m.group(0)).group(1)
    wr(mf, src.replace(m.group(0), "", 1))
    wr(crate + "/🦀️.rs", '//! 🎪️ %s showcase: the committed full showcase document decoded into the snapshot; the fixture stays under `🧪️tests/🧫️fixtures/🎪️showcase` (generated by the ticket script `🧰️scripts/showcase`).\n\n/// 🎟️ %s, decoded from the committed fixture `🧪️tests/🧫️fixtures/🎪️showcase/🔣️.json`.\npub fn full_showcase() -> %s::%s {\n    semio_framework_pack_json::from_json_str(include_str!("../🧪️tests/🧫️fixtures/🎪️showcase/🔣️.json"), semio_framework_pack_json::JsonMemberPolicy::Reject).expect("the committed showcase fixture decodes")\n}\n' % (key.upper().replace("EN", "EN "), doc, model.replace("-", "_"), ty))
    pkg = crate + "/📦️packages/🦀️rust"
    pack_path = re.search(r'%s = \{ path = "([^"]+)" \}' % PACK, rd(model_dir + "/📦️packages/🦀️rust/Cargo.toml")).group(1)
    pack_abs = os.path.normpath(os.path.join(model_dir + "/📦️packages/🦀️rust", pack_path))
    wr(pkg + "/Cargo.toml", '[package]\nworkspace = "%s"\nname = "%s"\nversion.workspace = true\nedition.workspace = true\nrust-version.workspace = true\ndescription = "%s showcase document"\n\n[package.metadata.semio]\nrole = "library"\n\n[lints]\nworkspace = true\n\n[lib]\npath = "../../🦀️.rs"\n\n[dependencies]\n%s = { path = "%s" }\n%s = { workspace = true }\n' % (relp(art, pkg), name, key.upper().replace("EN", "EN "), PACK, relp(pack_abs, pkg), model))
    register_workspace(art, name, pkg)
    script_register(art, model, name)
    for sub_dir, kind in CONSUMERS[key]:
        toml = sub + "/" + sub_dir + "/📦️packages/🦀️rust/Cargo.toml"
        t = rd(toml)
        sec = "[%s]\n" % kind
        assert sec in t, toml
        if name + " =" not in t:
            wr(toml, t.replace(sec, sec + "%s = { workspace = true }\n" % name, 1))
        cname = re.search(r'(?m)^name = "([^"]+)"', t).group(1)
        lock_add(cname, name, [model, PACK])
        for f in glob.glob(sub + "/" + sub_dir + "/**/*.rs", recursive=True):
            if "/📸️snapshot/" in f:
                continue
            s = rd(f)
            n = s.replace("%s::full_showcase()" % ty, "%s::full_showcase()" % name.replace("-", "_"))
            if n != s:
                wr(f, n)
                print("edit", f[len(SEMIO):])


main(sys.argv[1])

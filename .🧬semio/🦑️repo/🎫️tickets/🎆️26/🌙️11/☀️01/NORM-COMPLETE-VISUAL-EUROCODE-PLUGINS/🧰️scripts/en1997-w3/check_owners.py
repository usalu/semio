"""🧭️ Generates the check-family owner table of the EN 1997 scene kit from the `entity` of every check item of the spec trace (`🧭️spec-trace/🔣️.json`); `--check` fails when the committed block differs.
Usage: check_owners.py [--check]
"""
import json, sys
SUB = "/home/deck/semio/✏️s/🔌️plugins/📕️norm/🗿️artifacts/🌍️en1997/🏅️standards/🔖️1/🪆️subsets/✳️any"
KIT = f"{SUB}/🎬️scene/🧰️kit/🦀️.rs"
BEGIN, END = "// BEGIN check-owners (generated by check_owners.py)\n", "// END check-owners\n"
owners = {}
for item in json.load(open(f"{SUB}/🧭️spec-trace/🔣️.json"))["items"]:
    real = item.get("realisation") or {}
    if real.get("kind") == "check":
        for prefix in real["checks"]:
            owners.setdefault(item["entity"], set()).add(prefix)
rows = ["/// 🧭️ The collection whose entity draws each check family, from the `entity` of the spec-trace item that lists the family; longer prefixes first.", "pub const CHECK_OWNERS: &[(&str, &str)] = &["]
flat = sorted(((p, c) for c, ps in owners.items() for p in ps), key=lambda x: (-len(x[0]), x[0]))
rows += [f'    ("{p}", "{c}"),' for p, c in flat] + ["];", "",
    "/// 🧭️ The collection that owns the check `check_id` (longest family prefix), `None` for a check outside the spec trace.",
    "pub fn check_owner(check_id: &str) -> Option<&'static str> {",
    "    CHECK_OWNERS.iter().find(|(prefix, _)| check_id.starts_with(prefix)).map(|(_, collection)| *collection)", "}"]
block = BEGIN + "\n".join(rows) + "\n" + END
text = open(KIT).read()
if BEGIN in text:
    new = text[:text.index(BEGIN)] + block + text[text.index(END) + len(END):]
else:
    new = text.rstrip("\n") + "\n\n" + block
if "--check" in sys.argv:
    sys.exit(0 if new == text else "committed block differs")
open(KIT, "w").write(new)
print(len(flat), "families")

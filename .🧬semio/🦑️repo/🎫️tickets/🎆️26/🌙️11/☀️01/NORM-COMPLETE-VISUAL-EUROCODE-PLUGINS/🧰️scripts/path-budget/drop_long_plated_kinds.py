"""Deletes the three long duplicate plated-panel mutation kinds of en1993 (the short kinds stay): folders, fixtures, enum/mod/use lines, edit-rule rows, tags, test rows, oracle catalog entries. Twins (mutations json/graphql/proto/ts) are regenerated by `schema twins generate`. Usage: python -I drop_long_plated_kinds.py [--apply]"""
import json, os, re, shutil, sys
SUB = "/home/deck/semio/✏️s/🔌️plugins/📕️norm/🗿️artifacts/🔩️en1993/🏅️standards/🔖️1/🪆️subsets/✳️any"
KINDS = ["change-plated-lateral-pressure-coefficient", "change-plated-transverse-stiffener-inertia", "change-plated-stiffener-flange-thickness"]
def forms(k):
    p = k.split("-"); return [k, "_".join(p), "".join(x.title() for x in p), "".join(x.title() for x in p).replace("Change", "Changed", 1), "_".join(p).upper()]
TOK = [f for k in KINDS for f in forms(k)]
apply = "--apply" in sys.argv
TWINS = {"🔣️.json", "🔗️.graphql", "🛰️.proto", "🟦️.ts"}
def mentions(s): return any(t in s for t in TOK)
def drop(o):
    if isinstance(o, list):
        cleaned = [drop(x) for x in o]
        return [x for x in cleaned if not mentions(json.dumps(x, ensure_ascii=False))]
    if isinstance(o, dict): return {k: drop(v) for k, v in o.items()}
    return o
for d, ds, fs in os.walk(SUB):
    ds[:] = [x for x in ds if x not in ("target", "node_modules", "__pycache__")]
    for n in list(ds):
        if any(k in n for k in KINDS) and not any(k2 != next(k for k in KINDS if k in n) and False for k2 in KINDS):
            if n.endswith(tuple(KINDS)) :
                print("rmdir", os.path.join(d, n)[len(SUB):])
                if apply: shutil.rmtree(os.path.join(d, n))
                ds.remove(n)
    for f in fs:
        p = os.path.join(d, f)
        if f in TWINS and "mutations" in p and "oracles" not in p: continue
        if "🧫️fixtures" in p: continue
        try: t = open(p, encoding="utf-8").read()
        except Exception: continue
        if not mentions(t): continue
        if p.endswith("oracles/🔣️.json"):
            data = json.loads(t); out = json.dumps(drop(data), indent=2, ensure_ascii=False) + ("\n" if t.endswith("\n") else "")
            print("json", p[len(SUB):], len(t), "->", len(out))
            if apply: open(p, "w", encoding="utf-8").write(out)
            continue
        lines = t.split("\n"); keep = [l for l in lines if not mentions(l)]
        print("lines", p[len(SUB):], len(lines) - len(keep))
        if apply: open(p, "w", encoding="utf-8").write("\n".join(keep))

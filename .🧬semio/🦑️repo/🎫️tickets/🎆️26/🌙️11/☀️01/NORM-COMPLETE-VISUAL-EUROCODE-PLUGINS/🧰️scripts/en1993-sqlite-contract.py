"""Idempotent: derives the EN 1993 SQLite semantic contract (schemaBytes, table widths, table and column limits) from 🗄️.sql exactly as the independent extent does and rewrites the contract, the admission calls and the limit constants of the Rust and TypeScript tests."""
import json, os, re, sqlite3
S = os.environ.get('EN1993_GEN_ROOT', '/home/deck/semio/✏️s/🔌️plugins/📕️norm/🗿️artifacts/🔩️en1993/🏅️standards/🔖️1/🪆️subsets/✳️any') + '/🚪️io/🪶️sqlite/📸️snapshot/'
_S = "/home/deck/semio/✏️s/🔌️plugins/📕️norm/🗿️artifacts/🔩️en1993/🏅️standards/🔖️1/🪆️subsets/✳️any/🚪️io/🪶️sqlite/📸️snapshot/"
rd = lambda p: open(S + p, encoding="utf8").read()
def wr(p, t): open(S + p, "w", encoding="utf8").write(t)
db = sqlite3.connect(":memory:")
db.executescript(rd("🗄️.sql"))
tables = db.execute("select name,sql from sqlite_schema where type='table' order by name").fetchall()
bytes_ = sum(len(n.encode()) + len(s.encode()) for n, s in tables)
widths = {n: len(db.execute(f'pragma table_info("{n}")').fetchall()) for n, _ in tables}
T, W = len(tables), max(widths.values())
c = json.loads(rd("🧪️tests/🧫️fixtures/🎛️semantic.json"))
c["schemaBytes"], c["tableWidths"] = bytes_, dict(sorted(widths.items()))
wr("🧪️tests/🧫️fixtures/🎛️semantic.json", json.dumps(c, indent=2, ensure_ascii=False) + "\n")
t = rd("🧪️tests/🟦️.ts")
t = re.sub(r'schemaBytes"\]\)\.toEqual\(\d+\)', f'schemaBytes"]).toEqual({bytes_})', t)
t = re.sub(r'(tableWidths"\]\)\.toEqual\()\{[^}]*\}', lambda m: m.group(1) + json.dumps(dict(sorted(widths.items())), separators=(",", ":")), t)
t = re.sub(r"maxTables:\d+,maxColumns:\d+\}", f"maxTables:{T},maxColumns:{W}" + "}", t)
t = re.sub(r"maxTables:\d+\},\{\.\.\.limits,maxColumns:\d+", f"maxTables:{T - 1}" + "},{...limits,maxColumns:" + str(W - 1), t)
wr("🧪️tests/🟦️.ts", t)
t = rd("🧪️tests/🦀️.rs")
t = re.sub(r"max_tables:\d+,max_columns:\d+,", f"max_tables:{T},max_columns:{W},", t)
t = re.sub(r"max_tables:\d+,\.\.limits\},SqliteDatabaseLimits\{max_columns:\d+,", f"max_tables:{T - 1},..limits}},SqliteDatabaseLimits{{max_columns:{W - 1},", t)
t = re.sub(r"let limits=SqliteDatabaseLimits\{max_columns:\d+,", f"let limits=SqliteDatabaseLimits{{max_columns:{W - 1},", t)
t = re.sub(r"tables\.len\(\),\d+\)", f"tables.len(),{T})", t)
t = re.sub(r'\("tables",\d+\)', f'("tables",{T})', t)
t = re.sub(r'\("columns",\d+\)', f'("columns",{W})', t)
wr("🧪️tests/🦀️.rs", t)
t = rd("🦀️.rs")
t = re.sub(r"SQLITE_SCHEMA,\d+,\d+,c\)", f"SQLITE_SCHEMA,{T},{W},c)", t)
wr("🦀️.rs", t)
t = rd("🛂️admission/🦀️.rs")
t = re.sub(r"SQLITE_SCHEMA,\d+,\d+,count", f"SQLITE_SCHEMA,{T},{W},count", t)
wr("🛂️admission/🦀️.rs", t)
print(T, W, bytes_)

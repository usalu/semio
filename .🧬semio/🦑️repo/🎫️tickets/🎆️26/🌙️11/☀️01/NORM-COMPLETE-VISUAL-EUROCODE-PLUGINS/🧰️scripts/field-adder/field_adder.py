def sqlite(f):
    table, const, var = f.e["table"], f.e["sqlite_const"], f.e["row_var"]
    sql_type = "REAL" if f.ty == "f64" else "INTEGER NOT NULL CHECK(%s BETWEEN 0 AND 4294967295)" % f.name

    def count_of(text, pattern):
        return int(re.search(pattern, text).group(1))

    rs_text = rd(f.path("sqlite_rs"))
    columns = count_of(rs_text, r'entities\(database,"%s",(\d+),' % table)
    index = columns
    done = "%s:%s.real(" % (f.name, var) if f.ty == "f64" else "%s:unsigned(%s," % (f.name, var)
    if done in rs_text.replace(" ", ""):
        return

    def sql(text):
        line = re.search(r"^CREATE TABLE %s \(.*$" % table, text, re.M).group(0)
        if ",%s " % f.name in line:
            return text
        data_anchor = re.search(r",%s [A-Z ]+(?: NOT NULL)?(?: CHECK\([^)]*\))?," % f.after, line)
        assert data_anchor, "sql anchor"
        end = data_anchor.end()
        new = line[:end] + "%s %s," % (f.name, sql_type) + line[end:]
        if f.ty == "f64":
            new = new.rstrip(");").rstrip() + ",%s_ieee754_bits INTEGER NOT NULL,%s_ieee754_class TEXT NOT NULL);" % (f.name, f.name)
        return text.replace(line, new)
    edit(f.path("sql"), sql)

    def rs(text):
        cell = "Cell::Real(%s.%s)" % (var, f.name) if f.ty == "f64" else "Cell::Integer(i64::from(%s.%s))" % (var, f.name)
        text = once(text, r"(Cell::(?:Real|Text)\(&?%s\.%s\)|Cell::Integer\(i64::from\(%s\.%s\)\))(\]?,%s\))" % (var, f.after, var, f.after, const), lambda m: m.group(1) + "," + cell + m.group(2))
        if f.ty == "f64":
            text = once(text, r"(const %s:&\[FloatColumn\]=&\[[^\]]*)\];" % const, lambda m: m.group(1) + ",FloatColumn::Binary64(%d)];" % index)
        text = once(text, r'(entities\(database,"%s",)(\d+)' % table, lambda m: m.group(1) + str(columns + 1))
        read = "%s:%s.real(%d)?," % (f.name, var, index) if f.ty == "f64" else "%s:unsigned(%s,%d)?," % (f.name, var, index)
        return once(text, r"(%s:(?:reconstruct_text\(control,%s\.text\(\d+\)\?\)\?|%s\.real\(\d+\)\?|unsigned\(%s,\d+\)\?),)" % (f.after, var, var, var), lambda m: m.group(1) + read)
    edit(f.path("sqlite_rs"), rs)

    def ts(text):
        text = once(text, r"(%s=Omit<Exact<%s,)([^>]*?)(\">)" % (f.e["sqlite_ts_type"], f.e["model"]), lambda m: m.group(1) + m.group(2) + ('|"%s"' % f.cam if f.ty == "f64" else "") + m.group(3)) if f.ty == "f64" else text
        if f.ty == "f64":
            text = once(text, r"(const %s:readonly Ieee754Column\[\]=\[[0-9,]*?)\]\.map" % const, lambda m: m.group(1) + ",%d].map" % index)
        write = "%s.%s" % (var, f.cam) if f.ty == "f64" else "count(%s.%s)" % (var, f.cam)
        text = once(text, r'(,%s\.%s|,count\(%s\.%s\))(\],%s,options)' % (var, f.after_cam, var, f.after_cam, const), lambda m: m.group(1) + "," + write + m.group(2))
        text = once(text, r"entities\((tables\[\d+\]!),(\d+),%s," % const, lambda m: "entities(%s,%d,%s," % (m.group(1), columns + 1, const))
        read = "%s:readBinary64(%s,%d,%s)," % (f.cam, var, index, const) if f.ty == "f64" else "%s:unsigned(artifactSqliteInteger(%s,%d))," % (f.cam, var, index)
        return once(text, r"(%s:(?:readBinary64\(%s,\d+,%s\)|artifactSqliteText\(%s,\d+\)|unsigned\(artifactSqliteInteger\(%s,\d+\)\)),)" % (f.after_cam, var, const, var, var), lambda m: m.group(1) + read)
    edit(f.path("sqlite_ts"), ts)

    def tests_rs(text):
        if f.ty != "f64" or "%s.%s=v;" % (var, f.name) in text:
            return text
        anchor = "%s.%s=v;" % (var, f.spec.get("tests_after", f.after))
        return text.replace(anchor, anchor + "%s.%s=v;" % (var, f.name), 1) if anchor in text else text
    edit(f.path("sqlite_tests_rs"), tests_rs)

    def tests_ts(text):
        if f.ty != "f64" or '"%s"' % f.cam in text:
            return text
        anchor = '"%s"' % camel(f.spec.get("tests_after", f.after))
        return text.replace(anchor, '%s,"%s"' % (anchor, f.cam), 1)
    edit(f.path("sqlite_tests_ts"), tests_ts)


def sqlite_fixture(f):
    path = f.path("sqlite_fixture")
    data = rd(path)
    if '"%s"' % f.cam in data:
        return
    updated = insert_after_key(data, f.after_cam, f.cam, f.default_json)
    if updated == data:
        updated = re.sub(r'("%s":(?:"[^"]*"|[^,}\]]+)),' % f.after_cam, lambda m: m.group(0) + '"%s":%s,' % (f.cam, f.default_json), data)
    wr(path, updated)


def field_meta(f):
    unit_id = UNIT_IDS[f.unit]
    row = '    ("%s.%s", %s),\n' % (f.e["unit_prefix"], f.cam, ('mu("%s", "%s", UnitId::%s)' % (f.en, f.de, unit_id)) if unit_id else 'm("%s", "%s")' % (f.en, f.de))
    def go(text):
        if '"%s.%s"' % (f.e["unit_prefix"], f.cam) in text:
            return text
        return once(text, r'(    \("%s\.%s", [^\n]*\),\n)' % (re.escape(f.e["unit_prefix"]), f.after_cam), lambda m: m.group(1) + row)
    edit(f.path("field_meta"), go)


def insert_after_key(text, after_key, key, value):
    def go(m):
        indent = m.group(1)
        line = m.group(0)
        if not line.rstrip().endswith(","):
            line = line.rstrip("\n") + ",\n"
            return line + "%s\"%s\": %s\n" % (indent, key, value)
        return line + "%s\"%s\": %s,\n" % (indent, key, value)
    return re.sub(r'^(\s*)"%s": [^\n]*\n' % after_key, go, text, flags=re.M)


def fixtures(f):
    count = 0
    base = f.root
    for dirpath, dirs, files in os.walk(base):
        dirs[:] = [d for d in dirs if d not in ("target", "node_modules", "🧬️schema", "🔺️diff", "🔮️oracles")]
        if "/🧬️schema" in dirpath:
            continue
        for name in files:
            if not name.endswith(".json"):
                continue
            path = os.path.join(dirpath, name)
            text = rd(path)
            if '"%s"' % f.after_cam not in text or '"%s"' % f.cam in text or "sqlite" in path:
                continue
            wr(path, insert_after_key(text, f.after_cam, f.cam, f.default_json))
            count += 1
    print("  fixtures updated:", count)


def leaf_kind(f):
    spec = f.spec
    generator = f.p["generator"]
    text = rd(generator)
    line = 'L(%s, 0, "%s", "%s", "%s", %s, "%s", "%s", "%s", "%s", %s, crate="%s"),\n' % ({"beams": "B", "columns": "C"}[f.entity], f.name, f.ty, spec["kind"], '"%s"' % spec["ui_unit"] if spec.get("ui_unit") else "None", spec["leaf_en"], spec["leaf_de"], spec["group"], spec["emoji"], {"beams": "CB", "columns": "CC"}[f.entity], spec["crate"])
    anchor = "\n]\n\nCRATES = {"
    if 'L(%s, 0, "%s",' % ({"beams": "B", "columns": "C"}[f.entity], f.name) not in text:
        text = once(text, re.escape(anchor), lambda m: "\n" + line.rstrip("\n") + anchor)
    singular = f.e["singular"]
    block = re.search(r"ENTITY_PATCH_ORDER = \{.*?\n\}\n", text, re.S)
    match = re.search(r'("%s": \[[^\]]*)\]' % singular, block.group(0))
    if '"%s"' % f.name not in match.group(1):
        text = text.replace(block.group(0), block.group(0).replace(match.group(0), match.group(1) + ', "%s"]' % f.name, 1), 1)
    wr(generator, text)
    print("  generator updated")


def main():
    specs_path = [a for a in sys.argv[1:] if not a.startswith("--")][0]
    specs = json.load(open(specs_path, encoding="utf-8"))
    if specs["artifact"] == "en1998":
        sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
        import en1998_profile
        en1998_profile.apply(specs, DRY)
        return
    if specs["artifact"] == "en1990":
        sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
        import en1990_profile
        en1990_profile.apply(specs, DRY)
        return
    if specs["artifact"] == "en1996":
        sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
        import en1996_profile
        en1996_profile.apply(specs, DRY)
        return
    if specs["artifact"] == "en1997":
        sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
        import en1997_profile
        en1997_profile.apply(specs, DRY)
        return
    profile = PROFILES[specs["artifact"]]
    for crate in specs.get("crates", []):
        text = rd(profile["generator"])
        if '"%s":' % crate["name"] not in text:
            text = once(text, r'(CRATES = \{\n)', lambda m: m.group(1) + '    "%s": ("%s", "%s"),\n' % (crate["name"], crate["dir"], crate["description"]))
            wr(profile["generator"], text)
    for spec in specs["fields"]:
        print("field", spec["entity"], spec["field"])
        f = Field(profile, spec)
        json_schema(f)
        twins_from_json(f)
        model(f)
        sqlite(f)
        sqlite_fixture(f)
        field_meta(f)
        fixtures(f)
        if spec.get("kind"):
            leaf_kind(f)
    if specs.get("run_generator") and not DRY:
        subprocess.run(["python3", "-I", profile["generator"]], check=True)


if __name__ == "__main__":
    main()

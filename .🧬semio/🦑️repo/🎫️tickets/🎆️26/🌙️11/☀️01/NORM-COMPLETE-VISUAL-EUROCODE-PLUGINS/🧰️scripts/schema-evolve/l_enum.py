class Value:
    """🪙 The new token: variant name, EN + DE label, the token it follows."""

    def __init__(self, raw):
        self.enum, self.token = raw["enum"], raw["token"]
        self.variant = raw.get("variant") or pascal(self.token)
        self.label = raw["label"]
        for lang in ("en", "de"):
            if not self.label.get(lang):
                raise Unsupported(f"enum value {self.token}: both an EN and a DE label are required")
        self.after = raw.get("after")


def old_tokens(ctx, value):
    node = ctx.defs.get(value.enum)
    if not node or "enum" not in node:
        raise Unsupported(f"{value.enum} is no enum of the snapshot schema of {ctx.short}")
    return node["enum"]


def prepare(ctx):
    value = ctx.enum_value
    ctx.old = old_tokens(ctx, value)
    ctx.after_token = value.after or ctx.old[-1]
    if ctx.after_token not in ctx.old and value.token not in ctx.old:
        raise Unsupported(f"`after` {ctx.after_token!r} is not a token of {value.enum} ({', '.join(ctx.old)})")
    ctx.present = value.token in ctx.old
    ctx.old_variants = []
    return value


def schema_files(ctx):
    root = ctx.layout.any + "/🧬️schema"
    for p in walk_files(root, ("🔣️.json",)):
        text = ctx.plan.read(p)
        if f'"{ctx.enum_value.enum}"' in text and '"$defs"' in text:
            yield p, text


def json_layer(ctx):
    v = ctx.enum_value
    count = 0
    for p, text in schema_files(ctx):
        try:
            d = json.loads(text)
        except ValueError:
            continue
        node = d.get("$defs", {}).get(v.enum)
        if not node or "enum" not in node or v.token in node["enum"]:
            continue

        def go(t):
            root = parse(t)
            en = get(root, "$defs").get(v.enum).value
            t = l_leaf.insert_after_item(t, en.get("enum").value, ctx.after_token, v.token)
            en = get(parse(t), "$defs").get(v.enum).value
            ui = en.get("x-semio-ui")
            opts = ui and ui.value.get("options")
            if opts and not opts.value.get(v.token):
                key = ctx.after_token if opts.value.get(ctx.after_token) else opts.value.members[-1].key
                t = l_leaf.insert_after_member(t, opts.value, key, v.token, dict(v.label))
            return t
        from ctx import span_edit
        span_edit(ctx.plan, p, go)
        count += 1
    if not count:
        raise Unsupported(f"no schema document of {ctx.short} defines the enum {v.enum} with the token missing")
    ctx.plan.note(f"schema: {v.enum} gains `{v.token}` in {count} schema documents (labels EN + DE in x-semio-ui options); the twins (ts, proto, graphql, rust schema) are regenerated by `schema twins generate` in the apply run")


def rust_files(ctx, root=None):
    for p in walk_files(root or ctx.layout.dir, (".rs",)):
        yield p


def model_layer(ctx):
    v = ctx.enum_value
    rx = re.compile(r"^pub enum %s \{\n((?:    \w+,\n)+)\}\n" % re.escape(v.enum), re.M)
    hit = None
    for p in rust_files(ctx):
        if not p.endswith("/🦀️.rs") or "/🧬️schema/" not in p:
            continue
        text = ctx.plan.read(p)
        m = rx.search(text)
        if m:
            hit = (p, text, m)
            break
    if not hit:
        raise Unsupported(f"`pub enum {v.enum}` with plain unit variants not found in the Rust model of {ctx.short}")
    p, text, m = hit
    variants = re.findall(r"    (\w+),\n", m.group(1))
    if len(variants) != len(ctx.old):
        raise Unsupported(f"the Rust enum has {len(variants)} variants but the schema {len(ctx.old)} tokens")
    ctx.variant_of = dict(zip(ctx.old, variants))
    ctx.model_path = p
    if v.variant in variants:
        return
    after_variant = ctx.variant_of[ctx.after_token]
    at = m.start(1) + m.group(1).index(f"    {after_variant},\n") + len(f"    {after_variant},\n")
    ctx.plan.write(p, text[:at] + f"    {v.variant},\n" + text[at:])
    ctx.plan.note(f"model: variant {v.enum}::{v.variant} after {after_variant} in {ctx.plan.rel(p)}")


def arms(text, mask, enum):
    """🦴 Every `match` whose arm patterns mention `enum::`: [(match start, [(pattern text, pattern start, arm end)])]."""
    out = []
    for m in re.finditer(r"\bmatch\b", text):
        if not mask[m.start()]:
            continue
        depth, i = 0, m.end()
        while i < len(text):
            ch = text[i]
            if mask[i] and ch in "([":
                depth += 1
            elif mask[i] and ch in ")]":
                depth -= 1
            elif mask[i] and ch == "{" and depth == 0:
                break
            elif mask[i] and ch == ";" and depth == 0:
                i = len(text)
            i += 1
        if i >= len(text):
            continue
        close = match_close(text, mask, i)
        items, pos = [], i + 1
        while pos < close:
            while pos < close and text[pos] in " \t\r\n,":
                pos += 1
            if pos >= close:
                break
            arrow, d = None, 0
            for j in range(pos, close):
                if not mask[j]:
                    continue
                if text[j] in "([{":
                    d += 1
                elif text[j] in ")]}":
                    d -= 1
                elif d == 0 and text.startswith("=>", j):
                    arrow = j
                    break
            if arrow is None:
                break
            k = arrow + 2
            while k < close and text[k] in " \t\r\n":
                k += 1
            if k < close and text[k] == "{" and mask[k]:
                end = match_close(text, mask, k) + 1
                while end < close and text[end] in " \t":
                    end += 1
                if end < close and text[end] == ",":
                    end += 1
            else:
                d, end = 0, k
                while end < close:
                    if mask[end]:
                        if text[end] in "([{":
                            d += 1
                        elif text[end] in ")]}":
                            d -= 1
                        elif text[end] == "," and d == 0:
                            end += 1
                            break
                    end += 1
            items.append((text[pos:arrow].strip(), pos, end))
            pos = end
        if items and any(re.search(r"\b%s::" % re.escape(enum), text[a:b]) for _, a, b in items):
            out.append((m.start(), items))
    return out


def has_wildcard(items):
    for pattern, _, _ in items:
        head = re.split(r"\sif\s", pattern)[0].strip()
        if head == "_" or re.fullmatch(r"[a-z_]\w*(?:\s*@\s*_)?", head):
            return True
        if any(part.strip() == "_" for part in head.split("|")):
            return True
    return False


def clone_arm(text, a, b, enum, after_variant, after_token, v):
    """🪞 The arm cloned for the new value when its body is a mechanical mapping of variant or token; None when the body carries other data (manual arm)."""
    arm = text[a:b]
    pat, body = arm.split("=>", 1)
    swaps = [(re.compile(r"\b%s::%s\b" % (re.escape(enum), re.escape(after_variant))), f"{enum}::{v.variant}"),
             (re.compile(r'"%s"' % re.escape(after_token)), f'"{v.token}"')]
    new_body = body
    for rx, to in swaps:
        new_body = rx.sub(to, new_body)
    new_pat = pat
    for rx, to in swaps:
        new_pat = rx.sub(to, new_pat)
    if new_body == body or "|" in pat.split(" if ")[0]:
        return None
    return new_pat + "=>" + new_body


def arms_edit(ctx, text, path):
    """✂️ Adds the cloned arm to every match of the file that maps the `after` variant mechanically; returns the new text and the matches left for manual work."""
    v, enum = ctx.enum_value, ctx.enum_value.enum
    if f"{enum}::" not in text:
        return text, []
    mask = code_mask(text, "rs")
    manual, edits = [], []
    after_variant = ctx.variant_of[ctx.after_token]
    for start, items in arms(text, mask, enum):
        if any(re.search(r"\b%s::%s\b" % (re.escape(enum), re.escape(v.variant)), p) for p, _, _ in items):
            continue
        if any(re.fullmatch(r'"%s"' % re.escape(v.token), p.strip()) for p, _, _ in items):
            continue
        hit = next(((p, a, b) for p, a, b in items if re.fullmatch(r"(?:%s::%s|\"%s\")" % (re.escape(enum), re.escape(after_variant), re.escape(ctx.after_token)), re.split(r"\sif\s", p)[0].strip())), None)
        line = text.count("\n", 0, start) + 1
        if not hit:
            if not has_wildcard(items):
                manual.append((line, "no arm for the `after` variant to clone"))
            continue
        _, a, b = hit
        clone = clone_arm(text, a, b, enum, after_variant, ctx.after_token, v)
        if clone is None:
            if not has_wildcard(items):
                manual.append((line, "arm of the `after` variant carries other data"))
            continue
        tail = text[a:b].rstrip()
        index = [i for i, it in enumerate(items) if it[1] == a][0]
        gap = text[items[index - 1][2]:a] if index else ("\n" + re.match(r" *", text[text.rfind("\n", 0, a) + 1:]).group(0) if "\n" in text[text.rfind("\n", 0, a):a] else "")
        comma = tail.endswith(",")
        edits.append((a + len(tail), ("" if comma else ",") + gap + clone.strip().rstrip(",") + ("," if comma else "")))
    for at, add in sorted(edits, reverse=True):
        text = text[:at] + add + text[at:]
    return text, manual


def token_lists(ctx, text):
    """🔖 Quoted token lists equal to the old token list (`&["a", "b"]`, `["a","b"]`) get the new token."""
    v = ctx.enum_value
    rx = re.compile(r"(\[\s*)((?:\"[^\"]*\"\s*,\s*)*\"[^\"]*\")(\s*,?\s*\])")

    def swap(m):
        toks = re.findall(r'"([^"]*)"', m.group(2))
        if toks != ctx.old:
            return m.group(0)
        sep = re.search(r'"(\s*,\s*)"', m.group(2))
        i = toks.index(ctx.after_token) + 1
        return m.group(1) + (sep.group(1) if sep else ", ").join(f'"{x}"' for x in toks[:i] + [v.token] + toks[i:]) + m.group(3)
    return rx.sub(swap, text)


def arms_layer(ctx):
    v = ctx.enum_value
    todo = []
    for p in rust_files(ctx, ctx.layout.dir):
        rel = p[len(ctx.layout.any) + 1:]
        if (rel.startswith("🚪️io/") or p == ctx.model_path) and "/🧪️tests/" not in p:
            todo.append(p)
    added = 0
    for p in todo:
        text = ctx.plan.read(p)
        new, manual = arms_edit(ctx, text, p)
        new = token_lists(ctx, new)
        if new != text:
            ctx.plan.write(p, new)
            added += 1
        for line, why in manual:
            ctx.manual.append(f"{ctx.plan.rel(p)}:{line} {why}")
    ctx.plan.note(f"arms: mechanical arms cloned in {added} Rust files of the model and the io tree")
    ts = 0
    for p in walk_files(ctx.layout.dir + "/", (".ts",)):
        if "/🧬️schema/" in p or "/🧪️tests/" in p:
            continue
        text = ctx.plan.read(p)
        rx = re.compile(r"(\[\s*" + r"\s*,\s*".join(f'"{re.escape(t)}"' for t in ctx.old) + r")(\s*\])")
        new = rx.sub(lambda m: m.group(1) + f',"{v.token}"' + m.group(2), text)
        if new != text:
            ctx.plan.write(p, new)
            ts += 1
    ctx.plan.note(f"arms: {ts} TypeScript choice arrays get the token")


def ddl_layer(ctx):
    v = ctx.enum_value
    changed = False
    for p in walk_files(ctx.layout.dir, (".sql",)):
        if "🪶️sqlite" not in p:
            continue
        text = ctx.plan.read(p)
        rx = re.compile(r"(IN\s*\(\s*)((?:'[^']*'\s*,\s*)*'[^']*')(\s*\))")

        def swap(m):
            toks = re.findall(r"'([^']*)'", m.group(2))
            if toks != ctx.old:
                return m.group(0)
            sep = "," if re.search(r"'\s*,'", m.group(2)) else ", "
            i = toks.index(ctx.after_token) + 1
            return m.group(1) + sep.join(f"'{t}'" for t in toks[:i] + [v.token] + toks[i:]) + m.group(3)
        new = rx.sub(swap, text)
        if new != text:
            old_sql = text
            ctx.plan.write(p, new)
            changed = True
            import l_codec
            l_codec.contract(ctx, old_sql, new)
    if changed:
        ctx.plan.note(f"sqlite: CHECK lists of the columns of {v.enum} extended in the DDL (contract recomputed with python sqlite3)")


def meta_layer(ctx):
    v = ctx.enum_value
    count = 0
    for p in walk_files(ctx.layout.dir, (".rs",)):
        text = ctx.plan.read(p)
        if "NormFieldChoice" not in text or "/🧪️tests/" in p:
            continue
        groups, cur = [], []
        for m in l_wiring.ITEM.finditer(text):
            if cur and re.fullmatch(r",\s*", text[cur[-1].end():m.start()]):
                cur.append(m)
            else:
                if len(cur) > 1:
                    groups.append(cur)
                cur = [m]
        if len(cur) > 1:
            groups.append(cur)
        edits = []
        for g in groups:
            values = [re.search(r'"([^"]*)"', m.group(0)).group(1) for m in g]
            if values != ctx.old:
                continue
            k = values.index(ctx.after_token)
            sep = text[g[k].end():g[k + 1].start()] if k + 1 < len(g) else text[g[k - 1].end():g[k].start()]
            edits.append((g[k].end(), sep + l_wiring.choice_item(text, {"token": v.token, "label": v.label})))
        for at, add in sorted(edits, reverse=True):
            text = text[:at] + add + text[at:]
        if edits:
            ctx.plan.write(p, text)
            count += len(edits)
    ctx.plan.note(f"field-meta: {count} choice lists of {v.enum} get the entry with EN + DE labels")


def report_layer(ctx):
    v, enum = ctx.enum_value, ctx.enum_value.enum
    sites = []
    for p in walk_files(NORM, (".rs",)):
        if p.endswith("/🧬️schema/🦀️.rs"):
            continue
        text = ctx.plan.read(p)
        if f"{enum}::" not in text:
            continue
        if "/🗿️artifacts/" in p and not p.startswith(ctx.layout.dir) and ctx.layout.model_crate not in text:
            continue
        rel = ctx.plan.rel(p)
        mask = code_mask(text, "rs")
        for start, items in arms(text, mask, enum):
            if any(re.search(r"\b%s::%s\b" % (re.escape(enum), re.escape(v.variant)), pt) for pt, _, _ in items) or has_wildcard(items):
                continue
            sites.append(f"{rel}:{text.count(chr(10), 0, start) + 1} exhaustive match without wildcard, add the arm by hand")
        for m in re.finditer(r"\[\s*(?:%s::\w+\s*,\s*){%d,}%s::\w+\s*,?\s*\]" % (re.escape(enum), max(1, len(ctx.old) - 2), re.escape(enum)), text):
            if f"{enum}::{v.variant}" not in m.group(0):
                sites.append(f"{rel}:{text.count(chr(10), 0, m.start()) + 1} list of variants, add the entry by hand")
    for line in dict.fromkeys(ctx.manual + sites):
        ctx.plan.note("MANUAL " + line)
    ctx.manual = list(dict.fromkeys(ctx.manual + sites))
    ctx.plan.note(f"consumers: {len(ctx.manual)} sites need a manual arm or list entry (listed as MANUAL)")


def layers():
    def step(fn, needs_model=True):
        def run(ctx):
            if not hasattr(ctx, "old"):
                prepare(ctx)
                ctx.manual = []
            if needs_model and not hasattr(ctx, "model_path"):
                model_layer(ctx)
            if ctx.present and fn is not report_layer:
                return
            fn(ctx)
        return run
    return [("schema", step(json_layer, False)), ("model", step(lambda c: None)), ("arms", step(arms_layer)), ("sqlite", step(ddl_layer)), ("wiring", step(meta_layer)), ("consumers", step(report_layer))]

"""🧿 add-enum-value: one more token of an existing enum through the schema JSON, the Rust model, the mechanical arms of the artifact codecs (SQLite DDL CHECK lists, Rust helper arms, TypeScript choice arrays), the field-meta choice lists and the SQLite contract; every other exhaustive `match` of the enum in the norm tree is reported with file and line (manual arm), a wildcard arm is never inserted."""

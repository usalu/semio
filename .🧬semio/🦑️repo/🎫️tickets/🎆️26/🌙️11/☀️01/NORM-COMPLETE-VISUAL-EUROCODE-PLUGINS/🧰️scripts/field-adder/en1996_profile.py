def diff_json_coll(colls):
    path = DIFF + "/🔣️.json"

    def go(text):
        for c in colls:
            root = J.parse(text)
            defs = root.get("$defs").value
            if defs.get(c.patch):
                continue
            data = json.loads(text)["$defs"]
            snap = "https://json.schemas.assets.semio-tech.com/s/norm/en1996/snapshot.json#/$defs/%s"
            copies = {}
            for part in ("Removal", "Insertion", "Relocation", "Modification", "Delta"):
                blob = json.dumps(data["En1996Placement" + part]).replace("En1996Placement", "En1996" + c.single).replace(snap % "Placement", snap % c.row)
                copies["En1996%s%s" % (c.single, part)] = json.loads(blob)
            patch_props = {}
            for f in c.fields:
                if f.ty == "f64":
                    patch_props[f.cam] = {"anyOf": [{"type": "number"}, {"type": "null"}]}
                elif f.ty == "String":
                    patch_props[f.cam] = {"anyOf": [{"type": "string"}, {"type": "null"}]}
                else:
                    patch_props[f.cam] = {"anyOf": [{"$ref": snap % f.ty}, {"type": "null"}]}
            patch = {"title": c.patch, "type": "object", "additionalProperties": False, "properties": patch_props, "x-semio-formats": ["🔣️jsonschema", "🟦️typescript"]}
            after = "En1996PlacementDelta"
            for name, value in [(c.patch, patch)] + list(copies.items()):
                text = J.insert_member(text, J.parse(text).get("$defs").value, after, name, J.inline(value))
                after = name
            root = J.parse(text)
            text = J.insert_member(text, root.get("properties").value, "cases", c.camel, J.render({"$ref": "#/$defs/%s" % c.delta, "x-semio-state": "artifact"}, text, 2))
            root = J.parse(text)
            required = root.get("required").value
            names = [json.loads(i.text) for i in required.items]
            if c.camel not in names:
                text = J.insert_item(text, required, names.index("cases"), json.dumps(c.camel))
        return text
    edit(path, go)



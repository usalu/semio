def replay_value_bytes(sql, document):
    """Rows and value bytes of the SQLite database the Rust writer builds for `document`, replayed with python `sqlite3` column types: integers and reals count 8, text its UTF-8 length, IEEE pairs 8 and `finite` (6)."""
    con = sqlite3.connect(":memory:")
    con.executescript(sql)
    names = {t for t, *_ in TABLE_TREE}
    columns = {t: [r[1] for r in con.execute("pragma table_info(%s)" % t)] for t in names if con.execute("select 1 from sqlite_schema where name=?", (t,)).fetchone()}
    total = {"rows": 1, "bytes": 0}
    doc_columns = [r[1] for r in con.execute("pragma table_info(en1996_document)")]
    total["bytes"] += sum(8 if c == "id" else size_of(document.get(fa.camel(c))) for c in doc_columns)

    def cell(column, row):
        if column == "id" or column in PARENT_COLUMNS or column == "ordinal":
            return 8
        if column == "logical_id":
            return len(row["id"].encode())
        if column.endswith("_ieee754_bits"):
            return 8
        if column.endswith("_ieee754_class"):
            return 6
        return size_of(row.get(COLUMN_KEYS.get(column, fa.camel(column))))

    def walk(rows, table):
        for row in rows:
            total["rows"] += 1
            total["bytes"] += sum(cell(c, row) for c in columns[table])
            for child, key, parent in TABLE_TREE:
                if parent == table and child in columns:
                    walk(row.get(key, []), child)
    for table, key, parent in TABLE_TREE:
        if parent is None and table in columns:
            walk(document.get(key, []), table)
    return total["rows"], total["bytes"]


def size_of(value):
    if value is None:
        return 0
    if isinstance(value, str):
        return len(value.encode())
    return 8


def replay_schema(sql):
    con = sqlite3.connect(":memory:")
    con.executescript(sql)
    rows = con.execute("select name, sql from sqlite_schema where type='table' order by name").fetchall()
    widths = {n: len(con.execute("pragma table_info(%s)" % n).fetchall()) for n, _ in rows}
    return sum(len(n.encode()) + len(q.encode()) for n, q in rows), dict(sorted(widths.items()))



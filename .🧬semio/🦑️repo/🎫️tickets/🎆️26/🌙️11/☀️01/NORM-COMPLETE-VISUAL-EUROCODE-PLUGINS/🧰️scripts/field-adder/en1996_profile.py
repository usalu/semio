def model_wall(fields, literals):
    """The struct fields are generated from the schema; the struct literals (Default implementation, examples) name the new fields by hand."""
    def go(text):
        for f in fields:
            if len(re.findall(r"^\s+%s: " % f.name, text, re.M)) >= literals:
                continue
            found = len(re.findall(r"^(\s+)%s: [^,\n]+,\n" % f.after, text, re.M))
            assert found == literals, ("wall literals", f.after, found)
            text = re.sub(r"^(\s+)%s: [^,\n]+,\n" % f.after, lambda m: m.group(0) + "%s%s: %s,\n" % (m.group(1), f.name, f.default_rs), text, flags=re.M)
        return text
    edit(SNAP + "/🦀️.rs", go)



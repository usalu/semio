class Coll:
    """One new top-level row collection: `camel` is the snapshot field, `row` the Rust row type, `single` the delta name stem."""

    def __init__(self, spec, enums):
        self.spec = spec
        self.camel, self.snake, self.row, self.single = spec["camel"], snake_of(spec["camel"]), spec["row"], spec["single"]
        self.table, self.const = spec["table"], spec["const"]
        self.fields = [Field(dict(f, after=None), enums, "row") for f in spec["fields"]]
        self.delta, self.patch, self.key = "En1996%sDelta" % self.single, "En1996%sPatch" % self.single, "%sKey" % self.row
        self.sql_names = [f.sql_name for f in self.fields]

    @property
    def data_columns(self):
        return 4 + len(self.fields)

    @property
    def floats(self):
        return [4 + i for i, f in enumerate(self.fields) if f.ty == "f64"]

    @property
    def width(self):
        return self.data_columns + 2 * len(self.floats)


def collections_of(specs, enums):
    return [Coll(c, enums) for c in specs.get("collections", [])]


def model_coll(colls, literals):
    """The row structs and the struct fields are generated from the schema; the snapshot literals name the new collections by hand."""
    def go(text):
        for c in colls:
            if len(re.findall(r"^\s+%s: Vec::new\(\),\n" % c.snake, text, re.M)) >= literals:
                continue
            found = len(re.findall(r"^(\s+)placements: Vec::new\(\),\n", text, re.M))
            assert found == literals, ("snapshot literals", found)
            text = re.sub(r"^(\s+)placements: Vec::new\(\),\n", lambda m: m.group(0) + "%s%s: Vec::new(),\n" % (m.group(1), c.snake), text, flags=re.M)
        return text
    edit(SNAP + "/🦀️.rs", go)

    def artifact(text):
        for c in colls:
            if "%s: self.%s.clone()," % (c.snake, c.snake) in text:
                continue
            text = once(text, r"(            cases: self\.cases\.clone\(\),\n)", lambda m: m.group(1) + "            %s: self.%s.clone(),\n" % (c.snake, c.snake))
            text = once(text, r"(            cases: snapshot\.cases,\n)", lambda m: m.group(1) + "            %s: snapshot.%s,\n" % (c.snake, c.snake))
        return text
    edit(SCHEMA + "/🦀️.rs", artifact)



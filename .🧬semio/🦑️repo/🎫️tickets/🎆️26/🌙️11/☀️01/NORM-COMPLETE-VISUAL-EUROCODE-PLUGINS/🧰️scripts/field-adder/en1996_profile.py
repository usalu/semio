def fixtures_coll(colls):
    count = 0
    for path in json_files():
        text = rd(path)
        if '"placements"' not in text or '"cases"' not in text or all('"%s"' % c.camel in text for c in colls):
            continue
        root = J.parse(text)
        edits = []
        for trail, obj in J.find_objects(root, lambda o: o.get("placements") is not None and o.get("cases") is not None and o.get("walls") is not None):
            anchor = obj.get("cases")
            colon = text[anchor.key_end:anchor.value.start]
            index = obj.members.index(anchor)
            members = obj.members
            separator = text[anchor.value.end:members[index + 1].key_start] if index + 1 < len(members) else text[members[index - 1].value.end:anchor.key_start]
            line_start = text.rfind("\n", 0, anchor.key_start) + 1
            level = (anchor.key_start - line_start) // 2 if text[line_start:anchor.key_start].strip() == "" else 0
            insertion = ""
            for c in colls:
                if obj.get(c.camel):
                    continue
                if anchor.value.kind == "array":
                    value = "[]"
                elif anchor.value.kind == "object":
                    sibling = text[obj.get("placements").value.start:obj.get("placements").value.end]
                    value = sibling if re.fullmatch(r'\{\s*"removed":\s*\[\s*\],\s*"inserted":\s*\[\s*\],\s*"moved":\s*\[\s*\],\s*"modified":\s*\[\s*\]\s*\}', sibling) else J.render({"removed": [], "inserted": [], "moved": [], "modified": []}, text, level)
                else:
                    value = "null"
                insertion += separator + json.dumps(c.camel) + colon + value
            if insertion:
                edits.append((anchor.value.end, insertion))
        if edits:
            wr(path, J.apply_edits(text, edits))
            count += 1
    print("  collection fixtures updated:", count)



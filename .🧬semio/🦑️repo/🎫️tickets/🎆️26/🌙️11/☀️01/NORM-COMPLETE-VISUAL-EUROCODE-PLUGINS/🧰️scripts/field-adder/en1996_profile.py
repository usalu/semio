def snapshot_json(fields, enums):
    path = SNAP + "/🔣️.json"

    def go(text):
        for f in fields:
            root = J.parse(text)
            wall = root.get("$defs").value.get("MasonryWall").value
            props = wall.get("properties").value
            if not props.get(f.cam):
                text = J.insert_member(text, props, f.after_cam, f.cam, J.render(property_schema(f), text, 4))
                root = J.parse(text)
                wall = root.get("$defs").value.get("MasonryWall").value
            required = wall.get("required").value
            names = [json.loads(item.text) for item in required.items]
            if f.cam not in names:
                text = J.insert_item(text, required, names.index(f.after_cam), json.dumps(f.cam))
        for enum in enums.values():
            root = J.parse(text)
            text = json_defs_insert(text, root, "FrostClass", enum["name"], enum_schema(enum))
        return text
    edit(path, go)



def row_schema(c, ref_style):
    props = {"id": {"type": "string", "x-semio-ui": {"widget": "text", "label": {"en": c.spec["id_en"], "de": c.spec["id_de"]}}}}
    for f in c.fields:
        if f.name == "wall_id":
            props[f.cam] = {"type": "string", "x-semio-ui": {"widget": "reference", "label": {"en": f.en, "de": f.de}, "ref": {"kind": "wall"}}}
        elif f.enum:
            props[f.cam] = {"$ref": "#/$defs/%s" % f.ty, "x-semio-ui": {"label": {"en": f.en, "de": f.de}}} if ref_style else {"type": "string", "enum": enum_variants(f.enum), "x-semio-ui": {"label": {"en": f.en, "de": f.de}}}
        else:
            props[f.cam] = property_schema(f)
    return {"title": c.row, "type": "object", "additionalProperties": False, "required": ["id"] + [f.cam for f in c.fields], "properties": props}



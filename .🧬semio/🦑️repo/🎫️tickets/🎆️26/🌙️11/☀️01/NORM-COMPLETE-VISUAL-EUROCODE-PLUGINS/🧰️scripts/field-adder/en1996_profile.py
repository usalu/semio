def sql_text(f):
    if f.enum:
        return "%s TEXT NOT NULL CHECK (%s IN (%s))" % (f.sql_name, f.sql_name, ",".join("'%s'" % v for v in enum_variants(f.enum)))
    if f.ty == "String":
        return "%s TEXT NOT NULL" % f.sql_name

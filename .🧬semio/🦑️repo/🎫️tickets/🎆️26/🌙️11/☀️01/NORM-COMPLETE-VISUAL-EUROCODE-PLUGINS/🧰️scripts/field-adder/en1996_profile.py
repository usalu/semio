def fixtures_wall(fields):
    count = 0
    first = fields[0]
    for path in json_files():
        text = rd(path)
        if '"%s"' % first.after_cam not in text or '"%s"' % first.cam in text:
            continue
        root = J.parse(text)
        edits = []
        for trail, obj in J.find_objects(root, is_wall_object):
            anchor = obj.get(first.after_cam)
            patch = is_patch(trail)
            colon = text[anchor.key_end:anchor.value.start]
            members = obj.members
            index = members.index(anchor)
            prev_end = members[index - 1].value.end if index else None
            nxt = members[index + 1].key_start if index + 1 < len(members) else None
            separator = text[members[index].value.end:nxt] if nxt is not None else text[prev_end:anchor.key_start]
            insertion = ""
            for f in fields:
                insertion += separator + json.dumps(f.cam) + colon + ("null" if patch else f.default_json)
            edits.append((anchor.value.end, insertion))
        if edits:
            wr(path, J.apply_edits(text, edits))
            count += 1
    print("  fixtures updated:", count)



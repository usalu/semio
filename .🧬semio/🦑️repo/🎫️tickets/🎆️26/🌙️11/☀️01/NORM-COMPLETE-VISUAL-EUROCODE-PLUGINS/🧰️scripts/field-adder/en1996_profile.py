        floats = "".join(",FloatColumn::Binary64(%d)" % (columns + i) for i, f in enumerate(fields) if f.ty == "f64")
        text = once(text, r"(const WALL_FLOATS: &\[FloatColumn\] = &\[[^\]]*)\];", lambda m: m.group(1) + floats + "];")

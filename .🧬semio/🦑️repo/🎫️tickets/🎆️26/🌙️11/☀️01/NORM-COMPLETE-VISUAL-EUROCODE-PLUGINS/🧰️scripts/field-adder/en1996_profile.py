def ui_of(f):
    ui = {"label": {"en": f.en, "de": f.de}}
    if f.ty == "f64":
        ui = {"widget": "stepper", "label": ui["label"], **({"unit": f.spec["ui_unit"]} if f.spec.get("ui_unit") else {}), **({"displayUnit": f.spec["display_unit"], "displayFactor": f.spec["display_factor"]} if f.spec.get("display_unit") else {}), "step": f.spec.get("step", 1), "precision": f.spec.get("precision", 0)}

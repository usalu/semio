#!/usr/bin/env python3
"""Generates the proto/graphql/ts twins of the structural-scene schema from the Rust declarations. Usage: python3 -I wp01-gen-twins.py [--check]"""
import re, sys, pathlib

ROOT = pathlib.Path("/home/deck/semio/✏️s/🔌️plugins/📕️norm/🎬️structural-scene/🧬️schema")
MODULES = ["📐️geometry", "🎨️appearance", "🧱️section-shapes", "🏹️load-glyphs", "🧩️entities", "🏷️annotations", "🔺️scene-diff", "✅️validation"]
PARTS = {"📈️diagram2d": "diagram2d", "🕹️handles": "handles"}
EXTERNAL = {"FieldBinding": "🕹️handles"}
SCALARS = {"f64": ("number", "double", "Float"), "u8": ("number", "uint32", "Int"), "u32": ("number", "uint32", "Int"), "u64": ("number", "uint64", "Int"), "i32": ("number", "int32", "Int"), "bool": ("boolean", "bool", "Boolean"), "String": ("string", "string", "String")}

def match_brace(text, start):
    depth = 0
    for i in range(start, len(text)):
        if text[i] == "{": depth += 1
        elif text[i] == "}":
            depth -= 1
            if depth == 0: return i
    raise ValueError("unbalanced")

def split_top(text):
    parts, depth, cur = [], 0, ""
    for ch in text:
        if ch in "<{(": depth += 1
        elif ch in ">})": depth -= 1
        if ch == "," and depth == 0:
            parts.append(cur.strip()); cur = ""
        else: cur += ch
    if cur.strip(): parts.append(cur.strip())
    return [p for p in parts if p]

def camel(s):
    h, *t = s.split("_")
    return h + "".join(x.capitalize() for x in t)

def lower_camel(s):
    return s[0].lower() + s[1:]

def snake(s):
    return re.sub(r"(?<!^)(?=[A-Z])", "_", s).lower()

def parse_fields(body):
    out = []
    for f in split_top(body):
        m = re.match(r"(?:pub\s+)?(\w+)\s*:\s*(.+)$", f, re.S)
        out.append((m.group(1), re.sub(r"\s+", "", m.group(2)).replace("crate::", "")))
    return out

def parse_type(t):
    m = re.match(r"(Option|Vec|Box)<(.+)>$", t)
    return (m.group(1), parse_type(m.group(2))) if m else t

def parse():
    items = []
    for mod in MODULES:
        text = "\n".join(l for l in (ROOT / mod / "🦀️.rs").read_text().splitlines() if not l.strip().startswith("//"))
        for macro in re.finditer(r"(records|variants|choices)!\s*\{", text):
            end = match_brace(text, macro.end() - 1)
            block = text[macro.end():end]
            for it in re.finditer(r"pub\s+(struct|enum)\s+(\w+)\s*\{", block):
                b = block[it.end():match_brace(block, it.end() - 1)] if False else block[it.end(): it.end() + (match_brace(block, it.end() - 1) - it.end())]
                if it.group(1) == "struct":
                    items.append(("record", it.group(2), parse_fields(b)))
                elif macro.group(1) == "choices":
                    items.append(("choice", it.group(2), [v for v in split_top(b)]))
                else:
                    vs = []
                    for v in split_top(b):
                        m = re.match(r"(\w+)\s*\{(.*)\}$", v, re.S)
                        if m: vs.append((m.group(1), "named", parse_fields(m.group(2))))
                        else:
                            m = re.match(r"(\w+)\s*\((.+)\)$", v, re.S)
                            vs.append((m.group(1), "newtype", re.sub(r"\s+", "", m.group(2)).replace("crate::", "")) if m else (v.strip(), "unit", None))
                    items.append(("variant", it.group(2), vs))
    return items

def ts_type(t):
    t = parse_type(t)
    if isinstance(t, tuple):
        k, inner = t
        s = ts_type_node(inner)
        return f"{s}[]" if k == "Vec" else (f"{s} | null" if k == "Option" else s)
    return ts_type_node(t)

def ts_type_node(t):
    if isinstance(t, tuple):
        k, inner = t
        s = ts_type_node(inner)
        return f"{s}[]" if k == "Vec" else (f"({s} | null)" if k == "Option" else s)
    return SCALARS[t][0] if t in SCALARS else t

def proto_field(t):
    t = parse_type(t)
    prefix = ""
    if isinstance(t, tuple):
        prefix = "repeated " if t[0] == "Vec" else ("optional " if t[0] == "Option" else "")
        t = t[1]
        while isinstance(t, tuple): t = t[1]
    return prefix, (SCALARS[t][1] if t in SCALARS else t)

def gql_type(t):
    t = parse_type(t)
    def node(x):
        if isinstance(x, tuple):
            k, inner = x
            if k == "Vec": return f"[{node(inner)}!]"
            if k == "Box": return node(inner)
            return node(inner)
        return SCALARS[x][2] if x in SCALARS else x
    if isinstance(t, tuple) and t[0] == "Option": return node(t[1])
    if isinstance(t, tuple) and t[0] == "Box": return node(t[1]) + "!"
    return node(t) + "!"

def emit(items):
    ts = ["/** 🎬️ Structural scene wire twin, mirrors `./🦀️.rs` (canonical JSON: camelCase keys, variants as `{ kind, data }`). Generated by `wp01-gen-twins.py`. */"]
    ts += [f'export * from "./{p}/🟦️.ts";' for p in PARTS]
    ts += ['import type { FieldBinding } from "./🕹️handles/🟦️.ts";', ""]
    proto = ['syntax = "proto3";', "package semio.norm.structuralscene;", ""]
    proto += [f'import "{p}/🛰️.proto";' for p in PARTS]
    proto += ["", "message Empty {}", ""]
    gql = ["# 🎬️ Structural scene GraphQL twin, mirrors ./🦀️.rs. Generated by wp01-gen-twins.py. u64 maps to Int."]
    gql += [f"#import {p}/🔗️.graphql" for p in PARTS] + [""]
    for kind, name, body in items:
        if kind == "record":
            ts += [f"export interface {name} {{"] + [f"  {camel(f)}: {ts_type(t)};" for f, t in body] + ["}", ""]
            proto += [f"message {name} {{"] + [f"  {' '.join(x for x in proto_field(t) if x.endswith(' ') or True).replace('  ', ' ')} {f} = {i};".replace("  ", " ") for i, (f, t) in enumerate(body, 1)] + ["}", ""]
            gql += [f"type {name} {{"] + [f"  {camel(f)}: {gql_type(t)}" for f, t in body] + ["}", ""]
        elif kind == "choice":
            ts += [f"export type {name} = " + " | ".join(f'"{lower_camel(v)}"' for v in body) + ";", ""]
            proto += [f"enum {name} {{"] + [f"  {snake(name).upper()}_{snake(v).upper()} = {i};" for i, v in enumerate(body)] + ["}", ""]
            gql += [f"enum {name} {{"] + [f"  {v}" for v in body] + ["}", ""]
        else:
            arms, pm, gu, gt = [], [], [], []
            for i, (v, shape, data) in enumerate(body, 1):
                tag = lower_camel(v)
                if shape == "unit":
                    arms.append(f'  | {{ kind: "{tag}" }}')
                    pm.append(f"    Empty {snake(v)} = {i};")
                    gt += [f"type {name}{v} {{", "  kind: String!", "}", ""]
                elif shape == "newtype":
                    arms.append(f'  | {{ kind: "{tag}"; data: {ts_type(data)} }}')
                    p, ptype = proto_field(data)
                    pm.append(f"    {ptype} {snake(v)} = {i};")
                    gt += [f"type {name}{v} {{", "  kind: String!", f"  data: {gql_type(data)}", "}", ""]
                else:
                    arms.append(f'  | {{ kind: "{tag}"; data: {{ ' + "; ".join(f"{camel(f)}: {ts_type(t)}" for f, t in data) + " } }")
                    pm.insert(0, f"  message {v}Data {{")
                    msg = [f"  message {v}Data {{"] + [f"    {pf}{pt} {f} = {j};" for j, (f, t) in enumerate(data, 1) for pf, pt in [proto_field(t)]] + ["  }"]
                    pm.pop(0)
                    pm.append(("MSG", msg))
                    pm.append(f"    {v}Data {snake(v)} = {i};")
                    gt += [f"type {name}{v}Data {{"] + [f"  {camel(f)}: {gql_type(t)}" for f, t in data] + ["}", "", f"type {name}{v} {{", "  kind: String!", f"  data: {name}{v}Data!", "}", ""]
                gu.append(f"{name}{v}")
            ts += [f"export type {name} ="] + arms[:-1] + [arms[-1] + ";", ""]
            msgs = [x[1] for x in pm if isinstance(x, tuple)]
            fields = [x for x in pm if not isinstance(x, tuple)]
            proto += [f"message {name} {{"] + [l for m in msgs for l in m] + ["  oneof kind {"] + fields + ["  }", "}", ""]
            gql += gt + [f"union {name} = " + " | ".join(gu), ""]
    return "\n".join(ts), "\n".join(proto), "\n".join(gql)

def main():
    items = parse()
    names = {n for _, n, _ in items}
    ts, proto, gql = emit(items)
    outs = {"🟦️.ts": ts, "🛰️.proto": proto, "🔗️.graphql": gql}
    bad = 0
    for fn, text in outs.items():
        p = ROOT / fn
        text += "\n"
        if "--check" in sys.argv:
            if not p.exists() or p.read_text() != text: print("stale", fn); bad = 1
        else: p.write_text(text)
    print(len(items), "types")
    sys.exit(bad)

main()

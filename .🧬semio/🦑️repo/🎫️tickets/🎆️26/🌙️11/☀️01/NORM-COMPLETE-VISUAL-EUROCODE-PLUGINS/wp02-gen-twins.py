#!/usr/bin/env python3
"""Generates the proto/graphql/ts twins of the diagram2d and handles part files from their Rust declarations. Reuses the WP-01 generator functions. Usage: python3 -I wp02-gen-twins.py [--check]"""
import re, sys, pathlib

HERE = pathlib.Path(__file__).resolve().parent
src = (HERE / "wp01-gen-twins.py").read_text()
src = src[: src.rindex("main()")]
ns = {"__name__": "wp01"}
exec(compile(src, "wp01-gen-twins.py", "exec"), ns)
ROOT = ns["ROOT"]
PARTS = ["📈️diagram2d", "🕹️handles"]
SCALAR = set(ns["SCALARS"]) | {"Option", "Vec", "Box"}

def run(part):
    ns["MODULES"][:] = [part]
    ns["PARTS"].clear()
    ns["EXTERNAL"].clear()
    items = ns["parse"]()
    own = {name for _, name, _ in items}
    used = set()
    for kind, name, body in items:
        types = []
        if kind == "record": types = [t for _, t in body]
        elif kind == "variant": types = [d for _, shape, data in body for d in ([t for _, t in data] if shape == "named" else [data] if shape == "newtype" else [])]
        for t in types: used |= set(re.findall(r"[A-Z]\w*", t))
    external = sorted((used - own) - SCALAR)
    ts, proto, gql = ns["emit"](items)
    ts = "\n".join(l for l in ts.splitlines()[1:] if not l.startswith("export * from") and not l.startswith("import type"))
    proto = "\n".join(l for l in proto.splitlines() if not l.startswith('syntax') and not l.startswith("package") and not l.startswith("message Empty") and not l.startswith("import"))
    gql = "\n".join(l for l in gql.splitlines()[1:] if not l.startswith("#import"))
    ts = f"/** {part} wire twin, mirrors `./🦀️.rs` (generated by `wp02-gen-twins.py`). */\nimport type {{ {', '.join(external)} }} from \"../🟦️.ts\";\n\n" + ts.strip() + "\n"
    imports = ", ".join(external)
    proto = 'syntax = "proto3";\npackage semio.norm.structuralscene;\n\nimport "🛰️.proto";\n\n' + proto.strip() + "\n"
    gql = f"# {part} GraphQL twin, mirrors ./🦀️.rs (generated by wp02-gen-twins.py); external types: {imports}.\n\n" + gql.strip() + "\n"
    return {"🟦️.ts": ts, "🛰️.proto": proto, "🔗️.graphql": gql}, len(items)

LANES = pathlib.Path("/home/deck/semio/✏️s/🔌️plugins/📕️norm/📇️registry/🧬️contract/🖥️app-surface/🫧️live-lanes/🧬️schema")
SCENE = "🎬️structural-scene/🧬️schema"

def lanes():
    ns["ROOT"] = LANES
    ns["MODULES"][:] = ["."]
    ns["PARTS"].clear()
    ns["EXTERNAL"].clear()
    ns["SCALARS"]["DslValue"] = ("JsonValue", "google.protobuf.Value", "JSON")
    items = ns["parse"]()
    ts, proto, gql = ns["emit"](items)
    ts = "\n".join(l for l in ts.splitlines()[1:] if not l.startswith("import type"))
    proto = "\n".join(l for l in proto.splitlines() if not l.startswith(("syntax", "package", "message Empty", "import")))
    gql = "\n".join(l for l in gql.splitlines()[1:] if not l.startswith("#import"))
    ts = ("/** 🫧️ Live lanes wire twin, mirrors `./🦀️.rs` (generated by `wp02-gen-twins.py`). */\n"
          f'import type {{ EntityRef, Vec3 }} from "../../../../../../{SCENE}/🟦️.ts";\n\n'
          "export type JsonValue = null | boolean | number | string | JsonValue[] | { [key: string]: JsonValue };\n\n") + ts.strip() + "\n"
    proto = ('syntax = "proto3";\npackage semio.norm.livelanes;\n\nimport "google/protobuf/struct.proto";\n'
             f'import "{SCENE}/🛰️.proto";\n\n') + proto.strip().replace("google.protobuf.Value", "google.protobuf.Value") + "\n"
    gql = ("# 🫧️ Live lanes GraphQL twin, mirrors ./🦀️.rs (generated by wp02-gen-twins.py); external types: EntityRef, Vec3.\n"
           f"#import {SCENE}/🔗️.graphql\n\nscalar JSON\n\n") + gql.strip() + "\n"
    return {"🟦️.ts": ts, "🛰️.proto": proto, "🔗️.graphql": gql}, len(items)

bad = 0
outs, n = lanes()
for fn, text in outs.items():
    p = LANES / fn
    if "--check" in sys.argv:
        if not p.exists() or p.read_text() != text: print("stale lanes", fn); bad = 1
    else: p.write_text(text)
print("lanes", n, "types")
ns["ROOT"] = pathlib.Path("/home/deck/semio/✏️s/🔌️plugins/📕️norm/🎬️structural-scene/🧬️schema")
ROOT = ns["ROOT"]
for part in PARTS:
    outs, n = run(part)
    for fn, text in outs.items():
        p = ROOT / part / fn
        if "--check" in sys.argv:
            if not p.exists() or p.read_text() != text: print("stale", part, fn); bad = 1
        else: p.write_text(text)
    print(part, n, "types")
sys.exit(bad)

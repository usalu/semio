import { chromium } from "file:///C:/git/semio/node_modules/playwright/index.mjs";
const out = process.argv[2];
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1500, height: 1000 } });
const errors = [];
page.on("pageerror", (e) => errors.push(String(e)));
page.on("console", (m) => { if (m.type() === "error") errors.push(m.text()); });
await page.goto("http://localhost:6071/?view=thermal&scale=50&t=0.5", { waitUntil: "networkidle" });
await page.waitForSelector("[data-staffage-figure]", { timeout: 60000 });
const read = () => page.evaluate(() => ({ viewpoints: [...document.querySelectorAll("[data-staffage-figure]")].map((f) => [f.getAttribute("data-viewpoint"), f.getAttribute("data-time"), f.getAttribute("data-width-mm")]), live: document.querySelector("[data-viewpoint-announcement]")?.textContent }));
const before = await read();
await page.screenshot({ path: `${out}/single.png` });
await page.getByRole("radio", { name: "Three views" }).click();
await page.waitForSelector("[data-three-views]");
await page.waitForTimeout(800);
const sheet = await page.evaluate(() => {
  const group = document.querySelector("[data-three-views]");
  const rect = (el) => { const r = el.getBoundingClientRect(); return { x: +r.x.toFixed(1), y: +r.y.toFixed(1), w: +r.width.toFixed(1), h: +r.height.toFixed(1) }; };
  const cells = Object.fromEntries([...group.querySelectorAll("figure[data-viewpoint]")].map((f) => [f.getAttribute("data-viewpoint"), { ...rect(f), time: f.querySelector("[data-staffage-figure]")?.getAttribute("data-time"), mm: f.querySelector("[data-staffage-figure]")?.getAttribute("data-width-mm") }]));
  return { zoom: group.getAttribute("data-zoom"), order: [...group.querySelectorAll("figure[data-viewpoint]")].map((f) => f.getAttribute("data-viewpoint")), cells, mmPerPx: 25.4 / 96 };
});
await page.screenshot({ path: `${out}/three.png` });
const live = await page.evaluate(() => document.querySelector("[data-viewpoint-announcement]")?.textContent);
await page.getByRole("radio", { name: "Plan (top view)" }).click();
await page.waitForTimeout(500);
const after = await read();
const url = await page.evaluate(() => JSON.stringify(window.viewer));
await page.screenshot({ path: `${out}/plan.png` });
await page.goto("http://localhost:6071/?scale=500&vl=all", { waitUntil: "networkidle" });
await page.waitForSelector("[data-three-views]");
const unavailable = await page.evaluate(() => [...document.querySelectorAll("figure[data-viewpoint]")].map((f) => [f.getAttribute("data-viewpoint"), f.getAttribute("data-available"), f.textContent.slice(0, 160)]));
await page.screenshot({ path: `${out}/unavailable.png` });
await page.goto("http://localhost:6071/?lang=de&vl=all&scale=50", { waitUntil: "networkidle" });
await page.waitForSelector("[data-three-views]");
const german = await page.evaluate(() => [...document.querySelectorAll("[data-three-views] button")].map((b) => b.getAttribute("aria-label")));
await page.keyboard.press("Tab");
console.log(JSON.stringify({ before, sheet, live, after, viewer: JSON.parse(url), unavailable, german, errors }, null, 1));
await browser.close();

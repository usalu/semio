import{mkdirSync,mkdtempSync,readFileSync,rmSync,writeFileSync}from"node:fs";
import{tmpdir}from"node:os";
import{join}from"node:path";
import{createClosureSettlerV1,stampOfV1}from"../../../../🧮️derived-nodes/🧩️closure-kinds/🟨️.mjs";
import{createNodeStoreV1}from"../../../../🧮️derived-nodes/💾️store/🟨️.mjs";
import{derivedOwnerNameV1,suspectRowsV1}from"../../🟨️.mjs";
import{createFactIndexV1}from"../../../🟨️.mjs";
const N=Number(process.env.BENCH_CLOSURES??8129),SHARED=Number(process.env.BENCH_SHARED??60),EDITS=Number(process.env.BENCH_EDITS??100),MODE=process.env.BENCH_MODE??"after";
const names=Array.from({length:N},(_,at)=>"q"+String(at).padStart(5,"0")),row=(name:string)=>({kind:"derived",path:name,fact:"old"}) as never;
const index=createFactIndexV1(new Map([["holder",names.map(row)],...names.map(name=>[derivedOwnerNameV1(row(name)),[row(name),{kind:"file",path:"own/"+name,fact:"v"}]] as never)]));
const suspects=new Set(names.map(name=>derivedOwnerNameV1(row(name))));
const store=mkdtempSync(join(tmpdir(),"bench-store-")),ws=mkdtempSync(join(tmpdir(),"bench-ws-"));
mkdirSync(join(ws,"own"));mkdirSync(join(ws,"shared"));
for(let at=0;at<SHARED;at++)writeFileSync(join(ws,"shared/s"+at+".ts"),"s0-"+at);
for(const name of names)writeFileSync(join(ws,"own",name),"v0-"+name);
const text=(path:string)=>{try{return readFileSync(join(ws,path),"utf8");}catch{return"gone";}};
const fresh=()=>createClosureSettlerV1({store:createNodeStoreV1({root:store})});
const run=async(settler:ReturnType<typeof fresh>,stale:unknown[]|undefined)=>{
 let derived=0,rows=0;const t0=performance.now();
 const settled=await settler.settle({pseudoRows:suspectRowsV1(index,suspects),derive:async(r:{path:string})=>{derived++;return{fact:"old",parts:[...Array.from({length:SHARED},(_,at)=>[{kind:"file",path:"shared/s"+at+".ts",fact:text("shared/s"+at+".ts")}]),[{kind:"file",path:"own/"+r.path,fact:text("own/"+r.path)}]]};},hold:async(list:{path:string;fact:string}[])=>{rows+=list.length;return list.every(r=>text(r.path)===r.fact);},staleFacts:MODE==="before"?undefined:stale,vouchStamp:(name:string)=>stampOfV1(join(ws,name))} as never);
 return{settled,derived,rows,ms:Math.round(performance.now()-t0),vouched:settled.vouched,kept:settled.kept.size,held:settled.held.size};
};
const report=(step:string,r:any)=>console.log(JSON.stringify({mode:MODE,step,closures:N,derived:r.derived,rowsChecked:r.rows,ms:r.ms,vouched:r.vouched,kept:r.kept,held:r.held}));
const step=async(label:string,stale:unknown[]|undefined)=>{const settler=fresh(),r=await run(settler,stale);await settler.markIndexed({held:r.settled.held});report(label,r);return r;};
await step("cold",undefined);
const edited=names.slice(0,EDITS);for(const name of edited)writeFileSync(join(ws,"own",name),"v1-"+name);writeFileSync(join(ws,"shared/s0.ts"),"s1-0");
const stale=[...edited.map(name=>({kind:"file",path:"own/"+name,fact:"v0-"+name})),{kind:"file",path:"shared/s0.ts",fact:"s0-0"}];
await step("restart-1 (edits since the generation)",stale);
await step("restart-2 (same edits, killed and started again)",stale);
await step("restart-3",stale);
rmSync(store,{recursive:true,force:true});rmSync(ws,{recursive:true,force:true});

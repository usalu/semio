import {readFileSync,writeFileSync,mkdirSync} from "node:fs";
import {pathToFileURL} from "node:url";
import {resolve,join} from "node:path";
import {PATCHES} from "./patches.mjs";
const G="/Users/ueli/Documents/semio/🧰️framework/🛍️products/🦑️repo/🔨️modules/📚️library/🏗️build/🕸️graph/🕰️generations";
const out=process.argv[2];mkdirSync(out,{recursive:true});
const absolute=(text,dir)=>text.replace(/(from\s*|import\s*\(\s*|import\s*)(["'])(\.{1,2}\/[^"']+)\2/gu,(all,head,quote,spec)=>head+quote+pathToFileURL(resolve(dir,spec)).href+quote);
const patched=file=>{let text=readFileSync(file,"utf8");const row=PATCHES.find(item=>item.file===file);for(const[from,to]of row?.edits??[]){const count=text.split(from).length-1;if(count!==1)throw Error("anchor count "+count+" in "+file+": "+from.slice(0,70));text=text.replace(from,()=>to);}return text;};
const live={store:pathToFileURL(join(G,"🟨️.mjs")).href,schema:pathToFileURL(join(G,"🧬️schema/🔣️.json")).href};
const staged={store:pathToFileURL(join(out,"store.mjs")).href,schema:pathToFileURL(join(out,"schema.json")).href};
writeFileSync(join(out,"schema.json"),patched(join(G,"🧬️schema/🔣️.json")));
const fix=text=>text.split(live.store).join(staged.store).split(live.schema).join(staged.schema);
writeFileSync(join(out,"store.mjs"),fix(absolute(patched(join(G,"🟨️.mjs")),G)));
writeFileSync(join(out,"load.mjs"),fix(absolute(patched(join(G,"🔌️load/🟨️.mjs")),join(G,"🔌️load"))));

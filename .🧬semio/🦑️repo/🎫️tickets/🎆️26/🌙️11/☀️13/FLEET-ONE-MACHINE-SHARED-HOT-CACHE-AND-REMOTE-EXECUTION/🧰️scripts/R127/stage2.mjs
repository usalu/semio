writeFileSync(join(out,"world.ts"),absolute(readFileSync(worldFile,"utf8"),join(G,"🧪️tests/🏃️world")).split(pathToFileURL(join(G,"🔌️load/🟨️.mjs")).href).join(pathToFileURL(join(out,"load.mjs")).href));

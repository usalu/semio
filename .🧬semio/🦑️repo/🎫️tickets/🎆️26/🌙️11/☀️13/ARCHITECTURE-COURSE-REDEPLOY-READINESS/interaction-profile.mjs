import { createRequire } from "node:module";
const require = createRequire("/Users/ueli/Documents/semio/.cache/b/d/m/j/b87aa6c238609ac86876/node_modules/@playwright/test/");
const { chromium } = require("@playwright/test");
const rate = Number(process.env.RATE ?? 1), step = process.env.STEP ?? "intro", site = process.env.SITE ?? "http://127.0.0.1:6068";
const browser = await chromium.launch();
const context = await browser.newContext({ viewport: { width: 1280, height: 800 }, locale: "en" });
const page = await context.newPage();
await page.addInitScript(() => {
  window.__t = { long: [], events: [] };
  new PerformanceObserver((l) => l.getEntries().forEach((e) => __t.long.push({ s: Math.round(e.startTime), d: Math.round(e.duration) }))).observe({ type: "longtask", buffered: true });
  new PerformanceObserver((l) => l.getEntries().forEach((e) => __t.events.push({ n: e.name, s: Math.round(e.startTime), d: e.duration, delay: Math.round(e.processingStart - e.startTime), proc: Math.round(e.processingEnd - e.processingStart) }))).observe({ type: "event", durationThreshold: 16, buffered: true });
});
const cdp = await context.newCDPSession(page);
await cdp.send("Profiler.enable");
await cdp.send("Profiler.setSamplingInterval", { interval: 100 });
if (rate !== 1) await cdp.send("Emulation.setCPUThrottlingRate", { rate });
const idle = (ms) => page.waitForTimeout(ms);
const report = async (label) => {
  const { profile } = await cdp.send("Profiler.stop");
  const self = new Map();
  const byId = new Map(profile.nodes.map((n) => [n.id, n]));
  profile.samples.forEach((id, i) => { const n = byId.get(id); const key = `${n.callFrame.functionName || "(anon)"} ${n.callFrame.url.split("/").pop()}:${n.callFrame.lineNumber}`; self.set(key, (self.get(key) ?? 0) + (profile.timeDeltas[i] ?? 0) / 1000); });
  const parent = new Map(); for (const n of profile.nodes) for (const c of n.children ?? []) parent.set(c, n.id);
  const incl = new Map();
  profile.samples.forEach((id, i) => { const seen = new Set(); for (let at = id; at !== undefined; at = parent.get(at)) { const n = byId.get(at); const key = `${n.callFrame.functionName || "(anon)"} ${n.callFrame.url.split("/").pop().slice(0, 30)}:${n.callFrame.lineNumber}`; if (seen.has(key)) continue; seen.add(key); incl.set(key, (incl.get(key) ?? 0) + (profile.timeDeltas[i] ?? 0) / 1000); } });
  const inclusive = [...incl.entries()].filter(([k]) => !k.startsWith("(")).sort((a, b) => b[1] - a[1]).slice(0, 30).map(([k, v]) => `${v.toFixed(1)}ms ${k}`);
  const top = [...self.entries()].sort((a, b) => b[1] - a[1]).slice(0, 14).map(([k, v]) => `${v.toFixed(1)}ms ${k}`);
  const t = await page.evaluate(() => { const r = { long: __t.long, events: __t.events }; __t.long = []; __t.events = []; return r; });
  console.log(JSON.stringify({ label, rate, long: t.long.map((x) => x.d), events: t.events.filter((e) => e.proc > 8 || e.delay > 30).map((e) => `${e.n} delay ${e.delay} proc ${e.proc}`), top: top.slice(0, 8), inclusive }, null, 1));
};

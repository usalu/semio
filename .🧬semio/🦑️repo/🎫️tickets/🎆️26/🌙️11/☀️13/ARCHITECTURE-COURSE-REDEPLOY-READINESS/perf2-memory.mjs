/** 🧠️ Memory walk of one learner tab: intro, identity, home, then every quiz (start, one answer, submit, results, back to the grid) and the leaderboard, with the JS heap, DOM node, document and listener counts after a forced collection at every stop. Env: SITE, QUIZZES (runs, the ten quizzes in turn, more than ten starts them again), OUT (jsonl path). */
import { createRequire } from "node:module";
import { appendFileSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
const require = createRequire("/Users/ueli/Documents/semio/.cache/b/d/m/j/b87aa6c238609ac86876/node_modules/@playwright/test/");
const { chromium } = require("@playwright/test");
const site = process.env.SITE ?? "http://127.0.0.1:6069", out = process.env.OUT ?? "memory.jsonl", count = Number(process.env.QUIZZES ?? 10);
const IDS = ["physics", "ventilation", "heating", "cooling", "demand", "parametric-design", "grasshopper-data", "excel-workbook", "bim-concepts", "optimization-decisions"];
writeFileSync(out, "");
const browser = await chromium.launch();
const context = await browser.newContext({ viewport: { width: 1280, height: 800 }, locale: "en" });
const page = await context.newPage();
page.setDefaultTimeout(120_000);
const cdp = await context.newCDPSession(page);
await cdp.send("Performance.enable");
const root = await browser.newBrowserCDPSession();
const rss = async () => {
  const { processInfo } = await root.send("SystemInfo.getProcessInfo");
  const kb = (pid) => Number(execFileSync("ps", ["-o", "rss=", "-p", String(pid)], { encoding: "utf8" }).trim() || 0);
  const rows = processInfo.map((info) => ({ type: info.type, kb: kb(info.id) }));
  return { treeMB: Math.round(rows.reduce((sum, row) => sum + row.kb, 0) / 1024), rendererMB: Math.round(Math.max(0, ...rows.filter((row) => row.type === "renderer").map((row) => row.kb)) / 1024) };
};
const sample = async (label) => {
  await page.waitForTimeout(1200);
  for (let round = 0; round < 3; round++) await cdp.send("HeapProfiler.collectGarbage");
  const { metrics } = await cdp.send("Performance.getMetrics");
  const m = Object.fromEntries(metrics.map((x) => [x.name, x.value]));
  const d = await cdp.send("Memory.getDOMCounters");
  const row = { label, ...(await rss()), heapMB: Math.round(m.JSHeapUsedSize / 1048576 * 10) / 10, totalMB: Math.round(m.JSHeapTotalSize / 1048576), nodes: d.nodes, documents: d.documents, listeners: d.jsEventListeners };
  appendFileSync(out, JSON.stringify(row) + "\n");
  console.log(JSON.stringify(row));
};
await page.goto(site + "/", { waitUntil: "commit" });
await page.locator('[data-slot="introduction-close"]').waitFor();
await sample("intro");
await page.locator('[data-slot="introduction-close"]').click();
await page.locator('[data-slot="introduction-info-box"]').waitFor({ state: "detached" });
const learner = page.locator('[data-course-grid][data-grid-active] > [data-layered-overview] [data-layered-card="learner"] [data-overview-card-action="primary"]');
await learner.waitFor();
await learner.click();
const dialog = page.getByRole("dialog").filter({ has: page.locator('input[type="radio"][value="anonymous"]') });
await dialog.waitFor();
await sample("identity dialog");
await dialog.locator('input[type="radio"][value="name"]').click();
await dialog.locator('input[type="text"]').fill("Memory Walker");
await dialog.locator('[data-overview-card-action="primary"]').click();
await page.locator('[data-course-grid][data-grid-active] > [data-layered-overview]').waitFor();
await page.goto(site + "/?preview=1", { waitUntil: "commit" });
await page.locator('[data-course-grid][data-grid-active] > [data-layered-overview]').waitFor();
await sample("home");
for (let index = 0; index < count; index++) {
  await page.evaluate(() => (window.location.hash = "quizzes"));
  await page.locator('[data-course-grid="quizzes"][data-grid-active]').waitFor();
  const card = page.locator(`[data-course-grid][data-grid-active] > [data-layered-overview] [data-layered-card="${IDS[index % IDS.length]}"] [data-overview-card-action="primary"]`).first();
  await card.waitFor();
  await card.evaluate((element) => element.click());
  await page.locator('#course-main [data-card="run"]').first().waitFor();
  await sample(`quiz ${index + 1} run`);
  const choice = page.locator("#course-main [data-card=\"run\"] nav button").first();
  await choice.click();
  const select = page.locator('#course-main [data-card="task"] [data-course-item] select').first();
  if ((await select.count()) > 0) await select.selectOption({ index: 1 });
  await page.locator('#course-main [data-card="run"] [data-overview-card-action="primary"]').first().click();
  await page.getByRole("alertdialog").locator('[data-overview-card-action="primary"]').click();
  await page.locator('#course-main [data-card="results"]').first().waitFor();
  await sample(`quiz ${index + 1} results`);
}
await page.evaluate(() => (window.location.hash = "quizzes"));
await page.locator('[data-course-grid="quizzes"][data-grid-active]').waitFor();
await sample("grid after all quizzes");
await page.evaluate(() => (window.location.hash = "board"));
await page.waitForTimeout(3000);
await sample("leaderboard");
await page.waitForTimeout(15000);
await sample("steady 15 s later");
await browser.close();

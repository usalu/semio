import assert from "node:assert/strict";
import { mkdirSync, writeFileSync, renameSync, watch as watchNative } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";
import { EventEmitter } from "node:events";
const root = process.cwd(), ticket = dirname(dirname(fileURLToPath(import.meta.url)));
const evidence = join(ticket, "🗑️generated", "activation-observer-" + Date.now());
const directory = join(evidence, "activation");
mkdirSync(directory, { recursive: true });
const activation = await import(join(root, "🧰️framework/🛍️products/💻️os/🔨️modules/🧑‍💻dev/♻️activation/🟦️.ts"));
const { watch } = createRequire(import.meta.url)("chokidar");
const first = activation.nextActivationReceipt("note", "dev", [{ pluginId: "note", artifactSha256: "a".repeat(64) }], undefined, 100);
const path = join(directory, activation.ACTIVATION_RECEIPT_FILE);
const publish = (value: unknown): void => { writeFileSync(path + ".stage", JSON.stringify(value)); renameSync(path + ".stage", path); };
publish(first);
const receipts: unknown[] = [], oracle: unknown[] = [], errors: unknown[] = [];
const independent = watch(path, { ignoreInitial: true });
await new Promise<void>((done) => independent.once("ready", done));
independent.on("change", () => { oracle.push(activation.readActivationReceipt(directory)); });
const rawEvents: unknown[] = [];
const rawWatch = watchNative(directory, (kind, filename) => { rawEvents.push({ kind, filename }); console.log("[DEBUG] Raw receipt event", JSON.stringify({ kind, filename })); });
const observer = activation.observeActivationReceipts(directory, (value: unknown) => receipts.push(value), (error: unknown) => errors.push(error));
const settle = (): Promise<void> => new Promise((done) => setTimeout(done, 200));
try {
  assert.deepEqual(observer.snapshot(), first);
  assert.deepEqual(receipts, [first]);
  writeFileSync(join(evidence, "component.core.wasm"), "incomplete cached output");
  await settle();
  assert.equal(receipts.length, 1);
  publish(activation.nextActivationReceipt("note", "dev", first.plugins, first, 200));
  await settle();
  assert.equal(receipts.length, 1);
  const changed = activation.nextActivationReceipt("note", "dev", [{ pluginId: "note", artifactSha256: "b".repeat(64) }], first, 50);
  publish(changed);
  for (let attempt = 0; attempt < 20 && receipts.length < 2; attempt++) await settle();
  assert.deepEqual(receipts, [first, changed]);
  assert.deepEqual(oracle.at(-1), changed);
  assert.deepEqual(errors, []);
  observer.close();
  publish(activation.nextActivationReceipt("note", "dev", first.plugins, changed, 300));
  await settle();
  assert.equal(receipts.length, 2);
  writeFileSync(join(evidence, "receipts.json"), JSON.stringify(receipts, null, 2));
  console.log("[DEBUG] Explicit activation receipt observer: partial output ignored, warm identity stable, changed identity delivered, closure releases watcher; Chokidar agrees");
} finally { observer.close(); rawWatch.close(); writeFileSync(join(evidence, "raw-events.json"), JSON.stringify({ rawEvents, errors, oracle }, null, 2)); await independent.close(); }

const { semioActivationVitePlugin, PLUGIN_SOURCE_WATCH_PATH } = await import(join(root, "🧰️framework/🛍️products/💻️os/🔨️modules/🧑‍💻dev/📦️packages/🟦️typescript/🔌️vite-plugins.ts"));
const requests = new EventEmitter(), httpServer = new EventEmitter(), chunks: string[] = [], messages: unknown[] = [];
Object.assign(requests, { method: "GET", url: new URL(PLUGIN_SOURCE_WATCH_PATH, "http://127.0.0.1").pathname });
let middleware: Function | undefined, ended = false;
const plugin = semioActivationVitePlugin({ receiptDirectory: directory });
plugin.configureServer({ httpServer, ws: { send: (message: unknown) => messages.push(message) }, middlewares: { use: (handler: Function) => { middleware = handler; } } });
const response = { statusCode: 0, setHeader() {}, write: (chunk: string) => chunks.push(chunk), end: () => { ended = true; } };
middleware!(requests, response, () => assert.fail("Receipt SSE route fell through"));
assert.equal(response.statusCode, 200);
assert.ok(chunks.join("").includes('"kind":"snapshot"'));
const before = activation.readActivationReceipt(directory);
const after = activation.nextActivationReceipt("note", "dev", [{ pluginId: "note", artifactSha256: "d".repeat(64) }], before, 500);
assert.equal(activation.publishActivationReceipt(directory, before), false);
assert.equal(activation.publishActivationReceipt(directory, after), true);
for (let attempt = 0; attempt < 20 && !chunks.join("").includes('"kind":"built"'); attempt++) await settle();
assert.equal(chunks.filter((chunk) => chunk.includes('"kind":"built"')).length, 1);
httpServer.emit("close");
assert.equal(ended, true);
const count = chunks.length;
activation.publishActivationReceipt(directory, activation.nextActivationReceipt("note", "dev", first.plugins, after, 600));
await settle();
assert.equal(chunks.length, count);
plugin.closeBundle();
writeFileSync(join(evidence, "sse.json"), JSON.stringify({ chunks, messages }, null, 2));
console.log("[DEBUG] Actual activation Vite adapter sends snapshot and one changed-content event, closes SSE and its watcher on HTTP shutdown");

import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve, join } from "node:path";
const root = process.cwd(), output = resolve(import.meta.dir, "../../🗑️generated/native-binaryen");
assert.equal(process.platform, "darwin"); assert.equal(process.arch, "arm64");
mkdirSync(output, { recursive: true });
const url = "https://github.com/WebAssembly/binaryen/releases/download/version_130/binaryen-version_130-arm64-macos.tar.gz";
const response = await fetch(url, { signal: AbortSignal.timeout(60_000) });
assert.equal(response.ok, true, `${response.status}: ${url}`);
const bytes = Buffer.from(await response.arrayBuffer());
assert.equal(createHash("sha256").update(bytes).digest("hex"), "79d3ab9f417d9e215f15f598f523d001a7d9ac1e59367e5c869fbdabd1cba72e");
const archive = join(output, "binaryen.tar.gz"); writeFileSync(archive, bytes);
const unpack = Bun.spawnSync(["tar", "-xzf", archive, "-C", output], { stdout: "pipe", stderr: "pipe" });
assert.equal(unpack.exitCode, 0, unpack.stderr.toString());
const binary = join(output, "binaryen-version_130/bin/wasm-opt"), version = Bun.spawnSync([binary, "--version"], { stdout: "pipe", stderr: "pipe" });
assert.equal(version.exitCode, 0, version.stderr.toString());
console.log("[DEBUG] Verified official archive", version.stdout.toString().trim());
const input = join(root, "🧰️framework/🛍️products/💻️os/🔨️modules/🌊️flow/📦️packages/🦀️rust/🕸️bindings/flow_core_bg.wasm"), snapshot = join(output, "flow-input.wasm"), target = join(output, "flow-optimized.wasm");
const source = readFileSync(input); writeFileSync(snapshot, source);
const started = performance.now(), child = Bun.spawn([binary, snapshot, "-o", target, "-O", "--enable-bulk-memory", "--enable-nontrapping-float-to-int"], { stdout: "inherit", stderr: "inherit" });
const stop = () => child.kill("SIGKILL"), budget = setTimeout(stop, 120_000);
process.once("SIGINT", stop); process.once("SIGTERM", stop);
const progress = setInterval(() => console.log("[DEBUG] Native Binaryen running", Math.round(performance.now() - started), "ms"), 10_000);
let status: number;
try { status = await child.exited; } finally { clearInterval(progress); clearTimeout(budget); process.removeListener("SIGINT", stop); process.removeListener("SIGTERM", stop); }
assert.equal(status, 0);
const optimized = readFileSync(target); assert.equal(WebAssembly.validate(optimized), true);
console.log("[DEBUG] Real Flow native optimization PASS", JSON.stringify({ milliseconds: performance.now() - started, sourceBytes: source.length, outputBytes: optimized.length, sha256: createHash("sha256").update(optimized).digest("hex") }));

#!/usr/bin/env python3
"""⚙️ Moves `🏛️bestest`'s synthetic-EPW annual laws into the `🌦️epw` extension's tests (lane P1, slice S1a).

`🌦️epw` already owns `run_bestest` (decode EPW text, run a case), so the annual laws that parse a synthetic EPW year and
run cases through it are epw's; bestest keeps only its case-builder laws and never names epw.
"""
import sys
E = "/Users/ueli/Documents/semio/✏️s/🔌️plugins/🔋️energy/"
best_p = E + "🔨️modules/⚡️simulation/⚙️engine/🏛️bestest/🧪️tests/🔬️unit/🦀️.rs"
epw_p = E + "🧩️extensions/🌦️epw/🧪️tests/🔬️unit/🦀️.rs"
best, epw = open(best_p, encoding="utf-8").read(), open(epw_p, encoding="utf-8").read()
start, end = "//#region 🌦️SyntheticWeather", "//#endregion 🌦️SyntheticWeather\n"
if start in epw: sys.exit("already applied")
assert best.count(start) == 1; i = best.index(start); j = best.index(end, i) + len(end)
region = best[i:j]; best = best[:i].rstrip("\n") + "\n\n" + best[j:].lstrip("\n")
region = region.replace("crate::epw::parse(", "parse(").replace("COMMENTS 2,Generated by crate::bestest::tests::synthetic_annual_epw", "COMMENTS 2,Generated by crate::epw::tests::synthetic_annual_epw")
a = "use super::*;\n"; assert epw.count(a) == 1
epw = epw.replace(a, "use super::*;\nuse crate::bestest::{project, run};\nuse crate::results::Results;\n", 1).rstrip("\n") + "\n\n" + region
open(best_p, "w", encoding="utf-8").write(best); open(epw_p, "w", encoding="utf-8").write(epw)
print("ok")

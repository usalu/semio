SKIP_SUFFIXES = (".pyc",)
SINCE = os.stat(OVERLAY).st_birthtime


def walk(root: Path):
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [name for name in dirnames if name not in SKIP_DIRS and not name.startswith(".semio-describe-core-")]
        for name in filenames:
            if not name.endswith(SKIP_SUFFIXES):
                yield Path(dirpath, name).relative_to(root)


def changed():
    edits, created, removed = [], [], []
    for rel in walk(OVERLAY):
        path = OVERLAY / rel
        if path.is_symlink() or os.stat(path).st_mtime < SINCE:
            continue
        base = BASE / rel
        if not base.exists():
            created.append(rel)
        elif base.read_bytes() != path.read_bytes():
            edits.append(rel)
    for rel in walk(BASE):
        if not (OVERLAY / rel).exists() and not (BASE / rel).is_symlink():
            removed.append(rel)
    return sorted(edits), sorted(created), sorted(removed)


def hunks(old: str, new: str):
    a, b = old.splitlines(keepends=True), new.splitlines(keepends=True)
    for context in (3, 5, 8, 13, 21, 34):
        pairs, ok = [], True
        for group in difflib.SequenceMatcher(None, a, b, autojunk=False).get_grouped_opcodes(context):
            i1, i2, j1, j2 = group[0][1], group[-1][2], group[0][3], group[-1][4]
            before, after = "".join(a[i1:i2]), "".join(b[j1:j2])
            if not before or old.count(before) != 1:
                ok = False
                break
            pairs.append((before, after))
        if ok and apply(old, pairs) == new:
            return pairs
    return None


def apply(text: str, pairs):
    for before, after in pairs:
        if text.count(before) != 1:
            return None
        text = text.replace(before, after)
    return text



#!/usr/bin/env python3
"""📦️ Mirrors the live repo's node_modules into the U6 overlay for TS checks: every external package is a symlink to the live
install (its realpath resolves its own dependencies there), while workspace links (relative symlinks such as
`@semio-tech/framework -> ../../🧰️framework/...`) are copied verbatim, so they resolve to the overlay's edited sources.

Usage: overlay_node_modules.py <live root> <overlay root> <file listing node_modules dirs>"""
import os
import sys

live, overlay, listing = sys.argv[1:4]


def mirror(rel: str) -> int:
    source = os.path.join(live, rel)
    target = os.path.join(overlay, rel)
    os.makedirs(target, exist_ok=True)
    made = 0
    for name in os.listdir(source):
        entry = os.path.join(source, name)
        destination = os.path.join(target, name)
        if os.path.lexists(destination):
            continue
        if os.path.islink(entry) and not os.path.isabs(os.readlink(entry)):
            os.symlink(os.readlink(entry), destination)
        elif name.startswith("@") and os.path.isdir(entry) and not os.path.islink(entry):
            made += mirror(os.path.join(rel, name))
            continue
        else:
            os.symlink(entry, destination)
        made += 1
    return made


total = sum(mirror(line.strip().removeprefix("./")) for line in open(listing, encoding="utf-8") if line.strip())
print(f"overlay node_modules: {total} entries mirrored")

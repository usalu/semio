#!/usr/bin/env python3
"""🗺️ F9 carrier regeneration: rewrites every committed carrier of a `DefaultHasher` child id to the `store::content_id` the
production code now mints for the same content, from the old→new map the overlay recorder captured while the owners' tests
ran (`record-instrument.py`; lines `prefix<TAB>new<TAB>old,old,…`). Replacement is byte-exact and length-preserving
(`<prefix>-<16 hex>` → `<prefix>-<16 hex>`), so binary packs keep their framing. Describe outputs (plugin `🔣️.json`,
`🛂️.descriptor.semio`) are regenerated by the chain's describe step and left alone. Reports every carrier id the map does
not cover. usage: apply-map.py --map <record…> [--root <tree>] [--write] [--census <f9-carriers.json>]"""
import json
import re
import sys
from collections import Counter
from pathlib import Path

args = sys.argv[1:]
ROOT = Path(args[args.index("--root") + 1]) if "--root" in args else Path("/Users/ueli/Documents/semio")
HERE = Path(__file__).resolve().parent
CENSUS = Path(args[args.index("--census") + 1]) if "--census" in args else HERE.parent / "generated/f9-carriers-1.json"
maps = [Path(value) for index, value in enumerate(args) if index > 0 and args[index - 1] == "--map"]
WRITE = "--write" in args
old_to_new, conflicts = {}, set()
for record in maps:
    for line in record.read_text(encoding="utf-8").splitlines():
        parts = line.split("\t")
        if len(parts) != 3:
            continue
        prefix, new, olds = parts
        for old in olds.split(","):
            if old in old_to_new and old_to_new[old] != new:
                conflicts.add(old)
            old_to_new[old] = new
new_ids = set(old_to_new.values())
ID = re.compile(rb"(?<![A-Za-z0-9_])([a-z0-9][a-z0-9.-]*?-[0-9a-f]{16})(?![0-9a-zA-Z])")
carriers = [rel for rel in json.loads(CENSUS.read_text(encoding="utf-8")) if not (rel.endswith("/🔣️.json") and rel.count("/") == 2) and not rel.endswith("🛂️.descriptor.semio")]
changed, uncovered, replaced = {}, Counter(), 0
for rel in carriers:
    path = ROOT / rel
    if not path.is_file():
        uncovered[f"(missing file) {rel}"] += 1
        continue
    data = path.read_bytes()
    out, cursor, count = [], 0, 0
    for match in ID.finditer(data):
        token = match.group(1).decode("ascii", "replace")
        candidate = next((token[start:] for start in [0] + [i + 1 for i, c in enumerate(token) if c == "-"] if token[start:] in old_to_new), None)
        if candidate is None:
            if token not in new_ids and re.search(r"-(content|document|mesh|catalogs?|presentation|animation|flow|text|benchmarks|knowledge|scene|emblem|brep|model|asset|climate|drawing|io)-[0-9a-f]{16}$", "-" + token):
                uncovered[token] += 1
            continue
        begin = match.start(1) + (len(token) - len(candidate))
        out.append(data[cursor:begin])
        out.append(old_to_new[candidate].encode("ascii"))
        cursor = begin + len(candidate)
        count += 1
    if count:
        out.append(data[cursor:])
        changed[path] = b"".join(out)
        replaced += count
print(f"map: {len(old_to_new)} old candidates → {len(new_ids)} new ids; conflicts {len(conflicts)}")
print(f"carriers scanned {len(carriers)}; files changed {len(changed)}; ids replaced {replaced}; uncovered distinct ids {len(uncovered)}")
for token, count in uncovered.most_common(40):
    print(f"  uncovered {count:4d} {token}")
if WRITE and not conflicts:
    for path, data in changed.items():
        path.write_bytes(data)
    print("written")

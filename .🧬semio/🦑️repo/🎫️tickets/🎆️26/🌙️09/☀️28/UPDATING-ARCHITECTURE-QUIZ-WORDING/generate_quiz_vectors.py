class Learner:
    """🧑‍🎓️ Drives one learner through commands with the reference, recording steps and folding events."""

    def __init__(self, label, clock, registered=True, limits=None):
        self.label, self.clock, self.limits = label, clock, limits
        self.learner = hexid("learner-" + label)
        self.state = LC.empty_learner_state(self.learner)
        self.given = []
        self.events = []
        self.steps = []
        self.revisions = dict(REVISIONS)
        self.commands = 0
        self.challenges = {}
        if registered:
            event = {"type": "learner-registered", "learner": self.learner, "identity": {"kind": "pseudonym", "handle": label.title()}, "at": clock.tick()}
            self.given.append(event)
            self.events.append(event)
            self.state = LC.evolve_learner(self.state, event)

    def command_id(self):
        """🆔️ A fresh command id."""
        self.commands += 1
        return hexid("command-%s-%d" % (self.label, self.commands))

    def run_id(self, name):
        """🆔️ The id of one of this learner's runs."""
        return hexid("run-%s-%s" % (self.label, name))

    def decide(self, command, revise=None):
        """⚖️ Decides one command, folds its events, records the step; an ``at`` left open is the instant of the decision."""
        step = {"command": command}
        if revise:
            self.revisions.update(revise)
            step["revisions"] = dict(revise)
        now = self.clock.tick()
        if "at" in command and command["at"] is None:
            command["at"] = now
        decision = LC.decide_learner(self.state, command, {"now": now, "catalog": CATALOG, "quizzes": context_quizzes(self.revisions), "limits": self.limits or LC.DEFAULT_LIMITS})
        for event in decision.get("events", []):
            self.state = LC.evolve_learner(self.state, event)
            self.events.append(event)
        step["now"] = now
        step["expected"] = decision
        self.steps.append(step)
        return decision

    def identify(self, kind, handle=None, learner=None):
        """🙋️ identify-learner addressed to this learner's stream."""
        return self.decide(identify(self.label, kind, handle, learner=learner or self.learner, command=self.command_id()))

    def start(self, name, quiz, revise=None, challenge="medium", at=None):
        """▶️ start-run at a challenge; without ``at`` the learner started it at the instant of the decision."""
        self.challenges[name] = challenge
        return self.decide({"type": "start-run", "id": self.command_id(), "learner": self.learner, "run": self.run_id(name), "quiz": quiz, "challenge": challenge, "at": at}, revise)

    def open(self, name, task, at=None, revise=None):
        """🔓️ open-task; without ``at`` the learner acted at the instant of the decision."""
        return self.decide({"type": "open-task", "id": self.command_id(), "learner": self.learner, "run": self.run_id(name), "task": task, "at": at}, revise)

    def opened(self, name, task):
        """🕰️ When a task of one of this learner's runs was opened."""
        return LC.run_of(self.state, self.run_id(name))["opened"][task]

    def answer(self, name, task, answer, revise=None, at=None):
        """✍️ record-answer; without ``at`` the learner acted at the instant of the decision, on an opened task of a timed run a second after opening it."""
        run = LC.run_of(self.state, self.run_id(name))
        if at is None and run is not None and task in run["opened"]:
            at = run["opened"][task] + 1000
        return self.decide({"type": "record-answer", "id": self.command_id(), "learner": self.learner, "run": self.run_id(name), "task": task, "answer": answer, "at": at}, revise)

    def submit(self, name, revise=None):
        """📨️ submit-run."""
        return self.decide({"type": "submit-run", "id": self.command_id(), "learner": self.learner, "run": self.run_id(name)}, revise)

    def sheet(self, name, quiz):
        """🃏️ The sheet of one of this learner's runs, at the challenge it was started with."""
        return S.sheet_of(quiz, R.fnv1a32(self.run_id(name)), self.challenges.get(name, "medium"))

    def answer_all(self, name, quiz, perfect_tasks, skip=()):
        """✍️ Answers every sheet task: perfectly for the named tasks, worst otherwise; a timed task is opened first."""
        for task in self.sheet(name, quiz)["tasks"]:
            if task["id"] in skip:
                continue
            if "seconds" in task:
                self.open(name, task["id"])
            self.answer(name, task["id"], (correct_answer if task["id"] in perfect_tasks else reversed_answer)(task_of(quiz, task["id"]), task))

    def sequence(self, identifier, runs):
        """🎞️ The committed learner sequence with its final views — none for a learner that never registered."""
        built = {"id": identifier, "learner": self.learner, "given": self.given, "steps": self.steps}
        if self.limits is not None:
            built["limits"] = self.limits
        if self.state["identity"] is not None:
            built["views"] = {"runs": runs, "expected": {"learner": LC.learner_view(self.state), "runs": {run: LC.run_view(self.state, run, context_quizzes(self.revisions)) for run in runs}}}
        return built



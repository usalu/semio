def hides_keys(sheet_task):
    """🙈️ Whether a sheet task asks for guesses: a sorting without keys, a matching without cards."""
    return (sheet_task["kind"] == "sorting" and "keys" not in sheet_task) or (sheet_task["kind"] == "matching" and any("cards" not in dimension for dimension in sheet_task["dimensions"]))


def correct_answer(task, sheet_task):
    """✅️ The perfect answer to a sheet task: where the keys are hidden, every item guessed at its true value."""
    items = {item["id"]: item for item in task["items"]}
    if task["kind"] == "classification":
        return {"kind": "classification", "assignments": {item["id"]: items[item["id"]]["category"] for item in sheet_task["items"]}}
    if task["kind"] == "sorting":
        index = {item["id"]: position for position, item in enumerate(task["items"])}
        order = sorted((item["id"] for item in sheet_task["items"]), key=lambda identifier: (items[identifier]["value"], index[identifier]))
        return {"kind": "sorting", "order": order, **({"guesses": {identifier: items[identifier]["value"] for identifier in order}} if hides_keys(sheet_task) else {})}
    if hides_keys(sheet_task):
        return {"kind": "matching", "guesses": {dimension["id"]: {item["id"]: items[item["id"]]["values"][dimension["id"]] for item in sheet_task["items"]} for dimension in sheet_task["dimensions"]}}
    assignments = {}
    for dimension in sheet_task["dimensions"]:
        free = list(range(len(dimension["cards"])))
        chosen = {}
        for item in sheet_task["items"]:
            card = next(position for position in free if dimension["cards"][position] == items[item["id"]]["values"][dimension["id"]])
            free.remove(card)
            chosen[item["id"]] = card
        assignments[dimension["id"]] = chosen
    return {"kind": "matching", "assignments": assignments}


def reversed_answer(task, sheet_task):
    """↩️ The worst answer: sorting reversed, matching cards reversed, classification rotated by one category; where the keys are hidden the true values are guessed mirrored — the smallest item the largest value — so the order they imply is the reversed one."""
    perfect = correct_answer(task, sheet_task)
    if task["kind"] == "sorting":
        backwards = list(reversed(perfect["order"]))
        return {"kind": "sorting", "order": backwards, **({"guesses": {identifier: perfect["guesses"][mirrored] for identifier, mirrored in zip(backwards, perfect["order"])}} if "guesses" in perfect else {})}
    if task["kind"] == "classification":
        categories = [category["id"] for category in sheet_task["categories"]]
        return {"kind": "classification", "assignments": {item: categories[(categories.index(category) + 1) % len(categories)] for item, category in perfect["assignments"].items()}}
    if "guesses" in perfect:
        mirrored = {}
        for dimension, guesses in perfect["guesses"].items():
            ascending = sorted(guesses, key=lambda identifier: guesses[identifier])
            mirrored[dimension] = {identifier: guesses[opposite] for identifier, opposite in zip(ascending, reversed(ascending))}
        return {"kind": "matching", "guesses": mirrored}
    return {"kind": "matching", "assignments": {dimension: dict(zip(chosen.keys(), reversed(list(chosen.values())))) for dimension, chosen in perfect["assignments"].items()}}



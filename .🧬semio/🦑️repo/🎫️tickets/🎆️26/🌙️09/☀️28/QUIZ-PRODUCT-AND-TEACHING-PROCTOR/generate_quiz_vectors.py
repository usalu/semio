def rotation_seeds():
    """🔄️ Seeds whose pre-rotation draw of ``pair``/``triple`` is ascending, value-ascending only, or neither."""
    wanted = {}
    for seed in range(200):
        generator = S.Mt19937(seed)
        S.shuffle(generator, range(2))
        pair = [item["id"] for item in S.shuffle(generator, ROTATION["tasks"][0]["items"])]
        triple = [item["id"] for item in S.shuffle(generator, ROTATION["tasks"][1]["items"])]
        if pair == ["feather", "brick"] and triple == ["apple", "pear", "melon"]:
            wanted.setdefault("both-rotated", seed)
        if triple == ["pear", "apple", "melon"]:
            wanted.setdefault("tie-reversed-kept", seed)
        if pair == ["brick", "feather"] and triple[-1] != "melon":
            wanted.setdefault("neither-rotated", seed)
    return wanted



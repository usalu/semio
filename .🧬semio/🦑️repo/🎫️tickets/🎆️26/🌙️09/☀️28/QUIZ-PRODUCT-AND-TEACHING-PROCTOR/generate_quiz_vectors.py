class BoardLearner(Learner):
    """🧑‍🎓️ A learner of the leaderboard catalog, whose decisions are replayed only to produce events."""

    def decide(self, command, revise=None):
        """⚖️ Decides against the leaderboard catalog."""
        now = self.clock.tick()
        quizzes = {quiz["id"]: {"quiz": quiz, "revision": revision(quiz["id"] + "@1")} for quiz in [WARM_UP, COOL_DOWN]}
        decision = LC.decide_learner(self.state, command, {"now": now, "catalog": BOARD_CATALOG, "quizzes": quizzes})
        assert "events" in decision, (self.label, command, decision)
        for event in decision["events"]:
            self.state = LC.evolve_learner(self.state, event)
            self.events.append(event)
        return decision

    def play(self, name, quiz, perfect_tasks, at=None):
        """🎮️ Starts, answers and submits one run; ``at`` pins the submission time."""
        self.start(name, quiz["id"])
        self.answer_all(name, quiz, perfect_tasks)
        if at is not None:
            self.clock.now = at - 60000
        return self.submit(name)



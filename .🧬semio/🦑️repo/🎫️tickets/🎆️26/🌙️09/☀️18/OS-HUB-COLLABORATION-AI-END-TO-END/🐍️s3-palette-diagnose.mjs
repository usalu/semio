import { chromium } from "playwright";
const browser = await chromium.launch({ headless: true, args: ["--use-angle=metal"] });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
await page.goto("http://127.0.0.1:6071/", { waitUntil: "domcontentloaded", timeout: 300000 });
await page.waitForFunction(() => document.querySelector('[id="s-home-main"]') !== null, undefined, { timeout: 300000 }).catch(() => {});
await page.waitForTimeout(8000);
console.log("veils:", await page.locator('[data-slot="introduction-veil"]').count());
console.log("navbar:", await page.locator('[data-slot="navbar"]').count());
await page.keyboard.press("Meta+KeyK");
await page.waitForTimeout(2500);
console.log("dialogs:", await page.locator("[role='dialog']").count());
console.log("command-input:", await page.locator("[data-slot='command-input']").count());
console.log("slots:", JSON.stringify([...new Set(await page.evaluate(() => [...document.querySelectorAll("[data-slot]")].map(e => e.getAttribute("data-slot"))))].filter(s=>/command|dialog|palette|overlay|veil/i.test(s))));
await page.locator('[id="framework.category.command"]').first().click({ force: true }).catch(()=>{});
await page.waitForTimeout(2500);
console.log("after tab click dialogs:", await page.locator("[role='dialog']").count(), "cmdinput:", await page.locator("[data-slot='command-input']").count());
console.log("slots2:", JSON.stringify([...new Set(await page.evaluate(() => [...document.querySelectorAll("[data-slot]")].map(e => e.getAttribute("data-slot"))))].filter(s=>/command|dialog|palette|overlay/i.test(s))));
console.log("commandItems:", await page.locator('[data-command-item-id]').count());
console.log("body:", (await page.locator("body").innerText()).replace(/\s+/g," ").slice(0,400));
await browser.close();

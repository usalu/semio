/**
 * 🔬️ Measures the harness's resolution rules against a repository root carrying a catalog generated
 * from the modules on disk RIGHT NOW.
 *
 * `test schema --under <path>` deliberately skips `schemaResolutionDiagnostics` — resolution is a
 * whole-catalog question — so the only honest way to see a partition's `schema-ref-*`/
 * `schema-export-*` rows after an edit is a full run against a current catalog. The tracked
 * `🔣️schema-catalog.json` is generated and regenerated by the tooling worker, so this probe writes a
 * freshly generated one into a SHADOW root whose every other entry symlinks to the live tree, and
 * measures there. It never writes into the repository.
 *
 * Usage: bun wp4d-framework-measure.ts <shadow root>
 */
import { existsSync, lstatSync, mkdirSync, readdirSync, symlinkSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { inventorySchemaScopes, loadCatalogTaxonomy, renderSchemaCatalog } from "../../../../../../../🧰️framework/🛍️products/🦑️repo/🔨️modules/📚️library/🔍️discovery/🟦️.ts";
import { schemaContractDiagnostics } from "../../../../../../../🧰️framework/🛍️products/🦑️repo/🔨️modules/🧪️test/📦️packages/🟦️typescript/🟦️.ts";

const CATALOG_REL = "🧰️framework/🛍️products/🦑️repo/🔨️modules/📚️library/🔣️schema-catalog.json";
const REPO_ROOT = new URL("../../../../../../../", import.meta.url).pathname;

const shadowRoot = process.argv[2];
if (shadowRoot === undefined) throw new Error("usage: bun wp4d-framework-measure.ts <shadow root>");

const chain = CATALOG_REL.split("/");
let sourceRel = "";
for (let depth = 0; depth < chain.length; depth += 1) {
  const shadowDir = depth === 0 ? shadowRoot : join(shadowRoot, ...chain.slice(0, depth));
  const sourceDir = sourceRel.length === 0 ? REPO_ROOT : join(REPO_ROOT, sourceRel);
  mkdirSync(shadowDir, { recursive: true });
  for (const entry of readdirSync(sourceDir)) {
    if (entry === chain[depth]) continue;
    const link = join(shadowDir, entry);
    try {
      lstatSync(link);
    } catch {
      symlinkSync(join(sourceDir, entry), link);
    }
  }
  sourceRel = chain.slice(0, depth + 1).join("/");
}

const inventory = inventorySchemaScopes(REPO_ROOT, loadCatalogTaxonomy());
writeFileSync(join(shadowRoot, CATALOG_REL), renderSchemaCatalog(inventory.catalog));
console.log(`[DEBUG] generated catalog: ${Object.keys(inventory.catalog.scopes).length} scopes, ${inventory.diagnostics.length} generator diagnostics`);

const partition = (path: string | null): boolean => path !== null && path.startsWith("🧰️framework/🔨️modules");
const mine = (path: string | null): boolean => partition(path) && !path!.startsWith("🧰️framework/🔨️modules/🧬️schema") && !path!.startsWith("🧰️framework/🔨️modules/🖱️ui/") && !path!.includes("/🧬️mutations/");

const found = schemaContractDiagnostics(shadowRoot).filter((entry) => partition(entry.path) || partition(entry.scope === null ? null : inventory.catalog.scopes[entry.scope]?.path ?? null));
const locate = (entry: { path: string | null; scope: string | null }): string | null => entry.path ?? (entry.scope === null ? null : inventory.catalog.scopes[entry.scope]?.path ?? null);

for (const [label, rows] of [["🧰️framework/🔨️modules (all)", found], ["this partition", found.filter((entry) => mine(locate(entry)))]] as const) {
  const counts = new Map<string, number>();
  for (const entry of rows) counts.set(entry.code, (counts.get(entry.code) ?? 0) + 1);
  console.log(`[DEBUG] ${label}: ${rows.length} finding(s)`);
  for (const [code, count] of [...counts].sort((a, b) => b[1] - a[1])) console.log(`[DEBUG]   ${String(count).padStart(4)} × ${code}`);
}
for (const entry of found.filter((row) => mine(locate(row)))) console.log(`[DEBUG]   ! ${entry.code} ${locate(entry)} — ${entry.detail}`);
for (const entry of found.filter((row) => !mine(locate(row)))) console.log(`[DEBUG]   ~ (other partition) ${entry.code} ${locate(entry)}`);
if (!existsSync(join(shadowRoot, CATALOG_REL))) throw new Error("shadow catalog missing");

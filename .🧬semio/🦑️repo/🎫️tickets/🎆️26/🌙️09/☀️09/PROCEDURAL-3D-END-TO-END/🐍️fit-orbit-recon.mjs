import { chromium } from "playwright";
const url = process.env.SEMIO_PROBE_URL ?? "http://127.0.0.1:6022/?plugin=generation3d";
const browser = await chromium.launch({ headless: true, args: ["--enable-unsafe-webgpu", "--ignore-gpu-blocklist", "--use-angle=metal"] });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const lines = [];
page.on("console", (m) => lines.push(`${m.type()} ${m.text().slice(0, 400)}`));
await page.goto(url, { waitUntil: "domcontentloaded" });
await page.waitForTimeout(35000);
const box = await page.locator('[data-meshes-json] canvas').last().boundingBox();
const x = Math.round(box.x + box.width * 0.6), y = Math.round(box.y + box.height * 0.45);
const report = await page.evaluate(([px, py]) => {
  const describe = (el) => (el ? `${el.tagName}#${el.id || "-"}[slot=${el.getAttribute("data-slot") ?? "-"}] pe=${getComputedStyle(el).pointerEvents} cls=${String(el.className).slice(0, 110)}` : "null");
  const stack = document.elementsFromPoint(px, py).slice(0, 8).map(describe);
  const canvas = document.querySelector('[data-meshes-json] canvas');
  const chain = [];
  for (let el = canvas; el && chain.length < 8; el = el.parentElement) chain.push(describe(el));
  return { stack, chain };
}, [x, y]);
console.log("[DEBUG] elementsFromPoint\n" + report.stack.join("\n"));
console.log("[DEBUG] canvas ancestry\n" + report.chain.join("\n"));
const probeEvents = await page.evaluate(() => {
  const canvas = document.querySelector('[data-meshes-json] canvas');
  const seen = [];
  const on = (type) => canvas.addEventListener(type, (e) => seen.push(`${type} button=${e.button} alt=${e.altKey}`), true);
  ["pointerdown", "wheel", "pointermove"].forEach(on);
  globalThis.__seen = seen;
  return true;
});
await page.mouse.move(x, y);
await page.mouse.wheel(0, -400);
await page.keyboard.down("Alt");
await page.mouse.down({ button: "right" });
await page.mouse.move(x + 80, y + 30, { steps: 8 });
await page.mouse.up({ button: "right" });
await page.keyboard.up("Alt");
await page.waitForTimeout(2000);
console.log("[DEBUG] canvas received", JSON.stringify(await page.evaluate(() => globalThis.__seen.slice(0, 12))));
console.log("[DEBUG] camera", await page.evaluate(() => document.querySelector('[data-viewport-camera-json]')?.getAttribute("data-viewport-camera-json")));
console.log("[DEBUG] lines", lines.filter((l) => /camera|Camera|navigation/i.test(l)).slice(-8).join("\n"));
await browser.close();

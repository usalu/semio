fs.writeFileSync(destination, "//! 📊️ Calling-thread typed-operation publication census.\n" + section);
fs.writeFileSync(job, a.slice(0, start) + a.slice(end));
fs.writeFileSync(operation, b + "\n#[path = \"🧮️census/🦀️.rs\"]\nmod census;\npub use census::{record_typed_operation_unit, typed_operation_unit_census, TypedOperationUnitCensus, TypedOperationUnitKind};\n");
fs.writeFileSync(publication, c.replace(oldImport, "};\nuse semio_plugin_operation::{TypedOperationUnitKind, record_typed_operation_unit};"));
fs.writeFileSync(facade, d.replace("pub mod app {", "pub mod app {\n    pub use semio_plugin_operation::{typed_operation_unit_census, TypedOperationUnitCensus};"));

const fs = require("node:fs");
const path = require("node:path");
const base = "🧰️framework/🛍️products/💻️os/🔨️modules/🔌️plugin/";
const job = base + "👷️job/🦀️.rs";
const operation = base + "♻️cancellation/🦀️.rs";
const publication = base + "🧵️instance/🧾️typed-operations/📥️staging/📬️publication/🦀️.rs";
const facade = base + "🦀️.rs";
const destination = base + "♻️cancellation/🧮️census/🦀️.rs";
const a = fs.readFileSync(job, "utf8"), b = fs.readFileSync(operation, "utf8"), c = fs.readFileSync(publication, "utf8"), d = fs.readFileSync(facade, "utf8");
const start = a.indexOf("/// 📊️ What the typed-operation publication ladder"), end = a.indexOf("/// 🏃️ Upper bound on worker pump iterations", start);
const oldImport = ", TypedOperationUnitKind, record_typed_operation_unit};";

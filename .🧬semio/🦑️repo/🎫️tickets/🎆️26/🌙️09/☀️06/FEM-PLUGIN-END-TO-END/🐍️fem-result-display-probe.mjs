/** 📊️ Switches the results window to a modal mode-shape view through its own Actions pane and records the render. */
import { chromium } from "playwright";
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
const url = process.env.SEMIO_PROBE_URL ?? "http://127.0.0.1:6086/?plugin=fem2d";
const windowId = process.env.SEMIO_PROBE_RESULTS_WINDOW ?? "fem2dResults";
const surface = process.env.SEMIO_PROBE_RESULTS_SURFACE ?? "window:fem2d-results";
const outDir = join(import.meta.dir, "🗑️generated", process.env.SEMIO_PROBE_OUT ?? "result-display");
mkdirSync(outDir, { recursive: true });
const lines = [];
const t0 = Date.now();
const browser = await chromium.launch({ headless: true, args: ["--enable-unsafe-webgpu", "--ignore-gpu-blocklist", "--use-angle=metal"] });
const page = await (await browser.newContext({ viewport: { width: 1600, height: 1000 } })).newPage();
page.on("console", (m) => lines.push(`${Date.now() - t0} ${m.type()} ${m.text().slice(0, 600)}`));
await page.goto(url, { waitUntil: "domcontentloaded" });
for (let i = 0; i < 90; i++) { await page.waitForTimeout(1000); if (await page.evaluate(() => document.documentElement.getAttribute("data-semio-os-ready"))) break; }
await page.waitForTimeout(4000);
await page.locator(`[data-surface-id="${surface}"]`).first().click({ position: { x: 320, y: 320 } }).catch(() => {});
await page.waitForTimeout(800);
await page.locator(`[id="framework.window.${windowId}.engagement.toggle"]`).first().click({ timeout: 8000 });
await page.waitForTimeout(1200);
await page.locator('[id="action.setResultDisplay"]').first().click({ timeout: 8000 });
await page.waitForTimeout(1200);
const controls = await page.evaluate((windowId) => [...document.querySelectorAll(`[id="framework.window.${windowId}.engagement"] button, [id="framework.window.${windowId}.engagement"] input, [role="dialog"] button`)].map((el) => `${el.tagName}#${el.id}:${(el.innerText ?? el.value ?? "").toString().trim().replace(/\s+/g, " ").slice(0, 30)}`), windowId);
console.log("[DEBUG] controls", JSON.stringify(controls).slice(0, 1200));
const mode = page.locator('[id="mode"]').first();
await mode.click({ timeout: 5000 });
await page.waitForTimeout(500);
const options = await page.locator('[role="option"]').allInnerTexts().catch(() => []);
console.log("[DEBUG] mode options", JSON.stringify(options));
const modal = page.locator('[role="option"]').filter({ hasText: /modal/i }).first();
if (await modal.count()) await modal.click({ timeout: 5000 });
await page.waitForTimeout(500);
const modeIndex = page.locator('[id="modeIndex"]').first();
if (await modeIndex.count()) await modeIndex.fill("0");
const execute = page.locator(`[id="framework.window.${windowId}.action.setResultDisplay.execute"]`).first();
const executed = (await execute.count()) ? await execute.click({ timeout: 8000 }).then(() => "ok").catch((e) => String(e).slice(0, 100)) : "absent";
await page.waitForTimeout(8000);
const state = await page.evaluate((surface) => { const el = document.querySelector(`[data-surface-id="${surface}"]`); return { text: (el?.innerText ?? "").replace(/\s+/g, " ").slice(0, 200), canvases: el?.querySelectorAll("canvas").length ?? 0 }; }, surface);
console.log("[DEBUG] executed", executed, JSON.stringify(state));
await page.screenshot({ path: join(outDir, "final.png") });
writeFileSync(join(outDir, "console.txt"), lines.join("\n"));
console.log("[DEBUG] invocations", lines.filter((l) => /performInvocation \{.*setResultDisplay|action failed|render failed|shell fault/.test(l)).map((l) => l.slice(0, 300)).join(" || "));
await browser.close();

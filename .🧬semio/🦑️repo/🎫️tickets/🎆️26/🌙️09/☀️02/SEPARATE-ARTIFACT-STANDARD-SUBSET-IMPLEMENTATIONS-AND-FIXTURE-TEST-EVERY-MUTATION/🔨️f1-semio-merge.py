#!/usr/bin/env python3
"""🔨️ F1 — merges the fixtures `🔨️f1-semio-generate.py` produced into each of the seven semio
subsets' own `🧪️oracle/🔣️.json`, registering a `fixtureManifests[]` (schema `fixture/v2`) entry per
mutation. Each entry's `generator.oracle` names that subset's ALREADY-REGISTERED
`verified-native-second-implementation` entry — no new oracle is added by this script; the fixture
class is `third-party-generated` per the schema's own enum (the only class fitting a
generator-produced fixture), with the notes field stating plainly that the generator is this
repository's own independent second implementation, not a third-party package."""
import json
import os

REPO = os.getcwd()
TICKET = ".🧬semio/🦑️repo/🎫️tickets/🎆️26/🌙️09/☀️02/SEPARATE-ARTIFACT-STANDARD-SUBSET-IMPLEMENTATIONS-AND-FIXTURE-TEST-EVERY-MUTATION"
ROOT = "✏️s/🔌️plugins/🗄️stdio/🗿️artifacts/🧿️semio/🏅️standards/🔖️v1/🪆️subsets"

SUBSET_ORACLE = {
    "animation": "semio-animation-python-independent",
    "audio": "semio-audio-python-independent",
    "flow": "semio-flow-python-independent",
    "model": "semio-model-python-independent",
    "presentation": "semio-presentation-python-independent",
    "value": "semio-value-python-independent",
    "video": "semio-video-python-independent",
}


def merge_subset(subset, fragments):
    oracle_path = os.path.join(REPO, ROOT, f"✳️{subset}", "🧪️oracle", "🔣️.json")
    with open(oracle_path, "r", encoding="utf-8") as f:
        doc = json.load(f)

    doc.setdefault("fixtureManifests", [])
    existing_ids = {fm["id"] for fm in doc["fixtureManifests"]}

    for frag in fragments:
        if frag["id"] in existing_ids:
            continue
        entry = {
            "schema": "semio.repository-test.fixture/v2",
            "id": frag["id"],
            "class": "third-party-generated",
            "target": {"artifact": "s.stdio.semio", "standard": "v1", "subset": subset},
            "mutation": frag["mutation"],
            "outcome": "applied",
            "units": {"length": "unitless", "angle": "radian"},
            "files": frag["files"],
            "generator": {
                "oracle": SUBSET_ORACLE[subset],
                "packageVersion": "n/a",
                "engineFamily": "cpython",
                "engineVersion": "3",
                "command": f"uv run --group test python3 {TICKET}/🔨️f1-semio-generate.py",
                "platform": "darwin-arm64",
            },
            "provenance": {
                "source": "generated",
                "license": "AGPL-3.0-only",
                "attribution": (
                    "Generated by this subset's own registered `verified-native-second-implementation` "
                    f"oracle ({SUBSET_ORACLE[subset]}) — an independent Python second implementation of "
                    "this subset's mutation vocabulary, NOT a third-party package (no third-party library "
                    "in any ecosystem reads or writes semio's own .dsl.semio format); `class: "
                    "third-party-generated` is used only because it is the schema's own closest-fitting "
                    "enum value for a generator-produced fixture, not a claim of third-party origin."
                ),
                "security": "scanned-clean",
                "privacy": "no-personal-data",
            },
            "comparisonProfile": "ordered-json-v1",
            "reproducible": True,
            "family": "structural",
            "notes": (
                f"Applied {frag['mutation']} (payload {json.dumps(frag['mutation_payload'], ensure_ascii=False)}) to this "
                "subset's own real committed base document via its own, unmodified apply_mutation — every "
                "field touched is content already present in the real document (cloned or swapped between "
                "two real existing members), never an invented id or enum value. D3 registered only this "
                "subset's set-snapshot vector; this fixture discharges one of the remaining kinds its "
                "already-complete second implementation was never given evidence for."
            ),
        }
        doc["fixtureManifests"].append(entry)

    with open(oracle_path, "w", encoding="utf-8") as f:
        json.dump(doc, f, indent=2, ensure_ascii=False)
        f.write("\n")
    print(f"merged {len(fragments)} fixture(s) into {oracle_path}")


def main():
    frag_path = os.path.join(REPO, TICKET, "🗑️generated", "f1-semio-fragments.json")
    with open(frag_path, "r", encoding="utf-8") as f:
        fragments_by_subset = json.load(f)
    for subset, fragments in fragments_by_subset.items():
        merge_subset(subset, fragments)


if __name__ == "__main__":
    main()

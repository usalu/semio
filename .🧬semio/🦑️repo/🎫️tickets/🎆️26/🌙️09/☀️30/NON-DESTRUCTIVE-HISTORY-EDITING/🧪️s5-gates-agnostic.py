"""🪢️ Writes `📓️s5-gates-agnostic.md` from the output of the two artifact-agnostic gates (design §22.31 c, §22.32 d).

    bun ./📜️script.ts verify agnostic framework-names > names.txt ; bun ./📜️script.ts verify agnostic utility-machines > machines.txt
    python3 🧪️s5-gates-agnostic.py names.txt machines.txt <output.md>

Owner by host: React sources → S5-UI, wgpu sources → S5-WGPU, the plugin runtime → S5-RUNTIME, the board engine (`♾️infinite`) →
S5-PUZZLE, stories apart, everything else → coordinator.
"""
import collections
import re
import sys

NAME = re.compile(r"\[verify agnostic\] framework-names (.+?):(\d+) (\w+) (.*)")
MACHINE = re.compile(r"\[verify agnostic\] utility-machines (OFFENDER|machine) (\S+) utilities=(\d+) vocabulary=(\S+)")
PLUGIN_OWNERS = {"wfc": "S5-STROKES-NORM", "remodel": "S5-STROKES-NORM", "raster": "S5-STROKES-NORM", "process": "S5-STROKES-NORM", "block": "S5-TOOLS", "puzzle": "S5-PUZZLE", "cad": "S5-FLOWCAD"}


def owner(path):
    """🧑‍🔧 The work package a framework source belongs to, by host."""
    if "/📖️stories/" in path:
        return "stories (scope decision: coordinator)"
    if "/🧊️wgpu/" in path:
        return "S5-WGPU (wgpu hosts)"
    if "/🔌️plugin/" in path:
        return "S5-RUNTIME (plugin runtime)"
    if "/♾️infinite/" in path:
        return "S5-PUZZLE (board engine)"
    if path.endswith((".ts", ".tsx")) and ("/📺️renderer/" in path or "/🖱️ui/" in path):
        return "S5-UI (React hosts)"
    return "coordinator (other framework modules)"


def main():
    names, machines, output = sys.argv[1:4]
    hits = [NAME.match(line.rstrip("\n")) for line in open(names, encoding="utf-8")]
    hits = [(m.group(1), int(m.group(2)), m.group(3), m.group(4)) for m in hits if m]
    rows = [MACHINE.match(line.rstrip("\n")) for line in open(machines, encoding="utf-8")]
    rows = [(m.group(1), m.group(2), int(m.group(3)), m.group(4)) for m in rows if m]
    grouped = collections.defaultdict(lambda: collections.defaultdict(list))
    for path, line, name, text in hits:
        grouped[owner(path)][path].append((line, name, text))
    lines = ["# 🪢️ S5 gates — artifact-agnostic framework contract (design §22.31 c, §22.32 d)", ""]
    lines += ["Generated by `python3 T/🧪️s5-gates-agnostic.py` from `bun ./📜️script.ts verify agnostic framework-names` and `… utility-machines` (S5-GATES). Both gates are RED BY DESIGN until the owners land §22.31 / §22.32; the field list of the board contract is `📓️s5-board-contract.md`.", ""]
    lines += ["## 1. `verify agnostic framework-names` — no framework code names an artifact", ""]
    lines += ["Rule: a line of a tracked Rust / TypeScript source under `🧰️framework/` — outside `🧪️tests`, `🧫️fixtures`, `🔮️oracles`, generated trees, `*.test.*` and declaration files — that carries `puzzle` or `vortex` (case-insensitive, anywhere in a word) outside a doc comment. Identifiers, string literals and plain comments count; `///`, `//!` and `/** … */` do not.", ""]
    lines += [f"**{len(hits)} lines in {len({hit[0] for hit in hits})} files** ({sum(1 for hit in hits if hit[2] == 'puzzle')} `puzzle`, {sum(1 for hit in hits if hit[2] == 'vortex')} `vortex`).", "", "| Owner (by host) | Files | Lines |", "| --- | ---: | ---: |"]
    order = sorted(grouped, key=lambda name: -sum(len(found) for found in grouped[name].values()))
    for name in order:
        lines.append(f"| {name} | {len(grouped[name])} | {sum(len(found) for found in grouped[name].values())} |")
    lines.append("")
    for name in order:
        lines += [f"### {name}", ""]
        for path, found in sorted(grouped[name].items(), key=lambda item: -len(item[1])):
            lines += [f"`{path}` — {len(found)} line(s)", ""]
            lines += [f"- `:{line}` {word} — `{text[:110].replace('`', chr(39))}`" for line, word, text in found]
            lines.append("")
    offenders = [row for row in rows if row[0] == "OFFENDER"]
    lines += ["## 2. `verify agnostic utility-machines` — an artifact with a `UtilityDefinition` has machine vocabulary", ""]
    lines += ["Rule: an artifact tree (`✏️s/🔌️plugins/<plugin>/🗿️artifacts/<artifact>`) whose production Rust names `UtilityDefinition` uses at least one word of the framework tool-machine vocabulary (`ToolMachine`, `ToolMachineRunner`, `GestureTool`, `GestureChart`, `drive_gesture`, `drive_press`) — whole identifiers, outside test paths and doc comments. `ToolTransaction` alone is not a machine.", ""]
    lines += [f"**{len(rows)} artifacts declare utilities; {len(offenders)} use no machine vocabulary.**", "", "| Verdict | Owner | Artifact | Utility mentions | Machine vocabulary |", "| --- | --- | --- | ---: | --- |"]
    for verdict, artifact, count, vocabulary in sorted(rows, key=lambda row: (row[0] != "OFFENDER", row[1])):
        plugin = re.sub(r"^[^A-Za-z0-9]+", "", artifact.split("/")[2])
        lines.append(f"| {'OFFENDER' if verdict == 'OFFENDER' else 'ok'} | {PLUGIN_OWNERS.get(plugin, 'S5-TOOLS')} | `{artifact}` | {count} | {vocabulary.replace(',', ', ')} |")
    lines.append("")
    with open(output, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines) + "\n")
    print(f"[s5-gates-agnostic] {len(hits)} name line(s) in {len({hit[0] for hit in hits})} file(s), {len(rows)} utility artifact(s), {len(offenders)} offender(s) → {output}")
    for name in order:
        print(f"  {name}: {sum(len(found) for found in grouped[name].values())} line(s) in {len(grouped[name])} file(s)")


main()

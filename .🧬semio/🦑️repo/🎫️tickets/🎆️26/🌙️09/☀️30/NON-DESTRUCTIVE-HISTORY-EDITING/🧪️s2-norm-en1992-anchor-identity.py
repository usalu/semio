"""🧷️ S2-NORM item 2: the en1992 leaf directory `🧷change-anchor-a-s` renders the kind `change-anchor-as` (the wire
identity, unchanged), so the leaf, its fixture mirror and every path naming them move to `🧷change-anchor-as`.

  python3 🧪️s2-norm-en1992-anchor-identity.py [--check]

Moves the two directories, rewrites the exact references inside en1992 (lib-root `#[path]`s, catalog, feature tables with
their column alignment kept, case adapters, canonical test, vector-suite mount, descriptor owner and display name). The
plugin-wide `📇️mutation-leaf-taxonomy-v1` fixture is regenerated by its owner target; the two hot schema-catalog files are
edited by hand.
"""

import os
import re
import sys

ROOT = "/Users/ueli/Documents/semio"
SUBSET = f"{ROOT}/✏️s/🔌️plugins/📕️norm/🗿️artifacts/🏛️en1992/🏅️standards/🔖️1/🪆️subsets/✳️any"
OLD, NEW = "🧷change-anchor-a-s", "🧷change-anchor-as"
MOVES = [f"{SUBSET}/🧬️schema/🧬️mutations", f"{SUBSET}/🧫️fixtures/🧬️mutations"]
FILES = [
    f"{ROOT}/✏️s/🔌️plugins/📕️norm/🗿️artifacts/🏛️en1992/🦀️.rs",
    f"{SUBSET}/🔮️oracles/🔣️.json",
    f"{SUBSET}/🧪️tests/🏛️mutate-en1992-1/🥒️.feature",
    f"{SUBSET}/🧪️tests/🏛️mutate-en1992-1/🦀️.rs",
    f"{SUBSET}/🧪️tests/🏛️mutate-en1992-1/🐍️.py",
    f"{SUBSET}/🧬️schema/🧬️mutations/🧪️tests/🔬️fixture/🦀️.rs",
    f"{SUBSET}/🧬️schema/🧬️mutations/{NEW}/🔣️.json",
    f"{SUBSET}/🧬️schema/🧬️mutations/{NEW}/🧪️tests/✅apply/🦀️.rs",
]
DISPLAY = ('"displayName": "Change Anchor A S"', '"displayName": "Change Anchor A_s"')


def rewrite(text):
    text = re.sub(re.escape(OLD) + r"( +)\|", lambda match: f"{NEW}{match.group(1)} |", text)
    return text.replace(OLD, NEW).replace(*DISPLAY)


def main(check):
    pending = [root for root in MOVES if os.path.isdir(f"{root}/{OLD}")]
    stale = [path for path in FILES if os.path.exists(path) and OLD in open(path, encoding="utf-8").read()]
    if check:
        print(f"[s2-norm anchor] pending moves={len(pending)} stale files={len(stale)}")
        return 1 if pending or stale else 0
    for root in pending:
        assert not os.path.exists(f"{root}/{NEW}"), f"{root}/{NEW} exists"
        os.rename(f"{root}/{OLD}", f"{root}/{NEW}")
    for path in FILES:
        text = open(path, encoding="utf-8").read()
        updated = rewrite(text)
        if updated != text:
            open(path, "w", encoding="utf-8").write(updated)
            print(f"rewrote {os.path.relpath(path, ROOT)}")
    print(f"[s2-norm anchor] moved {len(pending)} directories")
    return 0


if __name__ == "__main__":
    sys.exit(main("--check" in sys.argv))

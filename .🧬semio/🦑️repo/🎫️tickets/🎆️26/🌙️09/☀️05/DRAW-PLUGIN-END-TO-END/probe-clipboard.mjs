/** 📋️ Copies, pastes, cuts and duplicates a layer by keyboard and panel and counts layers after each step. */
import { mkdirSync } from "node:fs";
import { createRequire } from "node:module";
import { join, resolve } from "node:path";
const require = createRequire(resolve("✏️s/🔌️plugins/🖍️draw/🧪️tests/🌐️browser/🟦️.mjs"));
const { chromium } = require("playwright");
const output = resolve(process.argv[2]);
mkdirSync(output, { recursive: true });
const browser = await chromium.launch({ headless: true, args: ["--use-angle=swiftshader", "--enable-unsafe-swiftshader", "--enable-unsafe-webgpu"] });
const page = await (await browser.newContext({ locale: "en", viewport: { width: 1600, height: 1000 }, permissions: ["clipboard-read", "clipboard-write"] })).newPage();
await page.routeWebSocket(address => address.searchParams.has("token"), () => undefined);
const errors = [];
page.on("console", message => { if (["error", "warning"].includes(message.type()) && !message.text().startsWith("[DEBUG] ")) errors.push(message.text().slice(0, 300)); });
page.on("pageerror", error => errors.push(String(error)));
await page.goto("http://127.0.0.1:6064/?plugin=draw");
await page.waitForFunction(() => document.documentElement.dataset.semioOsReady, undefined, { timeout: 90000 });
await page.waitForTimeout(6000);
await page.getByText("Artifact", { exact: true }).first().click();
const rows = () => page.locator('[role="treeitem"][id^="panel:framework.panel.artifact/drawing-play-layers"]').evaluateAll(nodes => nodes.map(node => node.id).filter(id => !id.includes(".add.")).map(id => id.split("drawing-play-layers.").pop().slice(0, 26)));
const settle = async (name, done) => { const start = Date.now(); let current = await rows(); while (Date.now() - start < 12000 && !done(current)) { await page.waitForTimeout(200); current = await rows(); } console.log(name, done(current) ? "ok" : "NO CHANGE", `${Date.now() - start} ms`, current.length, JSON.stringify(current), "errors", errors.length); return current; };
await page.locator('[id$="drawing-play-layers.path.emblem-teal"]').first().click();
await page.waitForTimeout(3000);
let before = await rows();
const focus = () => page.locator('[data-surface-role="editor"] [data-ui-node-key="drawing.play.composite"]').first().focus();
console.log("boot", before.length);
await focus(); await page.keyboard.press("Meta+c"); await page.waitForTimeout(4000); console.log("copy errors", errors.length, errors.slice(-2));
await focus(); await page.keyboard.press("Meta+v"); before = await settle("paste", now => now.length === before.length + 1);
await page.waitForTimeout(3000);
await focus(); await page.keyboard.press("Meta+x"); const count = before.length; before = await settle("cut", now => now.length === count - 1);
await page.waitForTimeout(3000);
await focus(); await page.keyboard.press("Meta+v"); const cutCount = before.length; before = await settle("paste-after-cut", now => now.length === cutCount + 1);
await page.waitForTimeout(3000);
await focus(); await page.keyboard.press("Meta+d"); const pasted = before.length; await settle("duplicate", now => now.length === pasted + 1);
await page.screenshot({ path: join(output, "end.png") });
console.log(errors.slice(0, 5));
await browser.close();

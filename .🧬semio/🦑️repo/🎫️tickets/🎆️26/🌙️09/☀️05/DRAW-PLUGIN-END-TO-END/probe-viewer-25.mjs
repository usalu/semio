import { createRequire } from 'node:module';
import { resolve } from 'node:path';
import { createHash } from 'node:crypto';
const require = createRequire(resolve('✏️s/🔌️plugins/🖍️draw/🧪️tests/🌐️browser/🟦️.mjs'));
const { chromium } = require('playwright');
const locale = process.argv[2];
const out = resolve(process.argv[3]);
const browser = await chromium.launch({ headless: true, args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--enable-unsafe-webgpu'] });
const page = await (await browser.newContext({ locale, viewport: { width: 1600, height: 1000 } })).newPage();
page.on('pageerror', e => console.log('PAGEERROR', e.message));
await page.routeWebSocket(address => address.searchParams.has('token'), () => undefined);
await page.goto(`http://127.0.0.1:6064/?plugin=draw&lang=${locale}`);
await page.waitForFunction(() => document.documentElement.dataset.semioOsReady, undefined, { timeout: 90000 });
await page.waitForTimeout(8000);
console.log('INITIAL', JSON.stringify(await page.getByRole('button').allTextContents()));
await page.getByRole('button', {name: locale === 'de' ? /Betrachter/ : /Viewer/}).click();
await page.waitForTimeout(12000);
console.log('VIEWER', JSON.stringify({text: await page.locator('body').innerText(), surfaces: await page.locator('[data-surface-role]').evaluateAll(es => es.map(e => ({role:e.getAttribute('data-surface-role'), canvases:e.querySelectorAll('canvas').length}))), canvases: await page.locator('canvas').count()}));
const canvas=page.locator('canvas').first();
const box=await canvas.boundingBox();
console.log('CANVAS',JSON.stringify(box));
const before=await page.screenshot({path: `${out}-${locale}-viewer.png`});
await page.mouse.move(box.x+box.width/2,box.y+box.height/2);
await page.mouse.wheel(0,-500);
await page.waitForTimeout(5000);
const after=await page.screenshot({path: `${out}-${locale}-zoom.png`});
console.log('CAMERA_SCREENSHOT_CHANGED',createHash('sha256').update(before).digest('hex') !== createHash('sha256').update(after).digest('hex'));
await page.getByRole('button', {name: /Editor/}).click();
await page.waitForTimeout(12000);
console.log('RETURN', JSON.stringify(await page.locator('body').innerText()));
await page.screenshot({path: `${out}-${locale}-editor.png`});
await browser.close();

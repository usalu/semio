/** ⏱️ Traces every archive-load poll of a Blank→Demo example switch: send duration and gap between polls. */
import { createRequire } from "node:module";
import { resolve } from "node:path";
const require = createRequire(resolve("✏️s/🔌️plugins/🖍️draw/🧪️tests/🌐️browser/🟦️.mjs"));
const { chromium } = require("playwright");
const base = process.argv[2] ?? "http://localhost:6064/?plugin=draw&lang=en";
const browser = await chromium.launch({ headless: true, args: ["--use-angle=swiftshader", "--enable-unsafe-swiftshader", "--enable-unsafe-webgpu"] });
const page = await (await browser.newContext({ locale: "en", viewport: { width: 1600, height: 1000 } })).newPage();
const t0 = performance.now();
let patched = 0;
await page.route(url => decodeURIComponent(url.href).includes("archive-transfer"), async route => {
  const response = await route.fetch();
  let body = await response.text();
  const before = body;
  body = body.replace(/const replyFrames = await this\.ledger\.send\(step\.command\);/, `const __s = performance.now(); const replyFrames = await this.ledger.send(step.command); console.log("[TRACE] send", Object.keys(step.command)[0], Math.round(performance.now() - __s), "ms");`);
  body = body.replace(/progress\?\.\(answer\.status\);/, `progress?.(answer.status); console.log("[TRACE] status", answer.status.state, answer.status.stage, answer.status.completed, answer.status.total);`);
  patched += body === before ? 0 : 1;
  await route.fulfill({ response, body });
});
page.on("console", m => { if (m.text().startsWith("[TRACE]")) console.log(Math.round(performance.now() - t0), m.text()); });
if (process.env.PROBE_DIAG) await page.addInitScript(() => localStorage.setItem("SEMIO_RUNTIME_DIAGNOSTICS", "1"));
await page.goto(base);
await page.waitForFunction(() => document.documentElement.dataset.semioOsReady, undefined, { timeout: 90000 });
console.log("PATCHED", patched);
const picker = page.locator('[id="playground.navbar.fixture"]').first();
await picker.getByText("Demo", { exact: true }).waitFor({ state: "visible", timeout: 60000 });
await page.waitForTimeout(5000);
const status = page.locator('[id="drawing-composite"] [data-slot="engagement-status"]');
if (!(await status.isVisible())) await page.locator('[id^="framework.window."][id$=".engagement.toggle"]').first().click();
await status.waitFor({ state: "visible", timeout: 15000 });
await page.evaluate(() => performance.clearMeasures());
await picker.click();
console.log(Math.round(performance.now() - t0), "SWITCH blank");
await page.getByRole("option", { name: "Blank Drawing", exact: true }).click();
await page.waitForTimeout(15000);
const top = async label => console.log("TOP", label, JSON.stringify(await page.evaluate(() => performance.getEntriesByType("measure").filter(m => m.name === "semio.hop.worker.guest").map(m => [Math.round(m.startTime), Math.round(m.duration), m.detail]).sort((a, b) => b[1] - a[1]).slice(0, 14))));
const steps = async label => console.log("STEPS", label, JSON.stringify(await page.evaluate(() => { const g = performance.getEntriesByType("measure").filter(m => m.name === "semio.hop.worker.guest"); const t0 = g[0]?.startTime ?? 0; const buckets = {}; let total = 0; for (const m of g) { const b = Math.floor((m.startTime - t0) / 2000) * 2; const n = m.detail?.driveSteps ?? 0; total += n; const e = buckets[b] ??= { turns: 0, steps: 0, ms: 0 }; e.turns++; e.steps += n; e.ms += Math.round(m.duration); } return { total, buckets }; })));
const breakdown = async label => console.log("BREAKDOWN", label, JSON.stringify(await page.evaluate(() => { const by = {}; for (const m of performance.getEntriesByType("measure")) { if (!m.name.startsWith("semio.hop.")) continue; const k = m.name.slice(10); const e = by[k] ??= { n: 0, total: 0, max: 0 }; e.n++; e.total += m.duration; e.max = Math.max(e.max, m.duration); } for (const e of Object.values(by)) { e.total = Math.round(e.total); e.max = Math.round(e.max); } return by; })));
await breakdown("blank");
await top("blank");
await steps("blank");
await page.evaluate(() => performance.clearMeasures());
await picker.click();
console.log(Math.round(performance.now() - t0), "SWITCH demo");
await page.getByRole("option", { name: "Demo", exact: true }).click();
const sample = () => page.evaluate(() => { const t = document.querySelector('[id="drawing-composite"] [data-slot="engagement-status"]')?.textContent ?? null; const m = t?.match(/(\d+) layers?/); return m ? Number(m[1]) : t; });
let last = "init";
const end = performance.now() + Number(process.argv[3] ?? 90000);
while (performance.now() < end) { const v = await sample().catch(() => "err"); if (v !== last) { console.log(Math.round(performance.now() - t0), "LAYERS", JSON.stringify(v)); last = v; } await page.waitForTimeout(250); }
await breakdown("demo");
console.log(Math.round(performance.now() - t0), "END");
await browser.close();

const MINE = new Set(['3', '4', '5', '6', '11', '12', '20', '23', '24', '42', '48', '49', '60', '68'])

const catalog = JSON.parse(readFileSync(CATALOG, 'utf8'))
let changed = 0
const unmapped = []
for (const entry of catalog.kinds) {
  const section = entry.id.split('/')[0]
  if (!MINE.has(section)) continue
  const hit = M[entry.slug]
  if (!hit) { unmapped.push(entry.id); continue }
  const [family, options] = hit
  entry.family = family
  entry.options = options
  if (NS[family]) entry.namespace = NS[family]
  if (DATA[family]) entry.data = DATA[family]
  changed++
}
writeFileSync(CATALOG, JSON.stringify(catalog, null, 2) + '\n', 'utf8')
console.log('rewritten', changed, 'entries')
console.log('left to their existing owner:', unmapped.join(' '))

// 🔍 distinctness check: no two kinds of one family may share an option string
const seen = new Map()
for (const entry of catalog.kinds) {
  if (!MINE.has(entry.id.split('/')[0])) continue
  if (!M[entry.slug]) continue
  const key = entry.family + '|' + JSON.stringify(entry.options)
  if (seen.has(key)) console.log('DUPLICATE', entry.id, 'vs', seen.get(key))
  else seen.set(key, entry.id)
}

const ADJ_ENDING: Record<Gender, string> = { m: "er", f: "e", n: "es", p: "e" };

const lower = (word: string): string => word.toLowerCase();
const capitalize = (word: string): string => word.charAt(0).toUpperCase() + word.slice(1);
const decapitalize = (word: string): string => word.charAt(0).toLowerCase() + word.slice(1);

/** 🇩🇪 Renders one English catalogue title as German. */
export function toGerman(title: string): string {
  const direct = OVERRIDES[title];
  if (direct !== undefined) return direct;
  const words = title.split(/\s+/).filter((word) => word.length > 0);
  if (words.length === 0) return title;

  const headWord = words[words.length - 1]!;
  const headEntry = LEXICON[lower(headWord)]?.head;
  const headDe = headEntry?.de ?? headWord;
  const gender: Gender = headEntry?.g ?? "n";

  const leading: string[] = [];
  const prefixes: { readonly de: string; readonly hyphen: boolean }[] = [];
  for (const word of words.slice(0, -1)) {
    const entry = LEXICON[lower(word)];
    if (entry?.adj !== undefined) { leading.push(entry.adj + ADJ_ENDING[gender]); continue; }
    if (entry?.keep !== undefined) { leading.push(entry.keep); continue; }
    if (entry?.mod !== undefined) { prefixes.push({ de: entry.mod.de, hyphen: entry.mod.hyphen === true }); continue; }
    prefixes.push({ de: word, hyphen: true });
  }

  let compound = headEntry === undefined ? headDe : capitalize(headDe);
  for (let index = prefixes.length - 1; index >= 0; index -= 1) {
    const prefix = prefixes[index]!;
    compound = prefix.hyphen ? `${prefix.de}-${compound}` : `${prefix.de}${decapitalize(compound)}`;
  }
  compound = capitalize(compound);
  if (leading.length === 0) return compound;
  return `${capitalize(leading[0]!)}${leading.length > 1 ? ` ${leading.slice(1).join(" ")}` : ""} ${compound}`;
}

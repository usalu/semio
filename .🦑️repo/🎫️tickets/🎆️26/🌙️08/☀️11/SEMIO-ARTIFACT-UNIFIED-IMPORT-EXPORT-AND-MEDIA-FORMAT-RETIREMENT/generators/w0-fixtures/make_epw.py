#!/usr/bin/env python3
"""Handcraft a real EnergyPlus Weather (.epw) file: 8 header lines +
24 hourly data records (one full day) with all 35 EPW columns populated
with plausible values, per the EnergyPlus Auxiliary Programs documentation
column order.
"""
import math
import sys

OUT = sys.argv[1]

# ---- 8 header lines (fixed EPW header block, in order) ----
# 1. LOCATION: City,State,Country,Source,WMO,Lat,Lon,TZ,Elevation
LOCATION = "LOCATION,Hannover,Niedersachsen,DEU,semio-fixture,10238,52.37,9.74,1.0,55.0"

# 2. DESIGN CONDITIONS (count + name/source, then 1997 ASHRAE HOF-style summary; kept minimal but well-formed)
DESIGN_CONDITIONS = "DESIGN CONDITIONS,1,Climate Design Data 2009 ASHRAE Handbook,,Heating,7,-11.5,-9.2,-18.6,2.9,-7.8,-15.5,3.4,4.1,-6,17.9,-4.9,17.2,-3.1,16.5,4.2,180,Cooling,7,10.4,32.4,21.9,30.9,21.5,29.5,21.1,22.8,29.6,21.9,28.4,21.4,27.4,20.9,4.4,300,17.9,12.1,26.2,16.6,11.4,25.2,16,10.7,24.4,64.5,29,60.9,27.9,58.1,27,1017,Extremes,10.2,8.6,7.4,29.4,-19.6,36.5,3.1,1.4,-21.6,38.1,-23.1,39.4,-24.5,40.5,-26.6,42.2"

# 3. TYPICAL/EXTREME PERIODS
TYPICAL_EXTREME = "TYPICAL/EXTREME PERIODS,6,Summer - Week Nearest Max Temperature For Period,Extreme,7/ 8,7/14,Summer - Week Nearest Average Temperature For Period,Typical,6/24,6/30,Winter - Week Nearest Min Temperature For Period,Extreme,1/ 1,1/ 7,Winter - Week Nearest Average Temperature For Period,Typical,1/22,1/28,Autumn - Week Nearest Average Temperature For Period,Typical,10/22,10/28,Spring - Week Nearest Average Temperature For Period,Typical,4/15,4/21"

# 4. GROUND TEMPERATURES: count then per-depth 16 values (depth,soil-cond,soil-density,soil-spec-heat, 12 monthly temps)
GROUND_TEMPERATURES = "GROUND TEMPERATURES,3,0.5,,,,4.90,4.20,5.40,8.70,13.70,17.60,19.60,19.10,16.30,12.30,8.40,5.90,2.0,,,,7.00,6.10,6.70,9.00,12.80,16.10,18.10,18.10,16.10,13.10,10.00,7.90,4.0,,,,9.20,8.10,8.10,9.40,11.90,14.30,16.10,16.60,15.60,13.80,11.60,9.90"

# 5. HOLIDAYS/DAYLIGHT SAVINGS
HOLIDAYS_DST = "HOLIDAYS/DAYLIGHT SAVINGS,No,0,0,0"

# 6/7. COMMENTS 1 and 2
COMMENTS_1 = "COMMENTS 1,semio W0 handcrafted EPW fixture -- structurally valid, plausible values, not a real station record."
COMMENTS_2 = "COMMENTS 2,Generated by make_epw.py for ticket SEMIO-ARTIFACT-UNIFIED-IMPORT-EXPORT-AND-MEDIA-FORMAT-RETIREMENT."

# 8. DATA PERIODS: count,records-per-hour,name,start-day-of-week,start-date,end-date
DATA_PERIODS = "DATA PERIODS,1,1,Data,Sunday, 1/ 1, 1/ 1"

HEADER_LINES = [
    LOCATION,
    DESIGN_CONDITIONS,
    TYPICAL_EXTREME,
    GROUND_TEMPERATURES,
    HOLIDAYS_DST,
    COMMENTS_1,
    COMMENTS_2,
    DATA_PERIODS,
]

assert len(HEADER_LINES) == 8

# ---- 35 EPW data columns, in spec order ----
COLUMNS = [
    "year", "month", "day", "hour", "minute",
    "data_source_uncertainty",
    "dry_bulb_temp", "dew_point_temp", "relative_humidity", "atmospheric_pressure",
    "extraterrestrial_horizontal_radiation", "extraterrestrial_direct_normal_radiation",
    "horizontal_infrared_radiation", "global_horizontal_radiation",
    "direct_normal_radiation", "diffuse_horizontal_radiation",
    "global_horizontal_illuminance", "direct_normal_illuminance", "diffuse_horizontal_illuminance",
    "zenith_luminance",
    "wind_direction", "wind_speed",
    "total_sky_cover", "opaque_sky_cover", "visibility", "ceiling_height",
    "present_weather_observation", "present_weather_codes",
    "precipitable_water", "aerosol_optical_depth", "snow_depth",
    "days_since_last_snowfall", "albedo",
    "liquid_precip_depth", "liquid_precip_quantity",
]
assert len(COLUMNS) == 35

def solar_shape(hour_of_day: int) -> float:
    """0 at night, peaked at midday -- simple daylight bell for plausible radiation values."""
    if hour_of_day < 6 or hour_of_day > 18:
        return 0.0
    x = (hour_of_day - 12) / 6.0
    return max(0.0, math.cos(x * math.pi / 2))

def make_record(hour: int) -> str:
    # EPW hour field is 1-24 (hour ending), minute typically 0 or 60 depending on source; use 60 (end-of-hour convention, common in TMY-derived files) -> use 0 for simplicity/clarity.
    year, month, day, minute = 2026, 1, 15, 0
    data_source_uncertainty = "?9?9?9?9E0?9?9?9?9?9?9?9?9?9?9?9?9?9?9?9?9?9?9?9?9?9?9?9?9?9?9?9?9"

    base_temp = -2.0
    diurnal = 6.0 * math.sin((hour - 6) / 24.0 * 2 * math.pi)
    dry_bulb_temp = round(base_temp + diurnal, 1)
    dew_point_temp = round(dry_bulb_temp - 4.5, 1)
    relative_humidity = round(max(20, min(100, 75 - diurnal * 3)))
    atmospheric_pressure = 101100

    sun = solar_shape(hour)
    extraterrestrial_horizontal_radiation = round(1200 * sun)
    extraterrestrial_direct_normal_radiation = round(1415 * (1 if sun > 0 else 0))
    horizontal_infrared_radiation = 280 + round(20 * sun)
    global_horizontal_radiation = round(650 * sun)
    direct_normal_radiation = round(500 * sun)
    diffuse_horizontal_radiation = round(150 * sun)
    global_horizontal_illuminance = round(70000 * sun)
    direct_normal_illuminance = round(60000 * sun)
    diffuse_horizontal_illuminance = round(15000 * sun)
    zenith_luminance = round(4500 * sun)

    wind_direction = (200 + hour * 5) % 360
    wind_speed = round(2.5 + 1.5 * math.sin(hour / 24.0 * 2 * math.pi), 1)
    total_sky_cover = (hour * 3) % 11
    opaque_sky_cover = (hour * 2) % 11
    visibility = 20.0
    ceiling_height = 22000
    present_weather_observation = 0
    present_weather_codes = "999999999"
    precipitable_water = 14
    aerosol_optical_depth = 0.081
    snow_depth = 0
    days_since_last_snowfall = 88
    albedo = 0.2
    liquid_precip_depth = 0
    liquid_precip_quantity = 0

    fields = [
        year, month, day, hour, minute,
        data_source_uncertainty,
        dry_bulb_temp, dew_point_temp, relative_humidity, atmospheric_pressure,
        extraterrestrial_horizontal_radiation, extraterrestrial_direct_normal_radiation,
        horizontal_infrared_radiation, global_horizontal_radiation,
        direct_normal_radiation, diffuse_horizontal_radiation,
        global_horizontal_illuminance, direct_normal_illuminance, diffuse_horizontal_illuminance,
        zenith_luminance,
        wind_direction, wind_speed,
        total_sky_cover, opaque_sky_cover, visibility, ceiling_height,
        present_weather_observation, present_weather_codes,
        precipitable_water, aerosol_optical_depth, snow_depth,
        days_since_last_snowfall, albedo,
        liquid_precip_depth, liquid_precip_quantity,
    ]
    assert len(fields) == 35
    return ",".join(str(f) for f in fields)

def main():
    records = [make_record(h) for h in range(1, 25)]  # EPW hours are 1..24
    lines = HEADER_LINES + records
    text = "\r\n".join(lines) + "\r\n"
    with open(OUT, "w", newline="") as fh:
        fh.write(text)
    return {
        "header_lines": len(HEADER_LINES),
        "records": len(records),
        "columns_per_record": 35,
        "total_lines": len(lines),
        "total_bytes": len(text.encode("utf-8")),
        "sample_record_0": records[0],
    }

if __name__ == "__main__":
    print(main())

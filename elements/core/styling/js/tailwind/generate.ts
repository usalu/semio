#!/usr/bin/env bun
/** @emoji ⚙️ Reads `elements/core/styling/tokens.json`; emits Tailwind palette CSS under `@elements/styling` and `Elements.Styling/Generated/Palette.g.cs` for Semio / Grasshopper / Rhino. */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const here = import.meta.dir;
const coreStylingRoot = join(here, "..", "..");
const elementsRoot = join(coreStylingRoot, "..", "..");
const tokensPath = join(coreStylingRoot, "tokens.json");
const stylingClientRoot = join(elementsRoot, "client", "lib", "styling");
const generatedDir = join(stylingClientRoot, "generated");
const repoRoot = join(elementsRoot, "..");
const netPaletteDir = join(repoRoot, "semio", "client", "lib", "net", "Elements.Styling", "Generated");

function colorKeyToCssVar(key: string): string {
	return `--color-${key.replaceAll("_", "-")}`;
}

function toPascalCase(s: string): string {
	return s
		.split(/[^a-zA-Z0-9]+/)
		.filter(Boolean)
		.map((p) => p[0]!.toUpperCase() + p.slice(1))
		.join("");
}

interface Tokens {
	version: number;
	colors: Record<string, string>;
	spacing: Record<string, string>;
	fontStacks: Record<string, string>;
	fontFaces: { family: string; src: string }[];
}

function loadTokens(): Tokens {
	const raw = readFileSync(tokensPath, "utf8");
	return JSON.parse(raw) as Tokens;
}

function emitPaletteFonts(tokens: Tokens): string {
	const assetBase = "../../../../assets";
	const lines: string[] = [
		"/* Generated from elements/core/styling/tokens.json — run `bun ./elements/core/styling/script.ts generate` or `nx run @elements/styling-core:generate`. */",
	];
	for (const face of tokens.fontFaces) {
		const fam = face.family.includes(" ") ? JSON.stringify(face.family) : `"${face.family}"`;
		lines.push("@font-face {");
		lines.push(`  font-family: ${fam};`);
		lines.push(`  src: url("${assetBase}/${face.src}") format("woff2");`);
		lines.push("  font-weight: normal;");
		lines.push("  font-style: normal;");
		lines.push("  font-display: swap;");
		lines.push("}");
		lines.push("");
	}
	return lines.join("\n");
}

function emitPaletteTheme(tokens: Tokens): string {
	const lines: string[] = [
		"/* Generated from elements/core/styling/tokens.json — run `bun ./elements/core/styling/script.ts generate` or `nx run @elements/styling-core:generate`. */",
		"@theme {",
		"  /* Primary brand colors */",
	];
	for (const [k, v] of Object.entries(tokens.colors)) {
		lines.push(`  ${colorKeyToCssVar(k)}: ${v};`);
	}
	lines.push("  /* Font interfaces */");
	lines.push(`  --font-sans: ${tokens.fontStacks.sans};`);
	lines.push(`  --font-serif: ${tokens.fontStacks.serif};`);
	lines.push(`  --font-mono: ${tokens.fontStacks.mono};`);
	lines.push("  /* Layout spacing */");
	for (const [k, v] of Object.entries(tokens.spacing)) {
		lines.push(`  --spacing-${k.replaceAll("_", "-")}: ${v};`);
	}
	lines.push("}");
	lines.push("");
	return lines.join("\n");
}

function emitCSharpPalette(tokens: Tokens): string {
	const lines: string[] = [
		"// <auto-generated />",
		"// Generated from elements/core/styling/tokens.json — run `bun ./elements/core/styling/script.ts generate` or `nx run @elements/styling-core:generate`.",
		"namespace Elements.Styling;",
		"",
		"public static class Palette",
		"{",
	];
	for (const [k, v] of Object.entries(tokens.colors)) {
		const name = toPascalCase(k);
		lines.push(`  public const string ${name} = "${v}";`);
	}
	lines.push("}");
	lines.push("");
	return lines.join("\n");
}

export function generateStylingArtifacts(): void {
	const tokens = loadTokens();
	mkdirSync(generatedDir, { recursive: true });
	mkdirSync(netPaletteDir, { recursive: true });
	writeFileSync(join(generatedDir, "palette-fonts.css"), emitPaletteFonts(tokens), "utf8");
	writeFileSync(join(generatedDir, "palette-theme.css"), emitPaletteTheme(tokens), "utf8");
	writeFileSync(join(netPaletteDir, "Palette.g.cs"), emitCSharpPalette(tokens), "utf8");
}

if (import.meta.main) {
	generateStylingArtifacts();
	console.log("elements styling-core: wrote @elements/styling/generated/*.css + Elements.Styling/Generated/Palette.g.cs");
}
